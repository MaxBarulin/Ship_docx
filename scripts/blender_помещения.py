def _кол(имя, родитель=None):
    c = bpy.data.collections.get(имя)
    if c is None:
        c = bpy.data.collections.new(имя)
        (родитель or bpy.context.scene.collection).children.link(c)
    return c


def _короб(имя, центр, размеры, кол, материал, угол=0.0):
    dx, dy, dz = (d / 2.0 for d in размеры)
    verts = [(sx * dx, sy * dy, sz * dz) for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]
    faces = [[0, 1, 3, 2], [4, 6, 7, 5], [0, 2, 6, 4], [1, 5, 7, 3], [0, 4, 5, 1], [2, 3, 7, 6]]
    старый = bpy.data.objects.get(имя)
    if старый is not None:
        bpy.data.objects.remove(старый, do_unlink=True)
    me = bpy.data.meshes.new(имя)
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False)
    me.update()
    ob = bpy.data.objects.new(имя, me)
    кол.objects.link(ob)
    ob.location = центр
    ob.rotation_euler = (0.0, 0.0, угол)
    Ст.назначить(ob, материал)
    return ob


def _стена_x(имя, x, y0, y1, z0, z1, кол, материал="Технические_серые"):
    """Поперечная стена в плоскости x, от y0 до y1."""
    return _короб(имя, (x, 0.5 * (y0 + y1), 0.5 * (z0 + z1)), (СТЕНА, abs(y1 - y0), z1 - z0), кол, материал)


def _стена_y(имя, y, x0, x1, z0, z1, кол, материал="Технические_серые"):
    """Продольная стена в плоскости y, от x0 до x1."""
    return _короб(имя, (0.5 * (x0 + x1), y, 0.5 * (z0 + z1)), (abs(x1 - x0), СТЕНА, z1 - z0), кол, материал)


def _полу(палуба, x, z):
    return SU.полуширота(x, ЯРУС[палуба], z=z)


def _перегородка_борт(имя, x, y0, палуба, z0, z1, кол, материал, знак=1, зазор=0.04):
    """Поперечная перегородка бортовой каюты: от y0 до обшивки борта.

    Борт яруса с завалом и утопленной верхней полосой — коробка до него
    либо врезается в обшивку у карниза, либо оставляет щель внизу. Поэтому
    наружная кромка идёт по профилю борта на этой абсциссе, отступая
    внутрь на «зазор». Тело — призма толщиной СТЕНА.
    """
    проф = SU.профиль(ЯРУС[палуба])
    кромка = []
    for dy, z in проф:
        zz = min(max(z, z0), z1)
        y = SU.полуширота(x, ЯРУС[палуба], z=zz) + dy - зазор
        кромка.append((y, zz))
    # обрезать по z0..z1, крайние точки на самих границах
    внутри = [(y, z) for y, z in кромка if z0 < z < z1]
    yн = SU.полуширота(x, ЯРУС[палуба], z=z0) + проф[0][0] - зазор
    yв = SU.полуширота(x, ЯРУС[палуба], z=z1) + проф[-1][0] - зазор
    контур = [(y0, z0), (yн, z0)] + внутри + [(yв, z1), (y0, z1)]
    if min(y for y, _ in контур[1:-1]) <= y0 + 0.05:
        return None
    verts, faces = [], []
    n = len(контур)
    for sx in (-1, 1):
        for y, z in контур:
            verts.append((x + sx * СТЕНА / 2.0, знак * y, z))
    faces.append(list(range(n))[::-1])
    faces.append([n + i for i in range(n)])
    for i in range(n):
        j = (i + 1) % n
        faces.append([i, j, n + j, n + i])
    старый = bpy.data.objects.get(имя)
    if старый is not None:
        bpy.data.objects.remove(старый, do_unlink=True)
    me = bpy.data.meshes.new(имя)
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False)
    me.update()
    ob = bpy.data.objects.new(имя, me)
    кол.objects.link(ob)
    Ст.назначить(ob, материал)
    # нормали наружу — знак обхода зависит от борта
    import bmesh
    bm = bmesh.new(); bm.from_mesh(me)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(me); bm.free()
    return ob


