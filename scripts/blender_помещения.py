def _мест(каюта, lx, ly, w, h, палуба):
    """Местные координаты каюты → мировые (центр коробки w x h в плане)."""
    x = каюта["x0"] + lx + w / 2.0
    знак = 1 if каюта["борт"] == "ПБ" else -1
    y0, y1 = sorted((abs(каюта["y0"]), abs(каюта["y1"])))
    if каюта["ряд"] == "борт":
        y = y0 + ly + h / 2.0             # коридор внутри, борт снаружи
    else:
        y = y1 - ly - h / 2.0             # коридор снаружи, ДП внутри
    return x, знак * y


def каюты(кол_стены, кол_мебель):
    сделано = []
    z_каб = {}
    for палуба in ("главная", "средняя"):
        z_каб[палуба] = ВЫСОТА[палуба]
    расст = GA.расстановка()
    # продольные стены коридоров и поперечные перегородки — по рядам
    рядыx = {}
    for c in расст:
        ключ = (c["палуба"], c["ряд"], c["борт"])
        рядыx.setdefault(ключ, []).append(c)
    for (палуба, ряд, борт), список in рядыx.items():
        z0, z1 = z_каб[палуба]
        знак = 1 if борт == "ПБ" else -1
        список.sort(key=lambda c: c["x0"])
        xa, xb = список[0]["x0"], список[-1]["x1"]
        # стена коридора: у бортовых — внутренняя граница, у внутренних — наружная;
        # глубина кают в ряду может меняться (экипаж 2,54 и 3,0), поэтому по каждой каюте
        def _yк(c):
            return min(abs(c["y0"]), abs(c["y1"])) if ряд == "борт" else max(abs(c["y0"]), abs(c["y1"]))
        # с дверными проёмами: сегменты стены между дверями; между соседними
        # каютами стена сплошная, разрыв ряда (поперечный проход) остаётся открытым
        k = 0
        x = None
        зоны_x = {z[0] for z in GA.ЗОНЫ[палуба]} | {z[1] for z in GA.ЗОНЫ[палуба]}
        for c in список:
            if x is None or c["x0"] > x + 0.05:
                x = c["x0"] + (0.05 if any(abs(c["x0"] - zx) < 1e-6 for zx in зоны_x) else 0.0)
            yк = _yк(c)
            lxд, шд = ПК.дверь(c["тип"])
            масштаб = min(1.0, (c["x1"] - c["x0"]) / ПК.мебель(c["тип"] if c["тип"] in ("люкс", "бизнес", "стандарт", "стандарт М4", "семейная", "эконом") else "стандарт")[0])
            дверь0 = c["x0"] + lxд * масштаб
            дверь1 = дверь0 + шд
            if дверь0 - x > 0.05:
                сделано.append(_стена_y("Каюта_коридор_%s_%s_%s_%02d" % (палуба, ряд, борт, k), знак * yк, x, дверь0 - 0.01, z0 + 0.01, z1 - 0.01, кол_стены, "Интерьер_дерево"))
                k += 1
            # притолока над дверью
            сделано.append(_стена_y("Каюта_притолока_%s_%s_%s_%02d" % (палуба, ряд, борт, k), знак * yк, дверь0, дверь1, z0 + 2.05, z1 - 0.01, кол_стены, "Интерьер_дерево"))
            x = дверь1 + 0.01
            следующая = список[список.index(c) + 1] if список.index(c) + 1 < len(список) else None
            if следующая is None or следующая["x0"] > c["x1"] + 0.05:
                xк = c["x1"] - (0.05 if any(abs(c["x1"] - zx) < 1e-6 for zx in зоны_x) else 0.0)
                if xк - x > 0.05:
                    сделано.append(_стена_y("Каюта_коридор_%s_%s_%s_%02d" % (палуба, ряд, борт, k), знак * yк, x, xк, z0 + 0.01, z1 - 0.01, кол_стены, "Интерьер_дерево"))
                    k += 1
                x = None
        # поперечные перегородки между каютами и по концам ряда
        границы = sorted({c["x0"] for c in список} | {c["x1"] for c in список})
        зоны_x = {z[0] for z in GA.ЗОНЫ[палуба]} | {z[1] for z in GA.ЗОНЫ[палуба]}
        for xg in границы:
            if any(abs(xg - zx) < 1e-6 for zx in зоны_x):
                continue                      # здесь стоит переборка зоны — перегородка не нужна
            соседи = [c for c in список if abs(c["x0"] - xg) < 1e-6 or abs(c["x1"] - xg) < 1e-6]
            y0 = min(min(abs(c["y0"]), abs(c["y1"])) for c in соседи)
            y1 = max(max(abs(c["y0"]), abs(c["y1"])) for c in соседи)
            имя = "Каюта_перегородка_%s_%s_%s_%.1f" % (палуба, ряд, борт, xg)
            if ряд == "борт":
                # до обшивки по профилю борта: без щели внизу и без врезки в карниз
                ob = _перегородка_борт(имя, xg, y0 + СТЕНА / 2.0 + 0.01, палуба, z0 + 0.01, z1 - 0.01,
                                       кол_стены, "Интерьер_дерево", знак)
                if ob is not None:
                    сделано.append(ob)
            else:
                # внутренний ряд: стена коридора стоит на y1, стена ДП — на y0
                сделано.append(_стена_x(имя, xg, знак * (y0 + СТЕНА / 2.0 + 0.01), знак * (y1 - СТЕНА / 2.0 - 0.01),
                                        z0 + 0.01, z1 - 0.01, кол_стены, "Интерьер_дерево"))
        if ряд == "внутр" and знак > 0:
            # стена по ДП между спинами внутренних кают — по непрерывным отрезкам ряда
            отрезки = []
            for c in список:
                if отрезки and c["x0"] <= отрезки[-1][1] + 0.05:
                    отрезки[-1][1] = c["x1"]
                else:
                    отрезки.append([c["x0"], c["x1"]])
            for xa_, xb_ in отрезки:
                сделано.append(_стена_y("Каюта_ДП_%s_%03.0f" % (палуба, xa_), 0.0, xa_, xb_, z0 + 0.01, z1 - 0.01,
                                        кол_стены, "Интерьер_дерево"))
    # мебель
    ВЫС = dict(санузел=2.15, койка=0.50, шкаф=1.95, стол=0.74, диван=0.85, кресло=0.9, тумба=0.5)
    for c in расст:
        z0 = z_каб[c["палуба"]][0]
        ф, гл, м = ПК.мебель(c["тип"] if c["тип"] in ("люкс", "бизнес", "стандарт", "стандарт М4", "семейная", "эконом") else "стандарт")
        # для кают экипажа — план стандарта, урезанный по фронту
        масштаб = (c["x1"] - c["x0"]) / ф
        for k, (имя, lx, ly, w, h, кл) in enumerate(м):
            w2, lx2 = w * min(1.0, масштаб), lx * min(1.0, масштаб)
            if ly + h > (abs(c["y1"]) - abs(c["y0"])) + 1e-6:
                h = max(0.3, (abs(c["y1"]) - abs(c["y0"])) - ly - ЗАЗОР)
            # отступ ЗАЗОР от стен, к которым предмет примыкает (lx≈0 / ly≈0 / до края)
            фк = c["x1"] - c["x0"]
            глк = abs(c["y1"]) - abs(c["y0"])
            ax, bx = lx2, lx2 + w2
            ay, by = ly, ly + h
            ax = max(ax, ЗАЗОР); bx = min(bx, фк - ЗАЗОР)
            ay = max(ay, ЗАЗОР); by = min(by, глк - ЗАЗОР)
            if bx - ax < 0.25 or by - ay < 0.25:
                continue
            w2, h = bx - ax, by - ay
            x, y = _мест(c, ax, ay, w2, h, c["палуба"])
            высота = ВЫС.get(кл, 0.6)
            if "2-яр" in имя:
                высота = 1.95
            мат = {"санузел": "Технические_серые", "койка": "Интерьер_дерево", "шкаф": "Интерьер_дерево",
                   "стол": "Интерьер_дерево", "диван": "Интерьер_дерево", "кресло": "Интерьер_дерево"}.get(кл, "Интерьер_дерево")
            сделано.append(_короб("Мебель_%s_%s_%s_%.0f_%d" % (c["палуба"], c["ряд"], c["борт"], c["x0"], k),
                                  (x, y, z0 + 0.01 + высота / 2.0), (w2, h, высота), кол_мебель, мат))
    return сделано


