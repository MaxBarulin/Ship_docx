def переборки(кол):
    """Поперечные переборки по границам зон с проёмами (двери, проходы) из
    gorizont_public.проёмы_переборки; в трюме — водонепроницаемые, глухие."""
    сделано = []
    for палуба in ("главная", "средняя"):
        z0, z1 = ВЫСОТА[палуба]
        границы = sorted({z[0] for z in GA.ЗОНЫ[палуба]} | {z[1] for z in GA.ЗОНЫ[палуба]})
        for x in границы:
            y = _полу(палуба, x, z0 + 0.6) - G.LINING / 2.0
            if y < 1.0:
                continue
            проёмы = sorted(PB.проёмы_переборки(палуба, x))
            # сегменты стены между проёмами, притолоки над проёмами
            края = [-y] + [v for p in проёмы for v in p] + [y]
            k = 0
            for i in range(0, len(края) - 1, 2):
                a_, b_ = края[i], края[i + 1]
                if b_ - a_ > 0.05:
                    сделано.append(_стена_x("Переборка_%s_%.0f_%d" % (палуба, x, k), x, a_, b_, z0 + 0.01, z1 - 0.01, кол)); k += 1
            for p0, p1 in проёмы:
                сделано.append(_стена_x("Переборка_%s_%.0f_притолока_%d" % (палуба, x, k), x, p0, p1, z0 + 2.10, z1 - 0.01, кол)); k += 1
    # трюм: водонепроницаемые переборки от второго дна до главной палубы
    for x in GA.ПЕРЕБОРКИ:
        zk = L.keel_z(x)
        y = L.section_y(2.0, zk, min(L.bottom_half(x), L.side_half(x)), G.DEPTH, L.side_half(x),
                        math.radians(L.flare(x)))
        y = (y or 0.5) - 0.06
        y = min(y, W.niche_half(x) - 0.06)
        сделано.append(_стена_x("Переборка_ВНП_%.0f" % x, x, -y, y, G.DECKS["первая"] + 0.01, G.DEPTH - 0.11, кол))
    return сделано


def второе_дно(кол):
    """Настил второго дна: плита по ширине днища с вырезом ниш колёс."""
    z = G.DECKS["первая"]
    verts, faces, строки = [], [], []
    x = 0.5
    while x <= G.LOA - 0.5:
        zk = L.keel_z(x)
        if zk < z - 0.05:
            y = L.section_y(z, zk, min(L.bottom_half(x), L.side_half(x)), G.DEPTH, L.side_half(x),
                            math.radians(L.flare(x))) or 0.0
            y = min(y - 0.03, W.niche_half(x) - 0.03)
            if y > 0.3:
                строки.append(len(verts))
                verts.extend([(x, y, z), (x, -y, z)])
            else:
                строки.append(None)
        else:
            строки.append(None)
        x += 1.0
    for a, b in zip(строки, строки[1:]):
        if a is not None and b is not None:
            faces.append([a, a + 1, b + 1, b])
    me = bpy.data.meshes.new("Палуба_первая")
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False); me.update()
    ob = bpy.data.objects.new("Палуба_первая", me)
    кол.objects.link(ob)
    if me.polygons and me.polygons[0].normal.z < 0:
        import bmesh
        bm = bmesh.new(); bm.from_mesh(me); bmesh.ops.reverse_faces(bm, faces=bm.faces[:]); bm.to_mesh(me); bm.free(); me.update()
    м = ob.modifiers.new("Толщина", "SOLIDIFY"); м.thickness = 0.08; м.offset = -1.0
    Ст.назначить(ob, "Технические_серые")
    return ob


def _марш(имя, xa, xb, za, zb, y, ширина, кол, материал="Интерьер_дерево", слой=0.18):
    """Лестничный марш: призма с проступями. От (xa, za) вверх к (xb, zb); xb может быть < xa."""
    n = max(4, int(round(abs(zb - za) / 0.18)))
    r = (zb - za) / n
    t = (xb - xa) / n
    верх = [(xa, za)]
    for i in range(n):
        верх.append((xa + i * t, za + (i + 1) * r))
        верх.append((xa + (i + 1) * t, za + (i + 1) * r))
    tg = abs(r / t)
    низ = [(xb, zb - слой), (xa + (слой / tg) * (1 if t > 0 else -1), za)]
    контур = верх + низ
    if t < 0:
        контур = list(reversed(контур))
    verts, faces = [], []
    n_ = len(контур)
    for sy in (-1, 1):
        for x, z in контур:
            verts.append((x, y + sy * ширина / 2.0, z))
    faces.append(list(range(n_))[::-1]); faces.append([n_ + i for i in range(n_)])
    for i in range(n_):
        j = (i + 1) % n_
        faces.append([i, j, n_ + j, n_ + i])
    старый = bpy.data.objects.get(имя)
    if старый is not None:
        bpy.data.objects.remove(старый, do_unlink=True)
    me = bpy.data.meshes.new(имя)
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False); me.update()
    ob = bpy.data.objects.new(имя, me)
    кол.objects.link(ob)
    Ст.назначить(ob, материал)
    import bmesh
    bm = bmesh.new(); bm.from_mesh(me); bmesh.ops.recalc_face_normals(bm, faces=bm.faces); bm.to_mesh(me); bm.free()
    return ob


def _перила(имя, x0, x1, y0, y1, z, кол, h=1.10):
    return _короб(имя, (0.5 * (x0 + x1), 0.5 * (y0 + y1), z + 0.01 + h / 2.0), (abs(x1 - x0), abs(y1 - y0), h), кол, "Остекление")


#: с какой палубы поднимается трап каждого холла (кормовой и атриум — до солнечной)
ТРАПЫ_ВВЕРХ = {"кормовой": ("главная", "средняя"), "атриум": ("главная", "средняя"), "носовой": ("главная",)}
#: верх лифтовых шахт: кормовой — башня на солнечной палубе, остальные до подволока средней
ЛИФТ_ВЕРХ = {"кормовой": G.DECKS["солнечная"] + 2.5}


def трапы(кол):
    """Трап-холлы: стены шахты, два марша с площадкой, ограждения колодцев; лифты."""
    сделано = []
    for имя, (a, b) in GA.ТРАПЫ.items():
        for палуба in ТРАПЫ_ВВЕРХ[имя]:
            z0, z1 = ВЫСОТА[палуба]
            zв = z1 + 0.10                                   # верх настила палубы выше
            yш = 1.6
            for s_ in (1, -1):
                сделано.append(_стена_y("Трап_%s_%s_стена_%d" % (имя, палуба, s_), s_ * yш, a + 0.05, b - 0.05, z0 + 0.01, z1 - 0.01, кол))
            zm = 0.5 * (z0 + zв)
            xa, xb = a + 0.2, b - 1.6
            сделано.append(_марш("Трап_%s_%s_марш_1" % (имя, палуба), xa, xb, z0 + 0.01, zm, 0.75, 1.3, кол))
            сделано.append(_марш("Трап_%s_%s_марш_2" % (имя, палуба), xb, xa, zm, zв, -0.75, 1.3, кол))
            сделано.append(_короб("Трап_%s_%s_площадка" % (имя, палуба), (0.5 * (xb + b - 0.2), 0.0, zm - 0.06), (b - 0.2 - xb, 2.8, 0.12), кол, "Интерьер_дерево"))
        # ограждение колодца на палубе, куда трап приходит и дальше не идёт
        верх = "средняя" if len(ТРАПЫ_ВВЕРХ[имя]) == 1 else "солнечная"
        zв = G.DECKS[верх]
        xa, xb = a + 0.2, b - 0.2
        if верх == "солнечная":
            сделано.append(_перила("Трап_%s_ограждение_ПБ" % имя, xa - 0.06, xb + 0.06, 1.55, 1.61, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_ЛБ" % имя, xa - 0.06, xb + 0.06, -1.61, -1.55, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_нос" % имя, xb, xb + 0.06, -1.55, 1.55, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_корма" % имя, xa - 0.06, xa, 0.06, 1.55, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_ДП" % имя, xa, xb, -0.03, 0.03, zв, кол))
        else:
            # на средней колодец носового трапа: шахты выше нет — перила
            сделано.append(_перила("Трап_%s_ограждение_ПБ" % имя, xa - 0.06, xb + 0.06, 1.55, 1.61, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_ЛБ" % имя, xa - 0.06, xb + 0.06, -1.61, -1.55, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_нос" % имя, xb, xb + 0.06, -1.55, 1.55, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_корма" % имя, xa - 0.06, xa, 0.06, 1.55, zв, кол))
            сделано.append(_перила("Трап_%s_ограждение_ДП" % имя, xa, xb, -0.03, 0.03, zв, кол))
    for имя, (a, b, y0, y1) in GA.ЛИФТЫ.items():
        z0 = G.DECKS["главная"]; z1 = ЛИФТ_ВЕРХ.get(имя, G.DECKS["солнечная"] - 0.10)
        сделано.append(_короб("Лифт_%s" % имя, (0.5 * (a + b), 0.5 * (y0 + y1), 0.5 * (z0 + z1)),
                              (b - a, y1 - y0, z1 - z0), кол, "Технические_серые"))
    return сделано


