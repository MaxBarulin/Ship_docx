_МЕБЕЛЬ = []


def комната(тип, ф, гл, окно, дверь_lx, дверь_w):
    t = СТЕНА
    короб("Пол", -t, ф + t, -t, гл + t, -0.05, 0.0, "пол")
    короб("Потолок", -t, ф + t, -t, гл + t, H, H + 0.05, "потолок")
    # боковые стены
    короб("Стена_x0", -t, 0.0, 0.0, гл, 0.0, H, "стена")
    короб("Стена_x1", ф, ф + t, 0.0, гл, 0.0, H, "стена")
    # стена коридора с дверным проёмом
    короб("Стена_коридор_а", -t, дверь_lx, -t, 0.0, 0.0, H, "стена")
    короб("Стена_коридор_б", дверь_lx + дверь_w, ф + t, -t, 0.0, 0.0, H, "стена")
    короб("Стена_коридор_притолока", дверь_lx, дверь_lx + дверь_w, -t, 0.0, 2.05, H, "стена")
    # дверь каюты — полотно, прикрыто
    короб("Дверь", дверь_lx + 0.02, дверь_lx + дверь_w - 0.02, -0.045, -0.015, 0.0, 2.03, "дерево")
    цилиндр("Дверь_ручка", дверь_lx + дверь_w - 0.12, -0.02, 1.0, 1.02, 0.012, "хром", 16, "y")
    # наружная стена: окно или глухая с виртуальным окном
    if окно:
        короб("Стена_борт_низ", -t, ф + t, гл, гл + t, 0.0, ПОДОКОННИК, "стена")
        короб("Стена_борт_верх", -t, ф + t, гл, гл + t, ОКНО_ВЕРХ, H, "стена")
        короб("Стена_борт_лев", -t, 0.15, гл, гл + t, ПОДОКОННИК, ОКНО_ВЕРХ, "стена")
        короб("Стена_борт_прав", ф - 0.15, ф + t, гл, гл + t, ПОДОКОННИК, ОКНО_ВЕРХ, "стена")
        короб("Окно_стекло", 0.15, ф - 0.15, гл + 0.02, гл + 0.03, ПОДОКОННИК, ОКНО_ВЕРХ, "стекло")
        # импосты шага 2 м как на фасаде
        x = 2.0
        while x < ф - 0.3:
            короб("Импост_%.0f" % x, x - 0.04, x + 0.04, гл, гл + t, ПОДОКОННИК, ОКНО_ВЕРХ, "рама")
            x += 2.0
        короб("Подоконник", 0.0, ф, гл - 0.08, гл + t, ПОДОКОННИК - 0.03, ПОДОКОННИК, "дерево_светлое")
        # шторы по краям окна и карниз
        короб("Карниз_штор", 0.0, ф, гл - 0.14, гл - 0.10, ОКНО_ВЕРХ + 0.02, ОКНО_ВЕРХ + 0.06, "хром")
        # шторы только в свободных углах окна: у койки или дивана вплотную к окну их не ставим
        for имя_ш, xa, xb in (("Штора_лев", 0.02, 0.28), ("Штора_прав", ф - 0.28, ф - 0.02)):
            занято = any(lx < xb + 0.05 and lx + w > xa - 0.05 and ly + h > гл - 0.2 for _, lx, ly, w, h, _ in _МЕБЕЛЬ)
            if not занято:
                короб(имя_ш, xa, xb, гл - 0.12, гл - 0.06, ПОДОКОННИК + 0.02, ОКНО_ВЕРХ + 0.02, "ткань")
        # вид за окном: вода до горизонта и далёкий низкий берег
        короб("Вода", -300.0, 300.0, гл + 0.5, 400.0, -3.0, -1.7, "вода")
        короб("Берег", -300.0, 300.0, 380.0, 400.0, -1.7, 4.0, "берег")
    else:
        короб("Стена_борт", -t, ф + t, гл, гл + t, 0.0, H, "стена")
        # виртуальное окно: светящаяся панель с рамой на участке стены, свободном от мебели
        занятые = sorted((lx - 0.05, lx + w + 0.05) for _, lx, ly, w, h, _ in _МЕБЕЛЬ if ly + h > гл - 0.3)
        свободные, x = [], 0.2
        for a, b in занятые:
            if a - x > 0.6:
                свободные.append((x, a))
            x = max(x, b)
        if ф - 0.2 - x > 0.6:
            свободные.append((x, ф - 0.2))
        a, b = max(свободные, key=lambda p: p[1] - p[0]) if свободные else (0.3, ф - 0.3)
        c = (a + b) / 2.0
        w_ = min(2.0, b - a - 0.2)
        x0, x1 = c - w_ / 2.0, c + w_ / 2.0
        короб("Виртуальное_окно_рама", x0 - 0.04, x1 + 0.04, гл - 0.05, гл - 0.0, 0.9, 2.05, "рама")
        короб("Виртуальное_окно", x0, x1, гл - 0.06, гл - 0.05, 0.94, 2.01, "виртуальное_окно")
    # плинтус, ковёр, светильники
    короб("Ковёр", 0.6, ф - 0.6, 0.5, гл - 0.6, 0.0, 0.012, "ковёр")
    n = max(2, int(ф / 2.0))
    for i in range(n):
        xc = ф * (i + 0.5) / n
        короб("Светильник_%d" % i, xc - 0.3, xc + 0.3, гл / 2 - 0.15, гл / 2 + 0.15, H - 0.02, H - 0.005, "свет")
    короб("Свет_у_двери", дверь_lx - 0.1, дверь_lx + дверь_w + 0.1, 0.25, 0.45, H - 0.02, H - 0.005, "свет")


