МАТ = {}


def _мат(имя, цвет, rough=0.5, metal=0.0, emission=0.0, glass=False, alpha=1.0):
    m = bpy.data.materials.get("Каюта_" + имя)
    if m is None:
        m = bpy.data.materials.new("Каюта_" + имя)
        m.use_nodes = True
    nt = m.node_tree
    bsdf = next((n for n in nt.nodes if n.type == "BSDF_PRINCIPLED"), None)
    r, g, b = [int(цвет[i:i + 2], 16) / 255.0 for i in (1, 3, 5)]
    rgb = (r ** 2.2, g ** 2.2, b ** 2.2, 1.0)
    bsdf.inputs["Base Color"].default_value = rgb
    bsdf.inputs["Roughness"].default_value = rough
    bsdf.inputs["Metallic"].default_value = metal
    for имя_входа in ("Emission Color",):
        if имя_входа in bsdf.inputs:
            bsdf.inputs[имя_входа].default_value = rgb if emission else (0, 0, 0, 1)
    if "Emission Strength" in bsdf.inputs:
        bsdf.inputs["Emission Strength"].default_value = emission
    for имя_входа in ("Transmission Weight", "Transmission"):
        if имя_входа in bsdf.inputs:
            bsdf.inputs[имя_входа].default_value = 1.0 if glass else 0.0
    if glass:
        bsdf.inputs["Roughness"].default_value = 0.02
    bsdf.inputs["Alpha"].default_value = alpha
    МАТ[имя] = m
    return m


