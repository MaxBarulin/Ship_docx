def _сетка(имя, verts, faces, кол, мат):
    """Замкнутая сетка с нормалями наружу."""
    me = bpy.data.meshes.new(имя)
    me.from_pydata([tuple(v) for v in verts], [], faces)
    me.validate(verbose=False)
    bm = bmesh.new(); bm.from_mesh(me)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(me); bm.free(); me.update()
    ob = bpy.data.objects.new(имя, me)
    кол.objects.link(ob)
    Мд._назначить(ob, мат)
    return ob


_ГРАНИ = [[0, 1, 2, 3], [4, 7, 6, 5], [0, 4, 5, 1], [1, 5, 6, 2], [2, 6, 7, 3], [3, 7, 4, 0]]


def _короб(имя, x0, x1, y0, y1, z0, z1, кол, мат):
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0), (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    return _сетка(имя, v, _ГРАНИ, кол, мат)


def _брус(имя, p0, p1, w, h, кол, мат, верх=(0.0, 0.0, 1.0)):
    """Брус w × h от точки до точки, торцы перпендикулярны оси."""
    p0, p1 = Vector(p0), Vector(p1)
    d = (p1 - p0).normalized()
    ref = Vector(верх) if abs(d.dot(Vector(верх))) < 0.95 else Vector((1.0, 0.0, 0.0))
    s = d.cross(ref).normalized()
    u = s.cross(d).normalized()
    углы = [(-1, -1), (1, -1), (1, 1), (-1, 1)]
    v = [p0 + s * (a * w / 2.0) + u * (b * h / 2.0) for a, b in углы] + [p1 + s * (a * w / 2.0) + u * (b * h / 2.0) for a, b in углы]
    return _сетка(имя, v, _ГРАНИ, кол, мат)


def _стойка(имя, низ, верх, a, кол, мат, b=None):
    """Наклонная стойка с горизонтальными торцами - сечение a × b в плане на обоих концах."""
    b = a if b is None else b
    (x0, y0, z0), (x1, y1, z1) = низ, верх
    v = [(x0 - a / 2, y0 - b / 2, z0), (x0 + a / 2, y0 - b / 2, z0), (x0 + a / 2, y0 + b / 2, z0), (x0 - a / 2, y0 + b / 2, z0),
         (x1 - a / 2, y1 - b / 2, z1), (x1 + a / 2, y1 - b / 2, z1), (x1 + a / 2, y1 + b / 2, z1), (x1 - a / 2, y1 + b / 2, z1)]
    return _сетка(имя, v, _ГРАНИ, кол, мат)


def _труба(имя, точки, r, кол, мат, n=10):
    """Замкнутая труба по ломаной - канат, трос, стропа, ось колеса."""
    P = [Vector(p) for p in точки]
    verts, faces = [], []
    prev_s = None
    for i, p in enumerate(P):
        t = (P[min(i + 1, len(P) - 1)] - P[max(i - 1, 0)]).normalized()
        ref = Vector((0.0, 0.0, 1.0)) if abs(t.z) < 0.9 else Vector((1.0, 0.0, 0.0))
        s = t.cross(ref).normalized() if prev_s is None else (prev_s - t * prev_s.dot(t)).normalized()
        u = s.cross(t).normalized()
        prev_s = s
        for k in range(n):
            a = 2 * math.pi * k / n
            verts.append(p + s * (r * math.cos(a)) + u * (r * math.sin(a)))
    m = len(P)
    for i in range(m - 1):
        for k in range(n):
            a, b = i * n + k, i * n + (k + 1) % n
            faces.append([a, b, b + n, a + n])
    faces.append(list(range(n))[::-1])
    faces.append([(m - 1) * n + k for k in range(n)])
    return _сетка(имя, verts, faces, кол, мат)


def _цилиндр(имя, x, y, z0, z1, r, кол, мат, n=20):
    return _труба(имя, [(x, y, z0), (x, y, z1)], r, кол, мат, n)


def _шар(имя, c, r, кол, мат, sx=1.0, sy=1.0, sz=1.0):
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=2, radius=r)
    for v in bm.verts:
        v.co = Vector((c[0] + v.co.x * sx, c[1] + v.co.y * sy, c[2] + v.co.z * sz))
    me = bpy.data.meshes.new(имя); bm.to_mesh(me); bm.free()
    ob = bpy.data.objects.new(имя, me); кол.objects.link(ob)
    Мд._назначить(ob, мат)
    return ob


