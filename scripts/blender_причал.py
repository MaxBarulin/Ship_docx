def _внутри(x, y):
    return 0.06 < x < G.LOA - 0.6 and abs(y) < L.side_half(x) - 0.06


def швартовы(кол):
    """Концы от кнехтов через планширь фальшборта к тумбам, с провесом."""
    к, т, R = BR.КНЕХТ, BR.ТУМБА, BR.ШВАРТОВ_R
    сделано = []
    занятые = set()
    for i, s in enumerate(BR.швартовы()):
        (xs, ys), (xt, yt) = s["кнехт"], s["тумба"]
        if (xt, yt) not in занятые:
            сделано += _тумба("Тумба_%d" % i, xt, yt, кол)
            занятые.add((xt, yt))
        d = Vector((xt - xs, yt - ys, 0.0)).normalized()
        p0 = Vector((xs, ys, G.DEPTH + 0.01 + 0.75 * к["h"])) + d * (к["a"] / 2.0 / max(abs(d.x), abs(d.y)) + R + 0.005)
        p3 = Vector((xt, yt, Zк + 0.30)) - d * (т["r"] + R + 0.005)
        lo, hi = 0.0, 1.0                       # где линия выходит за планширь
        for _ in range(40):
            mid = 0.5 * (lo + hi)
            q = p0.lerp(p3, mid)
            if _внутри(q.x, q.y):
                lo = mid
            else:
                hi = mid
        w = p0.lerp(p3, hi)
        w.z = G.DEPTH + 1.10 + R + 0.05
        точки = [p0, w]
        провес = 0.015 * (p3 - w).length
        for k in range(1, 6):
            f = k / 6.0
            q = w.lerp(p3, f)
            q.z -= 4.0 * провес * f * (1.0 - f)
            точки.append(q)
        точки.append(p3)
        сделано.append(_труба("Швартов_%d_%s" % (i, s["имя"].replace(" ", "_")), точки, R, кол, "Канат", 8))
    for j, x in enumerate((20.0, 36.0, 100.0, 116.0, 160.0)):
        сделано += _тумба("Тумба_свободная_%d" % j, x, Yс - т["от_кромки"], кол)
    return сделано


def трап(кол):
    """Телескопический трап из гаража через калитку фальшборта на кордон, с поручнями."""
    т = BR.ТРАП
    tr = BR.трап()
    x0, x1 = т["x0"], т["x1"]
    ya, yb = tr["y_двери"] - 0.04, tr["y_конца"]
    za, zb = G.DEPTH, Zк
    t = т["толщина"]
    v = [(x0, ya, za), (x1, ya, za), (x1, yb, zb), (x0, yb, zb), (x0, ya, za + t), (x1, ya, za + t), (x1, yb, zb + t), (x0, yb, zb + t)]
    сделано = [_сетка("Трап_настил", v, _ГРАНИ, кол, "Надстройка_серебро")]

    def z_верх(y):
        return za + t + (zb - za) * (y - ya) / (yb - ya)
    n = 4
    for сторона, x in (("л", x0 + 0.03), ("п", x1 - 0.03)):
        ys = [ya + (yb - ya) * (k + 0.5) / n for k in range(n)]
        for k, y in enumerate(ys):
            сделано.append(_короб("Трап_стойка_%s%d" % (сторона, k), x - 0.02, x + 0.02, y - 0.02, y + 0.02, z_верх(y) - 0.005, z_верх(y) + т["поручень"], кол, "Надстройка_серебро"))
        сделано.append(_труба("Трап_поручень_%s" % сторона, [(x, ya + 0.05, z_верх(ya) + т["поручень"] + 0.025), (x, yb - 0.05, z_верх(yb) + т["поручень"] + 0.025)], 0.025, кол, "Надстройка_серебро", 10))
    return сделано


def аппарель(кол):
    """Кормовая аппарель, опущенная на пандус, бортики по кромкам."""
    а = BR.аппарель()
    г = G.GARAGE
    ang, t, w = а["угол"], BR.АППАРЕЛЬ_ТОЛЩИНА, г["ramp_width"]
    d = Vector((-math.cos(ang), 0.0, -math.sin(ang)))
    nrm = Vector((-math.sin(ang), 0.0, math.cos(ang)))
    H = Vector((-0.03, 0.0, G.DEPTH))
    E = H + d * г["ramp_len"]
    низ_H, низ_E = H - nrm * t, E - nrm * t
    v = [(низ_H.x, -w / 2, низ_H.z), (низ_E.x, -w / 2, низ_E.z), (низ_E.x, w / 2, низ_E.z), (низ_H.x, w / 2, низ_H.z),
         (H.x, -w / 2, H.z), (E.x, -w / 2, E.z), (E.x, w / 2, E.z), (H.x, w / 2, H.z)]
    сделано = [_сетка("Аппарель_опущена", v, _ГРАНИ, кол, "Надстройка_серебро")]
    for k, y in enumerate((-w / 2 + 0.06, w / 2 - 0.06)):
        a = H + d * 0.05 + nrm * 0.075 + Vector((0, y, 0))
        b = E - d * 0.05 + nrm * 0.075 + Vector((0, y, 0))
        сделано.append(_брус("Аппарель_бортик_%d" % k, a, b, 0.10, 0.15, кол, "Надстройка_графит", верх=tuple(nrm)))
    return сделано, (H, d, nrm)


def фургон(имя, опора, вперёд, верх, кол, мат="Фургон"):
    """Фургон класса Б (5,6 × 2,3 × 2,7 м) колёсами на плоскости. Опора - середина базы на поверхности."""
    Q, f, n = Vector(опора), Vector(вперёд).normalized(), Vector(верх).normalized()
    s = n.cross(f).normalized()
    г = G.GARAGE
    Lh, W, Hh = г["vehicle_len"] / 2.0, г["vehicle_width"], г["vehicle_height"]
    r, база, колея = 0.34, 1.80, 0.85
    сделано = []

    def блок(имя_, a0, a1, b0, b1, c0, c1, мат_):
        v = [Q + f * a + s * b + n * c for a, b, c in ((a0, b0, c0), (a1, b0, c0), (a1, b1, c0), (a0, b1, c0),
                                                       (a0, b0, c1), (a1, b0, c1), (a1, b1, c1), (a0, b1, c1))]
        return _сетка(имя_, v, _ГРАНИ, кол, мат_)
    for i, a in enumerate((-база, база)):
        for j, b in enumerate((-колея, колея)):
            c = Q + f * a + s * b + n * r
            сделано.append(_труба("%s_колесо_%d%d" % (имя, i, j), [c - s * 0.12, c + s * 0.12], r, кол, "Шина", 16))
    сделано.append(блок(имя + "_рама", -база + r + 0.08, база - r - 0.08, -W / 2 + 0.1, W / 2 - 0.1, 0.30, 0.70, мат))
    сделано.append(блок(имя + "_бампер_п", база + r + 0.05, Lh, -W / 2 + 0.05, W / 2 - 0.05, 0.30, 0.70, мат))
    сделано.append(блок(имя + "_бампер_з", -Lh, -база - r - 0.05, -W / 2 + 0.05, W / 2 - 0.05, 0.30, 0.70, мат))
    сделано.append(блок(имя + "_кузов", -Lh, Lh, -W / 2, W / 2, 0.70, Hh, мат))
    сделано.append(блок(имя + "_лобовое", Lh + 0.001, Lh + 0.02, -W / 2 + 0.15, W / 2 - 0.15, 1.45, Hh - 0.35, "Остекление"))
    for j, b in enumerate((-W / 2 - 0.02, W / 2 + 0.001)):
        сделано.append(блок(имя + "_окно_%d" % j, Lh - 1.20, Lh - 0.20, b, b + 0.019, 1.45, Hh - 0.40, "Остекление"))
    return сделано


