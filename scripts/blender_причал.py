def замкнутость():
    """Открытые кромки в коллекциях причала - аудит судна «60_Окружение» пропускает."""
    плохие = []
    for имя in (КОЛ, КОЛ_ОКР):
        c = bpy.data.collections.get(имя)
        for o in (c.all_objects if c else []):
            if o.type != "MESH":
                continue
            bm = bmesh.new(); bm.from_mesh(o.data)
            n = sum(1 for e in bm.edges if e.is_boundary)
            bm.free()
            if n:
                плохие.append((o.name, n))
    return плохие


