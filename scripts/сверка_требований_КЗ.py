def _матрица():
    """Строки матрицы оценки: номер -> (раздел, описание, балл)."""
    z = zipfile.ZipFile(МАТРИЦА)
    ss = z.read("xl/sharedStrings.xml").decode("utf-8")
    строки = [html.unescape("".join(re.findall(r"<t[^>]*>(.*?)</t>", si, re.S)))
              for si in re.findall(r"<si>(.*?)</si>", ss, re.S)]
    лист = z.read("xl/worksheets/sheet1.xml").decode("utf-8")

    def кол(ref):
        n = 0
        for ch in re.match(r"([A-Z]+)", ref).group(1):
            n = n * 26 + ord(ch) - 64
        return n

    out, раздел = {}, ""
    for rn, body in re.findall(r'<row[^>]*r="(\d+)"[^>]*>(.*?)</row>', лист, re.S):
        cells = {}
        for c in re.finditer(r'<c r="([A-Z]+\d+)"([^>]*)>(.*?)</c>', body, re.S):
            v = re.search(r"<v>(.*?)</v>", c.group(3), re.S)
            if not v:
                continue
            val = v.group(1)
            if 't="s"' in c.group(2):
                val = строки[int(val)]
            cells[кол(c.group(1))] = html.unescape(val).strip()
        if re.fullmatch(r"[A-Z]\d+", cells.get(1, "")):
            раздел = "%s %s" % (cells[1], cells.get(2, ""))
        if cells.get(9):
            try:
                балл = float(cells[9])
            except ValueError:
                continue
            out[int(rn)] = (раздел, cells.get(4) or cells.get(6, "")[:70], балл)
    return out


def состояние_записки():
    """Сколько разделов записки заполнено, а сколько ещё заглушки."""
    if not os.path.exists(ЗАПИСКА):
        return None
    текст = io.open(ЗАПИСКА, encoding="utf-8").read()
    блоки = re.findall(r"(?m)^## (.+)$", текст)
    return dict(есть=True, блоков=len(блоки), дыр=текст.count("<!-- ДЫРА -->"),
                знаков=len(текст), блоки=блоки)


def отчёт(всё=False):
    м = _матрица()
    всего = sum(v[2] for v in м.values())

    print("ТРЕБОВАНИЯ КЗ: состав судна\n")
    плохо = 0
    for c in G.checks():
        ок = "ок" if c["ок"] else "НЕ СХОДИТСЯ"
        плохо += 0 if c["ок"] else 1
        print("  %-34s %-8s %-24s %s" % (c["что"], c["значение"], c["норма"], ок))
    print("\n  не сходится: %d из %d\n" % (плохо, len(G.checks())))

    СОСТОЯНИЯ = ("есть", "частично", "нет", "на площадке", "не размечено")
    сост = {к: 0.0 for к in СОСТОЯНИЯ}
    по_разделам = {}
    for rn, (раздел, имя, балл) in м.items():
        состояние = ПОКРЫТИЕ.get(rn, ("не размечено", ""))[0]
        сост[состояние] += балл
        d = по_разделам.setdefault(раздел, {к: 0.0 for к in СОСТОЯНИЯ})
        d[состояние] += балл

    з = состояние_записки()
    if з is None:
        print("ПОЯСНИТЕЛЬНАЯ ЗАПИСКА: нет файла docs/проект/записка.md\n")
    else:
        print("ПОЯСНИТЕЛЬНАЯ ЗАПИСКА: %d разделов, %d знаков, "
              "незаполненных разделов %d\n" % (з["блоков"], з["знаков"], з["дыр"]))

    print("МАТРИЦА ОЦЕНКИ: %.1f балла всего\n" % всего)
    print("  %-44s %6s %9s %6s %11s %7s"
          % ("раздел", "есть", "частично", "нет", "на площадке", "итого"))
    for раздел in sorted(по_разделам):
        d = по_разделам[раздел]
        print("  %-44s %6.2f %9.2f %6.2f %11.2f %7.2f"
              % (раздел[:44] or "A Работа команды", d["есть"], d["частично"],
                 d["нет"] + d["не размечено"], d["на площадке"], sum(d.values())))
    print("  %-44s %6.2f %9.2f %6.2f %11.2f %7.2f"
          % ("ВСЕГО", сост["есть"], сост["частично"],
             сост["нет"] + сост["не размечено"], сост["на площадке"], всего))
    документами = всего - сост["на площадке"]
    print("\n  Документами закрывается %.1f балла из %.0f. Закрыто %.1f, "
          "частично %.1f, не начато %.1f."
          % (документами, всего, сост["есть"], сост["частично"],
             сост["нет"] + сост["не размечено"]))

    дыры = [(rn, м[rn], ПОКРЫТИЕ[rn]) for rn in ПОКРЫТИЕ
            if ПОКРЫТИЕ[rn][0] == "нет" and rn in м]
    дыры.sort(key=lambda t: -t[1][2])
    print("\nДЫРЫ ПО УБЫВАНИЮ ЦЕНЫ (%.1f балла)\n"
          % sum(d[1][2] for d in дыры))
    for rn, (раздел, имя, балл) in ((d[0], d[1]) for d in дыры):
        print("  %4.2f  %-52s %s" % (балл, (имя or "—")[:52], ПОКРЫТИЕ[rn][1]))

    if всё:
        print("\nЧАСТИЧНО ЗАКРЫТО")
        for rn in sorted(ПОКРЫТИЕ):
            if ПОКРЫТИЕ[rn][0] == "частично" and rn in м:
                print("  %4.2f  %-52s %s"
                      % (м[rn][2], (м[rn][1] or "—")[:52], ПОКРЫТИЕ[rn][1]))
        print("\nЗАКРЫТО")
        for rn in sorted(ПОКРЫТИЕ):
            if ПОКРЫТИЕ[rn][0] == "есть" and rn in м:
                print("  %4.2f  %-52s %s"
                      % (м[rn][2], (м[rn][1] or "—")[:52], ПОКРЫТИЕ[rn][1]))


