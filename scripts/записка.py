#: Маркер незаполненного раздела. По нему считает сверка требований, и по
#: нему же видно человеку, что раздел не написан, а не «написан коротко».
МАРКЕР = "<!-- ДЫРА -->"


def дыра(что, кто, зачем):
    return ("\n%s\n> **НЕ ЗАПОЛНЕНО.** %s\n>\n> Владелец - %s.\n>\n> %s\n"
            % (МАРКЕР, что, кто, зачем))


#: рисунки записки по порядку появления: путь от корня проекта → номер
_РИСУНКИ = {}


def рис(путь, подпись):
    """Рисунок с подписью по ГОСТ Р 2.105 - «Рисунок N - Подпись», нумерация сквозная."""
    _РИСУНКИ[путь] = len(_РИСУНКИ) + 1
    return "\n![%s](../../%s)\n\nРисунок %d - %s\n" % (подпись, путь, _РИСУНКИ[путь], подпись)


def след(k=1):
    """Номер k-го следующего рисунка - чтобы сослаться на него в тексте до самого рисунка."""
    return len(_РИСУНКИ) + k


def номер(путь):
    return _РИСУНКИ[путь]


def таблица(шапка, строки):
    out = ["| " + " | ".join(шапка) + " |",
           "|" + "|".join("---" for _ in шапка) + "|"]
    for r in строки:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


