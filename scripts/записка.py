def запятая_в_таблицах(текст):
    """Десятичная запятая вместо точки — но только в таблицах.

    По-русски пишут «1,497 м», и в записке по ГОСТ это не придирка. Но
    слепая замена точки на запятую сломала бы номера стандартов: ГОСТ Р
    2.105 и ГОСТ 3.1118 тоже содержат цифру, точку и цифру. Поэтому замена
    идёт только по строкам таблиц, где номеров стандартов не бывает, а
    проза пишется сразу с запятыми.
    """
    out = []
    for строка in текст.split("\n"):
        if строка.startswith("|"):
            строка = re.sub(r"(?<=\d)\.(?=\d)", ",", строка)
        out.append(строка)
    return "\n".join(out)


