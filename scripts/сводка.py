def _есть(путь):
    п = os.path.join(ROOT, путь)
    if not os.path.exists(п):
        return 0
    if os.path.isdir(п):
        return sum(len(f) for _, _, f in os.walk(п))
    return 1


def требования():
    """Двенадцать минимальных требований КЗ — счётом из библиотек."""
    return G.checks()


def геометрия():
    """Проверки формы и движителя."""
    строки = []
    for имя, модуль, фн in (("Надстройка", "lib.gorizont_super", "проверки"),
                            ("Гребное колесо", "lib.gorizont_wheel", "checks"),
                            ("Компоновка", "lib.gorizont_ga", "checks"),
                            ("Управляемость и мелководье", "lib.gorizont_manoeuvre", "checks"),
                            ("Узел ось плицы", "lib.gorizont_node", "checks"),
                            ("Общественные помещения", "lib.gorizont_public", "проверки"),
                            ("Постройка и персонал", "lib.gorizont_build", "checks"),
                            ("Маршрут", "lib.gorizont_route", "checks"),
                            ("Целевая аудитория", "lib.gorizont_market", "checks"),
                            ("Солнечная палуба", "lib.gorizont_deckload", "checks")):
        try:
            м = importlib.import_module(модуль)
            for c in getattr(м, фн)():
                строки.append((имя, c["name"], c["value"], c["unit"],
                               c["ok"], c["note"]))
        except Exception as e:
            строки.append((имя, "модуль не отработал", 0, "", False, str(e)))
    return строки


def матрица():
    м = importlib.import_module("сверка_требований_КЗ")
    return м._матрица(), м.ПОКРЫТИЕ, м.состояние_записки()


