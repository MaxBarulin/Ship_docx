    г = геометрия()
    w("## 2. Проверки модели")
    w("")
    w("| Узел | Проверка | Значение | | Примечание |")
    w("|---|---|---|---|---|")
    for имя, наз, зн, ед, ок, прим in г:
        w("| %s | %s | %.2f %s | %s | %s |"
          % (имя, наз, зн, ед, "ок" if ок else "**нет**", прим))
    w("")

    # --- 3. артефакты
    w("## 3. Что лежит в репозитории")
    w("")
    w("| Артефакт | Файлов | Закрывает |")
    w("|---|---|---|")
    for путь, что, закр in АРТЕФАКТЫ:
        n = _есть(путь)
        w("| %s (`%s`) | %s | %s |"
          % (что, путь, n if n else "**нет**", закр))
    w("")

    # --- 4. матрица оценки
    try:
        (разделы, всего), покрытие, зап = матрица()
    except Exception as e:
        w("## 4. Матрица оценки")
        w("")
        w("Не прочиталась: `%s`" % e)
        разделы = None
    if разделы is not None:
        w("## 4. Матрица оценки: %.1f балла" % всего)
        w("")
        w("| Раздел | Есть | Частично | Не начато | На площадке | Итого |")
        w("|---|---|---|---|---|---|")
        s_e = s_ч = s_н = s_п = 0.0
        for имя, (e, ч, н, п) in разделы.items():
            s_e += e; s_ч += ч; s_н += н; s_п += п
            w("| %s | %.2f | %.2f | %.2f | %.2f | %.2f |"
              % (имя, e, ч, н, п, e + ч + н + п))
        w("| **ВСЕГО** | **%.2f** | **%.2f** | **%.2f** | **%.2f** | **%.2f** |"
          % (s_e, s_ч, s_н, s_п, s_e + s_ч + s_н + s_п))
        w("")
        w("Документами закрывается %.1f балла из %.1f: %.1f не зависит от нас "
          "и оценивается на площадке." % (всего - s_п, всего, s_п))
        w("")
        w("Записка: %d разделов, %d знаков, незаполненных мест %d."
          % (зап["разделов"], зап["знаков"], зап["дыр"]))
        w("")

    io.open(ВЫХОД_MD, "w", encoding="utf-8").write("\n".join(из_строк) + "\n")
    if verbose:
        print("Требования КЗ: не сходится %d из %d" % (len(плохо), len(т)))
