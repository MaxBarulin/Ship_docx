def размер(msp, x0, y0, x1, y1, txt, sc, off=0.0, layer="09_РАЗМЕРЫ", h=2.4):
    """Размерная линия между двумя точками с текстом над серединой (горизонтальная или вертикальная)."""
    if abs(y1 - y0) < 1e-6:
        y = y0 + off
        msp.add_line((x0, y), (x1, y), dxfattribs={"layer": layer})
        for x in (x0, x1):
            msp.add_line((x, y - 1.5 * sc), (x, y + 1.5 * sc), dxfattribs={"layer": layer})
            msp.add_line((x, y0), (x, y), dxfattribs={"layer": layer})
        ЧД.text(msp, 0.5 * (x0 + x1), y + 1.0 * sc, txt, h, sc, layer, TA.BOTTOM_CENTER)
    else:
        x = x0 + off
        msp.add_line((x, y0), (x, y1), dxfattribs={"layer": layer})
        for y in (y0, y1):
            msp.add_line((x - 1.5 * sc, y), (x + 1.5 * sc, y), dxfattribs={"layer": layer})
            msp.add_line((x0, y), (x, y), dxfattribs={"layer": layer})
        ЧД.text(msp, x - 1.0 * sc, 0.5 * (y0 + y1), txt, h, sc, layer, TA.BOTTOM_CENTER, rot=90)


