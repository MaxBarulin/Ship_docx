def габ_фиг(fig, s, k):
    """Ширина и высота надписи в дюймах на данной фигуре."""
    t = fig.text(0, 0, s, fontsize=k)
    bb = t.get_window_extent(renderer=fig.canvas.get_renderer())
    t.remove()
    return bb.width / fig.dpi, bb.height / fig.dpi


