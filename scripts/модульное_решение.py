    k = 0.1
    Lc, Bc = M.КОНТЕЙНЕР["длина"] * 1000 * k, M.КОНТЕЙНЕР["ширина"] * 1000 * k
    ax_, ay_ = M.КОНТЕЙНЕР["фитинги_x"] * 1000 * k, M.КОНТЕЙНЕР["фитинги_y"] * 1000 * k
    L.вид(-60.0, -780.0)
