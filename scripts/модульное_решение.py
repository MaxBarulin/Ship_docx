        ЧД.rect(msp, s["x0"] * K, s["y0"] * K, s["x1"] * K, s["y1"] * K, "05_ОБОРУДОВАНИЕ")
        if подписи and s["площадь"] >= 20:
            yl = (s["y1"] - 0.6) if s["площадь"] >= 60 else 0.5 * (s["y0"] + s["y1"])
            ЧД.text(msp, 0.5 * (s["x0"] + s["x1"]) * K, yl * K, s["имя"].split(" %")[0][:36], 2.0, sc, "05_ОБОРУДОВАНИЕ")
