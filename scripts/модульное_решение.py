    L.axis((-Lc / 2 - 30, 0), (Lc / 2 + 30, 0)); L.axis((0, -Bc / 2 - 30), (0, Bc / 2 + 30))
    for sx in (-1, 1):
        L.line((-Lc / 2 - 40, sx * ay_ / 2), (Lc / 2 + 40, sx * ay_ / 2), "22_ТОНКИЕ")
        for sy in (-1, 1):
            cx, cy = sx * ax_ / 2, sy * ay_ / 2
            rot = 0.0 if sx < 0 else 180.0
            for g, layer in Ч.план_корпуса():
                if layer == "21_НЕВИДИМЫЕ":
                    continue
                g = Ч.affinity.translate(Ч.affinity.scale(Ч.affinity.rotate(g, rot, origin=(0, 0)), k, k, origin=(0, 0)), cx, cy)
                L.geom(g, layer)
            a = 225.0 + rot
            arm = Ч.affinity.rotate(Ч.box(0, -T.РЫЧАГ["плечо"][0] / 2, T.РЫЧАГ["r_конца"], T.РЫЧАГ["плечо"][0] / 2), a, origin=(0, 0))
            L.geom(Ч.affinity.translate(Ч.affinity.scale(arm, k, k, origin=(0, 0)), cx, cy))
    L.title(0, Bc / 2 + 55, "Опоры под модулем 20' HC, М 1:20 (контур модуля - фантом)")
    L.dimh(-ax_ / 2, ax_ / 2, -ay_ / 2, -Bc / 2 - 30, ф(M.КОНТЕЙНЕР["фитинги_x"] * 1000, 0))
