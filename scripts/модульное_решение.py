def таблица(шапка, строки):
    out = ["| " + " | ".join(шапка) + " |", "|" + "|".join("---" for _ in шапка) + "|"]
    for r in строки:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def запятые(s):
    """Десятичная запятая в строках проверок библиотеки: «1.25 м» -> «1,25 м». Обозначение узла
    вида ВГ-2026.46.00 не трогается."""
    import re
    s = str(s).replace(T.MARK, "\0")
    return re.sub(r"(\d)\.(\d)", r"\1,\2", s).replace("\0", T.MARK)


