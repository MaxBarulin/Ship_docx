def палуба_план(msp, sc, слоты=True, подписи=True):
    """Контур настила, сооружения, ось - общая заготовка для МР-01 и МР-03."""
    ЧД.poly(msp, ЧД.tier_outline("средняя", G.DECKS["солнечная"] - 0.05), "02_ПАЛУБЫ", close=True)
