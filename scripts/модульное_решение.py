def мн(n, один, два, пять):
    """Число со словом в нужной форме: мн(72, "фундамент", "фундамента", "фундаментов")."""
    слово = один if n % 10 == 1 and n % 100 != 11 else два if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else пять
    return "%d %s" % (n, слово)


