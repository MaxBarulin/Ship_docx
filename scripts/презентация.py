def текст_docx(текст):
    """Текст выступления для докладчика - по слайдам, с примерным временем."""
    import docx
    from docx.shared import Pt as DPt
    d = docx.Document()
    st = d.styles["Normal"]
    st.font.name, st.font.size = "Times New Roman", DPt(14)
    st.element.rPr.rFonts.set("{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia", "Times New Roman")
    d.add_paragraph().add_run("Текст выступления").bold = True
    слов = sum(len(" ".join(a).split()) for _, _, a in текст)
    lo, hi = слов // 140, -(-слов // 110)
    d.add_paragraph("В тексте %d %s, это %d…%d %s спокойной речи при регламенте 7 минут." % (
        слов, мн(слов, ("слово", "слова", "слов")), lo, hi, мн(hi, ("минута", "минуты", "минут"))))
    for i, (заг, мин, абзацы) in enumerate(текст, 1):
        время = "%d с" % round(мин * 60) if мин < 1 else "%s мин" % з(мин, 1).replace(",0", "")
        d.add_paragraph().add_run("Слайд %d. %s, около %s" % (i, заг, время)).bold = True
        for a in абзацы:
            d.add_paragraph(a)
    d.save(ТЕКСТ)
    return слов


def powerpoint(кадры=None):
    """PowerPoint: PDF и, если задана папка, кадры слайдов 1600 × 900 для проверки глазами."""
    ps = ("$ErrorActionPreference='Stop'; $pp = New-Object -ComObject PowerPoint.Application; "
          "$p = $pp.Presentations.Open('%s', $true, $false, $false); $p.SaveAs('%s', 32); " % (PPTX.replace("'", "''"), PDF.replace("'", "''")))
    if кадры:
        ps += ("for ($i = 1; $i -le $p.Slides.Count; $i++) { $p.Slides.Item($i).Export(('%s\\' + $i + '.png'), 'PNG', 1600, 900) }; "
               % кадры.replace("'", "''"))
    ps += "'слайдов ' + $p.Slides.Count; $p.Close(); $pp.Quit()"
    r = subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command", ps], capture_output=True, text=True,
                       timeout=600, encoding="cp866", errors="replace")
    return (r.stdout + r.stderr).strip()


def проверка(текст):
    """Знаки, которых не должно быть в тексте слайдов и выступления: длинное и среднее тире, минус, точка с запятой."""
    плохо = []
    for заг, _, абзацы in текст:
        for a in абзацы:
            for знак in ("—", "–", "−", ";"):
                if знак in a:
                    плохо.append("%s: «%s»" % (заг, знак))
    return плохо


