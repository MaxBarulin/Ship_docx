def _растр(путь, tmp, пикс=2000):
    """Копия картинки для презентации - длинная сторона до пикс, фото в JPEG."""
    im = Image.open(путь)
    k = min(1.0, пикс / float(max(im.size)))
    if k < 1.0:
        im = im.resize((int(im.size[0] * k), int(im.size[1] * k)), Image.LANCZOS)
    имя = os.path.join(tmp, "%03d%s" % (len(os.listdir(tmp)), ".png" if путь.lower().endswith(".png") else ".jpg"))
    (im if имя.endswith(".png") else im.convert("RGB")).save(имя, **({} if имя.endswith(".png") else dict(quality=90)))
    return имя, im.size


def _верх(путь, tmp, от=0.2):
    """Верх листа до первой белой полосы ниже доли «от» высоты - проекция «корпус» без таблицы ординат."""
    im = Image.open(путь).convert("L")
    w, h = im.size
    px = im.load()
    белых = 0
    for y in range(int(h * от), h):
        белых = белых + 1 if all(px[x, y] > 245 for x in range(0, w, 4)) else 0
        if белых >= 12:
            имя = os.path.join(tmp, "верх_%s" % os.path.basename(путь))
            Image.open(путь).crop((0, 0, w, y - 6)).save(имя)
            return имя
    return путь


def _текст(slide, x, y, w, h, строки, size=18, bold=False, color=ГРАФИТ, align=PP_ALIGN.LEFT):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tb.text_frame
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(0.02)
    for i, s in enumerate(строки if isinstance(строки, (list, tuple)) else [строки]):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = align
        r = p.add_run()
        r.text = s
        r.font.name, r.font.size, r.font.bold, r.font.color.rgb = ШРИФТ, Pt(size), bold, color
    return tb


def _картинка(slide, путь, tmp, x, y, w, h, подпись=None, пикс=2000):
    """Картинка в рамку x, y, w, h с сохранением пропорций, по центру по ширине, подпись под ней."""
    файл, (pw, ph) = _растр(путь, tmp, пикс)
    k = min(w / pw, h / ph)
    ww, hh = pw * k, ph * k
    x0 = x + (w - ww) / 2.0
    slide.shapes.add_picture(файл, Inches(x0), Inches(y), Inches(ww), Inches(hh))
    if подпись:
        _текст(slide, x0, y + hh + 0.02, ww, 0.35, подпись, size=12, color=СЕРЫЙ)
    return hh


def _заголовок(slide, текст, n, логотип):
    _текст(slide, 0.5, 0.3, 12.3, 0.8, текст, size=30, bold=True)
    черта = slide.shapes.add_connector(1, Inches(0.55), Inches(1.08), Inches(1.85), Inches(1.08))
    черта.line.color.rgb = КРАСНЫЙ
    черта.line.width = Pt(3)
    _текст(slide, 0.5, 7.0, 1.0, 0.35, str(n), size=11, color=СЕРЫЙ)
    slide.shapes.add_picture(логотип, Inches(Ш - 0.5 - 1.1), Inches(6.88), height=Inches(0.48))


def _числа(slide, блоки, x, y, w, h, столбцом=True):
    """Число крупно и строка пояснения. Столбцом - справа от картинки, строкой - под картинками."""
    n = len(блоки)
    for i, (число, что) in enumerate(блоки):
        if столбцом:
            bx, by, bw = x, y + i * h / n, w
        else:
            bx, by, bw = x + i * w / n, y, w / n - 0.15
        _текст(slide, bx, by, bw, 0.6, число, size=28 if столбцом else 24, bold=True)
        _текст(slide, bx, by + (0.58 if столбцом else 0.5), bw, 0.8, что, size=15 if столбцом else 13, color=СЕРЫЙ)


def _заметки(slide, текст):
    slide.notes_slide.notes_text_frame.text = "\n\n".join(текст)


