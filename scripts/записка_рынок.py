def _предложения(пункты):
    """Пункты списка в ячейку таблицы - предложениями, без маркеров и точки с запятой."""
    return " ".join(p[0].upper() + p[1:] + ("" if p.endswith(".") else ".") for p in пункты)


def _нумерованные(пункты):
    return " ".join("%d) %s." % (i, p[0].upper() + p[1:]) for i, p in enumerate(пункты, 1))


def _диапазон(a, b, n=0):
    return ч(a, n) if abs(a - b) < 0.5 * 10 ** -n else "%s…%s" % (ч(min(a, b), n), ч(max(a, b), n))


def _млн(x, n=1):
    return ч(x / 1e6, n)


def _мн(n, одна, две, пять):
    """Число со словом в нужной форме - «1944 путёвки», «1945 путёвок»."""
    n = int(round(n))
    k = n % 100
    слово = пять if 11 <= k <= 14 else одна if k % 10 == 1 else две if 2 <= k % 10 <= 4 else пять
    return "%s %s" % (ч(n), слово)


