# --- отдельный запуск -----------------------------------------------------------
def _свои_функции():
    """Заменители функций записки для отдельного просмотра текста - своя нумерация рисунков."""
    рисунки = {}

    def рис(путь, подпись):
        рисунки[путь] = len(рисунки) + 1
        return "\n![%s](../../%s)\n\nРисунок %d - %s\n" % (подпись, путь, рисунки[путь], подпись)

    def след(k=1):
        return len(рисунки) + k

    def таблица(шапка, строки):
        out = ["| " + " | ".join(шапка) + " |", "|" + "|".join("---" for _ in шапка) + "|"]
        for r in строки:
            out.append("| " + " | ".join(str(c) for c in r) + " |")
        return "\n".join(out)
    return рис, след, таблица


