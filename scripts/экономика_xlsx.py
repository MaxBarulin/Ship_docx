class Лист(object):
    def __init__(self, wb, имя, заголовок, ширины):
        self.ws = wb.create_sheet(имя)
        self.имя = имя
        self.ws["A1"] = заголовок
        self.ws["A1"].font = ЗАГОЛОВОК
        for i, w in enumerate(ширины, 1):
            self.ws.column_dimensions[col(i)].width = w
        self.r = 3

    def шапка(self, *vals):
        for i, v in enumerate(vals, 1):
            c = self.ws.cell(self.r, i, v)
            c.font = ЖИРНЫЙ
            c.border = РАМКА
            c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        self.ws.row_dimensions[self.r].height = 32
        self.r += 1

    def строка(self, *vals, fmt=None, жир=False):
        """Строка таблицы. fmt - формат чисел по столбцам (список или один на все)."""
        for i, v in enumerate(vals, 1):
            c = self.ws.cell(self.r, i, v)
            c.font = ЖИРНЫЙ if жир else ШРИФТ
            c.border = РАМКА
            f = fmt[i - 1] if isinstance(fmt, (list, tuple)) else fmt
            if f and (isinstance(v, (int, float)) or (isinstance(v, str) and v.startswith("="))):
                c.number_format = f
            if isinstance(v, str) and not v.startswith("=") and len(v) > 30:
                c.alignment = Alignment(wrap_text=True, vertical="top")
        self.r += 1
        return self.r - 1

    def адр(self, r, c, abs_=True, лист=True):
        a = ("$%s$%d" if abs_ else "%s%d") % (col(c), r)
        return ("'%s'!%s" % (self.имя, a)) if лист else a


