def пересчитать():
    """Пересчёт и сохранение книги в Excel - в файле остаются значения формул. Без Excel - пропуск."""
    ps = ("$ErrorActionPreference='Stop'; $x = New-Object -ComObject Excel.Application; $x.DisplayAlerts = $false; "
          "$w = $x.Workbooks.Open('%s'); $x.CalculateFull(); $w.Save(); $w.Close($false); $x.Quit(); "
          "[System.Runtime.Interopservices.Marshal]::ReleaseComObject($x) | Out-Null; 'ok'") % OUT.replace("'", "''")
    try:
        r = subprocess.run(["powershell", "-NoProfile", "-NonInteractive", "-Command", ps], capture_output=True, text=True, timeout=180)
        return "ok" in r.stdout
    except Exception:
        return False


def сверить(ряды):
    wb = openpyxl.load_workbook(OUT, data_only=True)
    ws = wb["Калькуляция"]
    к = E.калькуляция()
    д = E.денежный_поток()
    пары = [("полная", ws.cell(ряды["полная"], 2).value, к["всего"]["полная"]),
            ("цена", ws.cell(ряды["цена"], 2).value, к["цена"]),
            ("цена с НДС", ws.cell(ряды["цена_ндс"], 2).value, к["цена_ндс"])]
    wo = wb["Окупаемость"]
    for r in range(1, wo.max_row + 1):
        if wo.cell(r, 1).value == "NPV":
            пары.append(("NPV", wo.cell(r, 6).value, д["NPV"]))
        if wo.cell(r, 1).value == "PI":
            пары.append(("PI", wo.cell(r, 6).value, д["PI"]))
        if wo.cell(r, 1).value == "IRR":
            пары.append(("IRR", 100.0 * wo.cell(r, 6).value, д["IRR"]))
    wb_ = wb["Безубыточность"]
    for r in range(1, wb_.max_row + 1):
        if str(wb_.cell(r, 1).value).startswith("Точка"):
            пары.append(("точка", wb_.cell(r, 2).value, E.безубыточность()["судов_в_год"]))
    плохо = 0
    for имя, xl, py in пары:
        ok = xl is not None and abs(float(xl) - py) <= max(1.0, abs(py) * 1e-9) if имя not in ("PI", "точка", "IRR") else \
            (xl is not None and abs(float(xl) - py) < 1e-6)
        плохо += 0 if ok else 1
        print("  %-12s Excel %s  библиотека %s  %s" % (имя, xl, round(py, 4), "ок" if ok else "РАСХОДИТСЯ"))
    return плохо


