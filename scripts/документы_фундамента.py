def эскиз_формы():
    """Карта эскизов. Форма в сборе - разрез по оси двух отливок, разъём по опорным полосам, отливки в верхней полуформе."""
    op = next(o for o in T.ТП_КОРПУС if o["no"] == "015")
    sh = eskd_tp.TechSheet("КЭ   ГОСТ 3.1105-84 форма 7", "ВГ-2026.46.01 КЭ015", ДЕТ_КОРПУС)
    sh.table([("Опер.", 10), ("Наименование операции", 50), ("Оснастка", 114)],
             [[op["no"], op["имя"], "модели ВГ-2026.46.01-МД, ящики стержневые -СЯ1, -СЯ2, опоки, скобы"]], row_h=8.0, head_h=8.0,
             size=2.1, center=(0,))
    л, о, г, к = T.ЛИТЬЁ, T.отливка(), T.груз_на_форму(), T.КОРПУС
    Lf, Bf, Hв, Hн = л["опока"]
    xc = Lf / 4.0 + 5.0
    ax = sh.sh.axes(eskd_tp.eskd.MARGIN_L + 2, sh.top - 100.0, 172.0, 96.0)
    ax.set_xlim(-355, 355); ax.set_ylim(-140, 250); ax.set_aspect("equal"); ax.axis("off")
    z0 = к["z"][0]

    def poly(pts, fc, lw=0.6, z=2, ec=INK):
        ax.add_patch(MPoly(pts, closed=True, facecolor=fc, edgecolor=ec, lw=lw, zorder=z))

    def выноска(n, xy, txy):
        ax.plot([xy[0], txy[0]], [xy[1], txy[1]], color=INK, lw=0.5, zorder=8)
        ax.plot([xy[0]], [xy[1]], marker="o", ms=1.8, color=INK, zorder=8)
        ax.add_patch(matplotlib.patches.Circle(txy, 11, facecolor="white", edgecolor=INK, lw=0.6, zorder=9))
        ax.text(txy[0], txy[1], "%d" % n, ha="center", va="center", fontsize=6.5, color=INK, zorder=10)

    poly([(-Lf / 2, -Hн), (Lf / 2, -Hн), (Lf / 2, Hв), (-Lf / 2, Hв)], SAND, lw=0.5, z=1)
    Wr, _, Hп = о["прибыль"]
    d1 = к["d_отв"] - 2 * T.ПРИПУСКИ["отверстие"]
    for sx in (-1, 1):
        poly([(sx * Lf / 2, -Hн), (sx * (Lf / 2 + 20), -Hн), (sx * (Lf / 2 + 20), Hв), (sx * Lf / 2, Hв)], FLASK, z=3)
        poly([(sx * xc + x, z - z0) for x, z in T.контур_корпуса_XZ()], METAL, z=4)
        for s2 in (-1, 1):
            xr = sx * xc + s2 * (к["центратор"][0] / 2 + 4 + Wr / 2 + 2)
            poly([(xr - Wr / 2, к["плечо_z"] - z0), (xr + Wr / 2, к["плечо_z"] - z0),
                  (xr + Wr / 2, к["плечо_z"] - z0 + Hп), (xr - Wr / 2, к["плечо_z"] - z0 + Hп)], METAL, z=4)
        poly([(sx * xc - d1 / 2, к["низ_z"] - z0 - 20), (sx * xc + d1 / 2, к["низ_z"] - z0 - 20),
              (sx * xc + d1 / 2, к["z"][1] - z0 + 20), (sx * xc - d1 / 2, к["z"][1] - z0 + 20)], CORE, z=5)
    d = о["d_стояка"]
    poly([(-d / 2, 0), (d / 2, 0), (d / 2, Hв + 25), (-d / 2, Hв + 25)], METAL, z=4)
    poly([(-(xc - 88), 0), (xc - 88, 0), (xc - 88, 10), (-(xc - 88), 10)], METAL, z=4)
    poly([(-45, Hв), (45, Hв), (45, Hв + 35), (-45, Hв + 35)], FLASK, z=3)
    ax.plot([-Lf / 2 - 30, Lf / 2 + 30], [0, 0], color=ACC, lw=1.1, ls=(0, (8, 2, 2, 2)), zorder=7)
    ax.text(Lf / 2 + 30, 10, "В", color=ACC, fontsize=8, ha="center")
    ax.text(Lf / 2 + 30, -26, "Н", color=ACC, fontsize=8, ha="center")
    ax.text(-Lf / 2 - 30, 8, "МФ", color=ACC, fontsize=7, ha="center")
    if г["груз_кг"]:
        ax.add_patch(Rectangle((Lf / 2 - 170, Hв + 2), 130, 34, facecolor="#5d6776", edgecolor=INK, lw=0.6, zorder=6))
        ax.text(Lf / 2 - 105, Hв + 19, "груз %d кг" % г["груз_кг"], color="white", fontsize=6.3, ha="center", va="center", zorder=7)
    xr_л = -xc - (к["центратор"][0] / 2 + 6 + Wr / 2)
    выноска(1, (xc + 70, 12), (xc + 95, 95))
    выноска(2, (xr_л, к["плечо_z"] - z0 + Hп - 10), (xr_л - 25, Hв + 60))
    выноска(3, (-xc, к["z"][1] - z0 + 12), (-xc + 15, Hв + 60))
    выноска(4, (0, Hв + 20), (60, Hв + 60))
    выноска(5, (-40, 5), (-40, -55))
    выноска(6, (xc + 120, Hв - 20), (xc + 120, Hв + 60))
    выноска(7, (xc + 90, -40), (xc + 135, -60))
    ax.annotate("", (Lf / 2 + 20, -Hн - 25), (-Lf / 2 - 20, -Hн - 25), arrowprops=dict(arrowstyle="<->", color=INK, lw=0.6))
    ax.text(-Lf / 4, -Hн - 50, "опока %d × %d × %d/%d" % л["опока"], ha="center", fontsize=6.5, color=INK)
    sh.top = sh.top - 104.0
    sh.block("Обозначения на эскизе", [
        "1 - отливка корпуса, две в форме. 2 - прибыли %d × %d × %d на плече, зеркало под утепляющей засыпкой." % (Wr, о["прибыль"][1], Hп),
        "3 - стержень Ст. 1 отверстия со знаками, Ст. 2 полости рукоятки - в плоскости разреза не показан.",
        "4 - чаша и стояк Ø%d. 5 - коллектор по разъёму и питатели в торцы опорных полос. 6 - полуформа верха %d. "
        "7 - полуформа низа %d. МФ - разъём." % (d, Hв, Hн)], size=2.2, gap=4.6)
    sh.block("Порядок сборки формы и контроль", [
        "Разъём по опорным полосам хвоста, обе отливки в полуформе верха, стояк между ними.",
        "Стержень Ст. 1 ставить в знаки низа и верха, Ст. 2 - знаком в переднюю прорезь.",
        "Подъёмная сила металла %s кН с запасом 1,3 против веса верха %s кН - %s." % (
            ф(г["F_кН"], 1), ф(г["вес_верха_кН"], 1),
            ("форму нагрузить %d кг или скрепить четырьмя скобами" % г["груз_кг"]) if г["груз_кг"] else "скрепить двумя скобами"),
        "Вентиляционные каналы над полостью и прибылями прочистить. Форму залить не позднее 24 ч после сборки."], size=2.2, gap=4.8)
    return sh.save(os.path.join(OUT, "46_КЭ015_форма.png"))


