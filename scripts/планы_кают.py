def _надпись(имя):
    """Надпись на мебели - как в расстановке, с «×» и существительным у двухъярусной."""
    s = имя.replace(" x ", " × ")
    if s.startswith("2-ярусная"):
        s = "койка " + s
    return s


class Лист:
    """Одна ось на весь лист, метры, масштаб общий. Размеры надписей - в метрах по
    метрикам шрифта: дюймы / (дюймов на метр)."""

    def __init__(self, W, H):
        self.k = ШИРИНА_ЛИСТА / W                       # дюймов на метр
        self.fig = plt.figure(figsize=(ШИРИНА_ЛИСТА, H * self.k))
        self.ax = self.fig.add_axes((0, 0, 1, 1))
        self.ax.set_xlim(0, W)
        self.ax.set_ylim(-H, 0)
        self.ax.set_aspect("equal")
        self.ax.axis("off")
        self.r = self.fig.canvas.get_renderer()

    def размер(self, текст, кегль=КЕГЛЬ, поворот=0):
        t = self.fig.text(0, 0, текст, fontsize=кегль, rotation=поворот)
        e = t.get_window_extent(self.r)
        t.remove()
        return e.width / self.fig.dpi / self.k, e.height / self.fig.dpi / self.k

    def линия(self, xs, ys, lw=ТОНК, **kw):
        self.ax.plot(xs, ys, color=ЧЁРН, lw=lw, solid_capstyle="butt", **kw)

    def текст(self, x, y, s, кегль=КЕГЛЬ, **kw):
        kw.setdefault("color", ЧЁРН)
        return self.ax.text(x, y, s, fontsize=кегль, **kw)

    def перенос(self, текст, ширина, кегль=КЕГЛЬ):
        """Строки не шире `ширина` метров - перенос по словам, не обрезка."""
        строки, тек = [], ""
        for слово in текст.split():
            проба = (тек + " " + слово).strip()
            if тек and self.размер(проба, кегль)[0] > ширина:
                строки.append(тек)
                тек = слово
            else:
                тек = проба
        if тек:
            строки.append(тек)
        return строки

    # размерные линии с засечками, как на строительных планах
    def засечка(self, x, y):
        self.линия([x - ЗАСЕЧКА, x + ЗАСЕЧКА], [y - ЗАСЕЧКА, y + ЗАСЕЧКА], lw=0.9)

    def размер_г(self, x0, x1, y_от, y, текст):
        for x in (x0, x1):
            self.линия([x, x], [y_от, y + ВЫЛЕТ])
            self.засечка(x, y)
        self.линия([x0 - ВЫЛЕТ, x1 + ВЫЛЕТ], [y, y])
        self.текст((x0 + x1) / 2.0, y + 0.05, текст, ha="center", va="bottom")

    def размер_в(self, y0, y1, x_от, x, текст):
        for y in (y0, y1):
            self.линия([x_от, x - ВЫЛЕТ], [y, y])
            self.засечка(x, y)
        self.линия([x, x], [y0 - ВЫЛЕТ, y1 + ВЫЛЕТ])
        self.текст(x - 0.05, (y0 + y1) / 2.0, текст, ha="right", va="center", rotation=90)


def _стены(Л, ox, oy, ф, гл, xд, дв, окно):
    """Переборки двойной линией. Проём двери в стене коридора, окно - лента
    остекления во всю ширину каюты: три тонкие линии в толще стены."""
    t = СТЕНА
    L = lambda xs, ys, lw=ТОЛСТ: Л.линия([ox + x for x in xs], [oy + y for y in ys], lw=lw)
    # боковые переборки
    L([0, 0], [0, гл]); L([-t, -t], [-t, гл + t])
    L([ф, ф], [0, гл]); L([ф + t, ф + t], [-t, гл + t])
    # стена коридора с проёмом двери
    L([0, xд], [0, 0]); L([xд + дв, ф], [0, 0])
    L([-t, xд], [-t, -t]); L([xд + дв, ф + t], [-t, -t])
    L([xд, xд], [-t, 0]); L([xд + дв, xд + дв], [-t, 0])
    # наружная стена: у бортовой каюты - окно, у внутренней - глухая
    if окно:
        L([-t, 0], [гл + t, гл + t]); L([ф, ф + t], [гл + t, гл + t])
        L([0, 0], [гл, гл + t]); L([ф, ф], [гл, гл + t])
        for y in (гл, гл + t / 2.0, гл + t):
            L([0, ф], [y, y], lw=ТОНК)
    else:
        L([0, ф], [гл, гл]); L([-t, ф + t], [гл + t, гл + t])


def _в_контур(Л, x, y, w, h, s):
    """Как поставить надпись в контур мебели - (поворот, текст) или None."""
    for вар in (s, s.replace(" ", "\n", 1)) if " " in s else (s,):
        for пов in (0, 90):
            tw, th = Л.размер(вар, КЕГЛЬ, пов)
            if tw + 2 * ОТСТУП <= w and th + 2 * ОТСТУП <= h:
                return пов, вар
    return None


def _выноска(Л, ox, oy, ф, гл, предмет, s, занято):
    """Надпись на полке в ближайшем свободном месте пола, линия-выноска с точкой в предмете."""
    x, y, w, h = предмет
    tw, th = Л.размер(s)
    th += 0.03                                    # надпись стоит на полке с зазором
    px, py = x + w / 2.0, y + h / 2.0             # точка выноски - середина предмета
    чужие = [r for r in занято if r != предмет]

    def внутри(qx, qy, r):
        return r[0] < qx < r[0] + r[2] and r[1] < qy < r[1] + r[3]

    def чистая(x0, y0, рамка):
        """Выноска от конца полки до точки не идёт через надпись и чужую мебель."""
        for i in range(1, 40):
            u = i / 40.0
            qx, qy = x0 + (px - x0) * u, y0 + (py - y0) * u
            if внутри(qx, qy, (рамка[0] + 0.02, рамка[1] + 0.02, рамка[2] - 0.04, рамка[3] - 0.02)):
                return False
            if any(внутри(qx, qy, r) for r in чужие):
                return False
        return True

    лучший = None
    шаг = 0.05
    # сначала с просторным зазором до мебели и стен, в тесноте - с минимальным
    for зазор in (3 * ОТСТУП, 2 * ОТСТУП, ОТСТУП):
        препятствия = [(a - зазор, b - зазор, c + 2 * зазор, d + 2 * зазор) for a, b, c, d in занято]
        for i in range(int((ф - tw - 2 * зазор) / шаг) + 1):
            for j in range(int((гл - th - 2 * зазор) / шаг) + 1):
                рамка = (зазор + i * шаг, зазор + j * шаг, tw, th)
                if any(_пересекаются(рамка, r) for r in препятствия):
                    continue
                # выноска - от ближнего к предмету конца полки
                конец = рамка[0] if abs(рамка[0] - px) < abs(рамка[0] + tw - px) else рамка[0] + tw
                if not чистая(конец, рамка[1], рамка):
                    continue
                d = math.hypot(конец - px, рамка[1] - py)
                if лучший is None or d < лучший[0]:
                    лучший = (d, рамка, конец)
        if лучший:
            break
    if лучший is None:
        return None
    _, (tx, ty, _, _), конец = лучший
    Л.текст(ox + tx, oy + ty + 0.03, s, ha="left", va="bottom")
    Л.линия([ox + tx, ox + tx + tw], [oy + ty, oy + ty])
    Л.линия([ox + конец, ox + px], [oy + ty, oy + py])
    Л.ax.plot([ox + px], [oy + py], "o", color=ЧЁРН, ms=2.2)
    занято.append((tx, ty, tw, th))
    return tx, ty, tw, th


def каюта(Л, тип, ox, oy, верх_ряда):
    """Каюта с внутренним углом у коридора в (ox, oy). Подпись типа - по верху ряда."""
    к = GA.КАЮТЫ[тип]
    ф, гл, м = мебель(тип)
    проверки, центр = эргономика(тип)
    ok = all(p[1] for p in проверки)
    су = [f for f in м if f[5] == "санузел"][0]
    дв = ДВЕРЬ_М4 if к.get("М4") else ДВЕРЬ
    xд = су[1] - дв - 0.05
    _стены(Л, ox, oy, ф, гл, xд, дв, к["окно"])

    # дверь: полотно и дуга открывания
    Л.линия([ox + xд, ox + xд], [oy, oy + дв], lw=0.9)
    Л.ax.add_patch(Arc((ox + xд, oy), 2 * дв, 2 * дв, theta1=0, theta2=90, color=ЧЁРН, lw=ТОНК))

    # мебель контуром; что не входит в контур - на выноску после всех контуров
    занято = [(x, y, w, h) for _, x, y, w, h, _ in м] + [(xд, 0.0, дв, дв)]
    на_выноску = []
    for имя, x, y, w, h, кл in м:
        Л.ax.add_patch(Rectangle((ox + x, oy + y), w, h, fill=False, ec=ЧЁРН,
                                 lw=0.7 if кл == "санузел" else ТОНК))
        s = _надпись(имя)
        как = _в_контур(Л, x, y, w, h, s)
        if как:
            пов, вар = как
            Л.текст(ox + x + w / 2.0, oy + y + h / 2.0, вар, ha="center", va="center",
                    rotation=пов, multialignment="center", linespacing=1.0)
        else:
            на_выноску.append(((x, y, w, h), s))

    if тип == "семейная":
        # раздвижная перегородка между торцами двух двухъярусных коек: делит
        # спальные половины, в открытом виде не мешает проходу вдоль каюты
        койки = sorted(f for f in м if f[5] == "койка")
        xp = (койки[0][1] + койки[0][3] + койки[1][1]) / 2.0
        шкафы = [f for f in м if f[5] == "шкаф"]
        y0 = max(f[2] + f[4] for f in шкафы) + 0.05 if шкафы else 0.6
        Л.линия([ox + xp, ox + xp], [oy + y0, oy + гл], lw=0.8, ls=(0, (4, 2)))
        s = "раздвижная\nперегородка"
        tw, th = Л.размер(s)
        yк = min(f[2] for f in койки)
        yt = (y0 + yк) / 2.0
        Л.текст(ox + xp - 0.08, oy + yt, s, ha="right", va="center", multialignment="right", linespacing=1.0)
        занято.append((xp - 0.08 - tw, yt - th / 2.0, tw + 0.08, th))

    if центр:
        R = G.TURN_CIRCLE / 2.0
        Л.ax.add_patch(Circle((ox + центр[0], oy + центр[1]), R, fill=False, ec=ЧЁРН, lw=0.6,
                              ls=(0, (8, 2, 1.5, 2))))
        s = "⌀" + P.ч(G.TURN_CIRCLE, 1)     # знак диаметра - в шрифте ГОСТ на U+2300, не на «Ø»
        tw, th = Л.размер(s)
        tx = центр[0] - R + 0.12
        Л.текст(ox + tx, oy + центр[1] + 0.1, s, ha="left", va="bottom")
        занято.append((tx, центр[1] + 0.1, tw, th))

    for предмет, s in на_выноску:
        _выноска(Л, ox, oy, ф, гл, предмет, s, занято)

    # размеры каюты в свету
    Л.размер_г(ox, ox + ф, oy + гл + СТЕНА, oy + гл + СТЕНА + РАЗМЕР, P.ч(ф, 1))
    Л.размер_в(oy, oy + гл, ox - СТЕНА, ox - СТЕНА - РАЗМЕР, P.ч(гл, 2))

    # подписи двери и коридора
    Л.текст(ox + xд + дв / 2.0, oy - СТЕНА - 0.06, "дверь " + P.ч(дв, 2), ha="center", va="top")
    Л.текст(ox + ф / 2.0, oy - СТЕНА - 0.40, "коридор %s м" % P.ч(GA.КОРИДОР, 2), ha="center", va="top")

    # подпись типа - по верху ряда, от наружной грани стены
    Л.текст(ox - СТЕНА, верх_ряда, заголовок(тип), кегль=КЕГЛЬ_ЗАГ, ha="left", va="top",
            color=ЧЁРН if ok else КРАСН)
    return проверки


