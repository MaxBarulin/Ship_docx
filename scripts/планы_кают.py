def build(verbose=True):
    # раскладка в метрах: столбцы по самой широкой каюте, ряды по самой глубокой
    ширина_ст = [max(мебель(ряд[c])[0] for ряд in СЕТКА) for c in range(2)]
    x_ст = [ПОЛЕ + ЛЕВО]
    x_ст.append(x_ст[0] + ширина_ст[0] + СТЕНА + ПРОМЕЖУТОК + ЛЕВО)
    W = x_ст[1] + ширина_ст[1] + СТЕНА + ПОЛЕ
    ряды, y = [], -ПОЛЕ
    for ряд in СЕТКА:
        гл = max(мебель(т)[1] for т in ряд)
        ряды.append((y, y - ВЕРХ - гл))            # верх ряда, низ каюты (внутренняя грань у коридора)
        y = y - ВЕРХ - гл - НИЗ - МЕЖДУ_РЯДАМ
    y_прим = y + МЕЖДУ_РЯДАМ - 0.12

    with P.чертёж():
        # высоту листа узнаём после переноса примечания - ширина от неё не зависит
        черн = Лист(W, 1.0)
        строки = черн.перенос(примечание(), W - 2 * ПОЛЕ)
        шаг = черн.размер("Ag", КЕГЛЬ)[1] * 1.15
        plt.close(черн.fig)
        H = -(y_прим - шаг * len(строки)) + ПОЛЕ

        Л = Лист(W, H)
        итог, плохо = [], 0
        for (верх, oy), ряд in zip(ряды, СЕТКА):
            for c, т in enumerate(ряд):
                пр = каюта(Л, т, x_ст[c], oy, верх)
                for имя, ok, поясн in пр:
                    итог.append((т, имя, ok, поясн))
                    if not ok:
                        плохо += 1
        for i, s in enumerate(строки):
            Л.текст(ПОЛЕ, y_прим - i * шаг, s, ha="left", va="top")

        p = os.path.join(OUT, "5_каюты.png")
        if плохо:
            p = os.path.join(OUT, "5_каюты_НЕ_ПРОШЛО.png")
        P.сохранить(Л.fig, p)
        plt.close(Л.fig)
    if verbose:
        for т, имя, ok, поясн in итог:
            if not ok:
                print("  НЕ ПРОШЛО - %-12s %s %s" % (т, имя, поясн))
        print("  ", os.path.basename(p), "- проверок %d, не прошло %d" % (len(итог), плохо))
    return p, плохо


if __name__ == "__main__":
    _, n = build()
    sys.exit(1 if n else 0)
