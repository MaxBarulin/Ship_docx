def _мест(n):
    if n % 10 == 1 and n % 100 != 11:
        return "место"
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return "места"
    return "мест"


def _площадь(a):
    """18,0 - одним знаком, 8,55 - двумя: число как есть, без округления до 8,5."""
    a = round(a, 2)
    return P.ч(a, 1) if abs(a * 10 - round(a * 10)) < 1e-6 else P.ч(a, 2)


