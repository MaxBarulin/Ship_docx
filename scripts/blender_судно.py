r"""Сборка судна с нуля: один вход, один порядок, аудит в конце.

    import blender_судно as С
    С.собрать()

Модуль заменяет россыпь построителей. Причина простая: собирать судно по
частям в уже населённой сцене — верный способ получить два тела в одном
объёме. Прежний файл это и показал: кожух колеса стоял дважды, резаки
булевых операций торчали за бортом, надстройка висела за обводом. Поэтому
здесь сцена сначала чистится целиком, и только потом строится.

Пересечений нет не потому, что их потом починили, а потому что геометрия
так задана:

  * **ниши колёс вырезаны в обводе, а не булевой операцией.** Полусечение
    корпуса само зажимает ординату на длине ниши — лофт выходит сразу с
    карманом, и в сцене не остаётся ни резаков, ни следов от них;
  * **настил главной палубы разорван там, где ходит колесо.** Грани в зоне
    колеса просто не ставятся: дырка в настиле — это проём, а не дефект;
  * **борт первого яруса уходит внутрь на длине кожуха.** Колесо на миделе
    поднимается на 2,3 м выше главной палубы и физически стоит в объёме
    яруса; ярус ему это место уступает, а снаружи проём закрывает кожух.
    За нишей встаёт двухсветный атриум — отсюда и планировка;
  * **все зазоры посчитаны до постройки.** `gorizont_super.clearances()` и
    `gorizont_wheel.checks()` меряют расстояния от габарита колеса до
    стенок кожуха и до палубы. Уйдёт хоть один в минус — это видно до
    того, как в сцене появится хоть одна вершина.

Проверка после сборки обязательна и не декоративна: `blender_аудит.pairs()`
с допуском 25 мм. Ноль пар — единственный приемлемый результат.
"""
