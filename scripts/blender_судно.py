def портал(кол):
    """Портал: две светлые стойки во всю высоту надстройки вокруг колеса и атриума."""
    п0, п1 = SU.портал()
    ст = SU.ПОРТАЛ["стойка"]
    сделано = []
    for k, (xa, xb) in enumerate(((п0 - ст, п0), (п1, п1 + ст))):
        for знак in (1, -1):
            кольца = []
            z = G.DECKS["главная"]
            while z <= G.DECKS["солнечная"] + 1e-6:
                ярус = "главная" if z < G.DECKS["средняя"] else "средняя"
                y = SU.полуширота(0.5 * (xa + xb), ярус, z=min(z, SU.ЯРУСЫ[ярус]["z1"] - 0.01))
                y = max(y, SU.кожух()["y_наруж"]) if z < SU.кожух()["z1"] else y
                y += SU.ПОРТАЛ["вынос"] + 0.012
                y = min(y, L.side_half(0.5 * (xa + xb)) - 0.06 - 0.005)   # не шире корпуса
                ring = [(знак * y, z), (знак * (y + 0.06), z)]
                кольца.append((z, ring))
                z += 0.35
            # лофт по z: кольцо = четыре точки (xa,y) (xb,y) (xb,y+t) (xa,y+t)
            verts, faces = [], []
            for z, ((y0, _), (y1, _)) in кольца:
                verts.extend([(xa, y0, z), (xb, y0, z), (xb, y1, z), (xa, y1, z)])
            n = 4
            for i in range(len(кольца) - 1):
                a = i * n
                for j in range(n):
                    faces.append([a + j, a + (j + 1) % n, a + n + (j + 1) % n, a + n + j])
            faces.append([3, 2, 1, 0])
            m = (len(кольца) - 1) * n
            faces.append([m, m + 1, m + 2, m + 3])
            ob = _объект("Портал_%s_%d" % ("ПБ" if знак > 0 else "ЛБ", k), verts, faces, кол, "Надстройка_серебро")
            сделано.append(ob)
    return сделано


def _путь(код, вынос, z):
    пб = [(x, SU.полуширота(x, код, z=z) + вынос) for x, _ in SU.обвод(код, шаг=ШАГ)]
    пб = [(x, y) for x, y in пб if y > 0.08]
    return пб + [(x, -y) for x, y in reversed(пб)]


def _полоса(имя, путь, z0, z1, кол, материал, толщина=0.02):
    """Открытая вертикальная полоса по пути [(x, y), …] — без замыкания.

    Для фальшбортов: замкнутая лента ставила поперечину через палубу в
    начале и в конце участка. Толщина делает полосу замкнутым телом.
    """
    verts, faces = [], []
    for x, y in путь:
        verts.extend([(x, y, z0), (x, y, z1)])
    for i in range(len(путь) - 1):
        a, b = 2 * i, 2 * (i + 1)
        faces.append([a, a + 1, b + 1, b])
    ob = _объект(имя, verts, faces, кол, материал)
    м = ob.modifiers.new("Толщина", "SOLIDIFY")
    м.thickness = толщина
    м.offset = 0.0
    return ob


def _лента(имя, путь, z0, z1, кол, материал, толщина=0.06):
    verts, faces = [], []
    for x, y in путь:
        verts.extend([(x, y, z0), (x, y, z1)])
    n = len(путь)
    for i in range(n):
        a, b = 2 * i, 2 * ((i + 1) % n)
        faces.append([a, a + 1, b + 1, b])
    ob = _объект(имя, verts, faces, кол, материал)
    if толщина > 0.0:
        м = ob.modifiers.new("Толщина", "SOLIDIFY")
        м.thickness = толщина
        м.offset = 0.0
    return ob


def линия(кол):
    """Акцентная линия по кромке прогулочной палубы, во всю длину судна."""
    z = G.DECKS["средняя"]
    к = SU.кожух()
    пб = []
    for x, _ in SU.обвод("главная", шаг=0.5):
        полу = SU.полуширота(x, "главная", z=z - 0.01)
        if полу <= 0.08:
            continue
        if SU.в_портале(x):
            полу = L.side_half(x) - SU.КАРНИЗ - 0.024
        пб.append((x, min(полу + SU.КАРНИЗ + 0.012, L.side_half(x) - 0.012)))   # не шире корпуса и с толщиной
    путь = пб + [(x, -y) for x, y in reversed(пб)]
    return _лента("Акцент_линия", путь, z - F.ВЫСОТА_ЛИНИИ, z, кол,
                  "Акцент_красный", 0.02)


# --- кожух колеса ------------------------------------------------------------
def кожух(знак, кол):
    """Блок-портал одного борта: щека заподлицо с бортом от главной до солнечной палубы.

    Одна оболочка: наружная щека с круглым окном колеса, два торца, крыша.
    Внутренняя сторона — борт яруса (он утоплен), поэтому не нужна. Лист
    60 мм внутрь, тело замкнутое. Над окном колеса — стекло атриума
    отдельным телом в углублении щеки.
    """
    п = SU.портал_блок()
    б = "ПБ" if знак > 0 else "ЛБ"
    y = п["y_наруж"] - SU.КОЖУХ_ЛИСТ / 2.0
    x0, x1, z0, z1 = п["x0"], п["x1"], п["z0"], п["z1"]
    nx, nz = 48, 28
    verts, faces = [], []
    # щека: сетка (x, z) без квадов внутри круга и внутри окна атриума
    сет = []
    for i in range(nx + 1):
        x = x0 + (x1 - x0) * i / nx
        ряд = []
        for j in range(nz + 1):
            z = z0 + (z1 - z0) * j / nz
            ряд.append(len(verts))
            verts.append((x, знак * y, z))
        сет.append(ряд)
    for i in range(nx):
        for j in range(nz):
            xc = x0 + (x1 - x0) * (i + 0.5) / nx
            zc = z0 + (z1 - z0) * (j + 0.5) / nz
            if SU.в_арке(xc, zc):
                continue
            if п["z_атриум0"] < zc < п["z_атриум1"] and x0 + 0.9 < xc < x1 - 0.9:
                continue
            q = [сет[i][j], сет[i][j + 1], сет[i + 1][j + 1], сет[i + 1][j]]
            faces.append(q if знак > 0 else list(reversed(q)))
    # торцы и крыша: от щеки к борту яруса (y_внутр)
    yi = знак * п["y_внутр"]
    for i_ in (0, nx):
        col = сет[i_]
        for j in range(nz):
            a, b = col[j], col[j + 1]
            va = len(verts); verts.append((verts[a][0], yi, verts[a][2]))
            vb = len(verts); verts.append((verts[b][0], yi, verts[b][2]))
            q = [a, b, vb, va] if (i_ == 0) == (знак > 0) else [a, va, vb, b]
            faces.append(q)
    top = [сет[i][nz] for i in range(nx + 1)]
    for i in range(nx):
        a, b = top[i], top[i + 1]
        va = len(verts); verts.append((verts[a][0], yi, z1))
        vb = len(verts); verts.append((verts[b][0], yi, z1))
        q = [a, va, vb, b] if знак > 0 else [a, b, vb, va]
        faces.append(q)
    ob = _объект("Портал_" + б, verts, faces, кол, "Надстройка_серебро")
    м = ob.modifiers.new("Лист", "SOLIDIFY")
    м.thickness = SU.КОЖУХ_ЛИСТ
    м.offset = 0.0          # симметрично: наружная грань щеки ровно в обводе с обоих бортов
    # окно атриума: стекло в углублении щеки
    za, zb = п["z_атриум0"], п["z_атриум1"]
    yg = знак * (y - 0.05)
    quads = [[(x0 + 0.9, yg, za), (x1 - 0.9, yg, za), (x1 - 0.9, yg, zb), (x0 + 0.9, yg, zb)]]
    if знак < 0:
        quads = [list(reversed(q)) for q in quads]
    _поверхность("Атриум_остекление_" + б, quads, кол, "Остекление", 0.03)
    # кольцо вокруг окна колеса
    quads = []
    cx, cz = SU.центр_проёма(); r_ = SU.радиус_проёма(); rr = SU.ПРОЁМ_КОЖУХА["рамка"]
    n_ = 48
    for i in range(n_):
        t0, t1 = math.pi * i / n_, math.pi * (i + 1) / n_
        pts = []
        for t in (t0, t1):
            for rad in (r_, r_ + rr):
                x = cx + rad * math.cos(t)
                z = max(z0, cz + rad * math.sin(t))
                pts.append((x, знак * (y + SU.КОЖУХ_ЛИСТ / 2.0 - 0.018), z))
        q = [pts[0], pts[2], pts[3], pts[1]]
        quads.append(q if знак > 0 else list(reversed(q)))
    _поверхность("Рамка_проёма_" + б, quads, кол, "Акцент_красный", 0.03)
    # ласточка: красная линия ныряет от кромки прогулочной палубы к кольцу
    zл = G.DECKS["средняя"] - F.ВЫСОТА_ЛИНИИ / 2.0
    R = r_ + rr
    полосы = []
    for xa, xb in ((x0 + 0.02, cx - R * 0.62), (x1 - 0.02, cx + R * 0.62)):
        путь = []
        zк = cz + math.sqrt(max(R * R - (R * 0.62) ** 2, 0.0))
        for k in range(25):
            t = k / 24.0
            xx = xa + (xb - xa) * t
            zz = zл + (zк - zл) * (3 * t * t - 2 * t ** 3)
            путь.append((xx, zz))
        полосы.append(путь)
    for k, путь in enumerate(полосы):
        quads = []
        w = F.ВЫСОТА_ЛИНИИ / 2.0
        for (xa_, za_), (xb_, zb_) in zip(путь, путь[1:]):
            dx, dz = xb_ - xa_, zb_ - za_
            l = math.hypot(dx, dz)
            nx_, nz_ = -dz / l * w, dx / l * w
            yy = знак * (y + SU.КОЖУХ_ЛИСТ / 2.0 - 0.018)
            q = [(xa_ - nx_, yy, za_ - nz_), (xb_ - nx_, yy, zb_ - nz_), (xb_ + nx_, yy, zb_ + nz_), (xa_ + nx_, yy, za_ + nz_)]
            quads.append(q if знак > 0 else list(reversed(q)))
        _поверхность("Ласточка_%s_%d" % (б, k), quads, кол, "Акцент_красный", 0.03)
    return ob


# --- гребное колесо ----------------------------------------------------------
def колесо(знак, кол):
    """Колесо: обод на окружности осей, механизм на внутренней стороне.

    Плоскости поперёк судна (от центра колеса yc, знак — к борту):

        диски обода       ±1,48   (толщина 0,10)
        оси плиц          ±1,50   сквозь диски
        полотно плиц      ±1,36   между дисками, не касаясь их
        механизм          −1,44   рычаги, тяги, кольцо — на внутренней
                                  стороне, где их с берега не видно

    Набор — одна сетка (сварено и запрессовано), плицы — отдельно.
    """
    б = "ПБ" if знак > 0 else "ЛБ"
    н = W.niche_geometry()
    к = SU.кожух()
    x0 = W.X_AXIS
    yc = знак * (н["y_внутренняя_кромка"] + W.WIDTH / 2.0)
    z0 = W.axis_height(G.DRAFT)
    Rп = W.PIVOT_RADIUS
    полуш = W.WIDTH / 2.0
    # Плоскости поперёк колеса, от центра yc. Ни одна деталь набора не
    # проходит сквозь другую — только касается торцом: слитая сетка с
    # самопересечениями ломает проверку «точка внутри» по чётности лучей,
    # и аудит начинает видеть пересечения там, где их нет.
    d_диск = полуш - 0.12                      # середина диска: 1,48
    т_диск = 0.10                              # толщина диска
    y_диск = [yc - знак * d_диск, yc + знак * d_диск]
    d_внутр = d_диск - т_диск / 2.0            # внутренняя грань диска: 1,43
    d_наруж = d_диск + т_диск / 2.0            # наружная грань диска: 1,53
    y_мех = yc - знак * (d_внутр - 0.035)      # механизм внутри, между диском и плицами:
                                              # снаружи диска до стенки ниши всего 7 см
    набор, сег = [], 64

    def кольцо(имя, cx, cz, y, r0, r1, толщ):
        verts, faces = [], []
        for yy in (y - толщ / 2.0, y + толщ / 2.0):
            for r in (r1, r0):
                for i in range(сег):
                    a = 2.0 * math.pi * i / сег
                    verts.append((cx + r * math.cos(a), yy, cz + r * math.sin(a)))
        for i in range(сег):
            j2 = (i + 1) % сег
            faces += [[i, j2, сег + j2, сег + i],
                      [2 * сег + i, 3 * сег + i, 3 * сег + j2, 2 * сег + j2],
                      [i, 2 * сег + i, 2 * сег + j2, j2],
                      [сег + i, сег + j2, 3 * сег + j2, 3 * сег + i]]
        return _объект(имя, verts, faces, кол, "Колесо_обод")

    # ступица между дисками, вал — двумя отрезками по её торцам
    h_ст = 2.0 * d_внутр
    набор.append(_цилиндр("_ступица", (x0, yc, z0), "y", W.HUB_RADIUS, h_ст, кол, "Колесо_обод"))
    # Внутренний подшипник — на той стенке, которая ближе к колесу: выше
    # главной палубы это щека кожуха (4,60), ниже — стенка ниши корпуса
    # (4,80). Ось на уровне палубы, вал ниже её тела проходит сквозь
    # стенку ниши — значит, кончается на ней, а не за ней.
    y_вн = знак * (max(к["y_внутр"], н["y_внутренняя_кромка"]) + 0.03)
    y_нар = знак * (н["y_наружная_кромка"] - 0.02)
    for имя, a, b in (("_вал_внутр", y_вн, yc - знак * d_внутр),
                      ("_вал_наруж", yc + знак * d_внутр, y_нар)):
        набор.append(_цилиндр(имя, (x0, 0.5 * (a + b), z0), "y",
                              W.SHAFT_RADIUS, abs(b - a), кол, "Колесо_обод"))

    for k, yo in enumerate(y_диск):
        набор.append(кольцо("_диск_%d" % k, x0, z0, yo, Rп - W.RIM_IN, Rп + W.RIM_OUT, т_диск))
        for i in range(W.BLADES):
            a = 2.0 * math.pi * (i + 0.5) / W.BLADES    # спицы между осями плиц
            r0, r1 = W.HUB_RADIUS, Rп - W.RIM_IN
            rm = 0.5 * (r0 + r1)
            набор.append(_короб("_спица_%02d_%d" % (i, k),
                                (x0 + rm * math.cos(a), yo, z0 + rm * math.sin(a)),
                                (r1 - r0, 0.07, 0.12), кол, "Колесо_обод", угол=-a))
    # оси плиц: отрезок между дисками и хвостовик наружу под рычаг
    for i in range(W.BLADES):
        a = 2.0 * math.pi * i / W.BLADES
        px, pz = x0 + Rп * math.cos(a), z0 + Rп * math.sin(a)
        набор.append(_цилиндр("_ось_%02d" % i, (px, yc, pz), "y", 0.05,
                              2.0 * d_внутр, кол, "Колесо_обод", сег=12))

    # Неподвижный эксцентриковый палец с бобышкой: на него сходятся тяги.
    # Три слоя тяг по оси — иначе двенадцать тяг в одной плоскости
    # сходятся в одну точку и режут друг друга у бобышки.
    ex, ez = W.eccentric_centre()
    слои = [y_мех + знак * (0.06 + 0.055 * k) for k in range(2)]   # к плицам, два слоя
    набор.append(_цилиндр("_эксцентрик", (x0 + ex, 0.5 * (слои[0] + слои[-1]) , z0 + ez),
                          "y", W.ECC_BOSS, abs(слои[-1] - слои[0]) + 0.06, кол, "Колесо_обод"))
    плицы = []
    for п in W.blade_positions(G.DRAFT):
        i = п["i"]
        px, pz = x0 + п["x"], п["z"]
        qx, qz = x0 + п["Qx"], п["Qz"]
        sx, sz = x0 + п["Sx"], п["Sz"]
        наклон = math.radians(п["tilt"])
        # кривошип: от поверхности оси до пальца, в плоскости рычагов
        lр = math.hypot(qx - px, qz - pz)
        ux, uz = (qx - px) / lр, (qz - pz) / lр
        набор.append(_короб("_кривошип_%02d" % i,
                            (px + ux * (0.05 + lр) / 2.0, y_мех, pz + uz * (0.05 + lр) / 2.0),
                            (lр - 0.05, 0.05, 0.09), кол, "Колесо_обод",
                            угол=-math.atan2(qz - pz, qx - px)))
        # палец кривошипа: сквозь кривошип в слой тяги
        y_т = слои[i % 2]
        набор.append(_цилиндр("_палец_%02d" % i, (qx, 0.5 * (y_мех + y_т), qz), "y",
                              W.PIN_RADIUS * 0.6, abs(y_т - y_мех) + 0.05, кол, "Колесо_обод", сег=10))
        # тяга: от пальца до бобышки эксцентрика, в своём слое
        lт = math.hypot(sx - qx, sz - qz)
        tx, tz = (sx - qx) / lт, (sz - qz) / lт
        L_ = lт - W.ECC_BOSS - 0.01
        набор.append(_короб("_тяга_%02d" % i,
                            (qx + tx * L_ / 2.0, y_т, qz + tz * L_ / 2.0),
                            (L_, 0.045, 0.06), кол, "Колесо_обод",
                            угол=-math.atan2(sz - qz, sx - qx)))
        # полотно плицы: висит от оси по направлению blade_direction, повёрнуто на tilt
        dx, dz = W.blade_direction(math.radians(п["a"]))
        r_ц = W.PIVOT_OFFSET + W.BLADE_HEIGHT / 2.0
        цx, цz = px + dx * r_ц, pz + dz * r_ц
        плицы.append(_короб("_плица_%02d" % i, (цx, yc, цz),
                            (W.BLADE_THICK, W.BLADE_SPAN, W.BLADE_HEIGHT), кол,
                            "Колесо_плица", угол=-наклон))
        for s_ in (-0.34, 0.0, 0.34):
            # ребро на тыльной (кормовой) стороне полотна
            nx, nz = -dz, dx                      # нормаль к полотну
            if nx > 0:
                nx, nz = -nx, -nz
            плицы.append(_короб("_ребро_%02d_%d" % (i, int(s_ * 100)),
                                (цx + nx * 0.0475, yc + s_ * W.BLADE_SPAN, цz + nz * 0.0475),
                                (0.06, 0.06, W.BLADE_HEIGHT * 0.90), кол, "Колесо_плица",
                                угол=-наклон))
        for s_ in (-0.42, 0.42):
            плицы.append(_короб("_проушина_%02d_%d" % (i, int(s_ * 100)),
                                (px + dx * 0.085, yc + s_ * W.BLADE_SPAN, pz + dz * 0.085),
                                (0.10, 0.08, 0.06), кол, "Колесо_плица", угол=-наклон))
    # Детали не сливаются. Колесо — сборка: оси касаются дисков торцами,
    # спицы — ступицы, и в слитой сетке эти касания дают совпадающие
    # грани, на которых тест «точка внутри» по чётности лучей ошибается.
    # Проверено: по отдельности 150 деталей дают ноль пар, слитые — две
    # ложные. Раздельно и честнее: каждая деталь потом уходит в спецификацию.
    под = bpy.data.collections.get("Колесо_" + б)
    if под is None:
        под = bpy.data.collections.new("Колесо_" + б)
        кол.children.link(под)
    for ob in набор + плицы:
        ob.name = "Колесо_%s|%s" % (б, ob.name.lstrip("_"))
        for c in list(ob.users_collection):
            c.objects.unlink(ob)
        под.objects.link(ob)
    return набор + плицы


# --- рубка и акцент ----------------------------------------------------------
def рубка(кол):
    """Рубка: лоб вперёд, корма назад, остекление по периметру, плавник-мачта сложен."""
    р = SU.РУБКА
    z0, z1 = р["z0"], р["z1"]
    h = z1 - z0
    накл = math.tan(math.radians(р["наклон_лба"]))
    кольца = []
    x = р["x0"]
    while x <= р["x1"] + 1e-6:
        полу = р["полу"]
        if x > р["x1"] - р["сход_нос"]:
            u = (x - (р["x1"] - р["сход_нос"])) / р["сход_нос"]
            полу = р["кромка_нос"] + (полу - р["кромка_нос"]) * (1.0 - min(u, 1.0) ** 1.8) ** 0.62
        борт = [(max(0.10, полу - (z - z0) * math.tan(SU.ЗАВАЛ)), z) for z in (z0, z0 + 0.55, z1 - 0.32, z1)]
        кольца.append((x, борт + [(-y, z) for y, z in reversed(борт)]))
        x += 0.5
    ob = _лофт("Рубка", кольца, кол, "Надстройка_графит")
    # наклоны: лоб вперёд на h·tg, корма назад на 0,8 м — по высоте линейно
    for v in ob.data.vertices:
        t = (v.co.z - z0) / h
        if v.co.x > р["x1"] - р["сход_нос"]:
            k = min(1.0, (v.co.x - (р["x1"] - р["сход_нос"])) / р["сход_нос"])
            v.co.x += h * накл * t * k
        elif v.co.x < р["x0"] + 1.0:
            v.co.x -= 0.8 * t
    ob.data.update()
    # остекление: лента по периметру, повторяет наклоны
    пб, x = [], р["x0"]
    while x <= р["x1"] + 1e-6:
        полу = р["полу"]
        if x > р["x1"] - р["сход_нос"]:
            u = (x - (р["x1"] - р["сход_нос"])) / р["сход_нос"]
            полу = р["кромка_нос"] + (полу - р["кромка_нос"]) * (1.0 - min(u, 1.0) ** 1.8) ** 0.62
        пб.append((x, полу - 0.10))
        x += 0.5
    путь = пб + [(x, -y) for x, y in reversed(пб)]
    ст = _лента("Рубка_остекление", путь, z0 + 0.62, z1 - 0.38, кол, "Остекление", 0.05)
    for v in ст.data.vertices:
        t = (v.co.z - z0) / h
        if v.co.x > р["x1"] - р["сход_нос"]:
            k = min(1.0, (v.co.x - (р["x1"] - р["сход_нос"])) / р["сход_нос"])
            v.co.x += h * накл * t * k
        elif v.co.x < р["x0"] + 1.0:
            v.co.x -= 0.8 * t
    ст.data.update()
    # плавник-мачта сложен назад по крыше
    _короб("Рубка_плавник", (р["x0"] - 1.2, 0.0, z1 + 0.12), (4.6, 0.16, 0.22), кол, "Надстройка_серебро")
    return ob


# --- ограждение --------------------------------------------------------------
def _участок(имя, путь, z, кол, высота=1.10):
    """Стеклянный фальшборт на одном участке: пластина 20 мм и поручень."""
    стекло = _полоса(имя + "_стекло", путь, z + 0.05, z + высота - 0.06, кол, "Остекление", 0.02)
    поручень = _полоса(имя + "_поручень", путь, z + высота - 0.06, z + высота, кол, "Надстройка_серебро", 0.06)
    return стекло, поручень


def ограждение_главной(кол):
    """Фальшборт главной палубы: по бортам с разрывом у портала, обход носа
    и кормы, проём аппарели в транце."""
    п0, п1 = SU.портал()
    отступ = 0.06
    z = G.DEPTH
    сделано = []
    for знак, б in ((1, "ПБ"), (-1, "ЛБ")):
        for k, (xa, xb) in enumerate(((5.0, п0 - 0.15), (п1 + 0.15, G.LOA - 10.0))):
            путь = [(x, знак * (L.side_half(x) - отступ)) for x in _хс(xa, xb, 1.5)]
            сделано += _участок("Фальшборт_главная_%s_%d" % (б, k), путь, z, кол)
        # корма: от x=5 к транцу и по транцу до проёма аппарели
        путь = [(x, знак * (L.side_half(x) - отступ)) for x in (5.0, 3.0, 1.0, 0.06)]
        путь += [(0.06, знак * y) for y in (L.side_half(0.06) - отступ - 0.5, 2.2)]
        сделано += _участок("Фальшборт_корма_%s" % б, путь, z, кол)
    # нос: одной полосой вокруг форштевня
    xs = _хс(G.LOA - 10.0, G.LOA - 0.6, 0.8)
    путь = [(x, L.side_half(x) - отступ) for x in xs] + [(x, -(L.side_half(x) - отступ)) for x in reversed(xs)]
    сделано += _участок("Фальшборт_нос", путь, z, кол)
    return сделано


def ограждение_солнечной(кол):
    """Фальшборт солнечной палубы по периметру, одной замкнутой полосой."""
    z = G.DECKS["солнечная"]
    точки = []
    for x, _ in SU.обвод("средняя", шаг=1.5):
        y = SU.полуширота(x, "средняя", z=z) + SU.КАРНИЗ - 0.10
        if SU.в_портале(x):
            y = L.side_half(x) - 0.12
        точки.append((x, y))
    путь = [(x, y) for x, y in точки if y > 0.1]
    полный = путь + [(x, -y) for x, y in reversed(путь)] + [путь[0]]
    return _участок("Фальшборт_солнечная", полный, z, кол)


def _хс(x0, x1, шаг):
    xs, x = [], x0
    while x < x1 - 1e-9:
        xs.append(x)
        x += шаг
    xs.append(x1)
    return xs


