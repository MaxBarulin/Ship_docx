def очистить(verbose=True):
    """Снести сцену целиком: объекты, сетки, коллекции, сироты."""
    for ob in list(bpy.data.objects):
        bpy.data.objects.remove(ob, do_unlink=True)
    for me in list(bpy.data.meshes):
        bpy.data.meshes.remove(me)
    for c in list(bpy.data.collections):
        bpy.data.collections.remove(c)
    for блок in (bpy.data.curves, bpy.data.lights, bpy.data.cameras):
        for d in list(блок):
            if d.users == 0:
                блок.remove(d)
    if verbose:
        print("Сцена очищена")


def _кол(имя):
    c = bpy.data.collections.get(имя)
    if c is None:
        c = bpy.data.collections.new(имя)
        bpy.context.scene.collection.children.link(c)
    return c


def _объект(имя, verts, faces, коллекция, материал=None):
    старый = bpy.data.objects.get(имя)
    if старый is not None:
        bpy.data.objects.remove(старый, do_unlink=True)
    me = bpy.data.meshes.new(имя)
    me.from_pydata(verts, [], faces)
    me.validate(verbose=False)
    me.update()
    ob = bpy.data.objects.new(имя, me)
    коллекция.objects.link(ob)
    if материал:
        Ст.назначить(ob, материал)
    return ob


def _лофт(имя, кольца, кол, материал=None, закрыть=True):
    """Лофт по кольцам [(x, [(y, z), …]), …] с равным числом точек."""
    verts, идх = [], []
    for x, точки in кольца:
        идх.append([len(verts) + i for i in range(len(точки))])
        verts.extend((x, y, z) for y, z in точки)
    faces, n = [], len(идх[0])
    for a, b in zip(идх, идх[1:]):
        for j in range(n):
            k = (j + 1) % n
            faces.append([a[j], a[k], b[k], b[j]])
    if закрыть:
        faces.append(list(reversed(идх[0])))
        faces.append(list(идх[-1]))
    return _объект(имя, verts, faces, кол, материал)


def _призма(имя, сечение, y0, y1, кол, материал=None):
    """Тело вращения нет — просто выдавить замкнутый контур (x,z) вдоль y."""
    n = len(сечение)
    verts = [(x, y0, z) for x, z in сечение] + [(x, y1, z) for x, z in сечение]
    faces = [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]
    faces.append(list(range(n - 1, -1, -1)))
    faces.append(list(range(n, 2 * n)))
    return _объект(имя, verts, faces, кол, материал)


def _цилиндр(имя, центр, ось, радиус, длина, кол, материал=None, сег=20):
    """Цилиндр вокруг локального нуля; место задаётся положением объекта.

    Координаты в сетку не запекаются: иначе поворот объекта пойдёт вокруг
    мирового нуля, а не вокруг детали. На прошлой сборке так разлетелись
    спицы колеса на сорок метров от судна.
    """
    verts, faces = [], []
    for s in (-0.5, 0.5):
        for i in range(сег):
            a = 2.0 * math.pi * i / сег
            verts.append((радиус * math.cos(a), s * длина, радиус * math.sin(a)))
    for i in range(сег):
        j = (i + 1) % сег
        faces.append([i, j, сег + j, сег + i])
    faces.append(list(range(сег - 1, -1, -1)))
    faces.append(list(range(сег, 2 * сег)))
    ob = _объект(имя, verts, faces, кол, материал)
    ob.location = центр
    if ось == "x":
        ob.rotation_euler = (0.0, 0.0, math.pi / 2.0)
    elif ось == "z":
        ob.rotation_euler = (math.pi / 2.0, 0.0, 0.0)
    return ob


def _короб(имя, центр, размеры, кол, материал=None, угол=0.0):
    dx, dy, dz = (d / 2.0 for d in размеры)
    verts = [(sx * dx, sy * dy, sz * dz)
             for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]
    faces = [[0, 1, 3, 2], [4, 6, 7, 5], [0, 2, 6, 4],
             [1, 5, 7, 3], [0, 4, 5, 1], [2, 3, 7, 6]]
    ob = _объект(имя, verts, faces, кол, материал)
    ob.location = центр
    ob.rotation_euler = (0.0, угол, 0.0)
    return ob


def _слить(имя, объекты, кол, материал=None):
    """Слить список объектов в одну сетку: внутри одного тела пересечений нет."""
    bm = bmesh.new()
    bpy.context.view_layer.update()   # иначе matrix_world ещё единичная
    for ob in объекты:
        tmp = bmesh.new()
        tmp.from_mesh(ob.data)
        tmp.transform(ob.matrix_basis)
        me = bpy.data.meshes.new("_tmp")
        tmp.to_mesh(me)
        tmp.free()
        bm.from_mesh(me)
        bpy.data.meshes.remove(me)
        bpy.data.objects.remove(ob, do_unlink=True)
    me = bpy.data.meshes.new(имя)
    bm.to_mesh(me)
    bm.free()
    ob = bpy.data.objects.new(имя, me)
    кол.objects.link(ob)
    if материал:
        Ст.назначить(ob, материал)
    return ob


# --- корпус ------------------------------------------------------------------
def _ниша_ординаты(x, z):
    """Предел ординаты на длине ниши колеса: от киля до палубы, со сходами."""
    return W.niche_half(x)


def полусечение(x):
    """Полусечение корпуса: (y, z) от ДП до кромки борта, с карманом ниши."""
    zk = L.keel_z(x)
    bb = L.side_half(x)
    bk = min(L.bottom_half(x), bb)
    phi = math.radians(L.flare(x))
    точки = [(min(bk * i / (ТОЧЕК_ДНИЩА - 1), _ниша_ординаты(x, zk)), zk)
             for i in range(ТОЧЕК_ДНИЩА)]
    zs = [zk + (G.DEPTH - zk) * i / ТОЧЕК_БОРТА
          for i in range(1, ТОЧЕК_БОРТА + 1)]
    # Две станции вплотную к низу ниши: без них ступенька кармана
    # размазывается по шпации и читается как вмятина, а не как вырез.
    for z in (НИША_Z0 - 0.01, НИША_Z0 + 0.01):
        zs.append(min(max(z, zk + 0.002), G.DEPTH - 0.002))
    for z in sorted(zs):
        y = L.section_y(z, zk, bk, G.DEPTH, bb, phi)
        y = bk if y is None else y
        точки.append((min(y, _ниша_ординаты(x, z)), z))
    return точки


def _станции():
    к = SU.кожух()
    xs = {round(i * ШАГ, 3) for i in range(int(G.LOA / ШАГ) + 1)}
    xs.add(G.LOA)
    # сходы ниши: станции через 0,25 м, чтобы косинус не превратился в ломаную
    for край in (к["ниша_x0"], к["ниша_x1"]):
        t = -W.NICHE_FAIR
        while t <= W.NICHE_FAIR + 1e-9:
            xs.add(round(край + t, 3))
            t += 0.25
    return sorted(xs)


def корпус(кол):
    кольца = []
    for x in _станции():
        полу = полусечение(x)
        кольца.append((x, полу + [(-y, z) for y, z in reversed(полу[:-1])]))
    ob = _лофт("Корпус_обшивка", кольца, кол, "Корпус_графит")
    return ob


# --- палубы ------------------------------------------------------------------
def палуба_главная(кол):
    """Настил главной палубы с проёмами под гребные колёса."""
    к = SU.кожух()
    пр0 = к["ниша_x0"] - ЗАЗОР_НАСТИЛА
    пр1 = к["ниша_x1"] + ЗАЗОР_НАСТИЛА
    внутр = к["колесо_внутр"] - ЗАЗОР_НАСТИЛА       # кромка проёма
    xs = sorted(set(_станции()) | {round(пр0, 3), round(пр1, 3)})
    z = G.DEPTH
    verts, faces = [], []
    строки = []
    for x in xs:
        bb = L.side_half(x) - 0.01
        ys = [-bb, -внутр, 0.0, внутр, bb] if bb > внутр else [-bb, 0.0, bb]
        ys = [-bb, -внутр, 0.0, внутр, bb] if bb > внутр + 0.05 else \
             [-bb, -bb * 0.5, 0.0, bb * 0.5, bb]
        строки.append((x, [len(verts) + i for i in range(len(ys))]))
        verts.extend((x, y, z) for y in ys)
    for (xa, a), (xb, b) in zip(строки, строки[1:]):
        в_проёме = пр0 - 1e-6 <= xa and xb <= пр1 + 1e-6
        for j in range(len(a) - 1):
            бортовая = j in (0, len(a) - 2)
            if в_проёме and бортовая and L.side_half(xa) > внутр + 0.05:
                continue                       # проём под колесо
            faces.append([a[j], a[j + 1], b[j + 1], b[j]])
    ob = _нормали_вверх(_объект("Палуба_главная", verts, faces, кол, "Палуба_серая"))
    м = ob.modifiers.new("Толщина", "SOLIDIFY")
    м.thickness = ПАЛУБА_ТОЛЩИНА
    м.offset = -1.0
    return ob


def _нормали_вверх(ob):
    """Развернуть грани настила так, чтобы нормали смотрели вверх.

    Solidify с offset=-1 растит тело против нормали. У главной палубы
    грани шли в порядке, дававшем нормаль вниз, и настил вырастал вверх —
    на 10 см в объём яруса и фальшборта. Порядок обхода — не то, на что
    стоит полагаться; проверяем и переворачиваем.
    """
    me = ob.data
    if me.polygons and me.polygons[0].normal.z < 0.0:
        bm = bmesh.new()
        bm.from_mesh(me)
        bmesh.ops.reverse_faces(bm, faces=bm.faces[:])
        bm.to_mesh(me)
        bm.free()
        me.update()
    return ob


def _плита(имя, точки, z, кол, материал, толщина=ПАЛУБА_ТОЛЩИНА, вырезы=()):
    """Плита по контуру с прямоугольными вырезами (x0, x1, y0, y1): проём атриума,
    колодцы трапов, шахты лифтов.

    Каждый ряд x несёт вершины на всех «станциях» y — границах всех вырезов
    плюс борта, — поэтому соседние ряды имеют общие рёбра и сетка остаётся
    замкнутой без Т-стыков. Грань между рядами и соседними станциями
    пропускается, если её прямоугольник лежит внутри выреза. Вырезы
    расширяют сетку рядов своими границами по x.
    """
    xs = sorted({round(x, 4) for x, _ in точки} | {round(v, 4) for c in вырезы for v in (c[0], c[1])})
    полу_по_x = {round(x, 4): полу for x, полу in точки}
    xs_т = [x for x, _ in точки]

    def полу(x):
        if x in полу_по_x:
            return полу_по_x[x]
        # линейная интерполяция по контуру
        for (xa, pa), (xb, pb) in zip(точки, точки[1:]):
            if xa <= x <= xb:
                t = (x - xa) / max(xb - xa, 1e-9)
                return pa + (pb - pa) * t
        return 0.0
    станции = sorted({round(v, 4) for c in вырезы for v in (c[2], c[3])})
    verts, faces = [], []
    ряды = []
    for x in xs:
        p = полу(x)
        if p <= 0.05:
            ряды.append(None); continue
        ys = [-p] + [y for y in станции if -p < y < p] + [p]
        ряды.append((x, [len(verts) + i for i in range(len(ys))], ys))
        verts.extend((x, y, z) for y in ys)

    def в_вырезе(xa, xb, ya, yb):
        for c in вырезы:
            if c[0] - 1e-6 <= xa and xb <= c[1] + 1e-6 and c[2] - 1e-6 <= ya and yb <= c[3] + 1e-6:
                return True
        return False
    for ra, rb in zip(ряды, ряды[1:]):
        if ra is None or rb is None:
            continue
        xa, ia, ya = ra; xb, ib, yb = rb
        # общие станции (внутренние) одинаковы, кроме бортовых крайних: сшиваем по индексам станций
        # ряды имеют одинаковый набор внутренних станций, если обе полушироты шире станций
        if len(ia) == len(ib):
            for j in range(len(ia) - 1):
                if в_вырезе(xa, xb, ya[j], ya[j + 1]) and в_вырезе(xa, xb, yb[j], yb[j + 1]):
                    continue
                faces.append([ia[j], ia[j + 1], ib[j + 1], ib[j]])
        else:
            # разное число станций (борт уже станции): треугольная застёжка по y
            i = j = 0
            while i < len(ia) - 1 or j < len(ib) - 1:
                if j >= len(ib) - 1 or (i < len(ia) - 1 and ya[i + 1] <= yb[j + 1] + 1e-9):
                    faces.append([ia[i], ia[i + 1], ib[j]]); i += 1
                else:
                    faces.append([ia[i], ib[j + 1], ib[j]]); j += 1
    ob = _нормали_вверх(_объект(имя, verts, faces, кол, материал))
    м = ob.modifiers.new("Толщина", "SOLIDIFY")
    м.thickness = толщина
    м.offset = -1.0
    return ob


def палуба_прогулочная(кол):
    """Настил на крыше первого яруса. Над кожухом идёт в полную ширину:
    средняя палуба нависает над кожухом колеса — как у прототипа."""
    к = SU.кожух()
    z = G.DECKS["средняя"]
    точки = []
    for x, _ in SU.обвод("главная", шаг=ШАГ):
        полу = SU.полуширота(x, "главная", z=z - 0.01)
        if SU.в_портале(x):
            полу = L.side_half(x) - SU.КАРНИЗ - 0.02
        точки.append((x, min(полу + SU.КАРНИЗ, L.side_half(x))
                      if полу > 0.05 else 0.0))
    # вырезы: проём атриума, колодцы трапов, шахты лифтов — из gorizont_public
    from lib import gorizont_public as PB
    return _плита("Палуба_прогулочная", точки, z, кол, "Палуба_серая", вырезы=PB.колодцы("средняя"))


def палуба_солнечная(кол):
    z = G.DECKS["солнечная"]
    точки = []
    for x, _ in SU.обвод("средняя", шаг=ШАГ):
        полу = SU.полуширота(x, "средняя", z=z - 0.01)
        if полу <= 0.05:
            точки.append((x, 0.0))
            continue
        полу = min(полу + SU.КАРНИЗ, L.side_half(x))
        if SU.в_портале(x):
            полу = L.side_half(x) - 0.02          # над блоком портала — до борта
        точки.append((x, полу))
    from lib import gorizont_public as PB
    return _плита("Палуба_солнечная", точки, z, кол, "Настил_дерево", вырезы=PB.колодцы("солнечная"))


