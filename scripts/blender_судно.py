def ярус(имя, код, кол):
    """Тело яруса. Утопленные панели уже сидят в полушироте — их даёт фасад."""
    проф = SU.профиль(код)
    z0 = SU.ЯРУСЫ[код]["z0"]
    tg = math.tan(SU.ЗАВАЛ)
    кольца = []
    for x, полу in SU.обвод(код, шаг=ШАГ):
        if полу <= 0.06:
            continue
        борт = []
        for dy, z in проф:
            y = SU.полуширота(x, код, z=z)          # с завалом и утоплением
            борт.append((max(0.06, y + dy), z))
        кольца.append((x, борт + [(-y, z) for y, z in reversed(борт)]))
    return _лофт(имя, кольца, кол, МАТЕРИАЛ_ЯРУСА[код])


def _поверхность(имя, quads, кол, материал, толщина=0.02):
    """Набор четырёхугольников одной сеткой, с толщиной наружу.

    Без толщины это был бы лист с открытыми кромками: править такое руками
    нельзя, и в булевых операциях он ведёт себя как дырка. Solidify с
    offset=1 растит тело наружу от поверхности, поэтому сама поверхность
    остаётся там, где посчитана, и в ярус ничего не входит.
    """
    verts, faces = [], []
    for q in quads:
        b = len(verts)
        verts.extend(q)
        faces.append([b, b + 1, b + 2, b + 3])
    ob = _объект(имя, verts, faces, кол, материал)
    м = ob.modifiers.new("Толщина", "SOLIDIFY")
    м.thickness = толщина
    м.offset = 1.0
    return ob


def проёмы(код, кол):
    """Остекление утопленных панелей: тёмная поверхность в глубине проёма."""
    низ, верх, вынос = SU.лента(код)
    quads = []
    for x0, x1, тип, _ in F.ПАНЕЛИ[код]:
        if тип != "проём":
            continue
        xs, x = [], x0 + 0.05
        while x < x1 - 0.05:
            xs.append(x)
            x += 0.25
        xs.append(x1 - 0.05)
        for знак in (1, -1):
            for a, b in zip(xs, xs[1:]):
                ya = SU.полуширота(a, код, z=низ + 0.5) + 0.03
                yb = SU.полуширота(b, код, z=низ + 0.5) + 0.03
                if ya <= 0.1 or yb <= 0.1:
                    continue
                q = [(a, знак * ya, низ + 0.04), (b, знак * yb, низ + 0.04),
                     (b, знак * yb, верх - 0.04), (a, знак * ya, верх - 0.04)]
                quads.append(q if знак > 0 else list(reversed(q)))
    return _поверхность("Остекление_проёмов_" + код, quads, кол, "Остекление")


def окна(код, кол):
    """Каюты: сплошная лента остекления с импостами на переборках.

    Иллюминаторов и окон «в ряд» на новых речных судах нет — стекло от
    пола до потолка, разделённое только тонкими импостами шага каюты.
    """
    низ, верх, _ = SU.лента(код)
    quads, импосты = [], []
    for x0, x1, тип, _ in F.ПАНЕЛИ[код]:
        if тип != "окна":
            continue
        xs, x = [], x0 + 0.05
        while x < x1 - 0.05:
            xs.append(x)
            x += 0.25
        xs.append(x1 - 0.05)
        for знак in (1, -1):
            for a, b in zip(xs, xs[1:]):
                ya = SU.полуширота(a, код, z=низ + 0.5) + 0.012
                yb = SU.полуширота(b, код, z=низ + 0.5) + 0.012
                if ya <= 0.1 or yb <= 0.1:
                    continue
                q = [(a, знак * ya, низ + 0.02), (b, знак * yb, низ + 0.02),
                     (b, знак * yb, верх - 0.02), (a, знак * ya, верх - 0.02)]
                quads.append(q if знак > 0 else list(reversed(q)))
            for xc in F.окна(код):
                xi = xc - F.ШАГ_ОКОН / 2.0
                if not (x0 + 0.3 < xi < x1 - 0.3):
                    continue
                yc_ = SU.полуширота(xi, код, z=низ + 0.5) + 0.045
                импосты.append(_короб("_импост_%s_%.1f_%d" % (код, xi, знак),
                                      (xi, знак * yc_, 0.5 * (низ + верх)),
                                      (F.ИМПОСТ, 0.05, верх - низ - 0.04), кол, "Надстройка_серебро"))
    ob = _поверхность("Остекление_кают_" + код, quads, кол, "Остекление")
    for k, i in enumerate(импосты):
        i.name = "Импост_%s_%02d" % (код, k)
    return ob


def решётки(код, кол):
    """Жалюзи технических помещений: тёмное поле и горизонтальные ламели."""
    z0 = SU.ЯРУСЫ[код]["z0"]
    низ, верх, _ = SU.лента(код)
    поле, ламели = [], []
    for x0, x1 in F.решётки(код):
        for знак in (1, -1):
            ya = SU.полуширота(x0, код, z=низ) + 0.01
            yb = SU.полуширота(x1, код, z=низ) + 0.01
            q = [(x0, знак * ya, низ), (x1, знак * yb, низ),
                 (x1, знак * yb, верх), (x0, знак * ya, верх)]
            поле.append(q if знак > 0 else list(reversed(q)))
            z = низ + 0.10
            while z < верх - 0.06:
                yc_ = SU.полуширота(0.5 * (x0 + x1), код, z=z) + 0.035
                ламели.append(_короб("_ламель_%.0f_%.2f_%d" % (x0, z, знак),
                                     (0.5 * (x0 + x1), знак * yc_, z),
                                     (x1 - x0 - 0.20, 0.05, 0.05), кол, "Решётка"))
                z += 0.16
    _поверхность("Решётка_поле_" + код, поле, кол, "Решётка")
    return _слить("Решётка_ламели_" + код, ламели, кол, "Решётка")


