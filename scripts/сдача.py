def _ф(*части):
    return os.path.join(*части)


def _имя(файл):
    """«01_общий_вид.jpg» → «01 Общий вид.jpg», «ВГ-2026_46_00_СБ.dwg» → «ВГ-2026.46.00 СБ.dwg»."""
    осн, ext = os.path.splitext(os.path.basename(файл))
    m = re.match(r"^ВГ-2026_46_(\d\d)(.*)$", осн)
    if m:
        return "ВГ-2026.46.%s%s%s" % (m.group(1), m.group(2).replace("_", " "), ext)
    слова = осн.replace("_", " ").split(" ")
    i = 1 if слова[0][:1].isdigit() and len(слова) > 1 else 0
    слова[i] = слова[i][:1].upper() + слова[i][1:]
    return " ".join(слова) + ext


