def листы_а4(pngs, путь):
    from PIL import Image
    ims = []
    for p in pngs:
        im = Image.open(_ф(ROOT, p))
        bg = Image.new("RGB", im.size, "white")
        bg.paste(im, mask=im.split()[3] if im.mode == "RGBA" else None)
        ims.append(bg)
    dpi = ims[0].size[0] / (210.0 / 25.4)                       # ширина листа А4
    ims[0].save(путь, "PDF", resolution=dpi, save_all=True, append_images=ims[1:], quality=92,
                title=os.path.splitext(os.path.basename(путь))[0], author=КОМАНДА)


ОТЧЁТ_МКЭ = _ф("docs", "команда", "Прочность", "Отчет 20ГСЛ.html")


def отчёт_мкэ(путь):
    """Отчёт APM FEM в PDF (приложение к КЗ, п. 4). HTML программы - в cp1251 без объявления кодировки и со
    ссылками на картинки, которых у файла нет: текст и таблицы как есть, битые картинки убираются, поля -
    отдельными рисунками рядом. Печать - Chrome через Playwright."""
    from playwright.sync_api import sync_playwright
    html = open(_ф(ROOT, ОТЧЁТ_МКЭ), encoding="cp1251").read()
    html = re.sub(r"(?is)<a href=\"[^\"]*_files[^\"]*\">\s*<img[^>]*>\s*</a>", "", html)
    html = html.replace("<html>", "<html><head><meta charset=\"utf-8\"><title>Отчёт МКЭ APM FEM</title></head>", 1)
    tmp = _ф(os.path.dirname(путь), "_отчёт.html")
    open(tmp, "w", encoding="utf-8").write(html)
    try:
        with sync_playwright() as pw:
            b = pw.chromium.launch(channel="chrome", headless=True)
            стр = b.new_page()
            стр.goto("file:///" + tmp.replace(os.sep, "/"))
            стр.pdf(path=путь, format="A4", margin=dict(top="15mm", bottom="15mm", left="15mm", right="15mm"))
            b.close()
    finally:
        os.remove(tmp)
    import pypdf
    r = pypdf.PdfReader(путь)
    w = pypdf.PdfWriter()
    for s in r.pages:
        w.add_page(s)
    w.metadata = {"/Title": "Отчёт МКЭ APM FEM, узел ВГ-2026.46.00", "/Author": КОМАНДА}
    with open(путь, "wb") as f:
        w.write(f)
    return len(w.pages)


def приложение_а(путь):
    """Приложение А - страницы ПЗ с колонтитулом «Приложение А» отдельным файлом (приложение к КЗ)."""
    import pypdf
