# --- вторая модель масс: якорь на прототипе -----------------------------------
# Всё выше считает массу от построенного «Горизонта». Это оказалось неверным
# якорем: наше судно весит 31,3 т на метр, а реально существующий мелкосидящий
# колёсный ПКС-180 «Золотое кольцо» — 13,8 т/м при осадке 1,2 м. Разница в 2,3
# раза объясняется по пунктам: три закрытых яруса вместо четырёх, 17,5 км/ч
# вместо 22 (а мощность идёт как куб скорости), отсюда втрое меньше и установка,
# и запас топлива, и ширина 13,8 против 16,5.
#
# Поэтому вторая модель масштабирует не наше судно, а прототип: то, что растёт
# с габаритом (корпус, надстройка, механизмы) — по L*B, то, что растёт с числом
# людей (насыщение, снабжение, запасы) — по людям. Разделение 55/45 взято по
# типовой раскладке мелкосидящего речного пассажирского судна и является
# главным допущением этой модели: его надо подтвердить расчётом
# gorizont_struct.steel_weight() на новых обводах, и до тех пор считать
# результаты оценкой, а не числом.
ПРОТОТИП = dict(
    имя="ПКС-180 «Золотое кольцо»", L=82.0, B=13.8, T=1.20, delta=0.88,
    пассажиров=180, экипаж=56, скорость=17.5, автономность=14,
    движитель="колёсный движительно-рулевой комплекс, электромеханический привод",
)
ДОЛЯ_ГАБАРИТ, ДОЛЯ_ЛЮДИ = 0.55, 0.45
ГАРАЖ_Т = 35.0    # 4 автомобиля, аппарель, вентиляция, орошение
СПГ_ДЕЛЬТА_Т = 60.0   # переход с дизеля на СПГ при мощности колёсного судна


def водоизмещение_прототипа():
    P = ПРОТОТИП
    return (P["L"] - 4.0) * P["B"] * P["T"] * P["delta"]


def адаптация(L, B, T, ярусов, пассажиров=212, экипаж=57, delta=0.88, b_super=None):
    """Судно нашей программы, отмасштабированное от прототипа."""
    P = ПРОТОТИП
    b_super = b_super if b_super else B - 2.5
    D_прот = водоизмещение_прототипа()
    люди_прот = P["пассажиров"] + P["экипаж"]

    габарит = D_прот * ДОЛЯ_ГАБАРИТ * (L / P["L"]) * (B / P["B"])
    люди = D_прот * ДОЛЯ_ЛЮДИ * (пассажиров + экипаж) / люди_прот
    масса = габарит + люди + ГАРАЖ_Т + СПГ_ДЕЛЬТА_Т

    D_обводы = (L - 6.0) * B * T * delta
    # Первый ярус внутри корпуса короче надстройки на длину машинного отделения
    # и оконечностей; верхние ярусы — по длине надстройки.
    площадь = max(0.0, L - 50.0) * b_super + (L - 15.0) * b_super * (ярусов - 1)
    return dict(L=L, B=B, T=T, ярусов=ярусов, D_обводы=D_обводы, масса=масса,
                баланс=D_обводы - масса, площадь=площадь, погонная=масса / L,
                габарит=габарит, люди=люди)


