def посчитать(v):
    D_обводы = v["lwl"] * v["B"] * v["T"] * v["delta"]
    kL = v["L"] / L_BASE

    группы = []
    for имя, m, закон in базовые_группы():
        if закон == "L":
            m2 = m * kL
        elif закон == "корпус":
            # Масса корпуса — это обшивка с набором по периметру сечения,
            # поэтому растёт с длиной и с периметром (B + 2*высота борта),
            # а не с одной длиной: широкий корпус дороже по стали.
            m2 = m * kL * ((v["B"] + 2 * DEPTH) / (B_BASE + 2 * DEPTH))
        elif закон == "ярус":
            m2 = m * kL * (v["tiers"] / TIERS_BASE) * (v.get("b_super", B_SUPER_BASE) / B_SUPER_BASE)
        elif закон == "трассы":
            m2 = m * kL ** 0.7
        elif закон == "эу":
            m2 = m * (1.0 + 0.10 * (kL - 1.0))
        else:
            m2 = m
        группы.append([имя, m, m2])

    # диета по долям групп
    срезано = []
    for позиция in v["диета"]:
        d = ДИЕТА[позиция]
        if "доля_группы" in d:
            имя_гр, доля = d["доля_группы"]
            for g in группы:
                if g[0] == имя_гр:
                    снято = g[2] * доля
                    g[2] -= снято
                    срезано.append((позиция, снято))
                    break
        elif d.get("тонн"):
            срезано.append((позиция, d["тонн"]))

    порожнём = sum(g[2] for g in группы)

    вода, прочее = дедвейт_прочее()
    вода_факт = вода - sum(t for п, t in срезано if п == "оборотная вода")

    k_сут = v["автономность"] / 15.0
    спг = СПГ_15СУТ * k_сут * v["спг"]
    топливная = спг * (1.0 + ТАНК_К_СПГ) + ДИЗЕЛЬ_15СУТ * k_сут * (1.0 - v["спг"])

    запас = 0.03 * порожнём
    дедвейт = топливная + вода_факт + прочее + запас
    D_масса = порожнём + дедвейт

    M = (M_WAVE_BASE * (v["L"] / L_BASE) ** 2 * (v["wave"] / H_WAVE_BASE)
         * (v["B"] / B_BASE))
    W_треб = M / SIGMA_ALLOW
    W_доступный = W_BASE * (v["B"] / B_BASE)

    return dict(в=v, группы=группы, срезано=срезано, порожнём=порожнём,
                дедвейт=дедвейт, топливная=топливная, D_обводы=D_обводы,
                D_масса=D_масса, баланс=D_обводы - D_масса,
                погонная=D_масса / v["L"], M=M, W_треб=W_треб,
                W_доступный=W_доступный, W_кратность=W_треб / W_доступный)


