def таблица(шапка, строки):
    out = ["| " + " | ".join(шапка) + " |", "|" + "|".join("---" for _ in шапка) + "|"]
    for r in строки:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


