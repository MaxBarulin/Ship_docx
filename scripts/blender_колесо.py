# -*- coding: utf-8 -*-
r"""Гребные колёса с шарнирными плицами.

Геометрию задаёт `gorizont_wheel`: диаметр, ширина, число плиц, заглубление,
положение оси и ниши. Ни одного числа здесь не набрано руками — иначе модель
и расчёт упора разойдутся, и никто этого не заметит.

Что должно быть видно на рендере сразу: **плицы висят вертикально.** У
жёсткого радиального колеса плица поворачивается вместе с ободом и на
верхней точке смотрит вверх; у шарнирного она подвешена на оси и
удерживается тягой от неподвижного эксцентрика, поэтому через всю дугу
идёт почти отвесно. Это не деталь отделки — это то, за счёт чего КПД 0,70
вместо 0,60 и удар при входе 13,4 кПа вместо 40,6.

Поэтому в модели тяги и эксцентрик построены, а не намечены: на защите
первый вопрос про колесо будет «а как плица держится вертикально».

Запуск внутри Blender:
    exec(open(r"<путь>/scripts/blender_колесо.py", encoding="utf-8").read())
    построить()
"""
import bpy, math, os, sys


def _корень():
    for кандидат in (
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        if "__file__" in globals() else None,
        os.environ.get("GORIZONT_ROOT"),
        os.path.dirname(os.path.dirname(bpy.data.filepath)) if bpy.data.filepath else None,
    ):
        if кандидат and os.path.isdir(os.path.join(кандидат, "src", "lib")):
            return кандидат
    raise RuntimeError("Не найден корень репозитория; задайте GORIZONT_ROOT")


ROOT = _корень()
for путь in (os.path.join(ROOT, "src"), os.path.join(ROOT, "scripts")):
    if путь not in sys.path:
        sys.path.insert(0, путь)

from lib import gorizont as G
from lib import gorizont_wheel as W
import blender_стиль as Ст

КОЛЛЕКЦИЯ = "05_Движитель"
СЕГМЕНТОВ_ОБОДА = 48
ВЫСОТА_ПЛИЦЫ = 1.00       # радиальный размер плицы
ТОЛЩИНА_ПЛИЦЫ = 0.04
ШИРИНА_ОБОДА = 0.12
РАДИУС_СТУПИЦЫ = 0.32
#: Эксцентрик смещён от оси вниз и в нос: он и задаёт плице угол, при
#: котором она идёт отвесно. Смещение — то, что настраивают на швартовных.
ЭКСЦЕНТРИК = (-0.35, -0.25)   # смещение по x и по z от оси колеса


def _коллекция(имя):
    кол = bpy.data.collections.get(имя)
    if кол is None:
        кол = bpy.data.collections.new(имя)
        bpy.context.scene.collection.children.link(кол)
    return кол


def _объект(имя, verts, faces, коллекция):
    старый = bpy.data.objects.get(имя)
    if старый is not None:
        bpy.data.objects.remove(старый, do_unlink=True)
    меш = bpy.data.meshes.new(имя)
    меш.from_pydata(verts, [], faces)
    меш.validate(verbose=False)
    меш.update()
    об = bpy.data.objects.new(имя, меш)
    коллекция.objects.link(об)
    return об


def _короб(имя, центр, размеры, коллекция):
    """Прямоугольный короб по центру и габаритам (dx, dy, dz)."""
    cx, cy, cz = центр
    dx, dy, dz = (d / 2.0 for d in размеры)
    verts = [(cx + sx * dx, cy + sy * dy, cz + sz * dz)
             for sx in (-1, 1) for sy in (-1, 1) for sz in (-1, 1)]
    faces = [[0, 1, 3, 2], [4, 6, 7, 5], [0, 2, 6, 4],
             [1, 5, 7, 3], [0, 4, 5, 1], [2, 3, 7, 6]]
    return _объект(имя, verts, faces, коллекция)


def _цилиндр(имя, центр, радиус, длина, коллекция, сегментов=24):
    """Цилиндр вдоль поперечной оси Y — так стоит вал колеса."""
    cx, cy, cz = центр
    verts, faces = [], []
    for i in range(сегментов):
        a = 2 * math.pi * i / сегментов
        y_, z_ = радиус * math.cos(a), радиус * math.sin(a)
        verts.append((cx + y_, cy - длина / 2.0, cz + z_))
        verts.append((cx + y_, cy + длина / 2.0, cz + z_))
    for i in range(сегментов):
        a, b = 2 * i, 2 * ((i + 1) % сегментов)
        faces.append([a, a + 1, b + 1, b])
    faces.append([2 * i for i in range(сегментов)])
    faces.append([2 * i + 1 for i in range(сегментов - 1, -1, -1)])
    return _объект(имя, verts, faces, коллекция)


def _обод(имя, центр, радиус, ширина_колеса, коллекция):
    """Обод коробчатого сечения: два кольца по краям ширины колеса."""
    cx, cy, cz = центр
    verts, faces = [], []
    r_вн = радиус - ШИРИНА_ОБОДА
    for сторона in (-1, 1):
        y = cy + сторона * (ширина_колеса / 2.0 - ШИРИНА_ОБОДА / 2.0)
        база = len(verts)
        for i in range(СЕГМЕНТОВ_ОБОДА):
            a = 2 * math.pi * i / СЕГМЕНТОВ_ОБОДА
            c, s = math.cos(a), math.sin(a)
            for r in (радиус, r_вн):
                for dy in (-ШИРИНА_ОБОДА / 2.0, ШИРИНА_ОБОДА / 2.0):
                    verts.append((cx + r * c, y + dy, cz + r * s))
        for i in range(СЕГМЕНТОВ_ОБОДА):
            a = база + 4 * i
            b = база + 4 * ((i + 1) % СЕГМЕНТОВ_ОБОДА)
            faces += [[a, a + 1, b + 1, b], [a + 2, b + 2, b + 3, a + 3],
                      [a, b, b + 2, a + 2], [a + 1, a + 3, b + 3, b + 1]]
    return _объект(имя, verts, faces, коллекция)


def колесо(сторона, коллекция=None):
    """Одно колесо: обод, спицы, ступица, вал, плицы, тяги, эксцентрик.

    `сторона` — +1 правый борт, -1 левый.
    """
    кол = коллекция or _коллекция(КОЛЛЕКЦИЯ)
    н = W.niche_geometry()
    R = W.DIAMETER / 2.0
    R_ось = R - ВЫСОТА_ПЛИЦЫ                  # радиус, на котором висят оси плиц
    x = W.X_AXIS
    y = сторона * (н["y_внутренняя_кромка"] + W.WIDTH / 2.0)
    z = W.axis_height(G.DRAFT)
    б = "ПБ" if сторона > 0 else "ЛБ"
    центр = (x, y, z)

    обод = _обод("Колесо_%s_обод" % б, центр, R_ось, W.WIDTH, кол)
    Ст.назначить(обод, "Колесо_обод")

    ступица = _цилиндр("Колесо_%s_ступица" % б, центр, РАДИУС_СТУПИЦЫ,
                       W.WIDTH * 0.7, кол)
    Ст.назначить(ступица, "Колесо_обод")
    вал = _цилиндр("Колесо_%s_вал" % б, (x, y - сторона * W.WIDTH * 0.8, z),
                   0.18, W.WIDTH * 0.9, кол)
    Ст.назначить(вал, "Колесо_обод")

    экс_x, экс_z = x + ЭКСЦЕНТРИК[0], z + ЭКСЦЕНТРИК[1]
    эксцентрик = _цилиндр("Колесо_%s_эксцентрик" % б, (экс_x, y, экс_z),
                          0.22, W.WIDTH * 0.75, кол)
    Ст.назначить(эксцентрик, "Колесо_обод")

    части = [обод, ступица, вал, эксцентрик]
    for i in range(W.BLADES):
        a = 2 * math.pi * i / W.BLADES
        px, pz = x + R_ось * math.cos(a), z + R_ось * math.sin(a)

        # Спица от ступицы к оси плицы
        спица = _короб("Колесо_%s_спица_%02d" % (б, i),
                       ((x + px) / 2.0, y, (z + pz) / 2.0),
                       (0.10, W.WIDTH * 0.9, 0.10), кол)
        спица.rotation_euler = (0.0, -a, 0.0)
        Ст.назначить(спица, "Колесо_обод")

        # Плица висит ОТВЕСНО от своей оси — в этом весь смысл шарнира.
        # Поворота по углу дуги у неё нет, и на рендере это видно.
        плица = _короб("Колесо_%s_плица_%02d" % (б, i),
                       (px, y, pz - ВЫСОТА_ПЛИЦЫ / 2.0),
                       (ТОЛЩИНА_ПЛИЦЫ, W.WIDTH, ВЫСОТА_ПЛИЦЫ), кол)
        Ст.назначить(плица, "Колесо_плица")

        # Тяга от кронштейна плицы к эксцентрику — то, что и держит угол
        тx, тz = px + 0.25, pz - 0.30
        dx, dz = экс_x - тx, экс_z - тz
        длина = math.hypot(dx, dz)
        тяга = _короб("Колесо_%s_тяга_%02d" % (б, i),
                      ((тx + экс_x) / 2.0, y, (тz + экс_z) / 2.0),
                      (длина, 0.05, 0.05), кол)
        тяга.rotation_euler = (0.0, -math.atan2(dz, dx), 0.0)
        Ст.назначить(тяга, "Леера_сталь")

        части += [спица, плица, тяга]

    # Кожух. Колесо выходит над главной палубой на 2,15 м, опустить его
    # нельзя: заглубление плицы задано, диаметр задан упором. Кожух ловит
    # воду, которую плица уносит вверх, и закрывает вращающиеся части.
    к = W.paddle_box(G.DRAFT, G.DECKS["главная"], G.DECKS["средняя"])
    кожух = _короб("Кожух_колеса_%s" % б,
                   (x, y, G.DECKS["главная"] + к["высота_кожуха"] / 2.0),
                   (к["длина"], к["ширина"], к["высота_кожуха"]), кол)
    мод = кожух.modifiers.new(name="Скругление", type="BEVEL")
    мод.width = 0.35          # плавная пластика по дизайн-системе
    мод.segments = 8
    мод.limit_method = "ANGLE"
    Ст.назначить(кожух, "Надстройка_белая")
    части.append(кожух)
    return части


def построить():
    """Оба колеса и сводка по режиму."""
    Ст.построить()
    кол = _коллекция(КОЛЛЕКЦИЯ)
    for сторона in (1, -1):
        колесо(сторона, кол)
    н = W.niche_geometry()
    р = W.summary()["режим"]
    print("Колёса построены: ⌀%.2f x %.2f м, %d шарнирных плиц"
          % (W.DIAMETER, W.WIDTH, W.BLADES))
    print("   ось на x = %.1f м, z = %.2f м, борт y = ±%.2f м"
          % (W.X_AXIS, W.axis_height(G.DRAFT),
             н["y_внутренняя_кромка"] + W.WIDTH / 2.0))
    print("   габарит с колёсами %.2f м при корпусе %.2f"
          % (н["габарит_с_колёсами"], W.HULL_BEAM))
    print("   режим %.1f км/ч: %.1f об/мин, КПД %.2f, %.0f кВт на два колеса"
          % (р["v_kmh"], р["об_мин"], р["кпд"], р["P_всего"]))
    к = W.paddle_box(G.DRAFT, G.DECKS["главная"], G.DECKS["средняя"])
    print("   кожух %.1f x %.1f x %.2f м, верх колеса на %.2f м от основной"
          % (к["длина"], к["ширина"], к["высота_кожуха"], к["верх_колеса"]))


if __name__ == "__main__":
    построить()
