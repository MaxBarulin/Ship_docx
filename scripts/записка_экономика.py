def _млн(x, nd=1):
    return ч(x / 1e6, nd)


def _мн(n, одна, две, пять):
    """Слово в числе по-русски: 1 день, 3 дня, 5 дней, 21 день."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return одна
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return две
    return пять


def _задача_имя(t):
    """Название задачи дорожной карты без номера - номер 3.2 в таблице стал бы десятичной дробью."""
    import re
    return re.sub(r"^\d+(\.\d+)*\.\s*", "", t["задача"])


def _п(x, nd=1):
    """Процент с запятой, без лишнего нуля."""
    s = ч(x, nd)
    return s[:-2] if s.endswith(",0") else s


