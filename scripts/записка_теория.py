def _непотопляемость():
    т = ["\n### А.4 Непотопляемость\n"]
    т.append("Корпус разделён %d водонепроницаемыми переборками на %d "
             "отсеков. Проверяется затопление каждого отсека в отдельности "
             "при коэффициенте проницаемости 0,85.\n"
             % (len(H.BULKHEADS) - 2, len(H.COMPARTMENTS)))
