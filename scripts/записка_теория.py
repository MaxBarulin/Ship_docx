_ТАБ_А = [0]


def _таб(шапка, строки, имя=None):
    """Таблица приложения с номером над ней слева: «Таблица А.N»."""
    _ТАБ_А[0] += 1
    out = ["Таблица А.%d%s\n" % (_ТАБ_А[0], " - " + имя if имя else ""),
           "| " + " | ".join(шапка) + " |",
           "|" + "|".join("---" for _ in шапка) + "|"]
    for r in строки:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


