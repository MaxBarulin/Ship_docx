def _запятая_в_прозе(текст, таблицы=False):
    """Десятичная запятая в тексте: «15.51 м» -> «15,51 м». Таблицы записки переводит
    её сборка, поэтому по умолчанию строки таблиц не трогаются."""
    out = []
    for s in текст.split("\n"):
        if таблицы or not s.lstrip().startswith("|"):
            # даты, «09.2028» и обозначения вроде ВГ-2026.46.00 не трогать - как в сборке записки
            защита = []

            def _prot(m):
                защита.append(m.group(0))
                return "\x00%d\x00" % (len(защита) - 1)
            s = re.sub(r"\b\d{1,2}\.\d{2}\.\d{4}\b|\b\d{2}\.\d{4}\b|\b\d+(?:\.\d+){2,}\b", _prot, s)
            s = re.sub(r"(?<=\d)\.(?=\d)", ",", s)
            s = re.sub(r"\x00(\d+)\x00", lambda m: защита[int(m.group(1))], s)
        out.append(s)
    return "\n".join(out)


