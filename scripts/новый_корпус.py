# -*- coding: utf-8 -*-
"""Обводы мелкосидящего колёсного корпуса 128 x 16,5 x 1,20 м.

Шаг 1 плана перехода на ПКС-180 (docs/проект/переход_на_ПКС180.md):
построить обводы и получить настоящую массу корпуса вместо двух
расходящихся оценок.

Корпус задаётся не таблицей ординат, а распределениями по длине — высотой
килевой линии, полуширотой днища, полуширотой по борту и развалом борта.
Таблица ординат из них генерируется той же геометрией сечения, что и у
построенного судна: плоское днище, скуловая дуга, касательная к днищу и
борту, прямой борт с развалом. Поэтому новые обводы можно считать тем же
`gorizont_hydro`, не переписывая в нём ни строки: модуль берёт обводы из
`gorizont.OFFSETS`, и мы их туда подменяем до импорта.

Что изменилось против построенного судна и почему:

  * высота борта 3,00 м вместо 4,20. При осадке 1,20 м надводный борт
    1,80 м — этого хватает по классу «О», а лишняя высота это лишняя сталь
    и лишний момент сопротивления, который здесь не нужен;
  * внутри корпуса один ярус помещений вместо двух. Настил на 0,90 м
    (крыша двойного дна), подволок на 3,00 — чистая высота 2,10;
  * цилиндрическая вставка длиннее: колёса стоят в бортовых нишах, гребных
    валов нет, и кормовая оконечность не обязана сужаться под винты. Это
    прямо даёт полноту, а полнота при малой осадке и есть водоизмещение;
  * ниши колёс вырезаны в борту и в обводы не входят: они уменьшают
    водоизмещение и это учтено отдельной поправкой, а не забыто.

    python scripts/новый_корпус.py            # отчёт
    python scripts/новый_корпус.py --таблица  # плюс плазовая таблица
"""
import os, sys, math

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))

from lib import gorizont as G
from lib import gorizont_lines as L
from lib import gorizont_hydro as H
from lib import gorizont_struct as S
from lib import gorizont_strength as St
from lib import gorizont_wheel as W

LOA, BEAM, DEPTH, DRAFT = G.LOA, G.BEAM, G.DEPTH, G.DRAFT
WATERLINES = G.WATERLINES
build = L.build


def объём_ниш(T):
    """Подводный объём двух ниш колёс, м3 — вычитается из водоизмещения."""
    return W.niche_buoyancy(T)["объём"]


def отчёт(таблица=False):
    print("Новый корпус: %.1f x %.1f м, высота борта %.2f, осадка %.2f\n"
          % (LOA, BEAM, DEPTH, DRAFT))
    print("%6s %9s %8s %8s %8s %8s %8s"
          % ("T", "D брутто", "ниши", "D нетто", "delta", "Aw", "Lвл"))
    for T in (1.00, 1.10, 1.20, 1.30, 1.50, 1.80):
        h = H.hydrostatics(T)
        ниши = объём_ниш(T)
        print("%6.2f %9.0f %8.0f %8.0f %8.3f %8.0f %8.1f"
              % (T, h["D"], ниши, h["D"] - ниши, h["delta"], h["Aw"], h["Lw"]))

    h = H.hydrostatics(DRAFT)
    print("\nНа расчётной осадке %.2f м: водоизмещение %.0f т, полнота %.3f"
          % (DRAFT, h["D"] - объём_ниш(DRAFT), h["delta"]))
    print("Площадь ватерлинии %.0f м2, смоченная поверхность %.0f м2"
          % (h["Aw"], h["S"]))
    print("Аппликата центра величины %.2f м, метацентрический радиус %.2f м"
          % (h["zc"], h["r"]))

    ст = S.steel_weight()
    print("\nМасса корпусной стали по связям: %.0f т, центр тяжести %.2f м" % (ст["m"], ст["z"]))
    for i in sorted(ст["items"], key=lambda i: -i["m"])[:8]:
        print("   %-46s %6.1f т" % (i["name"], i["m"]))

    r = St.stresses()
    print("\nПродольная прочность, класс «%s», допускаемое %.0f МПа:"
          % (G.RRR_CLASS, r["sigma_allow"]))
    for row in r["rows"]:
        print("   %-12s палуба %6.1f  днище %6.1f  %s"
              % (row["condition"], row["sigma_deck"], row["sigma_bot"],
                 "ок" if row["ok"] else "НЕ ПРОХОДИТ"))

    ws = H.weight_summary()
    eq = H.equilibrium()
    print("\nНагрузка масс: порожнём %.0f т, дедвейт %.0f т, полное %.0f т"
          % (ws["lightship"], ws["deadweight"], ws["D"]))
    print("Осадка равновесия %.2f м при расчётной %.2f — %s"
          % (eq["T"], DRAFT,
             "сходится" if abs(eq["T"] - DRAFT) < 0.05
             else "надо снять %.0f т" % (ws["D"] - H.hydrostatics(DRAFT)["D"])))

    if таблица:
        print("\nПлазовая таблица, мм от ДП (прочерк — ватерлиния ниже киля):")
        print("%5s %7s" % ("шп.", "x") + "".join("%7.2f" % z for z in WATERLINES))
        for n, x, zk, bk, zb, bb, ys in build()[0]:
            s = "%5s %7.2f" % (n, x)
            s += "".join("      -" if y is None else "%7.0f" % (y * 1000) for y in ys)
            print(s)


if __name__ == "__main__":
    отчёт("--таблица" in sys.argv)
