def рисунки_мкэ():
    """Картинки полей МКЭ для записок - без дерева модели и окна параметров КОМПАС, по контуру модели со шкалой.
    Поля, шкалы и метки MIN/MAX - как в отчёте. Пути к рисункам от корня проекта."""
    from PIL import Image
    пути = []
    for исх, имя, _ in МКЭ_РИСУНКИ:
        src = os.path.join(ROOT, "docs", "команда", "Прочность", исх)
        dst = os.path.join(ROOT, "renders", "горизонт_2026", "узел", имя)
        пути.append("renders/горизонт_2026/узел/" + имя)
        if os.path.exists(dst) and os.path.getmtime(dst) >= os.path.getmtime(src):
            continue
        im = Image.open(src).convert("RGB")
        px, (W, H) = im.load(), im.size

        def залить(x0, y0, x1, y1, xs):        # фон КОМПАС - вертикальный градиент: строка цветом фона слева
            for y in range(max(0, y0), min(H, y1)):
                c = px[xs, y]
                for x in range(max(0, x0), min(W, x1)):
                    px[x, y] = c
        залить(0, 0, 335, 225, 340)                                  # дерево модели
        залить(590, 0, 1300, 9, 580)                                 # обрывок панели инструментов сверху
        # окно «Параметры отображения» с тенью - сплошь светлые столбцы и строки (светлый логотип шкалы - узкий, не входит)
        светлые = im.crop((1500, 0, W, 380)).convert("L").point(lambda v: 1 if v >= 238 else 0)
        сw, сh = светлые.size
        с = светлые.load()
        столбцы = [x for x in range(сw) if sum(с[x, y] for y in range(сh)) > 150]
        группа = столбцы[:1]                        # первая группа с разрывами до 5 px (рамки внутри окна) - окно, не рамка шкалы
        for x in столбцы[1:]:
            if x - группа[-1] > 5:
                break
            группа.append(x)
        столбцы = группа
        if столбцы:
            x0, x1 = 1500 + столбцы[0], 1500 + столбцы[-1] + 1
            строки = [y for y in range(сh) if sum(с[x - 1500, y] for x in range(x0, x1)) > 0.3 * (x1 - x0)]
            серый = im.convert("L").load()
            ym = (строки[0] + строки[-1]) // 2
            шкала = next((x for x in range(x1, W - 1) if серый[x, ym] >= 248 and серый[x + 1, ym] < 40), x1 + 16)
            for y in range(max(0, строки[0] - 14), min(H, строки[-1] + 26)):
                c = px[x0 - 20, y]
                for x in range(x0 - 14, шкала):                     # правее рамки окна - только тень, тёмный текст шкалы цел
                    if x <= x1 + 2 or серый[x, y] >= 140:
                        px[x, y] = c
        поле = im.crop((0, 10, W, H)).convert("HSV").split()[1].point(lambda v: 255 if v > 70 else 0).getbbox()
        низ = 10 + поле[3] + 25 if поле else H
        tmp = dst + ".tmp.png"
        im.crop((max(0, (поле[0] if поле else 0) - 25), 0, W, min(H, низ))).save(tmp)
        os.replace(tmp, dst)
    return пути


def запятая(текст):
    """Десятичная запятая в строках таблиц. Обозначения, стандарты и даты не трогаются."""
    import re
    out = []
    for строка in текст.split("\n"):
        if строка.startswith("|"):
            защита = []

            def _prot(m):
                защита.append(m.group(0))
                return "\x00%d\x00" % (len(защита) - 1)
            строка = re.sub(r"задача [\d.]+\d|ВГ-\d+(?:\.\d+)+|ГОСТ(?: Р)?(?: ИСО)? \d+(?:\.\d+)+|\b\d{1,2}\.\d{2}\.\d{4}\b|\b\d+(?:\.\d+){2,}\b",
                            _prot, строка)
            строка = re.sub(r"(?<=\d)\.(?=\d)", ",", строка)
            строка = re.sub(r"\x00(\d+)\x00", lambda m: защита[int(m.group(1))], строка)
        out.append(строка)
    return "\n".join(out)


