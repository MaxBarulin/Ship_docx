def ф(x, nd=0):
    return (("%." + str(nd) + "f") % x).replace(".", ",")


def руб(x):
    return "{:,}".format(int(round(x))).replace(",", " ")


def знач(v):
    """Значение проверки для таблицы - числа с запятой."""
    if isinstance(v, float):
        return ("%.3f" % v).rstrip("0").rstrip(".").replace(".", ",")
    return str(v)


def таблица(шапка, строки):
    out = ["| " + " | ".join(шапка) + " |", "|" + "---|" * len(шапка)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in строки]
    return "\n".join(out)


def рис(путь, подпись):
    return "![%s](../../%s)\n\n*%s*" % (подпись, путь, подпись)


