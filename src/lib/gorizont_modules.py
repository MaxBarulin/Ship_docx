def checks():
    out = []

    def c(name, value, allow, unit, ok, note):
        out.append(dict(name=name, value=value, allow=allow, unit=unit, ok=bool(ok), note=note))

    сл = слоты()
    c("Слотов на двух площадках", len(сл), 12, "шт", len(сл) >= 12,
      "А - %d, Б - %d, фундаментов %d" % (sum(1 for s in сл if s["площадка"] == "А"), sum(1 for s in сл if s["площадка"] == "Б"), len(фундаменты())))
    п = проходы()
    c("Проход между рядами и у борта", min(п["между_рядами"], п["у_борта"]), ПРОХОД, "м", min(п["между_рядами"], п["у_борта"]) >= ПРОХОД,
      "три ряда на ширине %.2f м - между рядами %.2f, у борта %.2f, торцевой %.1f" % (п["ширина_настила"], п["между_рядами"], п["у_борта"], п["торцевой"]))
    свободно = G.module_clearance()["свободно"]
    c("Один ярус под мостом", round(КОНТЕЙНЕР["высота"] + G.MODULES["фундамент"], 2), свободно, "м",
      КОНТЕЙНЕР["высота"] + G.MODULES["фундамент"] <= свободно, "второй ярус не проходит - %.1f > %.1f" % (2 * КОНТЕЙНЕР["высота"] + G.MODULES["фундамент"], свободно))
    б = D.бюджет_массы()
    c("Предел массы по заданию против запаса по осадке", ЗАПАС_ГЛЕБА_Т, б["до_расчётной_т"], "т", ЗАПАС_ГЛЕБА_Т <= б["до_расчётной_т"],
      "85 т задания не выходят за %d т до расчётной осадки %.2f" % (б["до_расчётной_т"], G.DRAFT))
    for имя in ПОРЯДОК_ТЕМ:
        т = проверка_темы(имя)
        ok = т["в_запасе_глеба"] and т["в_расчётной_осадке"] and not т["ррр"] and т["хватает_мощности"] and т["симметрия_ок"] and т["в_SWL"]
        c("Тема «%s»" % имя, т["масса"], ЗАПАС_ГЛЕБА_Т, "т", ok,
          "%d мод., T %.3f, K %.1f, %.0f кВт из %.0f на стоянке, y ЦТ %.2f, опора - сжатие %.0f, отрыв %.0f кН" % (
              т["модулей"], т["осадка"], т["K"], т["мощность"], т["резерв_стоянка"], т["y_цт"], т["фитинг_кН"], т["отрыв_кН"]))
    T = _T()
    тк = T.checks()
    плохие = [x["name"] for x in тк if not x["ok"]]
    c("Узел крепления %s - проверки" % T.MARK, len(плохие), 0, "шт", not плохие,
      "%d проверок узла (качка, прочность, отливка, мощности, сроки), SWL опоры - сжатие %.0f, отрыв %.0f, сдвиг %.0f кН" % (
          len(тк), T.нагрузки()["SWL"]["сжатие"], T.нагрузки()["SWL"]["отрыв"], T.нагрузки()["SWL"]["сдвиг"]) + (", не прошло - " + ", ".join(плохие) if плохие else ""))
    return out


