def тема(имя):
    """Состав темы - модули по слотам, масса, мощность, среды, ЦТ, парусность."""
    т = ТЕМЫ[имя]
    сл = {s["слот"]: s for s in слоты()}
    строки, масса, мощность, xm, вода, стоки = [], 0.0, 0.0, 0.0, 0, 0
    for слот, тип in sorted(т["модули"].items()):
        if слот not in сл:
            raise KeyError("слота %s нет в сетке" % слот)
        м = МОДУЛИ[тип]
        строки.append(dict(слот=слот, тип=тип, масса=м["масса"], мощность=м["мощность"], вода=м["вода"], стоки=м["стоки"],
                           x=сл[слот]["xc"], y=сл[слот]["yc"]))
        масса += м["масса"]; мощность += м["мощность"]; xm += м["масса"] * сл[слот]["xc"]
        вода += 1 if м["вода"] else 0
        стоки += 1 if м["стоки"] else 0
    n = len(строки)
    x_цт = xm / масса if масса else D.H.equilibrium()["hydro"]["xf"]
    y_цт = sum(r["масса"] * r["y"] for r in строки) / масса if масса else 0.0
    парус = n * КОНТЕЙНЕР["длина"] * КОНТЕЙНЕР["высота"]
    return dict(имя=имя, описание=т["описание"], модули=строки, модулей=n, масса=round(масса, 1), мощность=round(мощность, 1),
                с_водой=вода, со_стоками=стоки, x_цт=round(x_цт, 1), y_цт=round(y_цт, 2), парусность=round(парус, 0))


def резерв_мощности(режим="стоянка"):
    """Резерв электростанции в режиме, кВт - столько могут брать модули."""
    r = next(r for r in P.table() if r["key"] == режим)
    return round(r["spare"], 0)


def проверка_темы(имя):
    """Тема с посадкой, остойчивостью, энергетикой и нагрузкой на фундамент (кэш на процесс)."""
    if имя in _ТЕМЫ:
        return _ТЕМЫ[имя]
    т = тема(имя)
    if т["модулей"]:
        h = D.с_нагрузкой(т["масса"], т["x_цт"], парусность_м2=т["парусность"], высота_парус=КОНТЕЙНЕР["высота"])
    else:
        h = D.с_нагрузкой(0.0, D.H.equilibrium()["hydro"]["xf"])
    тяж = max((МОДУЛИ[m["тип"]]["масса"] for m in т["модули"]), default=0.0)
    ф = расчёт_фундамента(тяж) if тяж else None
    SWL = _T().нагрузки()["SWL"]
    рез_ст, рез_мел = резерв_мощности("стоянка"), резерв_мощности("мелководье")
    т.update(осадка=h["T"], дифферент=h["дифферент"], K=h["K"], h=h["h"], крен_ветер=h["крен_ветер"], ррр=h["ррр_не_прошло"],
             в_запасе_глеба=т["масса"] <= ЗАПАС_ГЛЕБА_Т, в_расчётной_осадке=h["T"] <= G.DRAFT + 1e-6,
             резерв_стоянка=рез_ст, резерв_мелководье=рез_мел, хватает_мощности=т["мощность"] <= рез_ст,
             от_батареи_ч=round(0.8 * G.BATTERY_KWH / т["мощность"], 1) if т["мощность"] else None,
             фитинг_кН=ф["сжатие_кН"] if ф else 0.0, отрыв_кН=ф["отрыв_кН"] if ф else 0.0,
             в_SWL=(not ф) or (ф["сжатие_кН"] <= SWL["сжатие"] and ф["отрыв_кН"] <= SWL["отрыв"]),
             симметрия_ок=abs(т["y_цт"]) <= 0.6,
             высота_ок=КОНТЕЙНЕР["высота"] + G.MODULES["фундамент"] <= G.module_clearance()["свободно"])
    _ТЕМЫ[имя] = т
    return т


