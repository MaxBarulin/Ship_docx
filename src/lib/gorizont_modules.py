def слоты():
    """Сетка слотов - центр, углы, четыре фундамента, розетка коммуникаций."""
    global _СЛОТЫ
    if _СЛОТЫ is not None:
        return _СЛОТЫ
    out = []
    L, B = КОНТЕЙНЕР["длина"], КОНТЕЙНЕР["ширина"]
    for пл in ПЛОЩАДКИ:
        длина = пл["x1"] - пл["x0"]
        n = int((длина - ЗАЗОР_ВДОЛЬ) // (L + ЗАЗОР_ВДОЛЬ))
        поле = n * L + (n - 1) * ЗАЗОР_ВДОЛЬ
        x_start = пл["x0"] + (длина - поле) / 2.0
        for i in range(n):
            xc = x_start + i * (L + ЗАЗОР_ВДОЛЬ) + L / 2.0
            for yc in пл["ряды"]:
                имя = "%s-%d-%s" % (пл["имя"], i + 1, РЯДЫ_ИМЕНА[yc])
                фунд = [(round(xc + sx * КОНТЕЙНЕР["фитинги_x"] / 2.0, 3), round(yc + sy * КОНТЕЙНЕР["фитинги_y"] / 2.0, 3))
                        for sx in (-1, 1) for sy in (-1, 1)]
                out.append(dict(слот=имя, площадка=пл["имя"], вдоль=i + 1, ряд=РЯДЫ_ИМЕНА[yc], xc=round(xc, 3), yc=yc,
                                x0=round(xc - L / 2.0, 3), x1=round(xc + L / 2.0, 3), y0=round(yc - B / 2.0, 3), y1=round(yc + B / 2.0, 3),
                                фундаменты=фунд, розетка=(round(xc - L / 2.0 - 0.45, 3), round(yc, 3))))
    _СЛОТЫ = out
    return out


def фундаменты():
    """Все фундаменты twistlock на палубе - (№, слот, угол, x, y)."""
    out = []
    k = 0
    for s in слоты():
        for j, (x, y) in enumerate(s["фундаменты"], 1):
            k += 1
            out.append(dict(номер=k, слот=s["слот"], угол=j, x=x, y=y, шпангоут=round(x / S.SPACING, 1)))
    return out


