def расчёт_фундамента(масса_модуля=None, y_c=None, x_c=None, случай="эксплуатация"):
    """Нагрузка на одну опору фундамента от модуля (по умолчанию - самый тяжёлый каталога) при качке судна."""
    T = _T()
    m = масса_модуля if масса_модуля is not None else max(МОДУЛИ[k]["масса"] for k in ПОРЯДОК_МОДУЛЕЙ)
    ys = [y_c] if y_c is not None else sorted({s["yc"] for s in слоты()})
    r = max((T.реакции(m, y, x_c, случай) for y in ys), key=lambda r: (r["отрыв"], r["сжатие"]))
    м = T.массы()
    return dict(модуль_т=m, сжатие_кН=round(r["сжатие"], 1), отрыв_кН=round(r["отрыв"], 1), сдвиг_кН=round(r["сдвиг"], 1),
                SWL=T.нагрузки()["SWL"], масса_фундамента_кг=м["узел_с_листом"], фундаментов=len(фундаменты()))


