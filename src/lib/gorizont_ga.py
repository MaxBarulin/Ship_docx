ACCESSIBLE_BUILT = {"бизнес": 4, "люкс": 2, "стандарт": 2}

CREW_TYPES = {"экипаж_1": dict(width=2.0, depth=3.0, area=6.0, berths=1),
              "экипаж_2": dict(width=3.0, depth=3.0, area=9.0, berths=2)}

# Спасательные средства: (x центра, длина, вместимость) — по одному набору на борт
BOATS = [(44.60, 8.6, 100), (53.40, 8.0, 100), (94.10, 7.0, 70)]
BOAT_SPONSON_Y = 8.15           # внутри габаритной ширины 16.5
MUSTER_STATIONS = 4


def cabin_counts():
    n = {}
    for deck, mix in BUILT_CABINS.items():
        for cat, cnt in mix.items():
            n[cat] = n.get(cat, 0) + cnt
    return n


def passenger_cabins():
    return sum(c for k, c in cabin_counts().items() if k in G.CABIN_TYPES)


def passengers():
    return sum(c * G.CABIN_TYPES[k]["berths"]
               for k, c in cabin_counts().items() if k in G.CABIN_TYPES)


def crew_cabins():
    return sum(c for k, c in cabin_counts().items() if k in CREW_TYPES)


def crew():
    return sum(c * CREW_TYPES[k]["berths"]
               for k, c in cabin_counts().items() if k in CREW_TYPES)


def boat_capacity_per_side():
    return sum(b[2] for b in BOATS)


def people_on_board():
    return passengers() + crew()


def zone_length_check():
    out = {}
    for deck, zones in DECKS.items():
        out[deck] = dict(start=round(min(z[0] for z in zones), 1),
                         end=round(max(z[1] for z in zones), 1),
                         zones=len(zones))
    return out


def compare():
    """Таблица «по описанию / в модели / разница» по площадям помещений."""
    rows = []
    for deck, zones in DECKS.items():
        for x0, x1, kind, name, spec, built in zones:
            if spec is None or built is None:
                continue
            rows.append(dict(deck=deck, name=name, spec=spec, built=built,
                             delta=round(built - spec, 1),
                             pct=round(100.0 * (built - spec) / spec, 1)))
    return rows


def summary():
    return dict(
        pass_cabins=passenger_cabins(), passengers=passengers(),
        crew_cabins=crew_cabins(), crew=crew(),
        onboard=people_on_board(),
        boats_per_side=boat_capacity_per_side(),
        accessible=sum(ACCESSIBLE_BUILT.values()),
        decks_closed=4, roof=ROOF4,
    )
