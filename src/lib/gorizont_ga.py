def глубина_внутренней(палуба, x):
    """Глубина внутренней каюты: что остаётся от полуширины после бортовой и коридора."""
    return round(ширина_в_свету(палуба, x) / 2.0 - ГЛУБИНА_БОРТ - КОРИДОР, 2)


def расстановка():
    """Разложить каюты по рядам. Возвращает список кают с координатами."""
    каюты = []
    for палуба, x0, x1, ряд, посл in РЯДЫ:
        разрывы = [(a, b) for п, р, a, b in РАЗРЫВЫ if п == палуба and р == ряд]
        for борт in (1, -1):
            x, i = x0, 0
            while True:
                тип = посл[i % len(посл)]
                к = КАЮТЫ[тип]
                ф = к["фронт"]
                # перескочить разрыв
                for a, b in разрывы:
                    if x < b and x + ф > a:
                        x = max(x, b)
                if x + ф > x1 + 1e-6:
                    break
                # Наружная граница — по самому узкому сечению каюты (ярус к носу и
                # корме сужается) и на высоте 2,2 м (завал борта): иначе носовой
                # угол каюты или верх шкафа оказывается снаружи обшивки.
                ярус = "главная" if палуба == "главная" else "средняя"
                yб = min(SU.полуширота(xx, ярус, z=G.DECKS[палуба] + 2.2)
                         for xx in (x, x + ф / 2.0, x + ф)) - G.LINING / 2.0
                глубина = к["глубина"] or min(глубина_внутренней(палуба, xx) for xx in (x, x + ф))
                if ряд == "борт":
                    y0, y1 = yб - глубина, yб
                else:
                    y0, y1 = 0.0, глубина
                каюты.append(dict(тип=тип, категория=к["категория"], палуба=палуба, ряд=ряд,
                                  борт="ПБ" if борт > 0 else "ЛБ",
                                  x0=round(x, 2), x1=round(x + ф, 2),
                                  y0=round(борт * y0, 2), y1=round(борт * y1, 2),
                                  площадь=round(ф * глубина, 1), мест=к["мест"],
                                  М4=bool(к.get("М4")), окно=k_окно(к)))
                x += ф
                i += 1
    return каюты


def k_окно(к):
    return bool(к["окно"])


def итоги():
    """Сколько чего получилось. Это и есть вместимость судна."""
    кк = расстановка()
    пасс = [c for c in кк if c["категория"] != "экипаж"]
    эк = [c for c in кк if c["категория"] == "экипаж"]
    по_кат = {}
    for c in пасс:
        d = по_кат.setdefault(c["категория"], dict(кают=0, мест=0, площадь_мин=1e9))
        d["кают"] += 1
        d["мест"] += c["мест"]
        d["площадь_мин"] = min(d["площадь_мин"], c["площадь"])
    return dict(
        пассажирских_кают=len(пасс), пассажиров=sum(c["мест"] for c in пасс),
        кают_М4=sum(1 for c in пасс if c["М4"]), мест_М4=sum(c["мест"] for c in пасс if c["М4"]),
        кают_экипажа=len(эк), мест_экипажа=sum(c["мест"] for c in эк),
        по_категориям=по_кат,
        площадь_кают_мин=round(min(c["площадь"] for c in пасс), 1),
    )


def площадь_зоны(палуба, x0, x1, шаг=0.5):
    """Площадь зоны интегралом полушироты по длине."""
    ярус = "главная" if палуба in ("главная", "трюм", "второе дно") else "средняя"
    s, x = 0.0, x0
    while x < x1:
        xm = x + шаг / 2.0
        if палуба in ("трюм", "второе дно"):
            полу = L.side_half(xm) - 0.2
        else:
            полу = SU.полуширота(xm, ярус, z=G.DECKS.get(палуба, G.DECKS["солнечная"]) + 0.6)
        s += 2.0 * max(полу, 0.0) * шаг
        x += шаг
    return round(s, 1)


def зоны_с_площадями():
    вых = {}
    for палуба, список in ЗОНЫ.items():
        вых[палуба] = [dict(x0=x0, x1=x1, тип=т, имя=и, примечание=п,
                            площадь=площадь_зоны(палуба, x0, x1))
                       for x0, x1, т, и, п in список]
    return вых


