def cabin_total():
    n = {}
    for deck, mix in CABIN_MIX.items():
        for cat, cnt in mix.items():
            n[cat] = n.get(cat, 0) + cnt
    return n


def berths():
    return sum(c * CABIN_TYPES[k]["berths"] for k, c in cabin_total().items())


def transverse_check():
    used = 2 * (CABIN_DEPTH + CORRIDOR) + CENTRE_BLOCK + 0.5
    return {"used": round(used, 2), "available": SUPER_BEAM,
            "fits": abs(used - SUPER_BEAM) < 0.05}


def lux_transverse_check():
    used = 2 * (LUX_BALCONY + LUX_DEPTH) + 1.5 + 0.5
    return {"used": round(used, 2), "available": SUPER_BEAM,
            "fits": used <= SUPER_BEAM}
