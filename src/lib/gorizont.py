def actual_draft():
    """Осадка, на которой судно реально сидит по нагрузке масс.

    DRAFT — расчётная осадка, под которую построены обводы и колесо;
    фактическая считается гидростатикой из массы. Проверять требования надо
    по фактической, иначе проверка сходится на бумаге и расходится в воде.
    """
    from . import gorizont_hydro as _H
    return _H.equilibrium().get("T", DRAFT)


def under_keel(draft=None):
    """Запас воды под килём на расчётном фарватере, стоя."""
    return FAIRWAY_DEPTH - (actual_draft() if draft is None else draft)


