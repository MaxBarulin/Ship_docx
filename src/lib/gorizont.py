def tank_summary():
    """Итог по цистернам: объём и масса содержимого при полном запасе."""
    rows = []
    for t in TANKS:
        rows.append(dict(code=t["code"], name=t["name"], vol=t["vol"],
                         mass=round(t["vol"] * t["rho"], 1)))
    return dict(rows=rows,
                vol=round(sum(r["vol"] for r in rows), 1),
                mass=round(sum(r["mass"] for r in rows), 1))


