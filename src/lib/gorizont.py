def module_clearance():
    """Высота от настила солнечной палубы до предела по мосту, м, и запас над модулем."""
    от_вл = DECKS["солнечная"] - DRAFT
    свободно = BRIDGE_MIN - MODULES["запас_под_мост"] - от_вл
    модуль = MODULES["высота"] + MODULES["фундамент"]
    return dict(палуба_над_вл=round(от_вл, 2), свободно=round(свободно, 2), модуль=модуль,
                запас=round(свободно - модуль, 2))

