def tank_summary():
    """Итог по цистернам: объём и масса содержимого при полном запасе."""
    rows = [dict(code=t["code"], name=t["name"], vol=t["vol"],
                 mass=round(t["vol"] * t["rho"], 1)) for t in TANKS]
    return dict(rows=rows, vol=round(sum(r["vol"] for r in rows), 1),
                mass=round(sum(r["mass"] for r in rows), 1))


def offsets_rows():
    """Плазовая таблица в удобном для печати виде."""
    out = []
    for n, x, zk, bk, zb, bb, ys in OFFSETS:
        phi, r = SECTION_SHAPE[n]
        out.append(dict(n=n, x=x, z_kil=zk, b_kil=bk, z_brt=zb, b_brt=bb,
                        phi=phi, r=r, y=list(ys)))
    return out


def cabin_total():
    n = {}
    for deck, mix in CABIN_MIX.items():
        for cat, cnt in mix.items():
            n[cat] = n.get(cat, 0) + cnt
    return n


def berths():
    return sum(c * CABIN_TYPES[k]["berths"] for k, c in cabin_total().items())


def cabin_area():
    return sum(c * CABIN_TYPES[k]["area"] for k, c in cabin_total().items())


