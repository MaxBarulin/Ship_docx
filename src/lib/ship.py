# --- Ограничения трассы: вход, который команда не выбирает -----------------

LOCK_WIDTH = 17_600  # ширина камеры шлюза ЕГС
FAIRWAY_DEPTH = 4_000  # гарантированная глубина ЕГС

# --- Главные размерения (первое приближение от аналогов) -------------------

HULL_LENGTH = 141_000
