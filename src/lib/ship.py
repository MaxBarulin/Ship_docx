# --- Поперечная схема палубы кают ------------------------------------------

CORRIDOR_WIDTH = 1_600  # коридор: разворот кресла-коляски требует 1500
CABIN_DEPTH = 3_500  # глубина каюты от борта до коридора
BULKHEAD = 50  # толщина зашивки продольной переборки
PARTITION = 100  # толщина поперечной переборки между каютами

# --- Модульная сетка -------------------------------------------------------

MODULE = 1_300  # шаг сетки вдоль борта: категория = число модулей

MODULES = {"econom": 2, "standard": 3, "business": 4, "lux": 6}

# --- Высоты ----------------------------------------------------------------

CEILING_HEIGHT = 2_350  # высота помещения в свету
DECK_STRUCTURE = 350  # палубный набор и подволок
DECK_PITCH = CEILING_HEIGHT + DECK_STRUCTURE

# --- Компоновка судна ------------------------------------------------------

CABIN_ZONE_LENGTH = 90_000  # длина борта, занятая каютами
CABIN_DECKS = 3  # число палуб с каютами
BERTHS_PER_CABIN = 2


def cabin_width(category: str) -> float:
    """Габаритная ширина каюты вдоль борта, по осям переборок."""
    return MODULES[category] * MODULE


def clear_width(category: str) -> float:
    """Ширина в свету: габарит минус переборки."""
    return cabin_width(category) - PARTITION


def clear_depth() -> float:
    """Глубина в свету: от зашивки борта до переборки коридора."""
    return CABIN_DEPTH - 2 * BULKHEAD


def clear_area(category: str) -> float:
    """Площадь в свету, м² — величина, которую проверяет эксперт."""
    return clear_width(category) * clear_depth() / 1_000_000


def deck_beam_used() -> float:
    """Ширина, занятая поперечной схемой: каюта + коридор + каюта."""
    return 2 * CABIN_DEPTH + CORRIDOR_WIDTH


def promenade_width() -> float:
    """Что осталось по каждому борту: променад, он же вынос балконов люкса."""
    return (SUPERSTRUCTURE_BEAM - deck_beam_used()) / 2


def capacity(mix: dict[str, int]) -> dict:
    """Пассажировместимость для заданного набора кают на один борт одной палубы.

    mix — сколько кают каждой категории ставится на борту одной палубы.
    Возвращает занятую длину и итоговую вместимость судна.
    """
    length = sum(count * cabin_width(cat) for cat, count in mix.items())
    cabins = sum(mix.values()) * 2 * CABIN_DECKS  # два борта, N палуб
    return {
        "length_used": length,
        "length_available": CABIN_ZONE_LENGTH,
        "fits": length <= CABIN_ZONE_LENGTH,
        "cabins": cabins,
        "passengers": cabins * BERTHS_PER_CABIN,
    }


