    мм = масса_металла()
    сталь = sum(r["кол"] for r in материалы() if r["группа"] == "сталь")
    c("Сталь в закупке покрывает корпус", round(сталь, 1), round(мм["корпус"], 1), "т", сталь * КИМ >= мм["корпус"] - 0.5,
      "КИМ %.2f" % КИМ)
    ал = sum(r["кол"] for r in материалы() if r["группа"] == "алюминий")
    c("Алюминий в закупке покрывает надстройку", round(ал, 1), round(мм["надстройка"], 1), "т",
      ал * КИМ >= мм["надстройка"] - 0.5)
    т = B.трудоёмкость()
    нч = (т["T_гол"] + т["T_эмр"]) * B.K_ВН
    c("Трудоёмкость = постройка и электромонтаж по № 958 × K_вн", round(к["нч"]), round(нч), "н·ч", abs(к["нч"] - нч) < 1.0)
    c("Годы трудоёмкости сходятся", round(sum(к["нч_по_годам"].values())), round(к["нч"]), "н·ч",
      abs(sum(к["нч_по_годам"].values()) - к["нч"]) < 1.0)
    статьи = в["материальные"] + в["озп"] + в["дзп"] + в["страх"] + в["опр"] + в["охр"] + в["ком"]
    c("Калькуляция - статьи сходятся с полной", round(статьи), round(в["полная"]), "руб.", abs(статьи - в["полная"]) < 1.0)
    from . import gorizont_twistlock as T
