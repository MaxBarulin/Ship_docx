# --- даты -----------------------------------------------------------------------------------------
def _раб_дни(a, b):
    """Рабочих дней (пн-пт) с a по b включительно."""
    if b < a:
        return 0
    n = 0
    d = a
    while d <= b:
        if d.weekday() < 5:
            n += 1
        d += _dt.timedelta(days=1)
    return n


def _по_годам_дни(a, b):
    """Рабочие дни отрезка по календарным годам."""
    out = {}
    for y in range(a.year, b.year + 1):
        out[y] = _раб_дни(max(a, _dt.date(y, 1, 1)), min(b, _dt.date(y, 12, 31)))
    return out


def _месяцы_по_годам(a, b):
    """Календарные месяцы отрезка по годам 2027…2029 (дни / 30,44). Судно передаётся в начале 2030 года -
    эти дни относятся к 2029 году."""
    out = {y: 0.0 for y in ГОДЫ}
    for y in range(a.year, b.year + 1):
        d0, d1 = max(a, _dt.date(y, 1, 1)), min(b, _dt.date(y, 12, 31))
        if d1 >= d0:
            out[min(max(y, ГОДЫ[0]), ГОДЫ[-1])] += ((d1 - d0).days + 1) / 30.44
    return out


