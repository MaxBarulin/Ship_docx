    c("Серия в пределах рынка", 1 + СЕРИЯ, round(MK.продажи()["судов_под_SAM"], 1), "судов", 1 + СЕРИЯ <= MK.продажи()["судов_под_SAM"])
    д = денежный_поток()
    c("NPV программы положительный", round(д["NPV"] / 1e6, 1), 0.0, "млн руб.", д["NPV"] > 0)
    c("IRR выше ставки дисконтирования", round(д["IRR"], 1), СТАВКА_ДИСКОНТА, "%", д["IRR"] > СТАВКА_ДИСКОНТА)
    c("Окупаемость в горизонте программы", д["лет_д"] or 99, 2030 + СЕРИЯ - 2026, "лет", д["окупаемость_д"] is not None)
    return rows


