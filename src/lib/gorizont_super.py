"""Обвод надстройки - единственный источник формы для модели, планов и чертежей.

Модуль появился после прямого дефекта. Надстройка в модели строилась
коробкой постоянной полушироты 7,25 м от x=9 до x=121, при том что корпус
в носу сужается - на x=121 полуширота борта 3,82 м. Ярус висел в воздухе на
3,43 м за каждым бортом, а красная полоса шла прямым щитом до x=126, где
борт уже 1,25 м. Со стороны это читалось как квадратный помост, надетый на
обтекаемый корпус.

При этом правильный обвод в проекте был - `gorizont_hydro.super_half_breadth`
считала его для парусности. Модель просто им не пользовалась. Поэтому обвод
вынесен сюда, а гидростатика вызывает эту же функцию - разойтись парусности,
плану палубы, чертежу и 3D больше негде.

Форма задана тремя правилами, а не набором точек:

  * **ярус не может быть шире корпуса на своей абсциссе.** Полуширота
    режется по `side_half(x) - SIDE_WALK` - бортовой проход 1,0 м есть
    всегда, в том числе в оконечностях, где он и становится ограничением;
  * **нос ведётся длинным сходом,** а не срезается поперечной стенкой.
    Сход занимает 20 м у нижнего яруса и 17 м у верхнего и кончается не в
    точку, а скруглением 0,55 м - панорамный салон должен иметь ширину;
  * **ярусы кончаются в разных местах.** Борта в средней части идут в одной
    плоскости (верхний ярус ровно продолжает нижний с учётом завала), а
    силуэт ломается тем, что верхний ярус короче - в корме открытая терраса
    на крыше главной, в носу - уступ над панорамным салоном.

Завал борта 6° из `gorizont_style.ФОРМА` - не украшение - он определяет
ширину в свету на каждой палубе, а значит и глубину внутреннего ряда кают.
На средней палубе полуширота выходит 6,96 м, и ряд кают ложится ровно:
3,00 каюта + 1,30 коридор + 2,65 внутренняя каюта = 6,95 м.
"""
