#: Наклон торцов ярусов: на сколько метров верх торца сдвинут относительно
#: низа. Нос - вперёд (лоб нависает, как у современных речных судов),
#: корма верхнего яруса - назад (уступ читается как движение, а не как
#: лестница). Это единственное место, где задан силуэт в профиле: и
#: 2D-облик, и лофт модели читают его через `полуширота(x, ярус, z)`.
НАКЛОН_ТОРЦОВ = {"главная": dict(нос=1.6, корма=0.0),
                 "средняя": dict(нос=1.8, корма=-1.2)}


def границы_яруса(ярус, z=None):
    """x0, x1 яруса на высоте z с учётом наклона торцов."""
    я = ЯРУСЫ[ярус]
    if z is None:
        return я["x0"], я["x1"]
    t = max(0.0, min(1.0, (z - я["z0"]) / (я["z1"] - я["z0"])))
    н = НАКЛОН_ТОРЦОВ[ярус]
    return я["x0"] + н["корма"] * t, я["x1"] + н["нос"] * t

