"""Расстановка мебели в каютах — данные без графики.

Вынесено из `scripts/планы_кают.py`, чтобы и лист планировок, и модель в
Blender читали одну расстановку. В Blender нет matplotlib, а планировка —
это числа, а не рисунок.
"""
from . import gorizont as G
from . import gorizont_ga as GA

# --- нормы -------------------------------------------------------------------
КОЙКА_L, КОЙКА_B = 2.00, 0.80          # СанПиН п. 2.1.1.9
ПРОХОД = {1: 0.70, 2: 0.80, 3: 0.85, 4: 0.85}   # п. 2.1.1.8 по числу мест
ДВЕРЬ = 0.70
ДВЕРЬ_М4 = 0.90
САНУЗЕЛ_МИН = (1.20, 1.50)
ВЫСОТА_В_СВЕТУ = G.DECK_PITCH - G.LINING - 0.12   # 2,33 м
ВЫСОТА_НОРМА = {1: 2.0, 2: 2.2}                   # п. 2.1.1.6: ярусов → высота

ЦВЕТ = dict(койка="#f3e6de", санузел="#dbe7f0", шкаф="#e9e2d4", стол="#e7efe8",
            диван="#efe7ef", кресло="#efe7ef", тумба="#e9e2d4")


def мебель(тип):
    """Расстановка одной каюты: (имя, x, y, w, h, класс). Ось x — фронт
    вдоль коридора, y — от коридора (0) к борту (глубина).

    Правила расстановки, одни для всех:
      * санузел — у входа, в углу у коридора; дверь каюты рядом с ним;
      * койки — вдоль борта (у окна) или вдоль боковых переборок;
      * проход вдоль койки не уже нормы, ничего не стоит посреди пола;
      * стол — у окна между койками либо у боковой стены.
    """
    к = GA.КАЮТЫ[тип]
    ф = к["фронт"]
    гл = к["глубина"] or GA.глубина_внутренней("средняя", 45.0)
    м = []
    if тип == "люкс":            # 6,0 x 3,0
        м += [("санузел", ф - 2.2, 0.0, 2.2, 1.6, "санузел"),
              ("кровать 2,0 x 1,6", 0.1, гл - 1.6, 2.0, 1.6, "койка"),
              ("шкаф", 0.1, 0.0, 1.2, 0.6, "шкаф"),
              ("стол", 2.4, гл - 0.6, 1.2, 0.6, "стол"),
              ("диван", ф - 2.1, гл - 0.8, 1.9, 0.8, "диван")]
    elif тип == "бизнес":        # 5,0 x 3,0
        м += [("санузел", ф - 1.8, 0.0, 1.8, 1.5, "санузел"),
              ("кровать 2,0 x 1,6", 0.1, гл - 1.6, 2.0, 1.6, "койка"),
              ("шкаф", 0.1, 0.0, 1.2, 0.6, "шкаф"),
              ("стол", 2.4, гл - 0.6, 1.0, 0.6, "стол"),
              ("кресло", ф - 1.0, гл - 0.9, 0.8, 0.8, "кресло")]
    elif тип == "стандарт":      # 4,0 x 3,0, четыре места двумя двухъярусными
        м += [("санузел", ф - 1.5, 0.0, 1.5, 1.2, "санузел"),
              ("2-ярусная", 0.1, гл - 0.8, 2.0, 0.8, "койка"),          # вдоль окна
              ("2-ярусная", 0.1, 0.2, 0.8, 2.0, "койка"),               # вдоль левой стенки, торцом к первой
              ("шкаф", ф - 1.5, 1.3, 0.6, 0.9, "шкаф"),
              ("стол", ф - 0.75, гл - 0.55, 0.65, 0.5, "стол")]
    elif тип == "стандарт М4":   # 6,0 x 3,0: круг разворота между шкафом и санузлом
        м += [("санузел М4", ф - 2.0, 0.0, 2.0, 2.0, "санузел"),
              ("кровать 2,0 x 1,6", 0.1, гл - 1.6, 2.0, 1.6, "койка"),
              ("шкаф", 0.1, 0.0, 1.2, 0.6, "шкаф"),
              ("стол", ф - 1.8, гл - 0.55, 1.0, 0.5, "стол")]
    elif тип == "семейная":      # 5,6 x 2,42 внутренняя, четыре места
        # санузел посередине у коридора: тогда у обеих коек свободен проход
        # вдоль всей длины, а перегородка делит спальные половины
        м += [("санузел", ф / 2.0 - 0.75, 0.0, 1.5, 1.2, "санузел"),
              ("2-ярусная", 0.1, гл - 0.8, 2.0, 0.8, "койка"),
              ("2-ярусная", ф - 2.1, гл - 0.8, 2.0, 0.8, "койка"),
              ("шкаф", 0.1, 0.0, 1.0, 0.6, "шкаф"),
              ("шкаф", ф - 1.1, 0.0, 1.0, 0.6, "шкаф"),
              ("стол", ф / 2.0 - 0.65, гл - 0.55, 0.6, 0.5, "стол")]
    elif тип == "эконом":        # 3,8 x 2,42 внутренняя, два места одной двухъярусной
        # Четыре места сюда не встают по нормам: две койки 2,0 м, санузел
        # 1,2 x 1,5, дверь 0,7 и проходы 0,85 не складываются в 3,8 x 2,42.
        м += [("санузел", ф - 1.5, 0.0, 1.5, 1.2, "санузел"),
              ("2-ярусная", 0.1, 0.2, 0.8, 2.0, "койка"),               # вдоль левой стенки
              ("шкаф", 0.95, 0.0, 0.55, 0.5, "шкаф"),
              ("столик", ф - 1.4, гл - 0.5, 1.2, 0.45, "стол")]
    return ф, гл, м




def дверь(тип):
    """Положение двери каюты по фронту: (lx, ширина). Слева от санузла."""
    к = GA.КАЮТЫ[тип] if тип in GA.КАЮТЫ else GA.КАЮТЫ["стандарт"]
    ф, гл, м = мебель(тип if тип in ("люкс", "бизнес", "стандарт", "стандарт М4", "семейная", "эконом") else "стандарт")
    су = [f for f in м if f[5] == "санузел"][0]
    дв = ДВЕРЬ_М4 if к.get("М4") else ДВЕРЬ
    return су[1] - дв - 0.05, дв
