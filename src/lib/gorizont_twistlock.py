ДОЛЯ_СДВИГА = 0.5                # сдвиг модуля воспринимают две опоры из четырёх (зазоры центраторов в отверстиях)
#: Модули, которые на эти фундаменты не ставятся: тяжелее расчётного и в темы не входят.
