def нагрузки():
    """Расчётные нагрузки на одну опору - предельный и эксплуатационный случаи, посадка краном."""
    if "нагрузки" in _КЭШ:
        return _КЭШ["нагрузки"]
    M = _M()
    имя, m = расчётный_модуль()
    ряды = sorted({s["yc"] for s in M.слоты()})
    xs = [s["xc"] for s in M.слоты()]
    x_дальн = max(xs, key=lambda x: abs(x - качка()["xf"]))
    out = {}
    for случай in ("эксплуатация", "предельный"):
        рр = [реакции(m, y, x_дальн, случай) for y in ряды]
        худ = dict(max(рр, key=lambda r: r["отрыв"]))
        худ["сжатие"] = max(r["сжатие"] for r in рр)
        худ["сдвиг"] = max(r["сдвиг"] for r in рр)
        out[случай] = худ
    out["посадка"] = dict(сжатие=КОЭФФ_ПОСАДКИ * m * GRAV / 2.0)
    out["модуль"] = (имя, m)
    # по каталогу: у лёгких модулей отрыв от ветра и качки тоже есть
    out["по_модулям"] = []
    for k, v in M.МОДУЛИ.items():
        r = max((реакции(v["масса"], y, x_дальн, "предельный") for y in ряды), key=lambda r: r["отрыв"])
        out["по_модулям"].append((k, v["масса"], round(r["сжатие"], 1), round(r["отрыв"], 1), round(r["сдвиг"], 1)))
    # рабочая нагрузка узла (маркируется на корпусе): эксплуатационная, вверх до 5 кН
    э = out["эксплуатация"]
    окр = lambda x: 5.0 * math.ceil(x / 5.0)
    out["SWL"] = dict(отрыв=окр(э["отрыв"]), сжатие=окр(max(э["сжатие"], out["посадка"]["сжатие"])), сдвиг=окр(э["сдвиг"]))
    _КЭШ["нагрузки"] = out
    return out


