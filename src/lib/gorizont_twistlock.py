def объём_корпуса(отливка=False):
    """Объём корпуса, мм³. Деталь или отливка (с припусками, без просверленных отверстий, упор - из прибыли)."""
    к = КОРПУС
    A_фл = к["L_x"] * к["L_y"] - (4.0 - math.pi) * к["R_фл"] ** 2
    V = (A_фл - math.pi * к["D_в"] ** 2 / 4.0) * к["t_фл"]
    V += math.pi * (к["D_н"] ** 2 - к["D_в"] ** 2) / 4.0 * (к["H"] - к["t_фл"] - к["t_верх"])
    V += math.pi * к["D_н"] ** 2 / 4.0 * к["t_верх"]
    l_р = к["L_y"] / 2.0 - к["D_н"] / 2.0
    V += 2.0 * к["ребро"][0] * 0.5 * l_р * к["ребро"][1]
    V += 2.0 * math.pi * к["прилив"][0] ** 2 / 4.0 * к["прилив"][1]
    V -= к["окно"][2] / 360.0 * math.pi * (к["D_н"] ** 2 - к["D_в"] ** 2) / 4.0 * (к["окно"][1] - к["окно"][0])
    упор = _obround_area(*к["упор"][:2]) * к["упор"][2]
    отв = (4 * math.pi * к["d_отв"] ** 2 / 4.0 * к["t_фл"]
           + math.pi * к["d_вал"] ** 2 / 4.0 * (к["t_верх"] + к["упор"][2])
           + 2 * math.pi * к["d_фикс"] ** 2 / 4.0 * (к["прилив"][1] + 10.0))
    if not отливка:
        return V + упор - отв
    п = ПРИПУСКИ
    V += A_фл * п["подошва"] - math.pi * к["D_в"] ** 2 / 4.0 * п["подошва"]
    V += math.pi * к["D_н"] ** 2 / 4.0 * п["площадка"]
    return V                          # отверстия не отливаются; упор вырезается из шейки прибыли - в объём прибыли


