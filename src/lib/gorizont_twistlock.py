def момент_затяжки():
    """Момент затяжки болта, Н·м - затяжка 0,5σт, коэффициент момента 0,2 (нержавеющий крепёж со смазкой)."""
    б = БОЛТ
    return round(0.2 * б["затяжка"] * б["σт"] * б["As"] * б["d"] / 1000.0, -1)


def расчёт():
    """Все проверки прочности узла - строки (элемент, случай, величина, допускаемое, ед., запас, пояснение).
    Сжатие - по отчётам МКЭ, отрыв и сдвиг - аналитически."""
    if "расчёт" in _КЭШ:
        return _КЭШ["расчёт"]
    к, з, б, с, п = КОРПУС, ЗАПОР, БОЛТ, СТЕРЖЕНЬ, ПЛАТИК
    н = нагрузки()
    мк = мкэ()
    строки = []

    def row(элемент, случай, val, allow, ед, пояснение):
        строки.append(dict(элемент=элемент, случай=случай, значение=round(val, 1), допускаемое=round(allow, 1), ед=ед,
                           запас=round(allow / max(val, 1e-9), 2), ok=val <= allow + 1e-9, пояснение=пояснение))

    M = _M().КОНТЕЙНЕР
    отв_W = M["отверстие_мм"][1]
    # 1. Сжатие - отчёт МКЭ, линейно по силе. Посадка краном - кратковременная, проверяется как предельный случай
    for сл, C, имя in (("эксплуатация", н["эксплуатация"]["сжатие"], "эксплуатация"),
                       ("предельный", н["предельный"]["сжатие"], "предельный"),
                       ("предельный", н["посадка"]["сжатие"], "посадка")):
        σ = мк["σ_отч"] * C * 1000.0 / МКЭ["сила"]
        row("Корпус и платик - напряжение по МКЭ", имя, σ, доп("20ГСЛ", "σ", сл), "МПа",
            "сжатие %.1f кН против %.1f в отчёте МКЭ, запас по текучести 20ГСЛ %.2f при нужном %.2f" % (
                C, мк["P_отч"], запас_мкэ(C), 1.0 / ДОП[сл]["σ"]))
    for сл in ("эксплуатация", "предельный"):
        r = н[сл]
        N, Q = r["отрыв"] * 1e3, r["сдвиг"] * 1e3                     # Н; сдвиг от бортовой качки - вдоль X корпуса
        C = max(r["сжатие"], н["посадка"]["сжатие"]) * 1e3
        # 2. Стержень поз. 2 только поворачивает запор - отрыв идёт через шайбу поз. 5, проверки ниже
        # 3. Шов корпуса с платиком: отрыв, сдвиг и момент сдвига на высоте центратора
        ш = _шов_группа()
        h_Q = к["центратор"][2] / 2.0 - к["z"][0]
        σ_ш = math.hypot(N / ш["A"] + Q * h_Q / ш["W"], Q / ш["A"])
        row("Шов корпуса с платиком, катет %d" % ШОВ["катет"], сл, σ_ш, доп("20ГСЛ", "τ", сл), "МПа",
            "длина %.0f мм, толщина %.1f, сдвиг на высоте %.0f мм над платиком" % (шов_длина(), ш["a"], h_Q))
        # 4. Болты: сила на болт от отрыва и опрокидывающего момента сдвига; затяжка, нераскрытие, сдвиг
        F_v = б["затяжка"] * б["σт"] * б["As"]
        h_б = к["центратор"][2] / 2.0 - к["z"][0] + п["t"] + ОПОРА["прокладка"]
        T_внеш = N / б["n"] + Q * h_б / (б["n"] * п["болт_x"])
        F_b = F_v + б["χ"] * T_внеш
        row("Болт М%d %s - растяжение" % (б["d"], б["класс"]), сл, F_b / б["As"], 0.8 * б["σт"], "МПа",
            "затяжка %.0f кН (0,5σт), внешняя %.1f кН на болт, χ = %.2f" % (F_v / 1e3, T_внеш / 1e3, б["χ"]))
        остаток = F_v - (1.0 - б["χ"]) * T_внеш
        row("Стык - нераскрытие", сл, 0.2 * F_v / 1e3, остаток / 1e3, "кН",
            "остаток затяжки %.0f кН не меньше 0,2 затяжки" % (остаток / 1e3))
        трение = б["μ"] * (б["n"] * F_v - (1.0 - б["χ"]) * N)
        if сл == "эксплуатация":
            row("Сдвиг платика - держит трение", сл, Q / 1e3, трение / 1e3, "кН",
                "μ = %.2f по стеклотекстолиту, %d болта, минус отрыв" % (б["μ"], б["n"]))
        else:
            row("Болт М%d - срез при проскальзывании" % б["d"], сл, Q / б["n"] / б["As"], доп("А4-80", "τ", сл), "МПа",
                "трения %.0f кН не хватает - сдвиг на болты через втулки, овалы поперёк сдвига" % (трение / 1e3))
            row("Втулка изолирующая - смятие", сл, Q / б["n"] / (б["d"] * (ОПОРА["лист"][2] + ОПОРА["настил"])),
                МАТЕРИАЛЫ["СТЭФ"]["σсм_доп"] * 1.1, "МПа", "втулка в листе АМг5 и настиле, %d мм" % (ОПОРА["лист"][2] + ОПОРА["настил"]))
        # 5. Платик у болта - консоль от шва до оси болта (тавровая полка), ширина - половина платика
        e = п["болт_x"] - к["кромка"] - ШОВ["катет"]
        row("Платик 09Г2С у болта - изгиб", сл, T_внеш * e / (п["B"] / 2.0 * п["t"] ** 2 / 6.0), доп("09Г2С", "σ", сл), "МПа",
            "консоль %.1f мм от шва до болта, толщина %d, ширина %d" % (e, п["t"], п["B"] / 2))
