def _сечение_тавра(h, tw, bf, tf, b_пл, t_пл):
    """Тавр с присоединённым пояском настила - W по свободному пояску и по настилу, см³, площадь, см²."""
    parts = [(b_пл * t_пл, t_пл / 2.0, b_пл * t_пл ** 3 / 12.0),
             (h * tw, t_пл + h / 2.0, tw * h ** 3 / 12.0),
             (bf * tf, t_пл + h + tf / 2.0, bf * tf ** 3 / 12.0)]
    A = sum(a for a, _, _ in parts)
    z0 = sum(a * z for a, z, _ in parts) / A
    I = sum(i + a * (z - z0) ** 2 for a, z, i in parts)
    return dict(A=A / 100.0, W_пояс=I / (t_пл + h + tf - z0) / 1000.0, W_настил=I / z0 / 1000.0, z0=z0,
                масса_кг_м=(h * tw + bf * tf) * 1e-6 * МАТЕРИАЛЫ["АМг5"]["ρ"])


