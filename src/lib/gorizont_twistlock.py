    # тепловой узел - верхняя стенка с припуском площадки. Прибыль ставится на неё овалом по контуру
    # упора: упор потом вырезается фрезой из шейки прибыли - металл в нём самый плотный.
    t_узла = к["t_верх"] + п["площадка"]
    M_узла = t_узла / 2.0                                   # мм, плита охлаждается снизу (стержень) и сверху
    M_приб = 1.2 * M_узла
    Lr = к["упор"][0] + 2 * п["упор_бок"] + 6.0              # овал: упор, припуск на сторону и 3 мм запаса
    Wr = к["упор"][1] + 2 * п["упор_бок"] + 6.0
    A_r = _obround_area(Lr, Wr)
    P_r = 2.0 * (Lr - Wr) + math.pi * Wr
    # зеркало прибыли засыпается утепляющей смесью: верх не остывает, модуль прибыли = A / P при любой высоте
    if A_r / P_r < M_приб:
        raise ValueError("овальная прибыль %d × %d не набирает модуль %.1f" % (Lr, Wr, M_приб))
    # высота - по объёму питания: КПД·m_приб ≥ ε·(m_отл + m_приб), с запасом 15 %
    ε_v, η = л["усадка_объёмная"] / 100.0, л["КПД_прибыли"] / 100.0
    m_нужно = 1.15 * ε_v * м["отливка"] / (η - ε_v)
    Hп = 10.0 * math.ceil(max(m_нужно / (A_r * 1e-9 * ρ), 1.5 * Wr) / 10.0)
    D = Lr
    V_приб = A_r * Hп * 1e-9                                # м³
    m_приб = V_приб * ρ
    # питание: прибыль отдаёт КПД своего объёма, отливка и сама прибыль усаживаются на ε
    нужно = л["усадка_объёмная"] / 100.0 * (м["отливка"] + m_приб)
    отдаёт = л["КПД_прибыли"] / 100.0 * m_приб
    # литниковая система на форму: заливка τ = S·√G, напор по Асатиани, скорость по Бернулли
    m_литн = 0.10 * л["отливок_в_форме"] * (м["отливка"] + m_приб)
    G_ф = л["отливок_в_форме"] * (м["отливка"] + m_приб) + m_литн
    τ = л["S"] * math.sqrt(G_ф)
    H_ст = (л["опока"][2] + 50.0) / 1000.0                  # от питателя (разъём) до верха литниковой чаши
    C = (к["H"] + п["подошва"] + п["площадка"] + Hп) / 1000.0
    P = C
    H_р = H_ст - P ** 2 / (2.0 * C)
    F_ст = G_ф / (л["ρ_жидк"] * л["μ"] * τ * math.sqrt(2.0 * GRAV * H_р)) * 1e4      # см²
    F_шл, F_пит = 1.2 * F_ст, 1.4 * F_ст
    n_пит = 2 * л["отливок_в_форме"]
    # смесь и стержень
    Lf, Bf, Hв, Hн = л["опока"]
    V_опок = Lf * Bf * (Hв + Hн) * 1e-9
    V_мет = G_ф / ρ
    смесь_т = (V_опок - V_мет) * л["смесь"]["плотность"]
    # стержень: полость стакана с нижним знаком 40 мм, язык в окне и нога-знак снаружи стакана до верха модели -
    # без ноги модель не вынуть из формы: знак окна давал бы поднутрение
    доля = к["окно"][2] / 360.0
    V_стерж = (math.pi * к["D_в"] ** 2 / 4.0 * (к["H"] - к["t_верх"] + п["подошва"] + ЗНАК_НИЗ) +
               доля * math.pi * (к["D_н"] ** 2 - к["D_в"] ** 2) / 4.0 * (к["окно"][1] - к["окно"][0]) +
               доля * math.pi * ((к["D_н"] + 2 * ЗНАК_ОКНА) ** 2 - к["D_н"] ** 2) / 4.0 * (к["H"] + п["площадка"] - к["окно"][0])) * 1e-9
    стерж_кг = V_стерж * л["смесь"]["плотность"] * 1000.0
    форм_на_плавку = int(л["плавка_т"] * 1000.0 * 0.95 // G_ф)
    out = dict(масса_детали=м["корпус"], масса_отливки=round(м["отливка"], 1), модуль_узла=round(M_узла, 1), прибыль_W=Wr,
               модуль_прибыли=round(A_r / P_r, 1), модуль_нужен=round(M_приб, 1), прибыль_D=D, прибыль_H=Hп, масса_прибыли=round(m_приб, 1),
               питание_нужно_кг=round(нужно, 2), питание_отдаёт_кг=round(отдаёт, 2),
               металл_на_форму=round(G_ф, 1), литники_кг=round(m_литн, 1), τ_с=round(τ, 1), H_р_мм=round(H_р * 1000.0),
               F_ст=round(F_ст, 1), F_шл=round(F_шл, 1), F_пит=round(F_пит, 1), питателей=n_пит,
               d_стояка=round(math.sqrt(4.0 * F_ст / math.pi) * 10.0), пит_1=round(F_пит / n_пит, 1),
               выход_годного=round(100.0 * л["отливок_в_форме"] * м["корпус"] / G_ф, 1),
               смесь_на_форму_т=round(смесь_т, 3), смола_кг=round(смесь_т * 1000.0 * л["смесь"]["смола"] / 100.0, 1),
               стержень_кг=round(стерж_кг, 1), форм_на_плавку=форм_на_плавку,
               модель_масштаб=1.0 + УСАДКА / 100.0)
    _КЭШ["отливка"] = out
    return out


