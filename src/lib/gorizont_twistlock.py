def качка():
    """Параметры качки из теории корабля - периоды, амплитуды, ось, самый короткий период - расчётный."""
    if "качка" in _КЭШ:
        return _КЭШ["качка"]
    e = H.equilibrium()
    zg = e["zg"]
    периоды = []
    for T in (ОСАДКИ[0], e["T"], ОСАДКИ[1]):
        h = H.hydrostatics(T)["zm"] - zg
        периоды.append((round(T, 3), round(h, 2), round(H.roll_period(h), 2)))
    d = R.damping()
    w = H.weather_criterion()
    T_бк = min(p[2] for p in периоды)
    ψ = math.degrees(H.WAVE_HEIGHT[H.CLASS] / G.LOA)          # килевая: не больше h/L
    out = dict(класс=H.CLASS, волна=H.WAVE_HEIGHT[H.CLASS], длина_волны=H.WAVE_LENGTH[H.CLASS],
               давление_ветра_кПа=H.WIND_PRESSURE[H.CLASS], периоды=периоды, T_бк=T_бк,
               T_кк=round(H.pitch_period(), 2), θ_без=d["theta_before"], θ_с=d["theta_after"], ψ=round(ψ, 2),
               z_оси=round(zg, 2), xf=round(H.hydrostatics(e["T"])["xf"], 2), T=round(e["T"], 3), h=round(w["h"], 2))
    _КЭШ["качка"] = out
    return out


def _опоры_модуля():
    М = _M().КОНТЕЙНЕР
    z_ф = G.DECKS["солнечная"] + высота_опоры()                     # низ фитинга над ОП
    return dict(a=М["фитинги_x"], b=М["фитинги_y"], h_цт=М["высота"] / 2.0, z_ф=z_ф,
                A_борт=М["длина"] * М["высота"], A_торец=М["ширина"] * М["высота"])


def реакции(масса_т, y_c, x_c=None, случай="предельный"):
    """Реакции на опоры модуля массой m (т) в слоте с центром (x_c, y_c), кН на одну опору.

    Бортовая качка - инерционные ускорения в системе судна при наибольшем крене θ -
    поперечное g·sinθ + ε·Δz, вертикальное g·cosθ ± ε·y (ε = θ·(2π/T)²), ветер РКО
    на борт модуля в сторону крена. Опрокидывающий момент - на линию фитингов с
    подветренной стороны, отрыв - минус на наветренной паре.
    """
    к = качка()
    о = _опоры_модуля()
    θ = math.radians(к["θ_без"] if случай == "предельный" else к["θ_с"])
    ω = 2.0 * math.pi / к["T_бк"]
    ε = θ * ω ** 2
    dz = о["z_ф"] + о["h_цт"] - к["z_оси"]
    p = к["давление_ветра_кПа"]
    худшее = None
    макс_сжатие = 0.0                                                 # сжатие - наибольшее из двух кренов, отрыв - свой
    for знак in (1.0, -1.0):                                          # крен на правый и на левый борт
        a_y = GRAV * math.sin(θ) + ε * dz
        a_z = GRAV * math.cos(θ) + знак * ε * y_c
        F_y = масса_т * a_y + p * о["A_борт"]
        F_z = масса_т * a_z
        M = F_y * о["h_цт"]
        под = F_z / 2.0 + M / о["b"]                                  # на пару подветренных опор
        над = F_z / 2.0 - M / о["b"]
        r = dict(сжатие=под / 2.0, отрыв=max(-над / 2.0, 0.0), сдвиг=F_y * ДОЛЯ_СДВИГА,
                 a_y=a_y, a_z=a_z, F_y=F_y, F_z=F_z, M=M)
        макс_сжатие = max(макс_сжатие, r["сжатие"])
        if худшее is None or r["отрыв"] > худшее["отрыв"] or (r["отрыв"] == худшее["отрыв"] and r["сжатие"] > худшее["сжатие"]):
            худшее = dict(r)
    худшее["сжатие"] = макс_сжатие
    # килевая качка: продольный сдвиг и добавка к сжатию на опорах, дальних от центра площади ВЛ
    ψ = math.radians(к["ψ"])
    εψ = ψ * (2.0 * math.pi / к["T_кк"]) ** 2
    dx = abs((x_c if x_c is not None else к["xf"]) - к["xf"]) + о["a"] / 2.0
    a_x = GRAV * math.sin(ψ) + εψ * dz
    F_x = масса_т * a_x + p * о["A_торец"]
    сжатие_кк = масса_т * (GRAV + εψ * dx) / 4.0 + F_x * о["h_цт"] / о["a"] / 2.0
    худшее.update(ε=ε, dz=dz, θ=math.degrees(θ), F_x=F_x, сдвиг_x=F_x * ДОЛЯ_СДВИГА, сжатие_кк=сжатие_кк,
                  сжатие=max(худшее["сжатие"], сжатие_кк))
    return худшее


def модули_тем():
    """Типы модулей, которые входят в темы круизов."""
    M = _M()
    return sorted({тип for т in M.ТЕМЫ.values() for тип in т["модули"].values()})


def расчётный_модуль():
    """Самый тяжёлый модуль из тем - на него рассчитан узел. Глубокий бассейн в темы не входит и на
    фундаменты не ставится (`НЕ_СТАВИТСЯ`)."""
    М = _M().МОДУЛИ
    имя = max(модули_тем(), key=lambda k: М[k]["масса"])
    return имя, М[имя]["масса"]


def в_ряду(y_c, случай="предельный", масса_т=None):
    """Реакции на опору от расчётного модуля в ряду y_c - на дальнем от центра площади ВЛ слоте."""
    M = _M()
    xs = [s["xc"] for s in M.слоты()]
    x_дальн = max(xs, key=lambda x: abs(x - качка()["xf"]))
    return реакции(масса_т if масса_т is not None else расчётный_модуль()[1], y_c, x_дальн, случай)


def _ряды(тип):
    """Абсциссы рядов, куда правило размещения пускает модуль этого типа."""
    M = _M()
    доп_ = M.ряды_модуля(тип)
    return sorted({s["yc"] for s in M.слоты() if s["ряд"] in доп_})


def масса_предел_борт():
    """Масса модуля, при которой в бортовом ряду запас корпуса по МКЭ в предельном случае равен 1,25, т.
    Выше неё модуль ставится только в ДП - на ней основан порог правила размещения."""
    y = max(abs(s["yc"]) for s in _M().слоты())
    нуж = 1.0 / ДОП["предельный"]["σ"]
    lo, hi = 1.0, 30.0
    for _ in range(40):
        mid = (lo + hi) / 2.0
        if запас_мкэ(в_ряду(y, "предельный", mid)["сжатие"]) >= нуж:
            lo = mid
        else:
            hi = mid
    return round(lo, 2)


def нагрузки():
    """Расчётные нагрузки на одну опору - предельный и эксплуатационный случаи, посадка краном. Огибающая по
    всем модулям тем в рядах, разрешённых правилом размещения: тяжёлые - только ДП, остальные - все ряды."""
    if "нагрузки" in _КЭШ:
        return _КЭШ["нагрузки"]
    M = _M()
    имя, m = расчётный_модуль()
    xs = [s["xc"] for s in M.слоты()]
    x_дальн = max(xs, key=lambda x: abs(x - качка()["xf"]))
    out = {}
    for случай in ("эксплуатация", "предельный"):
        рр = [dict(реакции(M.МОДУЛИ[k]["масса"], y, x_дальн, случай), модуль=k, y=y) for k in модули_тем() for y in _ряды(k)]
        худ = dict(max(рр, key=lambda r: r["отрыв"]))
        сж = max(рр, key=lambda r: r["сжатие"])
        худ["сжатие"], худ["сжатие_от"] = сж["сжатие"], (сж["модуль"], сж["y"])
        худ["сдвиг"] = max(r["сдвиг"] for r in рр)
        out[случай] = худ
    out["посадка"] = dict(сжатие=КОЭФФ_ПОСАДКИ * m * GRAV / 2.0)
    out["модуль"] = (имя, m)
    out["статика"] = m * GRAV / 4.0
    # по модулям тем в разрешённых рядах: у лёгких модулей отрыв от ветра и качки тоже есть
    out["по_модулям"] = []
    for k in модули_тем():
        v = M.МОДУЛИ[k]
        рр = [реакции(v["масса"], y, x_дальн, "предельный") for y in _ряды(k)]
        r = max(рр, key=lambda r: r["отрыв"])
        out["по_модулям"].append((k, v["масса"], round(max(q["сжатие"] for q in рр), 1), round(r["отрыв"], 1), round(r["сдвиг"], 1),
                                  ", ".join(M.ряды_модуля(k))))
    out["по_модулям"].sort(key=lambda r: -r[1])
    # рабочая нагрузка узла (маркируется на платике): эксплуатационная, вверх до 5 кН
    э = out["эксплуатация"]
    окр = lambda x: 5.0 * math.ceil(x / 5.0)
    out["SWL"] = dict(отрыв=окр(э["отрыв"]), сжатие=окр(max(э["сжатие"], out["посадка"]["сжатие"])), сдвиг=окр(э["сдвиг"]))
    _КЭШ["нагрузки"] = out
    return out


