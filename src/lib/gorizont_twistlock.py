def отливка():
    """Литьё корпуса - прибыли по модулям охлаждения, литниковая система, металл и смесь на форму."""
    if "отливка" in _КЭШ:
        return _КЭШ["отливка"]
    к, п, л = КОРПУС, ПРИПУСКИ, ЛИТЬЁ
    ρ = МАТЕРИАЛЫ["20ГСЛ"]["ρ"]
    m_дет = массы()["корпус"]
    V_пр = (math.pi / 4.0 * (к["d_отв"] ** 2 - (к["d_отв"] - 2 * п["отверстие"]) ** 2) * (к["z"][1] - к["z"][0] - 3.0)
            + к["полоса"]["n"] * к["полоса"]["площадь"] * п["полосы"] + к["плечо_площадь"] * п["плечо"])
    m_отл = m_дет + V_пр * ρ * 1e-9
    # модуль охлаждения: отливка в среднем V/A, тепловой узел - сопряжение хвоста с плечом, 1,2 среднего
    M_отл = к["объём"] / к["площадь"]
    M_узла = 1.2 * M_отл
    M_приб = 1.2 * M_узла
    Wr, Lr = л["прибыль"]
    A_r, P_r = obround(Lr, Wr), 2.0 * (Lr - Wr) + math.pi * Wr
    # две прибыли на плече по обе стороны центратора, зеркало под утепляющей засыпкой: модуль = A / P
    ε, η = л["усадка_объёмная"] / 100.0, л["КПД_прибыли"] / 100.0
    m_нужно = 1.15 * ε * m_отл / (η - ε)
    Hп = 10.0 * math.ceil(max(m_нужно / 2.0 / (A_r * 1e-9 * ρ), 1.5 * Wr) / 10.0)
    m_приб = 2 * A_r * Hп * 1e-9 * ρ
    нужно, отдаёт = ε * (m_отл + m_приб), η * m_приб
    n = л["отливок_в_форме"]
    m_литн = 0.10 * n * (m_отл + m_приб)
    G_ф = n * (m_отл + m_приб) + m_литн
    τ = л["S"] * math.sqrt(G_ф)
    H_ст = (л["опока"][2] + 50.0) / 1000.0                    # от питателя (разъём) до верха чаши
    C = (к["z"][1] - к["z"][0]) / 1000.0                       # отливка вся в верхней полуформе
    H_р = H_ст - C / 2.0
    F_ст = G_ф / (л["ρ_жидк"] * л["μ"] * τ * math.sqrt(2.0 * GRAV * H_р)) * 1e4      # см²
    Lf, Bf, Hв, Hн = л["опока"]
    V_опок = Lf * Bf * (Hв + Hн) * 1e-9
    смесь_т = (V_опок - G_ф / ρ) * л["смесь"]["плотность"]
    # стержни: Ст. 1 - отверстие Ø26 со знаками по 20 мм, Ст. 2 - полость рукоятки со знаком наружу от лицевой
    # грани до разъёма формы (объём по 3D, CAD/src/twistlock.py стержень_2)
    d1 = к["d_отв"] - 2 * п["отверстие"]
    V_ст1 = math.pi * d1 ** 2 / 4.0 * (к["z"][1] - к["низ_z"] + 40.0)
    V_ст2 = 136400.0
    стерж_кг = (V_ст1 + V_ст2) * 1e-9 * л["смесь"]["плотность"] * 1000.0
    форм_на_плавку = int(л["плавка_кг"] * 0.95 // G_ф)
    out = dict(масса_детали=m_дет, масса_отливки=round(m_отл, 2), модуль_отливки=round(M_отл, 1), модуль_узла=round(M_узла, 1),
               модуль_прибыли=round(A_r / P_r, 1), модуль_нужен=round(M_приб, 1), прибыль=(Wr, Lr, Hп),
               масса_прибылей=round(m_приб, 2), питание_нужно_кг=round(нужно, 2), питание_отдаёт_кг=round(отдаёт, 2),
               металл_на_форму=round(G_ф, 1), литники_кг=round(m_литн, 2), τ_с=round(τ, 1), H_р_мм=round(H_р * 1000.0),
               F_ст=round(F_ст, 2), F_шл=round(1.2 * F_ст, 2), F_пит=round(1.4 * F_ст, 2), питателей=2 * n,
               d_стояка=round(math.sqrt(4.0 * F_ст / math.pi) * 10.0), пит_1=round(1.4 * F_ст / (2 * n), 2),
               выход_годного=round(100.0 * n * m_дет / G_ф, 1), смесь_на_форму_т=round(смесь_т, 3),
               смола_кг=round(смесь_т * 1000.0 * л["смесь"]["смола"] / 100.0, 2), стержни_кг=round(стерж_кг, 2),
               форм_на_плавку=форм_на_плавку, отливок_на_плавку=форм_на_плавку * n, модель_масштаб=1.0 + УСАДКА / 100.0)
    _КЭШ["отливка"] = out
    return out


def груз_на_форму():
    """Подъёмная сила металла на верхнюю полуформу и груз, который её держит (кН, кг). Разъём - по опорным
    полосам, отливка вся в верхней полуформе."""
    к, л = КОРПУС, ЛИТЬЁ
    о = отливка()
    n = л["отливок_в_форме"]
    S = n * к["габарит"][0] * к["габарит"][1] * 1e-6 + 0.25 * 0.03             # отливки и коллектор по разъёму, м²
    H_ст = (л["опока"][2] + 50.0) / 1000.0
    V_верх = n * (о["масса_отливки"] + о["масса_прибылей"] / 2.0) / МАТЕРИАЛЫ["20ГСЛ"]["ρ"]
    F_мет = л["ρ_жидк"] * GRAV * (S * H_ст - V_верх) / 1000.0
    F_ст = n * о["стержни_кг"] / (л["смесь"]["плотность"] * 1000.0) * (л["ρ_жидк"] - 1000.0 * л["смесь"]["плотность"]) * GRAV / 1000.0
    F = 1.3 * (F_мет + F_ст)
    Lf, Bf, Hв, _ = л["опока"]
    m_смеси = (Lf * Bf * Hв * 1e-9 - V_верх) * л["смесь"]["плотность"] * 1000.0
    m_опоки = 35.0                                           # опока верха 600 × 400 × 160, сварная - принято
    G_ = (m_смеси + m_опоки) * GRAV / 1000.0
    груз = max(0.0, (F - G_) * 1000.0 / GRAV)
    return dict(S_м2=round(S, 3), F_мет_кН=round(F_мет, 2), F_стержней_кН=round(F_ст, 2), F_кН=round(F, 2),
                вес_верха_кН=round(G_, 2), груз_кг=10.0 * math.ceil(груз / 10.0))


