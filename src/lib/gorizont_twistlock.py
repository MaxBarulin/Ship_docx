    M_р = 1000.0 * (р["r_конца"] - к["D_н"] / 2.0)
    row("Рычаг 09Г2С - изгиб, 1 кН на конце", "эксплуатация", M_р / (р["плечо"][0] * р["плечо"][1] ** 2 / 6.0), доп("09Г2С", "σ", "предельный"), "МПа",
        "плечо %.0f мм от стенки стакана, сечение %d × %d" % (р["r_конца"] - к["D_н"] / 2.0, р["плечо"][0], р["плечо"][1]))
    # 10. Усталость резьбы вала: отрыв пульсирует от нуля при каждом размахе качки
