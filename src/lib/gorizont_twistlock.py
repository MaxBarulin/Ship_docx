def мкэ():
    """Пересчёт отчётов МКЭ на корпус 20ГСЛ. Запас пропорционален пределу текучести: наименьший запас
    в обоих отчётах даёт одна точка с напряжением σ = σт / n."""
    σт = МАТЕРИАЛЫ["20ГСЛ"]["σт"]
    в = МКЭ["варианты"]
    σ_т = {k: v["σт"] / v["n_т"] for k, v in в.items()}
    n = min(v["n_т"] * σт / v["σт"] for v in в.values())
    return dict(σ_отч=round(max(σ_т.values()), 1), n_20ГСЛ=round(n, 2), n_в=round(МАТЕРИАЛЫ["20ГСЛ"]["σв"] / max(σ_т.values()), 2),
                P_отч=МКЭ["сила"] / 1000.0)


def запас_мкэ(P_кН):
    """Коэффициент запаса по текучести корпуса 20ГСЛ при сжатии P на опору - линейно от 33,1 кН."""
    return мкэ()["n_20ГСЛ"] * МКЭ["сила"] / 1000.0 / P_кН


