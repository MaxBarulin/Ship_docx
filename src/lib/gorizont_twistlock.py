# --- массы --------------------------------------------------------------------------------------
def _объём_запора():
    з = ЗАПОР
    L, W, hп, hк, (Lt, Wt) = з["голова"]
    A0, A1 = obround(L, W), obround(Lt, Wt)
    V_гол = A0 * hп + hк / 3.0 * (A0 + A1 + math.sqrt(A0 * A1))
    V_вал = math.pi * з["вал"] ** 2 / 4.0 * (з["z_вала"][1] - з["z_вала"][0])
    пр = з["проточка"]
    V_вал -= math.pi * (з["вал"] ** 2 - пр["d"] ** 2) / 4.0 * (пр["z"][1] - пр["z"][0])
    V_отв = math.pi * з["отв"] ** 2 / 4.0 * з["вал"]
    return V_гол + V_вал - V_отв, V_гол, V_вал - V_отв


def шайба_площадь():
    """Площадь шайбы-подковы в плане, мм² - круг D без отверстия d и без разреза шириной d до края."""
    ш = ШАЙБА
    return math.pi * (ш["D"] ** 2 - ш["d"] ** 2) / 4.0 - ш["разрез"] * (ш["D"] - ш["d"]) / 2.0


