def программа():
    """Программа выпуска на головное судно - 72 фундамента, ЗИП, установочная партия, разрушающие испытания."""
    n = len(_M().фундаменты())
    зип = int(math.ceil(0.05 * n))
    установочная = 6
    разрушающие = 1
    return dict(на_судно=n, зип=зип, установочная=установочная, разрушающие=разрушающие,
                всего=n + зип + разрушающие, серийная=n + зип + разрушающие - установочная)


def раскрой():
    """Раскрой листа 1500 × 6000 под платики: основная сетка и остаток полосой, повёрнутые платики."""
    Wл, Lл, t = 1500.0, 6000.0, ПЛАТИК["t"]
    рез, кромка = 4.0, 10.0
    a, b = ПЛАТИК["B"], ПЛАТИК["L"]
    nw = int((Wл - 2 * кромка + рез) // (a + рез))
    nl = int((Lл - 2 * кромка + рез) // (b + рез))
    остаток = Lл - 2 * кромка - nl * (b + рез)
    доп_ = int((Wл - 2 * кромка + рез) // (b + рез)) if остаток >= a else 0
