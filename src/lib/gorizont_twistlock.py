def _шов_группа():
    """Швы как линии с толщиной β·k: площадь, момент сопротивления при изгибе вокруг оси Y (сдвиг вдоль X)."""
    к, п = КОРПУС, КОРПУС["полоса"]
    a = ШОВ["β"] * ШОВ["катет"]
    l_т = к["кромка"] - п["x"][0]
    xc = (к["кромка"] + п["x"][0]) / 2.0
    A = a * шов_длина()
    I = п["n"] * a * п["длина"] * к["кромка"] ** 2 + 2 * п["n"] * (a * l_т ** 3 / 12.0 + a * l_т * xc ** 2)
    return dict(A=A, W=I / к["кромка"], a=a)


