        row("Головка - смятие днища фитинга", сл, N / (2.0 * свес * (W - 10.0)), доп("20ГЛ", "см", сл), "МПа",
            "две площадки %.0f × %.0f, фитинг литой, как корпус" % (свес, W - 10.0))
        # 2. Вал: растяжение по впадине резьбы, срез витков гайки
        d1 = 33.0 - 1.0825 * 1.5
        row("Вал 40Х - растяжение по резьбе %s" % з["резьба"], сл, N / (math.pi * d1 ** 2 / 4.0), доп("40Х", "σ", сл), "МПа",
            "внутренний диаметр резьбы %.1f мм" % d1)
        row("Гайка круглая - срез витков", сл, N / (math.pi * d1 * 10.0 * 0.75), доп("40Х", "τ", сл), "МПа",
            "высота гайки 10 мм, коэффициент полноты витка 0,75")
        # 3. Верхняя стенка стакана - кольцевая пластина под шайбой
        a, b_ = к["D_в"] / 2.0, 58.0 / 2.0
        β = _кольцевая_β(a / b_)
        row("Верхняя стенка стакана 20ГЛ - изгиб", сл, β * N / к["t_верх"] ** 2, доп("20ГЛ", "σ", сл), "МПа",
            "кольцевая пластина, заделка по стенке Ø%.0f, нагрузка по шайбе Ø58, a/b = %.2f, β = %.2f" % (к["D_в"], a / b_, β))
        # 4. Упор-центратор: смятие стенкой отверстия фитинга и срез по основанию
        Lу, Wу, hу = к["упор"]
        row("Упор - смятие стенкой отверстия фитинга", сл, Q / (hу * (Lу - Wу)), доп("20ГЛ", "см", сл), "МПа",
            "контакт по прямому участку %.0f мм на высоте %.0f" % (Lу - Wу, hу))
        A_осн = _obround_area(Lу, Wу) - math.pi * к["d_вал"] ** 2 / 4.0
        row("Упор - срез по основанию", сл, Q / A_осн, доп("20ГЛ", "τ", сл), "МПа", "площадь основания без отверстия вала %.0f мм²" % A_осн)
        # 5. Стенка стакана на уровне окна: отрыв + изгиб от сдвига
        z_Q = к["H"] + hу / 2.0
        A_ст = math.pi * (к["D_н"] ** 2 - к["D_в"] ** 2) / 4.0
        доля = 1.0 - к["окно"][2] / 360.0
        W_ст = math.pi * (к["D_н"] ** 4 - к["D_в"] ** 4) / (32.0 * к["D_н"])
        z_окна = 0.5 * (к["окно"][0] + к["окно"][1])
        σ_ок = N / (A_ст * доля) + Q * (z_Q - z_окна) / (0.5 * W_ст)
