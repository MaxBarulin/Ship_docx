"""Система раннего предупреждения качки и успокоительные цистерны.

Минимальное требование конкурсного задания, пункт «предусмотреть систему
раннего предупреждения качки». Здесь и состав системы, и расчёт пассивных
успокоительных цистерн U-образного типа, настроенных на период собственной
бортовой качки судна.

Почему это нужно именно нам: начальная метацентрическая высота 7,69 м при
ширине 16,5 м — судно очень остойчивое, но «жёсткое»: период качки 4,76 с,
ускорения на палубах высокие, пассажирам некомфортно. Цистерны гасят
резонансную качку, а система предупреждения даёт время увести судно с
резонансного курса до того, как качка разовьётся.

Настройка цистерны: период собственных колебаний жидкости в U-образной
цистерне

    T = 2 pi sqrt( (L_d * A_r / A_d + 2 h_r) / (2 g) )

где L_d — длина перепускного канала между бортовыми ветвями, A_r и A_d —
площади сечения ветви и канала, h_r — высота жидкости в ветви. Настройка
считается удачной, если T отличается от периода качки не более чем на 5 %.
"""

import math

from . import gorizont as G
from . import gorizont_hydro as H

GRAV = 9.81
RHO = 1.0                    # пресная вода в цистернах, т/м³

# Две цистерны: в корму и в нос от миделя, на первой палубе над вторым дном.
# Ветви разнесены к бортам, перепускной канал идёт под настилом.
# Ветви стоят в бортовых отсеках второго дна, где нет других цистерн:
# 46…58 м свободно между балластом 34…46 и пресной водой 58…80,
# 84…96 м — между сточными цистернами и балластом 100…116.
TANKS = [
    dict(code="УЦ-1", x0=46.0, x1=58.0, z0=0.00, note="в корму от миделя"),
    dict(code="УЦ-2", x0=84.0, x1=96.0, z0=0.00, note="в нос от миделя"),
]

BRANCH_B = 2.60              # ширина ветви поперёк судна, м
BRANCH_Y = 5.26              # отстояние оси ветви от диаметральной плоскости
DUCT_L = 10.52               # длина перепускного канала между ветвями, м
DUCT_H = 0.50                # высота канала, м
LEVEL = 0.45                 # рабочий уровень жидкости в ветви, м
AREA_RATIO = 1.0             # A_r / A_d — ветвь и канал равного сечения

# Состав системы раннего предупреждения: датчик, что меряет, зачем
SENSORS = [
    ("Инерциальный измерительный модуль MRU",
     "углы крена и дифферента, угловые скорости и ускорения, 100 Гц",
     "текущая качка и ускорения на палубах"),
    ("Гирокомпас с волоконно-оптическим датчиком",
     "курс и скорость поворота",
     "курсовой угол волнения, расчёт резонанса"),
    ("Волномерный радар X-диапазона",
     "высота, период и направление волн в радиусе 3 миль",
     "прогноз качки на 8…12 минут вперёд"),
    ("Метеостанция с датчиком ветра",
     "скорость и направление ветра, давление",
     "развитие волнения, ветровой крен"),
    ("Приёмник гидрометеопрогноза",
     "прогноз волнения по маршруту",
     "планирование курса и скорости на переходе"),
    ("Акселерометры на палубах, 6 точек",
     "вертикальные и боковые ускорения в залах и каютах",
     "контроль комфорта по ГОСТ Р ИСО 2631-1"),
]

# Что система делает с полученными данными
LOGIC = [
    "Считает период собственной бортовой качки по текущей остойчивости и "
    "сравнивает его с кажущимся периодом волны на текущем курсе.",
    "Строит карту резонансных курсов и скоростей и подсвечивает опасные "
    "секторы на экране в рубке.",
    "За 8…12 минут до входа в резонанс выдаёт предупреждение и предлагает "
    "уход по курсу или изменение скорости.",
    "Управляет уровнем в успокоительных цистернах: при малой качке жидкость "
    "перепускается в отстойник, чтобы не терять остойчивость на свободной "
    "поверхности.",
    "Пишет журнал качки и ускорений — он же вход для оценки комфорта и для "
    "системы автономного управления.",
]


def branch_area():
    """Площадь сечения ветви цистерны по ватерлинии жидкости, м²."""
    return BRANCH_B * (TANKS[0]["x1"] - TANKS[0]["x0"])


def tank_period(level=LEVEL, duct_l=DUCT_L, ratio=AREA_RATIO):
    """Период собственных колебаний жидкости в U-образной цистерне, с."""
    return 2.0 * math.pi * math.sqrt(
        (duct_l * ratio + 2.0 * level) / (2.0 * GRAV))


def required_duct(level=LEVEL, ratio=AREA_RATIO):
    """Какой длины нужен канал, чтобы попасть в период качки судна.

    Период качки сам зависит от массы жидкости в цистернах, поэтому
    настройка — задача с обратной связью: изменил длину канала, поехала
    масса, поехал период судна. Функция даёт длину под текущий период.
    """
    ts = H.roll_period()
    return round((2.0 * GRAV * (ts / (2.0 * math.pi)) ** 2 - 2.0 * level)
                 / ratio, 2)


def tuning(level=LEVEL, duct_l=DUCT_L, ratio=AREA_RATIO):
    """Сверка периода цистерны с периодом качки судна."""
    tt = tank_period(level, duct_l, ratio)
    ts = H.roll_period()
    return dict(tank=round(tt, 2), ship=round(ts, 2),
                delta=round(abs(tt - ts) / ts * 100.0, 1),
                ok=abs(tt - ts) / ts <= 0.05)


def water():
    """Масса рабочей жидкости и момент свободной поверхности."""
    a = branch_area()
    per_tank = 2.0 * a * LEVEL + DUCT_L * BRANCH_B * DUCT_H
    mass = per_tank * RHO * len(TANKS)
    # Момент свободной поверхности считается как для обычной цистерны —
    # момент инерции зеркала относительно собственной оси каждой ветви.
    # Переносный член A*y² сюда не входит: переток жидкости между ветвями
    # и есть полезное действие успокоителя, а не потеря остойчивости.
    l_tank = TANKS[0]["x1"] - TANKS[0]["x0"]
    i_branch = l_tank * BRANCH_B ** 3 / 12.0
    mfs = 2.0 * i_branch * RHO * len(TANKS)
    # без обращения к равновесию: водоизмещение само зависит от этой массы,
    # и вызов отсюда замкнул бы импорт
    return dict(volume=round(per_tank * len(TANKS), 1),
                mass=round(mass, 1),
                per_tank=round(per_tank, 1),
                mfs=round(mfs, 1))


def share():
    """Доля жидкости успокоителя от водоизмещения, %."""
    return round(water()["mass"] / H.equilibrium()["D"] * 100.0, 2)


def damping(reduction=0.45):
    """Оценка снижения амплитуды качки.

    Настроенная пассивная цистерна с массой жидкости около 1,5 % от
    водоизмещения снижает резонансную амплитуду на 40…55 %. Берётся нижняя
    граница диапазона: цистерна пассивная, без управления перепуском.
    """
    w = water()
    amp = H.weather_criterion()["theta_r"]
    return dict(theta_before=round(amp, 1),
                theta_after=round(amp * (1.0 - reduction), 1),
                reduction=int(reduction * 100),
                share=share())


def stability_cost():
    """Чем платим: потеря метацентрической высоты на свободной поверхности."""
    e = H.equilibrium()
    w = water()
    dh = w["mfs"] / e["D"]
    s = H.initial_stability()
    return dict(mfs=w["mfs"], dh=round(dh, 3), h_before=round(s["h"], 2),
                h_after=round(s["h"] - dh, 2),
                ok=(s["h"] - dh) >= 0.5)


def report():
    t = tuning()
    w = dict(water(), share=share())
    d = damping()
    c = stability_cost()
    return dict(tanks=TANKS, tuning=t, water=w, damping=d, cost=c,
                sensors=SENSORS, logic=LOGIC,
                geometry=dict(branch_b=BRANCH_B, branch_y=BRANCH_Y,
                              duct_l=DUCT_L, duct_h=DUCT_H, level=LEVEL,
                              length=TANKS[0]["x1"] - TANKS[0]["x0"]))


def checks():
    """Проверки, которые должны сойтись."""
    t = tuning()
    c = stability_cost()
    d = damping()
    return [
        dict(name="Настройка цистерны на период качки",
             value=t["tank"], allow=t["ship"], unit="с",
             ok=t["ok"], note="расхождение %.1f %% при допуске 5 %%"
             % t["delta"]),
        dict(name="Масса жидкости от водоизмещения",
             value=d["share"], allow=1.0, unit="%",
             ok=d["share"] >= 1.0,
             note="для заметного гашения нужно не менее 1 %"),
        dict(name="Метацентрическая высота с учётом свободной поверхности",
             value=c["h_after"], allow=0.5, unit="м", ok=c["ok"],
             note="норма РРР для пассажирских судов 0,5 м"),
    ]
