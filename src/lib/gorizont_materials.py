# -*- coding: utf-8 -*-
"""Сравнение сталей корпуса - 09Г2С, ВСт3сп5 и AH36.

Обоснование 09Г2С в записке было словесным. Здесь оно считается - для каждой
стали берётся допускаемое напряжение 0,60·ReH, сравнивается с расчётным
напряжением общей прочности и пересчитывается потребная масса связей и её
цена. Сталь, у которой допускаемое ниже расчётного, требует увеличения
связей пропорционально - отсюда и масса, и цена.

Характеристики - типовые значения по нормативным документам, названным в
поле `nd`. Цены - ориентир по прайсам металлотрейдеров осени 2025 года,
приведены для сравнения вариантов, а не как коммерческое предложение.
"""

from . import gorizont_strength as T
from . import gorizont_struct as S

# ReH, МПа; Rm, МПа (нижняя..верхняя); δ5, %; KCU, Дж/см² при t, °C;
# Cэкв, %; цена, тыс. руб/т
STEELS = [
    dict(key="ВСт3сп5", name="ВСт3сп5",
         nd="ГОСТ 380-2005, ГОСТ 535-2005",
         ReH=235.0, Rm=(370.0, 480.0), d5=26.0,
         kcu=29.0, kcu_t=-20.0, ceq=0.37, rho=7850.0, price=62.0,
         weld="Сваривается без подогрева до 30 мм, любые способы.",
         supply="Со склада, любой прокатный завод России.",
         note="Массовая углеродистая сталь обычной прочности."),
    dict(key="09Г2С", name="09Г2С, категория 12",
         nd="ГОСТ 19281-2014",
         ReH=325.0, Rm=(470.0, 630.0), d5=21.0,
         kcu=34.0, kcu_t=-40.0, ceq=0.42, rho=7850.0, price=78.0,
         weld="Сваривается без подогрева до 25 мм. При температуре ниже "
              "-10 °C подогрев 100…150 °C.",
         supply="Со склада, основная судостроительная марка РФ.",
         note="Низколегированная сталь повышенной прочности."),
    dict(key="AH36", name="AH36 / DH36",
         nd="Правила РС, МАКО UR W11",
         ReH=355.0, Rm=(490.0, 620.0), d5=21.0,
         kcu=34.0, kcu_t=-20.0, ceq=0.38, rho=7850.0, price=112.0,
         weld="Требует контроля погонной энергии 15…50 кДж/см и "
              "низководородных материалов.",
         supply="Под заказ, срок поставки 8…12 недель.",
         note="Судостроительная сталь повышенной прочности класса 36."),
]

SAFETY = 0.60            # доля ReH в допускаемом напряжении общей прочности
MIN_SCALE = 0.95         # ниже минимальных толщин РРР связи не уводят


def _max_sigma():
    """Наибольшее расчётное напряжение общей прочности, МПа."""
    r = T.stresses()
    return max(max(abs(row["sigma_deck"]), abs(row["sigma_bot"]))
               for row in r["rows"])


def compare():
    """Сравнение сталей по прочности, массе связей и цене."""
    sigma = _max_sigma()
    m0 = S.steel_weight()["m"]          # масса связей на 09Г2С, т
    base = next(s for s in STEELS if s["key"] == "09Г2С")
    out = []
    for st in STEELS:
        allow = SAFETY * st["ReH"]
        # потребное изменение момента сопротивления, а с ним и массы связей
        scale = max(MIN_SCALE, sigma / allow) if allow < sigma else \
            max(MIN_SCALE, base["ReH"] / st["ReH"])
        mass = m0 * scale
        out.append(dict(
            key=st["key"], name=st["name"], nd=st["nd"], ReH=st["ReH"],
            Rm=st["Rm"], d5=st["d5"], kcu=st["kcu"], kcu_t=st["kcu_t"],
            ceq=st["ceq"], price=st["price"], weld=st["weld"],
            supply=st["supply"], note=st["note"],
            allow=round(allow, 1), sigma=round(sigma, 1),
            ok=allow >= sigma,
            margin=round(allow / sigma, 3),
            scale=round(scale, 3),
            mass=round(mass, 0),
            cost=round(mass * st["price"] / 1000.0, 1),
            spec=round(st["ReH"] / (st["rho"] / 1000.0), 1)))
    return dict(sigma=round(sigma, 1), base_mass=round(m0, 0), rows=out)


def verdict():
    """Короткий вывод сравнения - тот же текст идёт в записку и на лист."""
    c = compare()
    by = {r["key"]: r for r in c["rows"]}
    v3, v9, ah = by["ВСт3сп5"], by["09Г2С"], by["AH36"]
    return [
        "Расчётное напряжение общей прочности %.1f МПа (прогиб на волне "
        "класса «М»)." % c["sigma"],
        "ВСт3сп5. Допускаемое %.0f МПа - ниже расчётного. Чтобы пройти, "
        "связи нужно усилить на %.0f %%, масса корпуса вырастет с %.0f до "
        "%.0f т." % (v3["allow"], (v3["scale"] - 1) * 100, c["base_mass"],
                     v3["mass"]),
        "При этом экономии нет - %.1f млн ₽ против %.1f млн ₽ у 09Г2С - "
        "дешёвая сталь съедает выигрыш массой."
        % (v3["cost"], v9["cost"]),
        "AH36 прошла бы с запасом %.0f %% и дала бы %.0f т экономии, но "
        "стоит %.1f млн ₽ - на %.0f %% дороже, и срок поставки 8…12 недель."
        % ((ah["margin"] - 1) * 100, c["base_mass"] - ah["mass"], ah["cost"],
           (ah["cost"] / v9["cost"] - 1) * 100),
        "09Г2С проходит с запасом %.0f %%, держит ударную вязкость при "
        "-40 °C (ледовые усиления «лёд 20») и есть на складе."
        % ((v9["margin"] - 1) * 100),
    ]
