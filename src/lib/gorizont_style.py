# -*- coding: utf-8 -*-
"""Дизайн-система проекта: цвет, форма, материалы.

Решение команды: корпус графитовый с красным акцентом в фирменной гамме
ОСК, пластика — плавная, ориентир по визуальному языку — новые речные
трамваи Москвы. Прототип по технике ПКС-180, но не по внешности: у него
ретро-стилизация, у нас современная.

Модуль — единственный источник цвета и материалов. Рендеры, схемы, планы
и презентация берут значения отсюда, поэтому судно на виде сбоку, на плане
палубы и на слайде окрашено одинаково. Раньше цвет жил в каждом скрипте
своей копией, и они расходились.

Формат цвета — hex для 2D-графики и линейный RGB для Blender: Blender
работает в линейном пространстве, и если положить в Principled BSDF
sRGB-значение напрямую, материал выйдет заметно светлее задуманного.
Перевод делает `linear()`, руками это пересчитывать не надо.

ВАЖНО: точное значение фирменного красного надо сверить с брендбуком ОСК
перед защитой. Здесь взят выверенный по контрасту оттенок, который
работает и на графите, и на светлом, но это наш подбор, а не выписка.
"""

# --- палитра -----------------------------------------------------------------
ПАЛИТРА = {
    "графит":          "#2E3338",   # борт корпуса, основной цвет судна
    "графит_тёмный":   "#20242A",   # подводная часть, тени, ниши колёс
    "графит_светлый":  "#3C444C",   # переходы, фальшборт
    "красный":         "#C8102E",   # фирменный акцент: полоса, колесо, знаки
    "красный_тёмный":  "#9E0C24",   # затенённые участки акцента
    "белый":           "#EDEFF1",   # надстройка, основной светлый объём
    "серый_тёплый":    "#C9CDD2",   # технические поверхности, леера
    "стекло":          "#1B2733",   # панорамное остекление, тонированное
    "дерево":          "#B08658",   # палубный настил, интерьерный акцент
    "дерево_тёмное":   "#6E4F30",   # мебель, интерьер
    "сталь":           "#8A9099",   # открытый металл, поручни
}

#: Фирменная пара, на которой держится всё остальное.
ОСНОВНЫЕ = ("графит", "красный")

# --- пластика ----------------------------------------------------------------
#: Правила формы. Это не пожелания, а то, что проверяется на модели:
#: если радиус скругления меньше указанного, силуэт разваливается на
#: коробки и перестаёт читаться как современное судно.
ФОРМА = dict(
    радиус_надстройки=1.20,      # скругление углов надстройки в плане, м
    радиус_носа=2.40,            # скругление передней кромки надстройки
    радиус_кромок=0.15,          # фаска всех видимых рёбер, м
    завал_борта=6.0,             # завал бортов надстройки внутрь, градусов
    лента_остекления=True,       # окна сливаются в непрерывную ленту
    высота_ленты=1.45,           # высота оконной ленты, м
    подоконник=0.85,             # низ ленты над палубой, м
    акцентная_полоса=0.35,       # ширина красной полосы вдоль борта, м
    полоса_над_ВЛ=1.10,          # высота оси полосы над ватерлинией, м
    окантовка_полосы=0.04,       # светлая отбивка сверху и снизу полосы, м
)

#: Красный на графите не читается — проверено `проверка_контраста()`:
#: 2,17 при пороге 3,0. Оба цвета тёмные, и на расстоянии полоса сливается
#: с бортом. Поднимать яркость красного нельзя, он перестанет быть
#: фирменным. Поэтому полоса идёт со светлой отбивкой в 40 мм сверху и
#: снизу: глаз цепляется за светлый контур, а красный работает как цвет.
#: Так сделано на речных трамваях и на всём пассажирском флоте до них.
ОТБИВКА_АКЦЕНТА = "белый"

#: Членение по высоте: тёмный низ, светлый верх, красная линия на стыке.
#: Ровно так сделаны речные трамваи, и работает это потому, что тёмный низ
#: зрительно опускает судно на воду, а светлый верх делает его лёгким.
ЧЛЕНЕНИЕ = [
    ("подводная часть",        "графит_тёмный", None,   1.20),
    ("борт корпуса",           "графит",        1.20,   3.00),
    ("акцентная полоса",       "красный",       1.10,   1.45),
    ("надстройка",             "белый",         3.00,   None),
]

# --- материалы для Blender ---------------------------------------------------
#: (цвет из палитры, шероховатость, металличность, пропускание)
МАТЕРИАЛЫ = {
    "Корпус_графит":      ("графит",         0.38, 0.15, 0.0),
    "Корпус_подводный":   ("графит_тёмный",  0.55, 0.10, 0.0),
    "Акцент_красный":     ("красный",        0.30, 0.10, 0.0),
    "Надстройка_белая":   ("белый",          0.35, 0.05, 0.0),
    "Остекление":         ("стекло",         0.05, 0.00, 0.85),
    "Колесо_плица":       ("красный",        0.45, 0.30, 0.0),
    "Колесо_обод":        ("сталь",          0.35, 0.85, 0.0),
    "Настил_дерево":      ("дерево",         0.55, 0.00, 0.0),
    "Леера_сталь":        ("сталь",          0.25, 0.90, 0.0),
    "Интерьер_дерево":    ("дерево_тёмное",  0.50, 0.00, 0.0),
    "Технические_серые":  ("серый_тёплый",   0.60, 0.20, 0.0),
}


def rgb(имя):
    """Цвет палитры как sRGB 0…1."""
    h = ПАЛИТРА[имя].lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def linear(имя):
    """Цвет палитры в линейном пространстве — то, что ждёт Blender.

    Principled BSDF принимает линейный RGB. Положить туда sRGB напрямую —
    типичная ошибка: графит выходит мышиным, красный — розовым.
    """
    def _c(v):
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    return tuple(_c(v) for v in rgb(имя))


def материал(имя):
    """Параметры материала для Principled BSDF."""
    цвет, шерох, металл, прозр = МАТЕРИАЛЫ[имя]
    return dict(name=имя, base_color=linear(цвет) + (1.0,),
                roughness=шерох, metallic=металл, transmission=прозр,
                hex=ПАЛИТРА[цвет])


def все_материалы():
    return [материал(k) for k in МАТЕРИАЛЫ]


def проверка_контраста():
    """Контраст акцента к фону: красный должен читаться и на графите, и на белом.

    Считается по относительной яркости WCAG. Порог 3:1 — минимум, при
    котором цветная деталь опознаётся на расстоянии, с которого смотрят
    на судно и на слайд.
    """
    def яркость(имя):
        r, g, b = linear(имя)
        return 0.2126 * r + 0.7152 * g + 0.0722 * b

    def пара(a, b):
        l1, l2 = яркость(a), яркость(b)
        hi, lo = max(l1, l2), min(l1, l2)
        return (hi + 0.05) / (lo + 0.05)

    out = []
    for фон in ("графит", "белый", "графит_тёмный"):
        k = пара("красный", фон)
        # Если красный сам по себе не читается, его вытягивает светлая
        # отбивка: значимым становится контраст отбивки к фону.
        k_отб = пара(ОТБИВКА_АКЦЕНТА, фон)
        out.append(dict(фон=фон, контраст=round(k, 2),
                        с_отбивкой=round(k_отб, 2),
                        ок=k >= 3.0 or k_отб >= 3.0,
                        нужна_отбивка=k < 3.0 <= k_отб))
    return out


def report():
    print("Дизайн-система: графит и фирменный красный, плавная пластика\n")
    print("Палитра:")
    for к, v in ПАЛИТРА.items():
        print("   %-18s %s" % (к, v))
    print("\nЧленение по высоте:")
    for имя, цвет, z0, z1 in ЧЛЕНЕНИЕ:
        низ = "от ОП" if z0 is None else "%.2f м" % z0
        верх = "до верха" if z1 is None else "%.2f м" % z1
        print("   %-22s %-16s %s … %s" % (имя, цвет, низ, верх))
    print("\nКонтраст красного к фону (порог 3,0):")
    for r in проверка_контраста():
        как = ("сам по себе" if r["контраст"] >= 3.0
               else "через отбивку %.2f" % r["с_отбивкой"])
        print("   на %-16s %5.2f  %s — %s" % (r["фон"], r["контраст"],
              "ок" if r["ок"] else "НЕ ЧИТАЕТСЯ", как))
    print("   отбивка: %s, %.0f мм сверху и снизу полосы"
          % (ОТБИВКА_АКЦЕНТА, ФОРМА["окантовка_полосы"] * 1000))
    print("\nМатериалов для Blender: %d" % len(МАТЕРИАЛЫ))


if __name__ == "__main__":
    report()
