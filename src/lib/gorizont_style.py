def rgb(имя):
    """Цвет палитры как sRGB 0…1."""
    h = ПАЛИТРА[имя].lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def linear(имя):
    """Цвет палитры в линейном пространстве - то, что ждёт Blender.

    Principled BSDF принимает линейный RGB. Положить туда sRGB напрямую -
    типичная ошибка. Графит выходит мышиным, красный - розовым.
    """
    def _c(v):
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    return tuple(_c(v) for v in rgb(имя))


def материал(имя):
    """Параметры материала для Principled BSDF."""
    цвет, шерох, металл, прозр = МАТЕРИАЛЫ[имя]
    return dict(name=имя, base_color=linear(цвет) + (1.0,),
                roughness=шерох, metallic=металл, transmission=прозр,
                hex=ПАЛИТРА[цвет])


def все_материалы():
    return [материал(k) for k in МАТЕРИАЛЫ]


def проверка_контраста():
    """Контраст акцента к фону - красный должен читаться и на графите, и на белом.

    Считается по относительной яркости WCAG. Порог 3:1 - минимум, при
    котором цветная деталь опознаётся на расстоянии, с которого смотрят
    на судно и на слайд.
    """
    def яркость(имя):
        r, g, b = linear(имя)
        return 0.2126 * r + 0.7152 * g + 0.0722 * b

    def пара(a, b):
        l1, l2 = яркость(a), яркость(b)
        hi, lo = max(l1, l2), min(l1, l2)
        return (hi + 0.05) / (lo + 0.05)

    out = []
    for фон in ("графит", "белый", "графит_тёмный"):
        k = пара("красный", фон)
        # Если красный сам по себе не читается, его вытягивает светлая
        # отбивка: значимым становится контраст отбивки к фону.
        k_отб = пара(ОТБИВКА_АКЦЕНТА, фон)
        out.append(dict(фон=фон, контраст=round(k, 2),
                        с_отбивкой=round(k_отб, 2),
                        ок=k >= 3.0 or k_отб >= 3.0,
                        нужна_отбивка=k < 3.0 <= k_отб))
    return out


