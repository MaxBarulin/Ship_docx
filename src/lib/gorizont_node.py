# -*- coding: utf-8 -*-
"""Узел для конструкторской документации: ось плицы с кривошипом ВГ-2026.31.00.

Зачем этот узел. Плица шарнирного колеса висит на оси, ось лежит в
подшипниках двух дисков обода, а кривошип на её конце через тягу и
неподвижный эксцентрик поворачивает плицу так, чтобы в воде она шла
отвесно. Ось несёт всю нагрузку плицы — рабочий упор и удар при входе в
воду, — и она же передаёт момент на кривошип. Узел сложный, сборочный, с
подшипниками, шпонками, посадками и расчётным случаем, поэтому он и взят
для чертежа, 3D-модели, спецификации и расчёта на прочность (блок 3 КЗ).

Геометрия сборки — та же, что в модели колеса `gorizont_wheel` и в
Blender (`blender_судно.колесо`): диски на ±1,48 м, ось сквозь диски,
кривошип внутри диска. Все размеры здесь в миллиметрах, силы в кН.
"""
import math
from . import gorizont as G
from . import gorizont_wheel as W

MARK = "ВГ-2026.31.00"
NAME = "Ось плицы с кривошипом"

# --- геометрия, мм -----------------------------------------------------------
D_AXIS = 100.0            # диаметр оси между дисками
D_JOURNAL = 90.0          # цапфа в подшипнике диска
L_JOURNAL = 110.0         # длина цапфы (толщина диска 100 + буртик)
DISC_Y = 1480.0           # диск обода от середины колеса (gorizont: d_диск = 1,48)
DISC_T = 100.0            # толщина диска
L_AXIS = 2.0 * (DISC_Y + DISC_T / 2.0) + 2.0 * 45.0   # общая длина оси с хвостовиками
BLADE_SPAN = W.BLADE_SPAN * 1000.0                   # рабочая длина плицы 2400
BLADE_H = W.BLADE_HEIGHT * 1000.0                    # высота плицы 700
BLADE_T = W.BLADE_THICK * 1000.0                     # толщина полотна 35
HUB_Y = (350.0, 1050.0)   # ступицы плицы: две пары, симметрично от середины
HUB_L = 160.0             # длина ступицы вдоль оси
HUB_D = 160.0             # наружный диаметр ступицы (разъёмный хомут)
LUG_T = 12.0              # проушина к полотну
KEY = (28, 16, 160)       # шпонка призматическая b x h x l ГОСТ 23360
CRANK_L = W.LEVER * 1000.0            # межцентровое кривошипа 600
CRANK_T = 30.0                        # толщина щеки кривошипа
CRANK_W = 140.0                       # ширина щеки
CRANK_HUB_D = 200.0                   # ступица кривошипа
CRANK_Y = DISC_Y - DISC_T / 2.0 - 90.0    # кривошип внутри диска: шпонка 160 не доходит до диска
PIN_D = 60.0              # палец кривошипа под головку тяги
PIN_L = 120.0
BUSH_D_OUT = 110.0        # втулка подшипника: наружный диаметр
BUSH_L = 100.0
NUT = "М80x3"             # гайка на хвостовике, с шайбой стопорной

# --- материалы ---------------------------------------------------------------
STEEL_AXIS = dict(name="Сталь 40Х ГОСТ 4543-2016, улучшение", sigma_t=785.0, sigma_b=980.0,
                  sigma_m1=410.0,   # предел выносливости при изгибе, МПа
                  rho=7850.0)
STEEL_STRUCT = dict(name="Сталь 09Г2С ГОСТ 19281-2014", sigma_t=345.0, sigma_b=490.0, rho=7850.0)
BUSHING = dict(name="Полимер Thordon SXL (аналог — капролон ПА-6 ГОСТ 24698)",
               p_allow=5.5,      # допускаемое давление, МПа, при смазке водой
               pv_allow=0.7)     # МПа·м/с
BOLT = dict(name="Болт М16 ГОСТ 7798-70, класс 8.8", d=16.0, sigma_t=640.0, n=8)

# --- нагрузки ----------------------------------------------------------------
K_DYN = 1.5               # динамика: топляк, рывки хода, неравномерность обода
K_SAFETY = 2.0            # требуемый запас по текучести в расчётном случае


def loads():
    """Нагрузки на плицу и ось из гидродинамики колеса."""
    from . import gorizont_hydro as H
    e = H.equilibrium()
    R = H.resistance(G.SPEED_KMH, T=e["T"])["R"]
    р = W.operating_point(R, G.SPEED_KMH)
    н = W.blade_load(G.SPEED_KMH, р["скольжение"])
    F_раб = н["F_рабочая"]
    F_удар = н["p_удара"] * н["площадь_плицы"]
    F = K_DYN * max(F_раб, F_удар)
    # момент на оси плицы: центр давления смещён от оси на PIVOT_OFFSET
    # плюс четверть высоты полотна при входе кромкой
    плечо = W.PIVOT_OFFSET + 0.25 * W.BLADE_HEIGHT
    M_t = F * плечо
    F_тяги = M_t / W.LEVER
    return dict(F_рабочая=F_раб, F_удара=F_удар, F_расчётная=F, плечо_момента=плечо,
                M_кручения=M_t, F_тяги=F_тяги, об_мин=р["об_мин"], p_удара=н["p_удара"])


def strength():
    """Расчёт на прочность: ось, подшипники, кривошип, палец, шпонка, болты."""
    l = loads()
    F = l["F_расчётная"]                      # кН
    # ось как балка на двух опорах (диски), нагрузка равномерная по плице
    L = 2.0 * DISC_Y / 1000.0                 # пролёт между дисками, м
    a = BLADE_SPAN / 2000.0                   # полудлина нагруженного участка, м
    q = F / (2.0 * a)                         # кН/м
    R_оп = F / 2.0
    M = R_оп * L / 2.0 - q * a * a / 2.0      # кН·м, в середине пролёта
    W_axis = math.pi * (D_AXIS / 1000.0) ** 3 / 32.0
    sigma = M / W_axis / 1000.0               # МПа
    # кручение оси от момента плицы (передаётся на кривошип)
    Wp = math.pi * (D_AXIS / 1000.0) ** 3 / 16.0
    tau = l["M_кручения"] / Wp / 1000.0
    sigma_eq = math.sqrt(sigma ** 2 + 3.0 * tau ** 2)
    n_axis = STEEL_AXIS["sigma_t"] / sigma_eq
    # выносливость: пульсирующий цикл (нагрузка в воде четверть оборота)
    k_sigma = 2.4                              # эффективный концентратор у шпоночного паза
    eps = 0.70                                 # масштабный фактор для Ø100
    sigma_a = sigma_eq / 2.0
    n_fat = STEEL_AXIS["sigma_m1"] / (k_sigma / eps * sigma_a + 0.1 * sigma_a)
    # цапфа в подшипнике
    W_j = math.pi * (D_JOURNAL / 1000.0) ** 3 / 32.0
    M_j = R_оп * 0.045                         # момент на консоли цапфы до середины подшипника
    sigma_j = M_j / W_j / 1000.0
    p_bush = R_оп * 1000.0 / (D_JOURNAL * BUSH_L)          # МПа
    v_bush = math.pi * D_JOURNAL / 1000.0 * l["об_мин"] / 60.0 * 2.0   # скорость качания ≈ 2 оборота плицы на оборот
    pv = p_bush * v_bush
    # кривошип: изгиб щеки силой тяги
    F_t = l["F_тяги"]
    M_c = F_t * (CRANK_L / 1000.0)
    W_c = CRANK_T / 1000.0 * (CRANK_W / 1000.0) ** 2 / 6.0
    sigma_c = M_c / W_c / 1000.0
    # палец кривошипа: срез и смятие
    A_pin = math.pi * (PIN_D / 1000.0) ** 2 / 4.0
    tau_pin = F_t / A_pin / 1000.0
    p_pin = F_t * 1000.0 / (PIN_D * (PIN_L - 20.0))
    # шпонка кривошипа: смятие
    b, h, lk = KEY
    p_key = l["M_кручения"] * 1e6 / (D_AXIS / 2.0) / ((h / 2.0) * (lk - b))   # Н/мм² при M в кН·м → 1e6 Н·мм
    # болты ступицы плицы: растяжение от F на одну ступицу (4 ступицы, по 8 болтов)
    F_hub = F / len(HUB_Y) / 2.0
    A_b = math.pi * (BOLT["d"] * 0.85 / 1000.0) ** 2 / 4.0
    sigma_b = F_hub / BOLT["n"] / A_b / 1000.0
    return dict(
        F=F, M_изгиба=M, sigma_изгиба=sigma, tau=tau, sigma_экв=sigma_eq,
        n_ось=n_axis, n_усталость=n_fat, sigma_цапфы=sigma_j, p_подшипника=p_bush,
        pv=pv, sigma_кривошипа=sigma_c, tau_пальца=tau_pin, p_пальца=p_pin,
        p_шпонки=p_key, sigma_болта=sigma_b, R_опоры=R_оп,
        ok=dict(ось=n_axis >= K_SAFETY, усталость=n_fat >= 1.5,
                подшипник=p_bush <= BUSHING["p_allow"] and pv <= BUSHING["pv_allow"],
                кривошип=STEEL_STRUCT["sigma_t"] / sigma_c >= K_SAFETY,
                палец=STEEL_AXIS["sigma_t"] * 0.6 / tau_pin >= K_SAFETY,
                шпонка=p_key <= 150.0,
                болты=BOLT["sigma_t"] / sigma_b >= 2.5))


def mass():
    """Масса деталей узла, кг."""
    rho = STEEL_AXIS["rho"] / 1e9        # кг/мм³
    axis = math.pi * (D_AXIS / 2.0) ** 2 * (L_AXIS - 2 * L_JOURNAL) * rho \
        + 2.0 * math.pi * (D_JOURNAL / 2.0) ** 2 * L_JOURNAL * rho
    hub = (math.pi * ((HUB_D / 2.0) ** 2 - (D_AXIS / 2.0) ** 2) * HUB_L
           + 2.0 * LUG_T * 120.0 * 220.0) * STEEL_STRUCT["rho"] / 1e9
    crank = (CRANK_T * CRANK_W * CRANK_L + math.pi * ((CRANK_HUB_D / 2.0) ** 2 - (D_AXIS / 2.0) ** 2) * 80.0) \
        * STEEL_STRUCT["rho"] / 1e9
    pin = math.pi * (PIN_D / 2.0) ** 2 * PIN_L * rho
    bush = math.pi * ((BUSH_D_OUT / 2.0) ** 2 - (D_JOURNAL / 2.0) ** 2) * BUSH_L * 1.2e-6
    return dict(ось=axis, ступица=hub, кривошип=crank, палец=pin, втулка=bush,
                всего=axis + 4 * hub + crank + pin + 2 * bush + 2.5)


