_ТИПЫ = []


def типы_кают():
    """Пассажирские каюты по типам в порядке прайса: кают, мест, площадь, окно, категория КЗ, описание."""
    if not _ТИПЫ:
        _ТИПЫ.extend(_типы_кают())
    return [dict(r, пл=list(r["пл"])) for r in _ТИПЫ]


def _типы_кают():
    по = {}
    for c in GA.расстановка():
        if c["категория"] == "экипаж":
            continue
        r = по.setdefault(c["тип"], dict(тип=c["тип"], кают=0, мест=0, пл=[], окно=c["окно"],
                                        категория=c["категория"]))
        r["кают"] += 1
        r["мест"] += c["мест"]
        r["пл"].append(c["площадь"])
    out = []
    for т in ТИПЫ_КАЮТ + tuple(sorted(set(по) - set(ТИПЫ_КАЮТ))):
        if т not in по:
            continue
        r = по[т]
        a, b = min(r["пл"]), max(r["пл"])
        r["площадь"] = ч(a, 1).replace(",0", "") if abs(a - b) < 0.05 else "%s…%s" % (ч(a, 1), ч(b, 1))
        r["описание"] = _ОПИСАНИЕ.get(т, "%s м²") % r["площадь"]
        out.append(r)
    return out


def прайс():
    """Цены по типам кают и выручка за рейс при полной загрузке."""
    out = []
    for r in типы_кают():
        т = r["тип"]
        ц, цс = ЦЕНА_КРУИЗА.get(т), ЦЕНА_СУТОК.get(т)
        out.append(dict(r, цена=ц, цена_суток=цс,
                        сутки_полного=None if ц is None else ц / R.ДНЕЙ,
                        скидка_полного=None if not (ц and цс) else 100.0 * (1 - ц / (цс * R.ДНЕЙ)),
                        за_рейс=None if ц is None else ц * r["мест"]))
    return out


def выручка_за_рейс(загрузка=1.0):
    """Круизная выручка одного рейса, руб."""
    return sum(r["за_рейс"] for r in прайс()) * загрузка


def средняя_цена():
    """Средневзвешенная цена путёвки (по местам в каютах), руб. за круиз и за сутки."""
    мест = sum(r["мест"] for r in прайс())
    ц = выручка_за_рейс() / мест
    return dict(круиз=ц, сутки=ц / R.ДНЕЙ, мест=мест)


def продажи(загрузка=None):
    """Путёвки за навигацию по типам кают и по сегментам. Путёвка - один пассажир на полный круиз."""
    з = ЗАГРУЗКА if загрузка is None else загрузка
    рейсов = рейсов_в_навигацию()
    по_типам = []
    for r in прайс():
        мест_нав = r["мест"] * рейсов
        по_типам.append(dict(тип=r["тип"], мест_за_навигацию=мест_нав, путёвок=int(round(мест_нав * з)),
                             цена=r["цена"]))
    for r in по_типам:
        r["выручка"] = r["путёвок"] * r["цена"]
    всего = sum(r["путёвок"] for r in по_типам)
    тр = объём_рынка()
    по_сегментам = []
    for с, р in zip(СЕГМЕНТЫ, тр["сегменты"]):
        мои = [r for r in по_типам if r["тип"] in с["каюты"]]
        п = sum(r["путёвок"] for r in мои)
        по_сегментам.append(dict(сегмент=с["имя"], кратко=с["кратко"], каюты=", ".join(с["каюты"]),
                                 мест_за_навигацию=sum(r["мест_за_навигацию"] for r in мои), путёвок=п,
                                 доля=100.0 * п / всего, доля_TAM=100.0 * п / р["пассажиров"]))
    мест_нав = sum(r["мест_за_навигацию"] for r in по_типам)
    return dict(рейсов=рейсов, загрузка=з, мест_за_навигацию=мест_нав, путёвок=всего,
                загрузка_факт=100.0 * всего / мест_нав, по_типам=по_типам, по_сегментам=по_сегментам,
                доля_SAM=100.0 * всего / тр["SAM"], доля_TAM=100.0 * всего / тр["TAM"],
                доля_SOM=100.0 * всего / тр["SOM"],
                судов_под_SAM=тр["SAM"] / всего)


def выручка():
    """Выручка за навигацию - круизы по типам кают плюс дополнительные услуги, руб."""
    п = продажи()
    круизы = sum(r["выручка"] for r in п["по_типам"])
    доп = круизы * ДОЛЯ_ДОП_ВЫРУЧКИ / 100.0
    гараж = G.GARAGE["places"] * п["рейсов"] * ДОПУСЛУГИ[0]["руб"]
    return dict(круизы=круизы, доп=доп, итого=круизы + доп, за_рейс_средняя=круизы / п["рейсов"],
                за_рейс_полная=выручка_за_рейс(), гараж_потолок=гараж, путёвок=п["путёвок"],
                статьи=[dict(r, доля=100.0 * r["выручка"] / (круизы + доп)) for r in п["по_типам"]]
                + [dict(тип="дополнительные услуги", путёвок=None, цена=None, выручка=доп,
                        доля=100.0 * доп / (круизы + доп))])


def объём_рынка():
    """TAM, SAM, SOM в пассажирах (путёвках) в год. Группы (заказы) - делением на места в каюте сегмента.

    База сегментов 1…3 - пассажиры (доля пассажиров круизов), база сегмента 4 - люди с
    инвалидностью, каждый едет с сопровождающим, поэтому там наоборот - пассажиров = групп × мест.
    """
    сег = []
    for с, в in zip(СЕГМЕНТЫ, ОБЪЁМ_РЫНКА_ВХОД):
        в_группе = GA.КАЮТЫ[с["каюты"][0]]["мест"]
        потенциальных = в["база"] * в["в_базе"] / 100.0
        ёмкость = потенциальных * в["целевых"] / 100.0
        if в["единица"] == "пассажир":
            пасс, групп = ёмкость, ёмкость / в_группе
        else:
            пасс, групп = ёмкость * в_группе, ёмкость
        сег.append(dict(сегмент=с["имя"], кратко=с["кратко"], база=в["база"], база_что=в["база_что"],
                        в_базе=в["в_базе"], потенциальных=потенциальных, целевых=в["целевых"],
                        единица=в["единица"], ёмкость=ёмкость, в_группе=в_группе,
                        пассажиров=пасс, групп=групп))
    tam = sum(r["пассажиров"] for r in сег)
    sam = tam * ДОЛЯ_SAM / 100.0
    som = sam * ДОЛЯ_SOM / 100.0
    ц = средняя_цена()["круиз"]
    return dict(сегменты=сег, TAM=tam, SAM=sam, SOM=som, групп=sum(r["групп"] for r in сег),
                TAM_руб=tam * ц, SAM_руб=sam * ц, SOM_руб=som * ц,
                доля_круизов=100.0 * КРУИЗНЫХ_ПАССАЖИРОВ_2025 / РЕЧНЫХ_ПАССАЖИРОВ_2025)


def сравнение_цен():
    """Цены аналогов за сутки против наших цен суток полного круиза."""
    наши = {r["тип"]: r for r in прайс()}
    out = []
    for а in АНАЛОГИ_ЦЕН:
        (с0, с1), (ц0, ц1) = а["суток"], а["цена"]
        сут_мин, сут_макс = ц0 / с1, ц1 / с0
        мы = [наши[т]["сутки_полного"] for т in а["наш"]]
        разница = [100.0 * (1 - м / сут_макс) for м in мы] + [100.0 * (1 - м / сут_мин) for м in мы]
        out.append(dict(а, сут_мин=сут_мин, сут_макс=сут_макс, наши_сутки=мы,
                        дешевле_мин=min(разница), дешевле_макс=max(разница),
                        наша_цена=[наши[т]["цена"] for т in а["наш"]]))
    return out


