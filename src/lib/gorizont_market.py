def рейсов_в_навигацию():
    return НАВИГАЦИЯ_СУТ // ОБОРОТ_СУТ


def вместимость():
    """Места на рейс и в навигацию по сегментам - из расстановки кают."""
    каюты = [c for c in GA.расстановка() if c["категория"] != "экипаж"]
    рейсов = рейсов_в_навигацию()
    out = []
    занято = set()
    for с in СЕГМЕНТЫ:
        мои = [c for c in каюты if c["тип"] in с["каюты"]]
        занято |= set(с["каюты"])
        мест = sum(c["мест"] for c in мои)
        out.append(dict(сегмент=с["имя"], каюты=", ".join(с["каюты"]), кают=len(мои), мест=мест,
                        доля=round(100.0 * мест / GA.итоги()["пассажиров"], 1),
                        в_навигацию=мест * рейсов, мотив=с["мотив"], география=с["география"], каналы=с["каналы"]))
    непокрытые = sorted({c["тип"] for c in каюты} - занято)
    return dict(строки=out, рейсов=рейсов, всего_мест=GA.итоги()["пассажиров"],
                всего_в_навигацию=GA.итоги()["пассажиров"] * рейсов, непокрытые=непокрытые)


def checks():
    в = вместимость()
    out = []

    def c(name, value, allow, unit, ok, note):
        out.append(dict(name=name, value=value, allow=allow, unit=unit, ok=bool(ok), note=note))

    c("Все типы кают отнесены к сегменту", len(в["непокрытые"]), 0, "типов", not в["непокрытые"],
      "без сегмента - %s" % (", ".join(в["непокрытые"]) or "-"))
    s = sum(r["доля"] for r in в["строки"])
    c("Доли сегментов складываются в 100 %", round(s, 1), 100, "%", abs(s - 100) < 0.6, "по местам в каютах")
    c("Рейсов в навигацию", в["рейсов"], 10, "рейсов", в["рейсов"] >= 10,
      "%d суток навигации / %d суток оборота" % (НАВИГАЦИЯ_СУТ, ОБОРОТ_СУТ))
    m4 = sum(r["мест"] for r in в["строки"] if "М4" in r["каюты"])
    c("Сегмент М4 не меньше нормы КЗ", m4, G.M4_REQUIRED, "мест", m4 >= G.M4_REQUIRED, "шесть кают М4")
    return out


