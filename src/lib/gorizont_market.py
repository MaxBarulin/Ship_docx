def ч(x, n=0):
    """Число по-русски: запятая в дробях, пробел в разрядах от 10 000 - «287 392 000», «4,8», «1944»."""
    s = "%.*f" % (n, x)
    цел, _, дробь = s.partition(".")
    знак = "-" if цел.startswith("-") else ""
    цел = цел.lstrip("-")
    if len(цел) > 4:
        цел = " ".join(цел[max(0, i - 3):i] for i in range(len(цел), 0, -3)[::-1])
    return знак + цел + ("," + дробь if дробь else "")


