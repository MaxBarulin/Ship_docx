def рейсов_в_навигацию():
    return НАВИГАЦИЯ_СУТ // ОБОРОТ_СУТ


def вместимость():
    """Места на рейс и в навигацию по сегментам - из расстановки кают."""
    каюты = [c for c in GA.расстановка() if c["категория"] != "экипаж"]
    рейсов = рейсов_в_навигацию()
    out = []
    занято = set()
    for с in СЕГМЕНТЫ:
        мои = [c for c in каюты if c["тип"] in с["каюты"]]
        занято |= set(с["каюты"])
        мест = sum(c["мест"] for c in мои)
        out.append(dict(сегмент=с["имя"], каюты=", ".join(с["каюты"]), кают=len(мои), мест=мест,
                        доля=round(100.0 * мест / GA.итоги()["пассажиров"], 1),
                        в_навигацию=мест * рейсов, мотив=с["мотив"], география=с["география"], каналы=с["каналы"]))
    непокрытые = sorted({c["тип"] for c in каюты} - занято)
    return dict(строки=out, рейсов=рейсов, всего_мест=GA.итоги()["пассажиров"],
                всего_в_навигацию=GA.итоги()["пассажиров"] * рейсов, непокрытые=непокрытые)


