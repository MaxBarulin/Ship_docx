def _тексты_данных():
    """Все тексты данных рынка одной строкой - для проверки слов, которых там быть не должно."""
    части = [СЕГМЕНТЫ, НАДСТРОЙКИ_СПРОСА, ПОЗИЦИОНИРОВАНИЕ, ОБЪЁМ_РЫНКА_ВХОД, ДОПУСЛУГИ, КОНКУРЕНТЫ,
             АНАЛОГИ_ЦЕН, _ОПИСАНИЕ, pest(), swot(), матрица_swot(), стратегия_4p(),
             [r["описание"] for r in типы_кают()]]
    return repr(части).lower()


def checks():
    в = вместимость()
    out = []

    def c(name, value, allow, unit, ok, note):
        out.append(dict(name=name, value=value, allow=allow, unit=unit, ok=bool(ok), note=note))

    c("Все типы кают отнесены к сегменту", len(в["непокрытые"]), 0, "типов", not в["непокрытые"],
      "без сегмента - %s" % (", ".join(в["непокрытые"]) or "-"))
    s = sum(r["доля"] for r in в["строки"])
    c("Доли сегментов складываются в 100 %", round(s, 1), 100, "%", abs(s - 100) < 0.6, "по местам в каютах")
    c("Рейсов в навигацию", в["рейсов"], 10, "рейсов", в["рейсов"] >= 10,
      "%d суток навигации / %d суток оборота" % (НАВИГАЦИЯ_СУТ, ОБОРОТ_СУТ))
    m4 = sum(r["мест"] for r in в["строки"] if "М4" in r["каюты"])
    c("Сегмент М4 не меньше нормы КЗ", m4, G.M4_REQUIRED, "мест", m4 >= G.M4_REQUIRED, "шесть кают М4")

    # --- цены, продажи, выручка ---
    типы = {r["тип"] for r in типы_кают()}
    без_цены = sorted(т for т in типы if т not in ЦЕНА_КРУИЗА or т not in ЦЕНА_СУТОК)
    c("Цены заданы для всех типов кают", len(без_цены), 0, "типов", not без_цены, ", ".join(без_цены) or "шесть типов")
    ряд = [ЦЕНА_КРУИЗА[т] for т in ("эконом", "стандарт", "бизнес", "люкс")]
    c("Цена растёт от эконома к люксу", ряд[-1], ряд[0], "руб.", all(a < b for a, b in zip(ряд, ряд[1:])),
      "эконом < стандарт < бизнес < люкс")
    дороже = [т for т in типы if ЦЕНА_КРУИЗА[т] > ЦЕНА_СУТОК[т] * R.ДНЕЙ + 0.5]
    ск = [r["скидка_полного"] for r in прайс()]
    c("Полный круиз не дороже суток × %d" % R.ДНЕЙ, len(дороже), 0, "типов", not дороже,
      ", ".join(дороже) or "скидка полного круиза %s…%s %%" % (ч(min(ск), 1), ч(max(ск), 1)))
    c("Загрузка в пределах 0…100 %", round(100 * ЗАГРУЗКА), 100, "%", 0 < ЗАГРУЗКА <= 1, "вход маркетинга")
    п = продажи()
    лишние = [r["тип"] for r in п["по_типам"] if r["путёвок"] > r["мест_за_навигацию"]]
    c("Путёвок не больше мест × рейсов", п["путёвок"], п["мест_за_навигацию"], "путёвок",
      not лишние and п["путёвок"] <= _И["пассажиров"] * рейсов_в_навигацию(), "%d мест × %d рейсов" % (_И["пассажиров"], п["рейсов"]))
    сп = sum(r["доля"] for r in п["по_сегментам"])
    c("Доли продаж по сегментам - 100 %", round(сп, 1), 100, "%", abs(сп - 100) < 0.05, "по путёвкам")
    # выручка независимо - по каждой каюте расстановки
    полная = sum(ЦЕНА_КРУИЗА[к["тип"]] * к["мест"] for к in GA.расстановка() if к["категория"] != "экипаж")
    вр = выручка()
    c("Выручка за рейс = цены × места", round(вр["за_рейс_полная"]), round(полная), "руб.",
      abs(вр["за_рейс_полная"] - полная) < 1, "полная загрузка, по каютам расстановки")
    точно = полная * п["рейсов"] * ЗАГРУЗКА
    допуск = 0.5 * sum(ЦЕНА_КРУИЗА[т] for т in типы)
    c("Выручка за навигацию = цены × проданные места", round(вр["круизы"]), round(точно), "руб.",
      abs(вр["круизы"] - точно) <= допуск, "расхождение %s руб. - округление путёвок до целых" % ч(вр["круизы"] - точно))
    р = объём_рынка()
    c("SOM покрывает продажи", round(р["SOM"]), п["путёвок"], "путёвок", р["SOM"] >= п["путёвок"],
      "план продаж - %s %% SOM" % ч(п["доля_SOM"], 1))
    б = _тексты_данных().count("балкон")
    c("Балконов в данных нет", б, 0, "упоминаний", б == 0, "бортовые каюты с панорамным остеклением")
    return out


