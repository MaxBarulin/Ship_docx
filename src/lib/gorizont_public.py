# --- геометрия ---------------------------------------------------------------
def ярус(палуба):
    return "главная" if палуба == "главная" else "средняя"


def борт(палуба, x0, x1, отступ=ОТСТУП_БОРТ):
    """Линия, дальше которой к борту мебель не ставится: зашивка минус отступ,
    на высоте 2,2 м над палубой (самый узкий уровень с завалом), минимум по x."""
    z = G.DECKS[палуба] + 2.2
    xs = [x0 + (x1 - x0) * i / 8.0 for i in range(9)]
    return min(SU.полуширота(x, ярус(палуба), z=z) for x in xs) - G.LINING / 2.0 - отступ


def _п(имя, кл, палуба, x0, x1, y0, y1, h=None):
    return dict(имя=имя, класс=кл, палуба=палуба, x0=round(x0, 3), x1=round(x1, 3),
                y0=round(min(y0, y1), 3), y1=round(max(y0, y1), 3), h=ВЫСОТА[кл] if h is None else h)


def _стол4(имя, палуба, cx, cy, a=0.9):
    """Квадратный стол на четверых со стульями по сторонам."""
    out = [_п(имя, "стол", палуба, cx - a / 2, cx + a / 2, cy - a / 2, cy + a / 2)]
    s = 0.45
    for k, (dx, dy) in enumerate(((0, a / 2 + 0.1), (0, -a / 2 - 0.1 - s), (a / 2 + 0.1, 0), (-a / 2 - 0.1 - s, 0))):
        if k < 2:
            out.append(_п(имя + "_стул%d" % k, "стул", палуба, cx - s / 2, cx + s / 2, cy + dy, cy + dy + s))
        else:
            out.append(_п(имя + "_стул%d" % k, "стул", палуба, cx + dx, cx + dx + s, cy - s / 2, cy + s / 2))
    return out


def _стол6(имя, палуба, cx, cy, знак):
    """Стол у окна на шестерых: столешница 1,8 x 0,8 и два дивана вдоль."""
    out = [_п(имя, "стол", палуба, cx - 0.9, cx + 0.9, cy - 0.4, cy + 0.4)]
    out.append(_п(имя + "_диван_борт", "диван", палуба, cx - 0.9, cx + 0.9, cy + 0.5, cy + 1.0) if знак > 0
               else _п(имя + "_диван_борт", "диван", палуба, cx - 0.9, cx + 0.9, cy - 1.0, cy - 0.5))
    out.append(_п(imя_(имя, "_диван_дп"), "диван", палуба, cx - 0.9, cx + 0.9, cy - 1.0, cy - 0.5) if знак > 0
               else _п(imя_(имя, "_диван_дп"), "диван", палуба, cx - 0.9, cx + 0.9, cy + 0.5, cy + 1.0))
    return out


def imя_(a, b):
    return a + b


