# --- проёмы переборок и колодцы палуб -----------------------------------------
def _коридоры(палуба, x):
    """Полосы коридоров кают, примыкающих к абсциссе x: [(y0, y1)] со знаком."""
    out = []
    for c in GA.расстановка():
        if c["палуба"] != палуба or not (abs(c["x0"] - x) < 1e-6 or abs(c["x1"] - x) < 1e-6):
            continue
        знак = 1 if c["борт"] == "ПБ" else -1
        a0, a1 = sorted((abs(c["y0"]), abs(c["y1"])))
        if c["ряд"] == "борт":
            out.append((знак * (a0 - GA.КОРИДОР), знак * a0))
        else:
            out.append((знак * a1, знак * (a1 + GA.КОРИДОР)))
    # объединить одинаковые
    res = []
    for y0, y1 in out:
        y0, y1 = sorted((round(y0, 2), round(y1, 2)))
        if (y0, y1) not in res:
            res.append((y0, y1))
    return res


def проёмы_переборки(палуба, x):
    """Проёмы (двери, проходы) в поперечной переборке зоны на абсциссе x: [(y0, y1)]."""
    зоны = GA.ЗОНЫ[палуба]
    виды = [z[2] for z in зоны if abs(z[0] - x) < 1e-6 or abs(z[1] - x) < 1e-6]
    if not виды:
        return []
    out = []
    if "cabins" in виды:
        out += _коридоры(палуба, x)
    if "trunk" in виды:
        out += [(1.7, 3.9), (-3.9, -1.7)]
    if палуба == "главная" and x in (74.0, 84.0):
        out += [(3.70, 5.10), (-5.10, -3.70)]
        if x == 84.0:
            out.append((-1.0, 1.0))
    if палуба == "главная" and x == 5.0:
        out.append((-1.8, 1.8))
    if палуба == "главная" and x == 130.0:
        out.append((-1.0, 1.0))
    if not out:
        out.append((-1.3, 1.3))
    return sorted(set(out))


def колодцы(плита):
    """Вырезы в настиле палубы: (x0, x1, y0, y1). плита — 'средняя' (прогулочная, 5,8 м)
    или 'солнечная' (8,6 м)."""
    X = W.X_AXIS
    out = []
    if плита == "средняя":
        for имя, (a, b) in GA.ТРАПЫ.items():
            out.append((a + 0.2, b - 0.2, -1.55, 1.55))
        for имя, (a, b, y0, y1) in GA.ЛИФТЫ.items():
            out.append((a - 0.01, b + 0.01, y0 - 0.01, y1 + 0.01))
        out.append((X + 1.0, X + 7.5, -3.4, 3.4))
    else:
        for имя in ("кормовой", "атриум"):
            a, b = GA.ТРАПЫ[имя]
            out.append((a + 0.2, b - 0.2, -1.55, 1.55))
        a, b, y0, y1 = GA.ЛИФТЫ["кормовой"]
        out.append((a - 0.01, b + 0.01, y0 - 0.01, y1 + 0.01))
        out.append((X + 1.0, X + 7.0, -3.4, 3.4))
    return out


# --- проверки ----------------------------------------------------------------
def _зона(палуба, x):
    for x0, x1, kind, name, note in GA.ЗОНЫ[палуба]:
        if x0 - 1e-6 <= x <= x1 + 1e-6:
            return (x0, x1, kind, name)
    return None


def _пересекаются(a, b, зазор=0.0):
    return not (a["x1"] <= b["x0"] + зазор or b["x1"] <= a["x0"] + зазор
                or a["y1"] <= b["y0"] + зазор or b["y1"] <= a["y0"] + зазор)


def _путь(палуба, x0, x1, предметы, шаг=0.10):
    """Есть ли путь шириной ПРОХОД от переборки x0 к переборке x1 через помещение."""
    r = ПРОХОД / 2.0 - 0.04          # допуск на сетку 0,1 м
    ярус_ = ярус(палуба)
    z = G.DECKS[палуба] + 1.0
    nx = int((x1 - x0) / шаг) + 1
    ymax = max(SU.полуширота(x, ярус_, z=z) for x in (x0, 0.5 * (x0 + x1), x1))
    ny = int(2 * ymax / шаг) + 1
    препятствия = [p for p in предметы if p["x1"] > x0 and p["x0"] < x1]
    # шахты трапов и лифтов — тоже препятствия
    for имя, (a, b) in GA.ТРАПЫ.items():
        препятствия.append(dict(x0=a, x1=b, y0=-1.6, y1=1.6))
    for имя, (a, b, ya, yb) in GA.ЛИФТЫ.items():
        препятствия.append(dict(x0=a, x1=b, y0=ya, y1=yb))
    if палуба == "главная":
        к = SU.кожух()
        for знак in (1, -1):
            препятствия.append(dict(x0=к["x0"], x1=к["x1"], y0=min(знак * к["y_внутр"], знак * 20), y1=max(знак * к["y_внутр"], знак * 20)))
    свободно = [[False] * ny for _ in range(nx)]
    for i in range(nx):
        x = x0 + i * шаг
        b = SU.полуширота(x, ярус_, z=z) - G.LINING / 2.0 - r
        for j in range(ny):
            y = -ymax + j * шаг
            if abs(y) > b:
                continue
            ok = True
            for p in препятствия:
                if p["x0"] - r <= x <= p["x1"] + r and p["y0"] - r <= y <= p["y1"] + r:
                    ok = False; break
            свободно[i][j] = ok
    # заливка от кормовой кромки
    from collections import deque
    старт = [(0, j) for j in range(ny) if свободно[0][j]]
    seen = set(старт)
    dq = deque(старт)
    while dq:
        i, j = dq.popleft()
        if i == nx - 1:
            return True
        for di, dj in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            a, b_ = i + di, j + dj
            if 0 <= a < nx and 0 <= b_ < ny and свободно[a][b_] and (a, b_) not in seen:
                seen.add((a, b_)); dq.append((a, b_))
    return False


def проверки():
    out = []
    предметы = мебель()
    # 1. внутри зоны и внутри обшивки
    вне = []
    for p in предметы:
        if p["палуба"] == "солнечная":
            continue
        z0 = _зона(p["палуба"], p["x0"] + 1e-3); z1 = _зона(p["палуба"], p["x1"] - 1e-3)
        if z0 is None or z1 is None or z0 != z1:
            вне.append(p["имя"]); continue
        b = борт(p["палуба"], p["x0"], p["x1"], 0.0)
        if p["класс"] != "ограждение" and (p["y1"] > b + 1e-6 or p["y0"] < -b - 1e-6):
            вне.append(p["имя"])
    out.append(dict(name="Мебель внутри зон и обшивки", value=len(вне), allow=0, unit="шт", ok=not вне,
                    note=", ".join(вне[:4])))
    # 2. без пересечений между собой (стулья со столом могут касаться)
    пары = 0
    прим = []
    for i in range(len(предметы)):
        for j in range(i + 1, len(предметы)):
            a, b_ = предметы[i], предметы[j]
            if a["палуба"] != b_["палуба"]:
                continue
            if _пересекаются(a, b_):
                пары += 1
                if len(прим) < 3:
                    прим.append(a["имя"] + "×" + b_["имя"])
    out.append(dict(name="Мебель без пересечений", value=пары, allow=0, unit="пар", ok=пары == 0, note=", ".join(прим)))
    # 3. не в шахтах
    в_шахте = []
    for p in предметы:
        for имя, (a, b) in GA.ТРАПЫ.items():
            if _пересекаются(p, dict(x0=a, x1=b, y0=-1.6, y1=1.6)):
                в_шахте.append(p["имя"])
        for имя, (a, b, ya, yb) in GA.ЛИФТЫ.items():
            if p["палуба"] != "солнечная" and _пересекаются(p, dict(x0=a, x1=b, y0=ya, y1=yb)):
                в_шахте.append(p["имя"])
    в_шахте = [n for n in в_шахте if not (n.startswith("Смотровая") or n.startswith("Шезлонг") or n.startswith("Бар_солн"))]
    out.append(dict(name="Мебель вне шахт трапов и лифтов", value=len(в_шахте), allow=0, unit="шт", ok=not в_шахте, note=", ".join(в_шахте[:4])))
    # 4. пути эвакуации через общественные помещения
    плохие = []
    n = 0
    for палуба in ("главная", "средняя"):
        for x0, x1, kind, name, note in GA.ЗОНЫ[палуба]:
            if kind not in ("public", "service") or (x1 - x0) < 4.0:
                continue
            if палуба == "средняя" and (x0 < 20.0 or x0 >= 114.0):
                continue                     # тупиковые помещения с одним входом из трап-холла: клуб и спа
            n += 1
            if not _путь(палуба, x0, x1, [p for p in предметы if p["палуба"] == палуба]):
                плохие.append("%s %.0f…%.0f" % (палуба, x0, x1))
    out.append(dict(name="Путь эвакуации %.2f м через каждое помещение" % ПРОХОД, value=len(плохие), allow=0, unit="из %d" % n,
                    ok=not плохие, note=", ".join(плохие)))
    # 5. посадка ресторана
    мест = sum(4 for p in предметы if p["имя"].startswith("Стол_") and p["класс"] == "стол") + \
        sum(6 for p in предметы if p["имя"].startswith("Окно_") and p["класс"] == "стол")
    норма = -(-GA.итоги()["пассажиров"] // 2)
    out.append(dict(name="Ресторан: мест за столами в одну смену", value=мест, allow=норма, unit="мест", ok=мест >= норма,
                    note="две смены на %d пассажиров" % GA.итоги()["пассажиров"]))
    театр_мест = sum(int(round((p["y1"] - p["y0"]) / 0.6)) for p in предметы if p["имя"].startswith("Ряд_"))
    out.append(dict(name="Театр-лаунж: сидячих мест", value=театр_мест, allow=60, unit="мест", ok=театр_мест >= 60, note="плюс бар и стоячие"))
    return out


