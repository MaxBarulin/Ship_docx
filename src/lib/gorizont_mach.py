def total_mass():
    return round(sum((e[2] * e[6]) for e in EQUIPMENT if e[6]), 1)


def boxes(mirror_only=False):
    """Развёрнутый список прямоугольников для чертежа: (code, x0,x1,y0,y1,z0,z1)."""
    out = []
    for code, name, n, b, mir, p, m, note in EQUIPMENT:
        x0, x1, y0, y1, z0, z1 = b
        out.append((code, x0, x1, y0, y1, z0, z1))
        if mir:
            out.append((code, x0, x1, -y1, -y0, z0, z1))
    return out
