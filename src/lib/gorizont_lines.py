# -*- coding: utf-8 -*-
"""Обводы мелкосидящего колёсного корпуса: плазовая таблица из геометрии.

Корпус задаётся не таблицей ординат, а распределениями по длине — высотой
килевой линии, полуширотой днища, полуширотой по борту и развалом борта.
Таблица ординат генерируется из них той же геометрией сечения, что была у
предыдущего корпуса: плоское днище, скуловая дуга, касательная и к днищу и
к борту, прямой борт с развалом. Поэтому таблицу можно снимать с плаза и
пересчитывать вручную — ординаты сойдутся.

Так сделано, чтобы обводы правились в четырёх функциях, а не в трёхстах
числах: поменял подъём днища в корме — таблица пересобралась сама, и
гидростатика с набором поехали следом.

Что определило форму:

  * осадка 1,50 м при 212 пассажирах. Водоизмещение при такой осадке даёт
    только полнота, поэтому цилиндрическая вставка тянется от 0,16 до 0,80
    длины — почти две трети корпуса идут одним сечением. Целились в 1,20,
    но подробный счёт массы по связям дал 2635 т вместо оценочных 2005,
    и 1,50 — это то, что честно получается; разбор в плане перехода;
  * колёса в кормовых нишах. Гребных валов нет, и корма не обязана
    сужаться под винты: она остаётся полной, что и даёт полноту 0,85;
  * высота борта 3,00 м. При осадке 1,20 надводный борт 1,80 — этого
    хватает по классу «О», а лишняя высота это лишняя сталь.
"""
import math

# --- главные размерения ------------------------------------------------------
LOA, BEAM, DEPTH, DRAFT = 128.0, 16.5, 3.00, 1.50
HALF = BEAM / 2.0
FRAMES = 20
WATERLINES = (0.00, 0.15, 0.30, 0.45, 0.60, 0.80, 1.00,
              1.20, 1.50, 1.80, 2.20, 2.60, 3.00)

# Ниши колёс: вырез в борту под колесо с приводом. Объём ниши ниже
# ватерлинии вычитается из водоизмещения — иначе судно «плавает» на воде,
# которой в нишах нет.
WHEEL_X = 84.0            # центр колеса от кормового перпендикуляра
NICHE_LEN, NICHE_WIDTH = 7.2, 3.6
NICHE_Z0, NICHE_Z1 = 0.55, 3.00    # от какой до какой высоты вырезана ниша


def _s(x):
    """Безразмерная абсцисса 0 (корма) … 1 (нос)."""
    return x / LOA


def keel_z(x):
    """Высота килевой линии. Плоское днище на средней части, подъём к
    оконечностям: в корме под колёсный поток, в носу под всплытие."""
    s = _s(x)
    if s < 0.16:
        t = (0.16 - s) / 0.16
        return 0.95 * t ** 1.7
    if s > 0.80:
        t = (s - 0.80) / 0.20
        return 2.05 * t ** 1.9
    return 0.0


def bottom_half(x):
    """Полуширота плоского днища у килевой линии."""
    s = _s(x)
    if s < 0.16:
        t = s / 0.16
        return 3.30 + 4.05 * t ** 0.62
    if s > 0.80:
        t = (s - 0.80) / 0.20
        return 7.35 * (1.0 - t) ** 0.78
    return 7.35


def side_half(x):
    """Полуширота по верхней кромке борта."""
    s = _s(x)
    if s < 0.10:
        t = s / 0.10
        return 6.25 + (HALF - 6.25) * t ** 0.55
    if s > 0.84:
        t = (s - 0.84) / 0.16
        return HALF * (1.0 - t ** 1.45) + 0.12 * t ** 1.45
    return HALF


def flare(x):
    """Развал борта от вертикали, градусов. В оконечностях больше."""
    s = _s(x)
    if s < 0.16:
        return 2.0 + 9.0 * (0.16 - s) / 0.16
    if s > 0.80:
        return 2.0 + 11.0 * (s - 0.80) / 0.20
    return 1.2


def stations():
    """Теоретические шпангоуты: основные через L/20 плюс полушпангоуты."""
    ns = [0, 0.5, 1, 1.5] + list(range(2, 19)) + [18.5, 19, 19.5, 20]
    ns = sorted(set(ns))
    return [(n, n * LOA / FRAMES) for n in ns]


def bilge_radius(bk, bb, zk, zb, phi):
    s, c = math.sin(phi), math.cos(phi)
    return ((bb - bk) * c - (zb - zk) * s) / (1.0 - s)


def section_y(z, zk, bk, zb, bb, phi):
    if z < zk - 1e-9:
        return None
    if z >= zb - 1e-9:
        return bb
    r = bilge_radius(bk, bb, zk, zb, phi)
    if r <= 1e-6:
        t = (z - zk) / max(zb - zk, 1e-9)
        return bk + (bb - bk) * t
    z_t = zk + r * (1.0 - math.sin(phi))
    if z <= z_t:
        d = z - zk - r
        return bk + math.sqrt(max(r * r - d * d, 0.0))
    return bk + r * math.cos(phi) + (z - z_t) * math.tan(phi)


def build():
    """Плазовая таблица и параметры сечений в формате gorizont.OFFSETS."""
    offsets, shapes = [], {}
    for n, x in stations():
        zk, bk = keel_z(x), bottom_half(x)
        bb = side_half(x)
        phi = math.radians(flare(x))
        bk = min(bk, bb)                 # в оконечностях днище уже борта
        r = bilge_radius(bk, bb, zk, DEPTH, phi)
        ys = tuple(None if (y := section_y(z, zk, bk, DEPTH, bb, phi)) is None
                   else round(y, 3) for z in WATERLINES)
        offsets.append((n, round(x, 3), round(zk, 3), round(bk, 3),
                        DEPTH, round(bb, 3), ys))
        shapes[n] = (round(math.degrees(phi), 2), round(r, 3))
    return offsets, shapes


