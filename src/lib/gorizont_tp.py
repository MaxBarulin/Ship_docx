def totals():
    """Сумма норм времени на деталь и на узел."""
    tsht = sum(o["tsht"] for o in OPS)
    tpz = sum(o["tpz"] for o in OPS)
    n = DETAIL["batch"]
    return dict(tsht=round(tsht, 2), tpz=round(tpz, 2),
                per_detail=round(tsht + tpz / n, 2),
                per_node=round(n * tsht + tpz, 2), batch=n)


def op(no):
    for o in OPS:
        if o["no"] == no:
            return o
    raise KeyError(no)
