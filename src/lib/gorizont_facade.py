# -*- coding: utf-8 -*-
"""Фасад - как планировка выходит на борт.

Борт судна не рисуется - он получается из того, что стоит за ним. Каждой
зоне общего расположения соответствует свой тип поверхности:

    проём     общественное помещение - длинная утопленная панель
              остекления с закруглёнными торцами. Ресторан, салон, спа,
              галерея атриума - там, где нужен вид и где нет переборок
              кают;
    окна      каюты - ряд одинаковых квадратных окон с шагом каюты. Ритм
              окон на борту это ритм переборок внутри;
    решётка   технические помещения - жалюзи вентиляции гаража и
              машинного отделения;
    глухо     то, чему окна не нужны - камбуз, театр, кладовые.

Поэтому изменение компоновки меняет и фасад. Передвинул ресторан - уехала
панель. Это и есть требование заказчика «дизайн, обусловленный внутренним
наполнением», выраженное кодом, а не словами.

Ориентир по пластике - современные речные суда - тёмный корпус, светлая
лента главной палубы с глубокими тёмными панелями, тонкая акцентная линия
по её верхней кромке, тёмный ярус кают над ней. Цвет - из
`gorizont_style.ПАЛИТРА` - графит, чёрный, красный.

Повторять ориентир один в один нельзя - это снимает балл за
оригинальность, и заслуженно. Что наше и только наше:

  * **арка колеса на миделе** - у прототипов-винтовых судов её нет, а у
    колёсных она ретро. Здесь арка современная, и за ней атриум;
  * **акцентная линия обходит арку.** На ориентире линия просто идёт по
    кромке. У нас она ныряет вниз, обводит проём кожуха и возвращается -
    линия и рамка арки это одна деталь;
  * **окна кают вертикальные,** 1,10 x 1,55, а не квадратные - пропорция
    окна повторяет пропорцию каюты в плане (узкая и глубокая);
  * **нос - длинный остеклённый сход** с панорамным салоном, а не
    заострённый форштевень с глухим бортом.
"""

# --- панели по палубам ---------------------------------------------------------
#: (x0, x1, тип, за чем стоит)
from . import gorizont as _G
from . import gorizont_wheel as _W

_X = _W.X_AXIS          # ось колеса: атриум и всё, что к нему привязано
_L = _G.LOA

#: Абсциссы - от ориентиров: корма (0), ось колеса (_X), нос (_L). Так
#: панели едут вместе с планировкой при смене длины судна.
ПАНЕЛИ = {
    "главная": [
        (5.0, 20.0, "решётка", "гараж, вентиляция и комплекс высадки"),
        (26.0, _X - 8.0, "окна", "каюты стандарт и экипаж"),
        (_X + 8.0, _X + 18.0, "глухо", "камбуз, раздаточная"),
        (_X + 18.0, _L - 40.0, "проём", "главный ресторан"),
        (_L - 40.0, _L - 32.0, "окна", "каюты стандарт"),
        (_L - 26.0, _L - 16.0, "проём", "театр-лаунж"),
        (_L - 16.0, _L - 10.0, "проём", "носовой панорамный салон"),
    ],
    "средняя": [
        (15.0, 20.0, "проём", "детский клуб и мастерская"),
        (26.0, _X - 8.0, "окна", "каюты"),
        (_X - 8.0, _X + 8.0, "проём", "галерея атриума над колёсами"),
        (_X + 8.0, _L - 32.0, "окна", "каюты бизнес и люкс"),
        (_L - 26.0, _L - 22.0, "проём", "спа"),
    ],
}

ГЛУБИНА_ПРОЁМА = 0.25      # утопление панели остекления в борт
ТОРЕЦ_ПРОЁМА = 0.60        # длина закругления торца панели
#: Окна кают - не прямоугольники в стене, а сплошная лента остекления от
#: пола до потолка с тонкими импостами на переборках кают (шаг ШАГ_ОКОН).
#: Так делают все новые речные суда: иллюминаторов и «окон в ряд» на них
#: больше нет. Ширина импоста - 0,12 м.
ИМПОСТ = 0.12
ОКНО_Ш = 1.10              # (оставлено для планов кают: створка)
ОКНО_В = 1.55
ШАГ_ОКОН = 2.00            # шаг окон - шаг каютных переборок в модуле
ВЫСОТА_ЛИНИИ = 0.10        # акцентная линия по кромке главной палубы


def панель(ярус, x):
    """Панель, в которую попадает абсцисса, или None."""
    for x0, x1, тип, что in ПАНЕЛИ.get(ярус, ()):
        if x0 <= x <= x1:
            return dict(x0=x0, x1=x1, тип=тип, что=что)
    return None


def углубление(ярус, x, внутри_ленты):
    """Глубина утопления борта на абсциссе x внутри оконной ленты.

    Торцы панели закругляются - глубина плавно сходит на нет на длине
    ТОРЕЦ_ПРОЁМА, иначе панель кончается ступенькой и читается как вырез.
    """
    if not внутри_ленты:
        return 0.0
    п = панель(ярус, x)
    if п is None or п["тип"] != "проём":
        return 0.0
    от_края = min(x - п["x0"], п["x1"] - x)
    if от_края >= ТОРЕЦ_ПРОЁМА:
        return ГЛУБИНА_ПРОЁМА
    u = max(0.0, от_края) / ТОРЕЦ_ПРОЁМА
    return ГЛУБИНА_ПРОЁМА * (1.0 - (1.0 - u) ** 2) ** 0.5


def окна(ярус):
    """Абсциссы центров квадратных окон по всем панелям типа «окна»."""
    вых = []
    for x0, x1, тип, _ in ПАНЕЛИ.get(ярус, ()):
        if тип != "окна":
            continue
        n = int((x1 - x0) / ШАГ_ОКОН)
        отступ = (x1 - x0 - n * ШАГ_ОКОН) / 2.0 + ШАГ_ОКОН / 2.0
        вых.extend(x0 + отступ + i * ШАГ_ОКОН for i in range(n))
    return вых


def решётки(ярус):
    return [(x0, x1) for x0, x1, тип, _ in ПАНЕЛИ.get(ярус, ()) if тип == "решётка"]


def станции(ярус):
    """Абсциссы, где обвод надо уплотнить - торцы панелей."""
    вых = set()
    for x0, x1, тип, _ in ПАНЕЛИ.get(ярус, ()):
        if тип == "проём":
            for край in (x0, x1):
                t = -ТОРЕЦ_ПРОЁМА
                while t <= ТОРЕЦ_ПРОЁМА + 1e-9:
                    вых.add(round(край + t, 3))
                    t += 0.15
    return вых


def проверки(длина_яруса):
    """Панели не перекрываются и не выходят за ярус."""
    вых = []
    for ярус, список in ПАНЕЛИ.items():
        x0я, x1я = длина_яруса[ярус]
        отсорт = sorted(список)
        пересечений = sum(1 for a, b in zip(отсорт, отсорт[1:]) if b[0] < a[1] - 1e-9)
        вне = sum(1 for p in список if p[0] < x0я - 1e-9 or p[1] > x1я + 1e-9)
        вых.append(dict(name="Панели фасада - %s" % ярус,
                        value=пересечений + вне, allow=0, unit="шт",
                        ok=пересечений + вне == 0,
                        note="перекрытий %d, за ярусом %d" % (пересечений, вне)))
    return вых
