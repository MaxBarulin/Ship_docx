"""Люди на борту: масштабные фигуры для видов с уровня глаз.

Отдельный модуль и отдельная модель, а не часть судна: манекен — это
масштабная линейка, а не деталь конструкции. В STEP судна ему делать
нечего (он попадёт в проверки пересечений и в состав деталей), а без него
рендер с уровня глаз не читается — на картинке без человека парапет
высотой 1.1 м и стеклянная стена высотой 2.5 м выглядят одинаково.

Рост берётся расчётный: 1800 мм — мужчина, 1950 мм — высокий. Глаз у них
на 1690 и 1830 мм; с этих же высот снимаются виды в scripts/walkthrough.py.
"""

from __future__ import annotations

from cadgen import build123d as bd

from . import public_furniture as pf
from . import ship

EYE = pf.EYE_HEIGHT  # 1690 мм — глаз мужчины ростом 1800 мм
EYE_TALL = 1_830  # глаз при росте 1950 мм

# Палуба, x, y, разворот, рост. Точки выбраны там, где что-то проверяется:
# у ограждения — его высота, в коридоре — ширина прохода, в зале — шаг
# посадки. Разворот 0 — лицом в нос.
CROWD = [
    # Солнечная: в проходе МЕЖДУ рядом шезлонгов и ограждением, а не в
    # самом шезлонге — иначе фигура растёт прямо из лежака.
    ("солнечная", 30_000, 4_600, 180, 1_800),
    ("солнечная", 31_500, 4_600, 180, 1_950),
    ("солнечная", 33_000, -4_600, 0, 1_800),
    ("солнечная", 60_000, 4_600, 90, 1_800),
    ("солнечная", 95_000, 0, 0, 1_800),
    ("верхняя", 25_000, 2_000, 0, 1_800),
    ("верхняя", 26_500, -1_600, 180, 1_800),
    ("верхняя", 60_000, 2_200, 90, 1_800),
    ("верхняя", 63_000, 2_200, 270, 1_950),
    ("шлюпочная", 18_500, 2_400, 0, 1_800),
    ("шлюпочная", 20_000, -2_200, 180, 1_950),
    ("средняя", 50_000, 2_200, 90, 1_800),
    ("средняя", 53_000, 2_200, 270, 1_800),
    ("главная", 25_000, 3_200, 0, 1_800),
    ("главная", 27_000, -3_000, 180, 1_950),
    ("главная", 56_000, 3_000, 90, 1_800),
    ("главная", 59_500, 6_900, 90, 1_800),
    ("главная", 62_500, 7_500, 270, 1_950),
    ("главная", 70_000, -7_300, 270, 1_800),
]


def crowd():
    """Фигуры по палубам: {номер яруса: [детали]} — ярусы как в vessel.build."""
    from . import vessel

    tiers: dict[int, list] = {}
    for deck, x, y, facing, height in CROWD:
        level = vessel.DECK_LEVEL[deck]
        index = TIER[deck]
        for item in pf.figure(height, facing=facing):
            moved = bd.Pos(x, y, level) * item
            moved.label, moved.color = item.label, item.color
            tiers.setdefault(index, []).append(moved)
    return tiers


# Ярус, к которому фигура едет во взрыв-схеме: тот же, что у её палубы.
TIER = {"главная": 1, "средняя": 2, "шлюпочная": 3, "верхняя": 4,
        "солнечная": 5}


def eye(deck, height=1_800):
    """Высота глаза над указанной палубой в системе координат судна."""
    from . import vessel

    return vessel.DECK_LEVEL[deck] + (EYE_TALL if height >= 1_950 else EYE)


assert set(TIER) <= set(ship.DECK_SHAPE), "палуба фигуры не описана обводом"
