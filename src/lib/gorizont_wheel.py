def eccentric_centre():
    b = math.radians(ECCENTRIC_BETA)
    return (ECCENTRIC_E * math.cos(b), ECCENTRIC_E * math.sin(b))


def _пересечение(A, ra, B, rb, ориентир):
    dx, dz = B[0] - A[0], B[1] - A[1]
    d = math.hypot(dx, dz)
    if d > ra + rb or d < abs(ra - rb) or d < 1e-12:
        return None
    a1 = (ra * ra - rb * rb + d * d) / (2.0 * d)
    h2 = ra * ra - a1 * a1
    if h2 < 0.0:
        return None
    h = math.sqrt(h2)
    mx, mz = A[0] + a1 * dx / d, A[1] + a1 * dz / d
    ux, uz = -dz / d, dx / d
    в = ((mx + h * ux, mz + h * uz), (mx - h * ux, mz - h * uz))
    return min(в, key=lambda q: (q[0] - ориентир[0]) ** 2 + (q[1] - ориентир[1]) ** 2)


def _база_рычага():
    """Направление кривошипа при отвесной плице, рад."""
    g = math.radians(LEVER_ANGLE)
    return math.atan2(-math.cos(g), math.sin(g))


_КЭШ = {}


def _оборот(n=360):
    """Решение механизма на полном обороте от нижней точки, с ведением ветви."""
    if n in _КЭШ:
        return _КЭШ[n]
    E = eccentric_centre()
    б = _база_рычага()
    вых, prevQ, prevP = [], None, None
    for i in range(n):
        a = -math.pi / 2.0 + 2.0 * math.pi * i / n
        P = (PIVOT_RADIUS * math.cos(a), PIVOT_RADIUS * math.sin(a))
        if prevQ is None:
            ор = (P[0] + LEVER * math.cos(б), P[1] + LEVER * math.sin(б))
        else:
            ор = (prevQ[0] + P[0] - prevP[0], prevQ[1] + P[1] - prevP[1])
        Q = _пересечение(P, LEVER, E, ROD, ор)
        if Q is None:
            _КЭШ[n] = None
            return None
        tilt = math.atan2(Q[1] - P[1], Q[0] - P[0]) - б
        tilt = (tilt + math.pi) % (2.0 * math.pi) - math.pi
        вых.append(dict(a=a, P=P, Q=Q, E=E, tilt=tilt))
        prevQ, prevP = Q, P
    _КЭШ[n] = вых
    return вых


def linkage(a):
    """Механизм для плицы на часовом угле a (рад от +x) - P, Q, E и угол от отвеса."""
    об = _оборот()
    E = eccentric_centre()
    if об is None:
        return dict(P=None, Q=None, S=E, E=E, tilt=None, ok=False)
    n = len(об)
    k = int(round(((a + math.pi / 2.0) % (2.0 * math.pi)) / (2.0 * math.pi) * n)) % n
    r = об[k]
    P = (PIVOT_RADIUS * math.cos(a), PIVOT_RADIUS * math.sin(a))
    б = _база_рычага()
    ор = (P[0] + LEVER * math.cos(r["tilt"] + б), P[1] + LEVER * math.sin(r["tilt"] + б))
    Q = _пересечение(P, LEVER, E, ROD, ор) or r["Q"]
    tilt = math.atan2(Q[1] - P[1], Q[0] - P[0]) - б
    tilt = (tilt + math.pi) % (2.0 * math.pi) - math.pi
    return dict(P=P, Q=Q, S=E, E=E, tilt=tilt, ok=True)


def blade_tilt(a):
    """Угол полотна плицы от отвеса, градусов, плюс - верх кромки в нос."""
    л = linkage(a)
    return None if л["tilt"] is None else math.degrees(л["tilt"])


def blade_direction(a):
    """Единичный вектор вдоль полотна от оси вниз, в плоскости x-z."""
    t = math.radians(blade_tilt(a) or 0.0) - math.pi / 2.0
    return (math.cos(t), math.sin(t))


def entry_angle():
    дуга, _, _ = immersion_arc()
    return math.radians(-90.0 + дуга / 2.0)


def _до_отрезка(T, A, B):
    ax, az = B[0] - A[0], B[1] - A[1]
    L2 = ax * ax + az * az
    if L2 < 1e-12:
        return math.hypot(T[0] - A[0], T[1] - A[1])
    t = max(0.0, min(1.0, ((T[0] - A[0]) * ax + (T[1] - A[1]) * az) / L2))
    return math.hypot(T[0] - A[0] - t * ax, T[1] - A[1] - t * az)


def envelope():
    """Верх колеса над осью с учётом всего, что вращается - полотно, кривошип, обод."""
    об = _оборот()
    if об is None:
        return None
    m = max(PIVOT_RADIUS + RIM_OUT, eccentric_centre()[1] + ECC_BOSS)
    for r in об:
        d = r["tilt"] - math.pi / 2.0
        m = max(m, r["P"][1] + BLADE_HEIGHT * math.sin(d), r["Q"][1] + PIN_RADIUS)
    return m


def feathering_sweep(n=360):
    об = _оборот(n)
    if об is None:
        return dict(ok=False)
    дуга, _, _ = immersion_arc()
    зазор = 1e9
    шаг_a = 2.0 * math.pi / BLADES
    for r in об[::3]:
        a = r["a"]
        for s_ in (1, -1):
            Pn = (PIVOT_RADIUS * math.cos(a + s_ * шаг_a), PIVOT_RADIUS * math.sin(a + s_ * шаг_a))
            зазор = min(зазор, _до_отрезка(Pn, r["P"], r["Q"]) - PIN_RADIUS)
    скачок = max(abs(((math.degrees(b["tilt"] - a_["tilt"]) + 180.0) % 360.0) - 180.0)
                 for a_, b in zip(об, об[1:] + об[:1]))
    шаг = 2.0 * math.pi * PIVOT_RADIUS / BLADES
    return dict(ok=True, вход=blade_tilt(entry_angle()), низ=blade_tilt(-math.pi / 2.0),
                выход=blade_tilt(math.radians(-90.0 - дуга / 2.0)),
                верх=blade_tilt(math.pi / 2.0), скачок=скачок,
                зазор_рычага=зазор, шаг_плиц=шаг,
                просвет_между_плицами=шаг - BLADE_HEIGHT * 0.5)


def blade_positions(draft, phase=0.0):
    z0 = axis_height(draft)
    вых = []
    for i in range(BLADES):
        a = 2.0 * math.pi * i / BLADES + phase
        л = linkage(a)
        вых.append(dict(i=i, a=math.degrees(a) % 360.0,
                        x=л["P"][0], z=z0 + л["P"][1],
                        Qx=л["Q"][0], Qz=z0 + л["Q"][1],
                        Sx=л["E"][0], Sz=z0 + л["E"][1],
                        tilt=math.degrees(л["tilt"])))
    return вых


