def propeller_comparison(draft, R_kn, v_kmh):
    """Почему колесо, а не винт - предельный диаметр винта при этой осадке.

    Винт должен целиком уместиться под ватерлинией с заглублением верхней
    кромки не менее 0,25 диаметра, иначе он засасывает воздух. При осадке
    1,20 м это ограничение и решает вопрос.
    """
    d_max = max(0.0, (draft - 0.25) / 1.25)
    A = math.pi * d_max ** 2 / 4.0
    v = v_kmh / 3.6
    T = R_kn / 0.85 * 1000.0                                # Н, а не кН
    Ct = T / max(0.5 * RHO * A * v ** 2, 1e-6) if A > 0 else float("inf")
    eta_ideal = 2.0 / (1.0 + math.sqrt(1.0 + Ct)) if A > 0 else 0.0
    return dict(d_max=d_max, площадь_диска=A, Ct=Ct, кпд_идеальный=eta_ideal)


