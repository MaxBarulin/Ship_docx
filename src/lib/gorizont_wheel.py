# -*- coding: utf-8 -*-
"""Колёсный движительно-рулевой комплекс.

Два гребных колеса в бортовых нишах, каждое со своим электромеханическим
приводом. Колесо выбрано не ради стиля - при осадке 1,20 м винт ограничен
диаметром 0,77 м и не заглубляется, а у колеса осадка движителя - это
заглубление плицы, и от осадки судна она не зависит.

Методика. Колесо считается как движитель, отбрасывающий воду назад:
плица, идущая по окружности со скоростью u, разгоняет воду от скорости
набегания v до u, и упор берётся из изменения количества движения на
площади погружённых плиц. Скольжение s = (u - v)/u - тот же параметр, что
относительная поступь у винта, и идеальный КПД у колеса равен 1 - s
ровно по той же причине.

Отдельно считается нагрузка на плицу, и считается двумя случаями, потому
что они дают разные числа:

  * рабочая нагрузка - доля упора, приходящаяся на одну погружённую плицу;
  * удар при входе в воду - плица входит под углом, нормальная составляющая
    её скорости бьёт по воде, и давление удара оказывается больше рабочего.

Второй случай и есть расчётный для конструкции плицы. Это важно - если
считать плицу только по упору, она выйдет вдвое слабее, чем нужно.

Все скорости в м/с, силы в кН, мощности в кВт, размеры в метрах.
"""
import math

RHO = 1000.0                  # плотность пресной воды, кг/м3

# --- тип плицы ---------------------------------------------------------------
#: Плицы шарнирные (поворотные): каждая подвешена на оси и удерживается
#: тягой от неподвижного эксцентрика, поэтому идёт через всю дугу почти
#: вертикально, а не поворачивается вместе с колесом.
#:
#: Что это даёт против жёсткой радиальной плицы:
#:   * плица входит в воду кромкой, а не плашмя. Удар при входе падает в
#:     разы: вместо удара плоской пластины получается клиновое врезание;
#:   * плица работает почти на всей дуге погружения, а не только у нижней
#:     точки, потому что не заваливается. Эффективное число плиц в воде
#:     растёт с 0,67 геометрического до 0,85;
#:   * на выходе плица не поднимает воду - уходит главная потеря колеса.
#:
#: Чем платим и что проверить:
#:   * механизм. Ось плицы, тяга, эксцентрик - это детали, которых у
#:     радиального колеса нет, и они в воде;
#:   * плавник. На Волге идёт топляк, и тяга шарнира уязвимее жёсткой
#:     плицы. Решение - срезной палец в тяге и защитная решётка перед
#:     колесом: гнётся дешёвая деталь, а не колесо;
#:   * стоимость и трудоёмкость выше. Зато узел для КД получается
#:     настоящий, а не подбор профиля по таблице.
BLADE_TYPE = "шарнирная (поворотная), привод от неподвижного эксцентрика"
FEATHERING = True

# --- геометрия комплекса -----------------------------------------------------
#: Диаметр по нижней кромке плицы в нижнем положении.
#:
#: Диаметр упирается не в упор, а в среднюю палубу, и считать это
#: ограничение надо по шарнирному колесу, а не по жёсткому. У жёсткого
#: плица сидит на ободе радиуса R, и верхняя точка колеса - это R над
#: осью. У шарнирного плица висит отвесно под своей осью и выше окружности
#: осей не поднимается никогда, поэтому верх колеса это R_ОСЕЙ над осью,
#: а R_ОСЕЙ меньше R на высоту плицы.
#:
#: Разница не косметическая: по жёсткой схеме предел выходил 4,40 м, по
#: шарнирной - 5,25. Взято 5,20 с запасом 0,10 м до кожуха.
#:
#:     верх = (T - i + R) + R_ОСЕЙ + обод <= палуба_средняя - 0,35
#:
#: Больший диаметр даёт меньшую частоту вращения при той же окружной
#: скорости (22 об/мин против 28) и более длинную дугу погружения в
#: метрах, то есть больше работы на оборот и меньше ударов в секунду.
DIAMETER = 4.90          # диаметр колеса по нижней кромке плицы
WIDTH = 3.20             # ширина колеса (длина плицы вдоль оси)
BLADES = 12              # число плиц
IMMERSION = 0.75         # заглубление кромки плицы в нижнем положении
COUNT = 2                # колёс на судне

#: Габаритная ширина колеса `WIDTH` и рабочая длина плицы - разные числа.
#: Полотно ходит между дисками обода: в верхнем положении отвесная плица
#: висит внутрь колеса и проходит ровно там, где стоят спицы. Значит она
#: обязана быть уже расстояния между дисками, иначе при каждом обороте
#: срезает набор. Проверено на модели: пересечение 27 мм.
RIM_GAP = 0.40           # от кромки плицы до внутренней плоскости диска: там ходит механизм
BLADE_SPAN = WIDTH - 2.0 * RIM_GAP     # рабочая длина плицы вдоль оси
BLADE_HEIGHT = 0.70      # высота плицы поперёк потока
BLADE_THICK = 0.035      # толщина полотна плицы (лист с рёбрами)
RIM_WIDTH = 0.15         # ширина обода по радиусу
#: Полотно плицы крепится к оси не серединой, а верхней кромкой через
#: проушины, и кромка сидит на PIVOT_OFFSET ниже центра оси. Если этого не
#: учесть, заглубление плицы в нижнем положении уезжает на ту же величину,
#: и весь расчёт упора считается не для той геометрии, которая построена.
PIVOT_OFFSET = 0.05
PIVOT_RADIUS = DIAMETER / 2.0 - BLADE_HEIGHT - PIVOT_OFFSET
#: Обод сидит на окружности осей плиц: оси проходят сквозь диски обода и
#: опираются на них. Колесо тогда читается как колесо - два круга, между
#: ними плицы. Вариант с ободом внутри и кронштейнами наружу пробовался и
#: давал на виде сбоку кашу из спиц, кронштейнов и кольца.
RIM_RADIUS = PIVOT_RADIUS
RIM_OUT = 0.06                        # вынос обода наружу от окружности осей
RIM_IN = 0.14                         # ширина обода внутрь
SPOKE_SECTION = (0.10, 0.05)          # спица: высота и толщина
HUB_RADIUS = 0.28        # радиус ступицы: бобышка эксцентрика на 0,34 от оси должна пройти мимо
SHAFT_RADIUS = 0.175     # радиус гребного вала
DECK_CLEARANCE = 0.22    # от верха колеса до средней палубы: настил, лист кожуха, зазор

# --- механизм поворота плиц --------------------------------------------------
#: Механизм Моргана: тяги всех плиц сходятся на одном неподвижном
#: эксцентриковом пальце E, смещённом от оси колеса на e в нос. У каждой
#: плицы короткий кривошип LEVER, перпендикулярный полотну; тяга ROD идёт
#: от пальца кривошипа к E. Четырёхзвенник C-P-Q-E решается на каждом
#: положении, ветвь ведётся по непрерывности от нижней точки.
#:
#: Что даёт: в воде плица почти отвесна (вход 9,8°, низ 0,3°, выход
#: -8,6° от отвеса), наверху откинута наружу-назад, а не висит внутрь к
#: ступице. Первый вариант - параллелограмм с вращающимся кольцом - держал
#: плицу отвесно на всём обороте; выглядело сломанным и не встречается ни
#: на одном реальном колесе. Он же давал плицу внутри спиц наверху.
#:
#: Числа подобраны сеткой по трём условиям: угол в воде <= 20°, верх
#: колеса вместе с механизмом под листом кожуха, кривошип не задевает
#: соседние оси (>= 0,12 м). Проверяется `checks()`, а не верится.
ECCENTRIC_E = 0.50       # вынос неподвижного пальца от оси колеса
ECCENTRIC_BETA = 0.0     # направление выноса: в нос
LEVER = 0.60             # кривошип на оси плицы
LEVER_ANGLE = 90.0       # угол кривошипа к полотну плицы (в нос от отвеса)
ROD = 1.70               # тяга от пальца кривошипа до эксцентрика
PIN_RADIUS = 0.055
ECC_BOSS = 0.16          # радиус бобышки эксцентрикового пальца

#: Абсцисса оси колеса от кормового перпендикуляра. Колёса стоят на
#: миделе, как у прототипа ПКС-180 (кожух с названием на 46 % длины от
#: кормы): потеря плавучести в нишах даёт просадку, а не дифферент;
#: транец свободен под аппарель и комплекс высадки; над колёсами встаёт
#: атриум. Прежний кормовой вариант мотивировался так:
#: там они работают в следе корпуса (попутный поток снижает скорость
#: набегания и поднимает пропульсивный коэффициент), не шумят под
#: пассажирским блоком в средней части и не требуют длинных передач от
#: машинного отделения.
#:
#: Продольное положение упора на дифферент не влияет: упор и сопротивление
#: оба горизонтальны, момент даёт только их разнос по высоте. На дифферент
#: здесь работает другое - потеря плавучести в нишах, см. `niche_buoyancy`.
X_AXIS = 66.0     # 0,47 L: как у прототипа

# --- ниши --------------------------------------------------------------------
#: Габаритная ширина судна с колёсами. Ограничение команды: колёса не
#: выходят за 16 м, то есть прячутся внутрь обвода корпуса 16,5 м целиком.
BEAM_OVERALL_MAX = 16.00
HULL_BEAM = 16.50
NICHE_LEN = 7.20         # длина прямой части ниши вдоль судна
NICHE_CLEARANCE = 0.15   # зазор между колесом и стенками ниши
#: Ниша вырезана от киля до палубы, а не от 0,55 м. Первый вариант оставлял
#: под колесом полку днища шириной 3,45 м, и нижняя кромка плицы проходила в
#: 0,20 м над ней: воде некуда уходить из-под плицы, колесо толкало бы её в
#: собственную полку. Гребное колесо работает только в свободной воде -
#: снизу и сзади ничего быть не должно.
NICHE_Z0 = 0.0
#: Торцы ниши - не поперечные стенки, а плавные сходы: передний вводит
#: поток в нишу без застойной зоны и удара, задний выпускает колёсную струю
#: вдоль борта. Длина каждого схода 2,5 м.
NICHE_FAIR = 2.5

# --- КПД и потери ------------------------------------------------------------
#: Механический КПД привода: редуктор и подшипники вала колеса.
ETA_MECH = 0.96
#: КПД электропривода от шин ГРЩ до вала колеса.
ETA_DRIVE = 0.93
#: Потери на вход и выход плицы. У жёсткой радиальной плицы это главная
#: потеря колеса: на выходе плица поднимает воду. Шарнирная уходит из воды
#: вертикально и почти ничего не поднимает.
ETA_ENTRY = 0.95 if FEATHERING else 0.85
#: Коэффициент засасывания. У колеса в бортовой нише он мал: колесо
#: работает вне следа корпуса, в отличие от винта за кормой.
THRUST_DEDUCTION = 0.08

#: Коэффициент удара при входе плицы: отношение давления удара к
#: скоростному напору нормальной составляющей. Для плоской пластины,
#: входящей плашмя, берут 2,5…5. Шарнирная плица входит кромкой, смоченная
#: площадь нарастает постепенно, и коэффициент падает до величины порядка
#: единицы - это клиновое врезание, а не шлёпок.
SLAM_COEF = 1.1 if FEATHERING else 3.0

#: Доля дуги, на которой плица работает эффективно. Жёсткая заваливается и
#: тянет только у нижней точки, шарнирная держит плоскость через всю дугу.
BLADE_EFFICIENCY_ARC = 0.85 if FEATHERING else 0.67


def axis_height(draft):
    """Высота оси колеса над основной плоскостью."""
    return draft + DIAMETER / 2.0 - IMMERSION


def top_height(draft):
    """Верхняя точка колеса за оборот - по всему механизму, см. `envelope`."""
    e = envelope()
    return axis_height(draft) + (e if e is not None else PIVOT_RADIUS + RIM_OUT)


def max_diameter(draft, deck_z, clearance=DECK_CLEARANCE):
    """Предельный диаметр при заданной палубе над колесом."""
    return 2.0 * (deck_z - clearance - RIM_WIDTH - draft + IMMERSION
                  - BLADE_HEIGHT) / 2.0 * 2.0 / 2.0 * 2.0 - 0.0


def niche_geometry():
    """Ниша в борту - куда встаёт колесо, чтобы не выйти за габарит 16 м.

    Наружная плоскость колеса ставится по габаритному ограничению, а не
    по борту - колесо целиком внутри обвода, и швартовка бортом остаётся
    возможной - иначе колесо било бы о причал.
    """
    y_наружу = BEAM_OVERALL_MAX / 2.0
    y_внутрь = y_наружу - WIDTH
    борт = HULL_BEAM / 2.0
    глубина = борт - y_внутрь + NICHE_CLEARANCE
    return dict(y_наружная_кромка=y_наружу, y_внутренняя_кромка=y_внутрь,
                борт=борт, утоплено_от_борта=борт - y_наружу,
                глубина_ниши=глубина, длина_ниши=NICHE_LEN,
                ширина_перемычки=2.0 * y_внутрь,
                габарит_с_колёсами=2.0 * y_наружу)


def niche_half(x):
    """Ордината стенки ниши на абсциссе x, вне ниши - полуширота борта.

    Прямая часть - y_внутренней кромки, на сходах ордината идёт к борту по
    косинусу - гладко и без излома, чтобы обшивку можно было гнуть, а поток -
    не отрывать.
    """
    н = niche_geometry()
    d = abs(x - X_AXIS) - NICHE_LEN / 2.0
    if d <= 0.0:
        return н["y_внутренняя_кромка"]
    if d >= NICHE_FAIR:
        return н["борт"]
    t = d / NICHE_FAIR
    return н["y_внутренняя_кромка"] + (н["борт"] - н["y_внутренняя_кромка"]) * (1.0 - math.cos(math.pi * t)) / 2.0


def paddle_box(draft, deck_z, tier_z=None):
    """Кожух колеса - колесо выходит над главной палубой, и это нормально.

    При осадке 1,50 м ось колеса стоит на 2,95 м от основной, а верхняя
    кромка плицы - на 5,15, то есть на 2,15 м выше главной палубы. Опустить
    колесо нельзя - заглубление плицы задано, а диаметр задан упором.
    Поэтому над палубой ставится кожух - та самая деталь, по которой
    колёсное судно узнают с берега.

    Кожух не украшение - он ловит воду, которую плица уносит вверх, держит
    её внутри и не даёт залить бортовой проход, а заодно закрывает
    вращающиеся части от пассажиров.
    """
    верх = top_height(draft)
    н = niche_geometry()
    return dict(верх_колеса=верх, над_палубой=верх - deck_z,
                высота_кожуха=верх - deck_z + 0.30,
                длина=NICHE_LEN + 1.0, ширина=WIDTH + 2 * NICHE_CLEARANCE,
                y_центр=н["y_внутренняя_кромка"] + WIDTH / 2.0,
                упирается_в_ярус=(tier_z is not None and верх + 0.30 > tier_z))


def niche_buoyancy(draft, z0=None):
    """Потерянная плавучесть в нишах, т, и где она приложена.

    Ниши на миделе, потеря плавучести даёт просадку без дифферента. Объём -
    прямая часть плюс два схода (по половине объёма каждый).
    """
    z0 = NICHE_Z0 if z0 is None else z0
    н = niche_geometry()
    h = max(0.0, draft - z0)
    L_экв = NICHE_LEN + NICHE_FAIR          # два схода по половине
    V = COUNT * L_экв * н["глубина_ниши"] * h
    return dict(объём=V, масса=V * 1.0, x=X_AXIS, z=z0 + h / 2.0, длина_экв=L_экв)


def blade_area():
    """Площадь погружённой части одной плицы в нижнем положении.

    Считается по рабочей длине BLADE_SPAN, а не по габаритной ширине
    колеса - воду толкает полотно, а не диски обода.
    """
    return BLADE_SPAN * IMMERSION


def immersion_arc():
    """Угол дуги погружения, градусов, и число одновременно погружённых плиц."""
    r = DIAMETER / 2.0
    cos_t = (r - IMMERSION) / r
    theta = math.degrees(math.acos(max(-1.0, min(1.0, cos_t))))
    дуга = 2.0 * theta
    n = дуга / (360.0 / BLADES)
    # Крайние плицы погружены едва-едва, поэтому эффективное число меньше
    # геометрического. Насколько меньше - зависит от типа плицы.
    return дуга, n, n * BLADE_EFFICIENCY_ARC


def rpm_for_speed(v_kmh, slip=0.18):
    """Частота вращения, об/мин, при заданной скорости и скольжении."""
    v = v_kmh / 3.6
    u = v / (1.0 - slip)
    return 60.0 * u / (math.pi * DIAMETER), u


def thrust(v_kmh, slip=0.18):
    """Упор одного колеса, кН, при заданном скольжении."""
    v = v_kmh / 3.6
    u = v / (1.0 - slip)
    _, _, n_eff = immersion_arc()
    A = blade_area() * n_eff
    # Изменение количества движения: масса воды, проходящей через диск
    # плиц за секунду, умноженная на приращение скорости. Ньютоны делим
    # на 1000 - наружу модуль отдаёт килоньютоны.
    return RHO * A * u * (u - v) / 1000.0


def bollard_thrust(k_dead_water=0.7):
    """Упор одного колеса при стоящем судне (швартовный), кН.

    Окружная скорость - как на полном ходу, скорость набегания - ноль, на
    мёртвой воде плица работает хуже, чем в потоке, отсюда коэффициент 0,7.
    Этим упором судно разворачивается на месте и тормозит реверсом.
    """
    _, u = rpm_for_speed(17.5, 0.20)
    _, _, n_eff = immersion_arc()
    return RHO * blade_area() * n_eff * u * u / 1000.0 * k_dead_water


def slip_for_thrust(T_req, v_kmh, lo=0.02, hi=0.80):
    """Подобрать скольжение, при котором колесо даёт нужный упор."""
    for _ in range(80):
        mid = 0.5 * (lo + hi)
        if thrust(v_kmh, mid) < T_req:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def efficiency(slip):
    """КПД колеса - идеальный по скольжению, с потерями на вход и выход."""
    return (1.0 - slip) * ETA_ENTRY


def operating_point(R_kn, v_kmh):
    """Рабочая точка комплекса по буксировочному сопротивлению.

    R_kn - буксировочное сопротивление корпуса на этой скорости.
    """
    T_общий = R_kn / (1.0 - THRUST_DEDUCTION)
    T_колесо = T_общий / COUNT
    s = slip_for_thrust(T_колесо, v_kmh)
    n, u = rpm_for_speed(v_kmh, s)
    eta = efficiency(s)
    v = v_kmh / 3.6
    P_вал = T_колесо * v / eta / ETA_MECH
    P_шины = P_вал / ETA_DRIVE
    return dict(v_kmh=v_kmh, R=R_kn, T_общий=T_общий, T_колесо=T_колесо,
                скольжение=s, об_мин=n, u=u, кпд=eta,
                P_вал=P_вал, P_шины=P_шины, P_всего=P_шины * COUNT)


def blade_load(v_kmh, slip):
    """Нагрузка на плицу - рабочая и ударная при входе в воду."""
    _, _, n_eff = immersion_arc()
    T_колесо = thrust(v_kmh, slip)
    F_раб = T_колесо / max(n_eff, 1e-6)
    p_раб = F_раб / blade_area()

    # Вход в воду: плица входит на угле дуги погружения, нормальная к
    # поверхности составляющая её окружной скорости и бьёт по воде.
    дуга, _, _ = immersion_arc()
    theta = math.radians(дуга / 2.0)
    _, u = rpm_for_speed(v_kmh, slip)
    v_norm = u * math.sin(theta)
    p_удар = 0.5 * RHO * SLAM_COEF * v_norm ** 2 / 1000.0   # кПа
    return dict(F_рабочая=F_раб, p_рабочая=p_раб, v_входа=v_norm,
                p_удара=p_удар, p_расчётное=max(p_раб, p_удар),
                площадь_плицы=blade_area())



