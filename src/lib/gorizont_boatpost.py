# -*- coding: utf-8 -*-
"""Узел ВГ-2026.15.00 «Шлюпочный пост».

Один пост на борт — площадка спонсона со шлюпкой, шлюпбалкой, кильблоками,
съёмным ограждением и посадочной площадкой. На судне шесть таких постов
(три на борт), в версии «Эконом» — восемь.

Числа согласованы с моделью (blender/gorizont.blend, коллекция
06_Спасательные_средства) и с расчётом кницы в gorizont_strength.py.
"""
from . import gorizont_strength as St

RHO = 7.85e-3                 # кг/см3 -> т/м3 = 7.85; здесь кг/(мм2*м)
STEEL = "09Г2С ГОСТ 19281-2014"

# габариты поста по модели
X0, X1 = 40.30, 48.90         # длина площадки по шлюпке
Y_IN, Y_OUT = 5.65, 8.15      # от внутренней кромки спонсона до борта
Z_DECK = 9.80                 # настил шлюпочной палубы
SPONSON_Y0 = 7.00             # кромка палубы, дальше — спонсон на кницах
BRACKET_PITCH = 2.20
N_BRACKETS = 5


def _plate(area_m2, t_mm):
    return round(area_m2 * t_mm * 7.85, 1)      # кг


def _bar(length_m, b_mm, t_mm):
    return round(length_m * b_mm * t_mm * 7.85e-3, 1)


L_POST = X1 - X0
SPONSON_AREA = L_POST * (Y_OUT - SPONSON_Y0)

# поз., обозначение, наименование, кол., материал / примечание, масса кг за штуку
PARTS = [
    (1, "ВГ-2026.15.01", "Кница спонсона", N_BRACKETS, STEEL,
     St.report()["bracket"]["mass_kg"]),
    (2, "ВГ-2026.15.02", "Настил спонсона, лист 6", 1,
     "Лист 6 ГОСТ 19903, " + STEEL, _plate(SPONSON_AREA, 6.0)),
    (3, "ВГ-2026.15.03", "Обделка кромки, полоса 100 x 8", 1,
     "Полоса 100 x 8 ГОСТ 103, " + STEEL, _bar(L_POST + 2.3, 100, 8)),
    (4, "ВГ-2026.15.04", "Рама шлюпбалки гравитационной", 2,
     "Труба 168 x 8 ГОСТ 8732, " + STEEL, 178.0),
    (5, "ВГ-2026.15.05", "Кильблок с ложементом", 2,
     STEEL + ", подушка — резина 40", 46.0),
    (6, "ВГ-2026.15.06", "Ограждение съёмное с калиткой", 1,
     "Труба 42 x 3, " + STEEL, 38.0),
    (7, "ВГ-2026.15.07", "Фундамент лебёдки", 1,
     "Лист 10 и полоса, " + STEEL, 55.0),
    (8, "ВГ-2026.15.08", "Площадка посадки с трапом", 1,
     "Настил рифлёный 4, " + STEEL, 118.0),
    (9, "ВГ-2026.15.09", "Подкрепление палубы под шлюпбалку", 2,
     "Лист 10, " + STEEL, 64.0),
]

# покупные изделия
BOUGHT = [
    (10, "—", "Лебёдка шлюпочная с ленточным тормозом", 1,
     "по ТУ изготовителя, ручной и электропривод", 320.0),
    (11, "—", "Шлюпка спасательная закрытая, 100 чел.", 1,
     "с двигателем и снабжением", 3100.0),
    (12, "—", "Тали, лопари, блоки, разобщающее устройство", 1,
     "комплект спускового устройства", 85.0),
]


def steel_mass():
    return round(sum(n * m for _, _, _, n, _, m in PARTS), 1)


def total_mass():
    return round(steel_mass() + sum(n * m for _, _, _, n, _, m in BOUGHT), 1)


def rows():
    out = []
    for p in PARTS + BOUGHT:
        num, mark, name, n, mat, m = p
        out.append(dict(pos=num, mark=mark, name=name, n=n, material=mat,
                        mass=m, total=round(n * m, 1),
                        kind="деталь" if mark != "—" else "покупное"))
    return out
