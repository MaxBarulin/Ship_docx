# -*- coding: utf-8 -*-
"""Стоянка у причала порта приписки: швартовка, сход на берег, смена модулей краном.

Самара — начало и конец кольцевого маршрута (`gorizont_route`): здесь пассажиры
садятся и сходят, здесь же между рейсами меняется тема солнечной палубы. Причал
грузопассажирский, из трёх частей:

  * **стенка** вдоль левого борта: кордон на `КОРДОН` над водой, кранцы, тумбы;
    судно стоит лагом, между бортом и стенкой — кранцы (`ОТБОЙ`);
  * **аппарельный пандус** за кормой: бетонный откос 1:8, уходящий под воду.
    Кормовая аппарель 9 × 3,6 м ложится на откос при любом уровне воды — так
    устроены паромные причалы; на стенку того же уровня, что палуба, аппарель
    толщиной 0,3 м не легла бы: её шарнир на палубе, а низ — под кордоном;
  * **портальный кран** на рельсах вдоль кордона: ставит модули на солнечную
    палубу через левый борт до дальнего ряда у правого.

Из этих чисел собирается сцена `scripts/blender_причал.py`. Проверки: трап и
аппарель проходимы для кресла-коляски (уклон не круче `G.RAMP_MAX_SLOPE`),
кранцы держат борт, кран достаёт дальний слот и поднимает самый тяжёлый модуль,
модуль проносится над соседними с зазором, крюк не упирается в оголовок.

    python -m lib.gorizont_berth      # из src
"""
import math
from . import gorizont as G
from . import gorizont_lines as L
from . import gorizont_modules as M
from . import gorizont_super as SU
from . import gorizont_twistlock as T
from . import gorizont_wheel as W

ВОДА = G.DRAFT                      # отметка воды в осях судна, м от ОП (расчётная осадка)
КОРДОН = 1.80                       # верх стенки над водой, м: палуба на 1,70 — сход почти вровень
Z_КОРДОН = ВОДА + КОРДОН
ОТБОЙ = 0.60                        # от наибольшей полушироты до лица стенки, м
Y_СТЕНКА = -(G.BEAM / 2.0 + ОТБОЙ)  # стоим лагом левым бортом
КРАНЕЦ = dict(r=0.25, длина=2.0, шаг=8.0, z=ВОДА + 0.90)   # цилиндрический кранец на цепях по лицу стенки

#: Кнехты судна на главной палубе, (x, y). Ставит их `blender_помещения`, заводит концы — эта библиотека.
_X = W.X_AXIS
КНЕХТЫ = [(G.LOA - 8.0, 3.0), (G.LOA - 8.0, -3.0), (3.0, 5.2), (3.0, -5.2),
          (_X - 14.0, 7.6), (_X - 14.0, -7.6), (_X + 20.0, 7.6), (_X + 20.0, -7.6)]
КНЕХТ = dict(a=0.40, h=0.58)        # тумба кнехта, м

#: Тумбы причала вдоль кордона и швартовы: (название, кнехт судна, x тумбы). Тумбы — в 0,5 м от кромки.
ТУМБА = dict(r=0.20, h=0.45, r_шапки=0.28, h_шапки=0.10, от_кромки=0.50)
ШВАРТОВЫ = [("кормовой продольный", 3, -4.0),
            ("кормовой шпринг", 5, _X + 0.0),
            ("носовой шпринг", 7, _X + 6.0),
            ("носовой продольный", 1, G.LOA + 8.0)]
ШВАРТОВ_R = 0.024                   # полиамидный канат 48 мм

#: Телескопический трап из гаража (gorizont_ga: «комплекс высадки на берег, телескопический трап ЛБ»).
ТРАП = dict(x0=12.6, x1=13.8, толщина=0.15, поручень=1.00, длина_max=6.0, на_причал=0.50)

#: Пандус под аппарель: откос за транцем. Носок уходит под воду, гребень выходит на кордон.
ПАНДУС = dict(уклон=0.125, торец_x=-0.80, под_водой=0.30, y1=12.0)
АППАРЕЛЬ_ТОЛЩИНА = 0.30

#: Портальный кран порта (класс 16 т / 32 м, как краны речных портов Волги); рельсы вдоль кордона.
КРАН = dict(г_п=16.0, вылет_max=32.0, вылет_min=8.0, колея=10.5, база=10.5, от_кромки=2.0,
            портал=9.0, оголовок=25.0, траверса_т=1.3, траверса_h=0.25, стропы_h=3.0, подвеска_h=1.2)
ЗАЗОР_ПРОНОСА = 0.50                # модуль над соседними и над фальшбортом, м
ФАЛЬШБОРТ_СОЛНЕЧНОЙ = 1.10          # высота ограждения солнечной палубы (blender_судно._участок)


def трап():
    """Трап от двери гаража в ярусе до кордона: длина по горизонтали, перепад, уклон, диапазон уровней воды."""
    т = ТРАП
    xc = 0.5 * (т["x0"] + т["x1"])
    y_двери = -SU.полуширота(xc, "главная", z=G.DEPTH + 0.5)
    y_конца = Y_СТЕНКА - т["на_причал"]
    длина = abs(y_конца - y_двери)
    перепад = Z_КОРДОН - G.DEPTH
    уклон = abs(перепад) / длина
    # при длине выдвижения до длина_max трап держит уклон на перепаде до ±длина_max·уклон_max
    доп = т["длина_max"] * G.RAMP_MAX_SLOPE
    return dict(x=xc, y_двери=round(y_двери, 3), y_конца=round(y_конца, 3), длина=round(длина, 2), перепад=round(перепад, 2),
                уклон=round(уклон, 3), кордон_min=round(G.DEPTH - доп - ВОДА, 2), кордон_max=round(G.DEPTH + доп - ВОДА, 2))


def аппарель():
    """Аппарель на пандусе: уклон, при котором носок аппарели ложится на откос; точки шарнира и носка."""
    г, п = G.GARAGE, ПАНДУС
    t = АППАРЕЛЬ_ТОЛЩИНА
    z_носка_пандуса = ВОДА - п["под_водой"]

    def откос(x):
        return z_носка_пандуса + п["уклон"] * (п["торец_x"] - x)
    # шарнир на палубе у транца; ищем угол, при котором низ аппарели на конце касается откоса
    lo, hi = 0.0, 0.5
    for _ in range(60):
        a = 0.5 * (lo + hi)
        x_к = -г["ramp_len"] * math.cos(a)
        z_низ = G.DEPTH - г["ramp_len"] * math.sin(a) - t / math.cos(a)
        if z_низ > откос(x_к):
            lo = a
        else:
            hi = a
    a = 0.5 * (lo + hi)
    x_к = -г["ramp_len"] * math.cos(a)
    гребень = п["торец_x"] - (Z_КОРДОН - z_носка_пандуса) / п["уклон"]
    return dict(угол=a, уклон=round(math.tan(a), 3), шарнир=(0.0, G.DEPTH), носок=(round(x_к, 3), round(G.DEPTH - г["ramp_len"] * math.sin(a), 3)),
                гребень_x=round(гребень, 2), z_носка_пандуса=round(z_носка_пандуса, 2), откос=откос)


def ось_крана():
    """Поперечная координата оси поворота крана: середина колеи."""
    return Y_СТЕНКА - КРАН["от_кромки"] - КРАН["колея"] / 2.0


def подъём(слот, тема):
    """Высота проноса над своим слотом, м: низ модуля выше соседей на пути от кордона и выше фальшборта на ЗАЗОР_ПРОНОСА."""
    сд = {s["слот"]: s for s in M.слоты()}
    s = сд[слот]
    z0 = G.DECKS["солнечная"] + T.высота_опоры()
    верх = G.DECKS["солнечная"] + ФАЛЬШБОРТ_СОЛНЕЧНОЙ - z0
    for сл, тип in M.ТЕМЫ[тема]["модули"].items():
        o = сд[сл]
        if сл == слот or o["x1"] <= s["x0"] or o["x0"] >= s["x1"]:
            continue
        if Y_СТЕНКА < o["yc"] < s["yc"]:
            верх = max(верх, M.высота_модуля(тип))
    return round(верх + ЗАЗОР_ПРОНОСА, 2)


def кран(слот="А-3-ПБ", тема="президентская"):
    """Кран над слотом: вылеты до ближнего и дальнего ряда, груз на крюке, высоты крюка и оголовка."""
    к = КРАН
    y0 = ось_крана()
    ряды = sorted({s["yc"] for s in M.слоты()})
    сд = {s["слот"]: s for s in M.слоты()}
    s = сд[слот]
    тип = M.ТЕМЫ[тема]["модули"].get(слот, "люкс")
    п = подъём(слот, тема)
    z_низ = G.DECKS["солнечная"] + T.высота_опоры() + п
    z_крюк = z_низ + M.высота_модуля(тип) + к["траверса_h"] + к["стропы_h"]
    груз = max(M.МОДУЛИ[t]["масса"] for t in M.ПОРЯДОК_МОДУЛЕЙ if t in {x for x in M.ТЕМЫ[тема]["модули"].values()}) + к["траверса_т"]
    груз_каталог = max(M.МОДУЛИ[t]["масса"] for t in M.ПОРЯДОК_МОДУЛЕЙ if not t.endswith("глубокий")) + к["траверса_т"]
    return dict(ось_y=round(y0, 3), вылет=round(s["yc"] - y0, 2), вылет_дальний=round(max(ряды) - y0, 2), вылет_ближний=round(min(ряды) - y0, 2),
                подъём=п, z_низ=round(z_низ, 3), z_крюк=round(z_крюк, 3), z_оголовок=round(Z_КОРДОН + к["оголовок"], 3),
                груз_т=round(груз, 1), груз_каталог_т=round(груз_каталог, 1), тип=тип, x=s["xc"], y=s["yc"])


def швартовы():
    """Концы: от кнехта судна к тумбе кордона; длина в плане и угол к диаметральной плоскости."""
    out = []
    for имя, k, x_т in ШВАРТОВЫ:
        xs, ys = КНЕХТЫ[k]
        y_т = Y_СТЕНКА - ТУМБА["от_кромки"]
        dx, dy = x_т - xs, y_т - ys
        out.append(dict(имя=имя, кнехт=(xs, ys), тумба=(x_т, y_т), длина=round(math.hypot(dx, dy), 1),
                        угол=round(math.degrees(math.atan2(abs(dy), abs(dx))), 0)))
    return out


def кранцы(x0=-2.0, x1=None):
    """Абсциссы кранцев по лицу стенки вдоль судна."""
    x1 = G.LOA + 4.0 if x1 is None else x1
    out, x = [], x0
    while x <= x1:
        out.append(round(x, 2))
        x += КРАНЕЦ["шаг"]
    return out


def checks():
    out = []

    def c(name, value, allow, unit, ok, note):
        out.append(dict(name=name, value=value, allow=allow, unit=unit, ok=bool(ok), note=note))

    т = трап()
    c("Трап: уклон при кордоне %.2f м над водой" % КОРДОН, т["уклон"], G.RAMP_MAX_SLOPE, "", т["уклон"] <= G.RAMP_MAX_SLOPE,
      "перепад %.2f м на %.2f м от двери гаража до кордона" % (т["перепад"], т["длина"]))
    c("Трап: сход без ступеней", "%.2f…%.2f" % (т["кордон_min"], т["кордон_max"]), КОРДОН, "м", т["кордон_min"] <= КОРДОН <= т["кордон_max"],
      "кордон над водой, при выдвижении до %.1f м уклон не круче %.2f" % (ТРАП["длина_max"], G.RAMP_MAX_SLOPE))
    а = аппарель()
    c("Аппарель на пандусе: уклон", а["уклон"], G.RAMP_MAX_SLOPE, "", а["уклон"] <= G.RAMP_MAX_SLOPE,
      "откос 1:%.0f, носок пандуса на %.2f м под водой; автомобиль и кресло-коляска съезжают на откос" % (1 / ПАНДУС["уклон"], ПАНДУС["под_водой"]))
    c("Аппарель: носок на откосе", а["носок"][0], ПАНДУС["торец_x"], "м", а["гребень_x"] < а["носок"][0] < ПАНДУС["торец_x"],
      "носок x = %.2f между гребнем %.2f и торцом %.2f" % (а["носок"][0], а["гребень_x"], ПАНДУС["торец_x"]))
    зазор = -Y_СТЕНКА - 2 * КРАНЕЦ["r"] - G.BEAM / 2.0
    c("Кранцы: зазор до борта", round(зазор, 2), 0.05, "м", зазор >= 0.05, "лицо стенки y = %.2f, кранец Ø%.1f м" % (Y_СТЕНКА, 2 * КРАНЕЦ["r"]))
    к = кран()
    c("Кран: вылет до дальнего ряда", к["вылет_дальний"], КРАН["вылет_max"], "м", к["вылет_дальний"] <= КРАН["вылет_max"],
      "ось крана y = %.2f; ближний ряд %.1f м (не меньше %.0f)" % (к["ось_y"], к["вылет_ближний"], КРАН["вылет_min"]))
    c("Кран: самый тяжёлый модуль каталога с траверсой", к["груз_каталог_т"], КРАН["г_п"], "т", к["груз_каталог_т"] <= КРАН["г_п"],
      "бассейн с водой %.1f т + траверса %.1f т; в теме — до %.1f т" % (M.МОДУЛИ["бассейн"]["масса"], КРАН["траверса_т"], к["груз_т"]))
    c("Кран: крюк под оголовком", к["z_крюк"] + КРАН["подвеска_h"], к["z_оголовок"], "м", к["z_крюк"] + КРАН["подвеска_h"] + 1.0 <= к["z_оголовок"],
      "подъём над слотом %.2f м — пронос над соседними с зазором %.1f м" % (к["подъём"], ЗАЗОР_ПРОНОСА))
    ш = швартовы()
    c("Швартовы", len(ш), 4, "шт", len(ш) >= 4 and all(s["длина"] >= 6.0 for s in ш),
      "; ".join("%s %.0f м" % (s["имя"], s["длина"]) for s in ш))
    return out


