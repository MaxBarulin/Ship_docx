def stopping():
    """Торможение реверсом с полного хода."""
    # Реверс шарнирного колеса: эксцентрик неподвижен, при обратном ходе
    # плица входит в воду не кромкой, а под углом, - упор на заднем ходу
    # берётся долей ASTERN от швартовного.
    thrust = P.COUNT * P.bollard_thrust() * ASTERN * 1000.0
    m = H.equilibrium()["D"] * ADDED_MASS * 1000.0
    speed = G.SPEED_KMH / 3.6
    dist = m * speed * speed / (2.0 * thrust)
    time = m * speed / thrust
    return dict(speed=round(speed, 2), speed_kmh=G.SPEED_KMH,
                mass=round(m / 1000.0, 0), thrust=round(thrust / 1000.0, 0),
                distance=round(dist, 0), time=round(time, 0))


def reaction():
    """Дистанция, на которой система обязана начать действовать."""
    s = stopping()
    t_all = REACT_DETECT + REACT_DECIDE + REACT_ACT
    run = s["speed"] * t_all
    manoeuvre = run + s["distance"]
    return dict(t_detect=REACT_DETECT, t_decide=REACT_DECIDE,
                t_act=REACT_ACT, t_total=t_all,
                run=round(run, 0), stop=s["distance"],
                manoeuvre=round(manoeuvre, 0),
                required=round(manoeuvre * SAFE_MARGIN, 0))


def head_on():
    """Встречное расхождение - сближение идёт двумя скоростями."""
    r = reaction()
    s = stopping()
    closing = 2.0 * s["speed"]          # оба судна идут полным ходом
    return dict(closing=round(closing, 2),
                time=round(r["required"] / closing, 0),
                required=r["required"])


def coverage():
    """Хватает ли дальности датчиков под потребную дистанцию."""
    need = reaction()["required"]
    rows = []
    for name, rng, what, backup in SENSORS:
        if rng <= 0.0:
            continue
        rows.append(dict(name=name, range=rng, what=what, backup=backup,
                         ratio=round(rng / need, 1), ok=rng >= need))
    return dict(need=need, rows=rows,
                ok=any(r["ok"] for r in rows))


def checks():
    r = reaction()
    c = coverage()
    h = head_on()
    main = [x for x in c["rows"] if "АИС" in x["name"]][0]
    return [
        dict(name="Дистанция начала манёвра", value=r["manoeuvre"],
             allow=r["stop"], unit="м", ok=r["manoeuvre"] > r["stop"],
             note="тормозной путь %.0f м плюс %.0f м за время реакции"
                  % (r["stop"], r["run"])),
        dict(name="Потребная дальность обнаружения", value=c["need"],
             allow=c["need"], unit="м", ok=True,
             note="двойной запас к дистанции начала манёвра"),
        dict(name="Дальность АИС к потребной", value=main["ratio"],
             allow=1.0, unit="раз", ok=main["ratio"] >= 1.0,
             note="АИС даёт %d км при потребных %.1f км"
                  % (main["range"] / 1000, c["need"] / 1000)),
        dict(name="Время на встречное расхождение", value=h["time"],
             allow=r["t_total"], unit="с", ok=h["time"] > r["t_total"],
             note="скорость сближения %.1f м/с" % h["closing"]),
    ]


def report():
    return dict(degree=DEGREE, degree_name=DEGREE_NAME,
                sensors=SENSORS, functions=FUNCTIONS, failsafe=FAILSAFE,
                stopping=stopping(), reaction=reaction(),
                head_on=head_on(), coverage=coverage(), checks=checks())


