# -*- coding: utf-8 -*-
"""Управляемость и мелководье: хватает ли колёс и что делать на 1,5 м.

Два вопроса, на которые проект обязан ответить числом:

1. **Управляемость.** Колёса с независимым приводом дают пару сил: одно
   вперёд, другое назад. Плечо — расстояние между колёсами, 12,8 м. Это
   мало: носовое подруливающее с тем же упором стоит на плече 60 м и даёт
   момент впятеро больше. Поэтому разнотяг — это разворот на месте у
   стенки без спешки, а не удержание носа в воротах шлюза при боковом
   ветре. Для ветра — носовой водомёт (pump-jet): он ставится заподлицо с
   днищем, забирает воду снизу и выбрасывает вбок, туннеля не нужно — на
   осадке 1,3 м туннельный подруль просто не помещается.

2. **Мелководье.** При глубине h судно идёт по «своей» воде: если скорость
   приближается к sqrt(g·h) (число Фруда по глубине Fnh → 1), поперечная
   волна не успевает уходить от корпуса, вода под днищем ускоряется,
   давление падает, и судно проседает — это просадка (squat). На 1,5 м
   sqrt(g·h) = 3,84 м/с = 13,8 км/ч; на 17,5 км/ч мы за этим порогом.
   Просадка по Баррасу для открытой воды: S = Cb·V²/100, V в узлах.
   Запас под килём — это глубина минус осадка минус просадка, и он должен
   оставаться положительным *на той скорости, которой судно идёт по мели*.

Всё считается из библиотек; в записку идёт таблица, а не прилагательные.
"""
import math

from . import gorizont as G
from . import gorizont_hydro as H
from . import gorizont_wheel as W

RHO_AIR = 1.225
CD_AIR = 0.8                 # надстройка бортом к ветру
CD_YAW = 1.0                 # поперечное сопротивление плоского корпуса при вращении
WIND_LOCK = 10.0             # м/с — при большем ветре шлюзование прекращают и так
UNDER_KEEL_MIN = 0.10        # запас под килём с просадкой на коротком мелком участке
FNH_MAX = 0.65

#: Носовой водомёт. Упор по каталожным данным струйных подрулей: ~13 кН на
#: 100 кВт. Мощность взята так, чтобы вместе с колёсами держать нос при
#: 10 м/с бокового ветра на входе в шлюз.
BOW_JET_KW = 250.0
JET_KN_PER_KW = 0.13


def wheel_couple(v_kmh=0.0):
    """Момент разворота на месте от разнотяга колёс, кН·м."""
    н = W.niche_geometry()
    плечо = 2.0 * (н["y_внутренняя_кромка"] + W.WIDTH / 2.0)
    T0 = W.bollard_thrust()
    return dict(плечо=плечо, упор_колеса=T0, момент=T0 * плечо)


def yaw_time_360(момент_кнм, T=None):
    """Время разворота на 360° на месте, с, при равновесии момент = демпфирование.

    Демпфирование — интеграл квадратичного сопротивления пластины длиной L и
    осадкой T, вращающейся вокруг миделя: M = 0,5·rho·Cd·T·r²·2·(L/2)^4/4.
    """
    T = H.equilibrium().get("T", G.DRAFT) if T is None else T
    k = 0.5 * 1000.0 * CD_YAW * T * 2.0 * (G.LOA / 2.0) ** 4 / 4.0
    r = math.sqrt(момент_кнм * 1000.0 / k)
    return 2.0 * math.pi / r


def bow_jet():
    упор = BOW_JET_KW * JET_KN_PER_KW
    плечо = G.LOA * 0.45                       # от миделя до водомёта в носу
    return dict(мощность=BOW_JET_KW, упор=упор, плечо=плечо, момент=упор * плечо)


def wind_force(v_wind=WIND_LOCK):
    """Боковая сила ветра на судно, кН, и её момент относительно миделя."""
    борт = G.LOA * (G.DECKS["солнечная"] - G.DRAFT) * 0.85     # парусность с проёмами
    F = 0.5 * RHO_AIR * CD_AIR * v_wind ** 2 * борт / 1000.0
    # центр парусности чуть в корме от миделя: рубка и надстройка равномерны
    return dict(площадь=борт, сила=F, момент=F * 0.05 * G.LOA)


def squat(v_kmh, cb=None):
    """Просадка по Баррасу для открытой воды, м. V в узлах."""
    cb = H.equilibrium()["D"] / (G.LOA * G.BEAM * H.equilibrium().get("T", G.DRAFT)) if cb is None else cb
    V = v_kmh / 1.852
    return cb * V * V / 100.0


def shallow_table(depths=(1.5, 2.0, 2.5, 3.0, 4.0, 6.0), T=None):
    """Для каждой глубины: предел по Fnh, скорость, просадка, запас под килём."""
    T = H.equilibrium().get("T", G.DRAFT) if T is None else T
    rows = []
    for h in depths:
        v_fnh = FNH_MAX * math.sqrt(9.81 * h) * 3.6
        # скорость, при которой запас под килём с просадкой ещё >= минимума
        v = 0.0
        while v + 0.5 <= min(v_fnh, G.SPEED_KMH) and h - T - squat(v + 0.5) >= UNDER_KEEL_MIN:
            v += 0.5
        rows.append(dict(h=h, v_fnh=round(v_fnh, 1), v=round(v, 1), squat=round(squat(v), 2),
                         запас=round(h - T - squat(v), 2)))
    return rows


def checks(T=None):
    T = H.equilibrium().get("T", G.DRAFT) if T is None else T
    к = wheel_couple()
    дж = bow_jet()
    в = wind_force()
    t360 = yaw_time_360(к["момент"] + дж["момент"], T)
    мель = shallow_table((G.FAIRWAY_DEPTH,), T)[0]
    from . import gorizont_autonomy as A
    ст = A.stopping()
    return [
        dict(name="Разворот на месте: колёса + водомёт", value=round(t360 / 60.0, 1), allow=6.0,
             unit="мин на 360°", ok=t360 <= 360.0,
             note="пара колёс %.0f кН·м на плече %.1f м, водомёт %.0f кН на плече %.0f м"
                  % (к["момент"], к["плечо"], дж["упор"], дж["плечо"])),
        dict(name="Нос против ветра %.0f м/с у шлюза" % WIND_LOCK, value=round(дж["момент"], 0),
             allow=round(в["момент"], 0), unit="кН·м", ok=дж["момент"] >= в["момент"],
             note="ветер %.0f кН на парусности %.0f м²; держим водомётом и разнотягом" % (в["сила"], в["площадь"])),
        dict(name="Скорость на глубине %.1f м" % G.FAIRWAY_DEPTH, value=мель["v"], allow=мель["v_fnh"],
             unit="км/ч", ok=мель["v"] > 0.0,
             note="просадка %.2f м, под килём %.2f м при осадке %.2f" % (мель["squat"], мель["запас"], T)),
        dict(name="Запас под килём на %.1f м с просадкой" % G.FAIRWAY_DEPTH, value=мель["запас"],
             allow=UNDER_KEEL_MIN, unit="м", ok=мель["запас"] >= UNDER_KEEL_MIN,
             note="на скорости %.1f км/ч" % мель["v"]),
        dict(name="Тормозной путь реверсом с полного хода", value=round(ст["distance"], 0),
             allow=round(3.0 * G.LOA, 0), unit="м", ok=ст["distance"] <= 3.0 * G.LOA,
             note="%.0f с; норма практики — не больше трёх длин" % ст["time"]),
    ]


def report():
    return dict(колёса=wheel_couple(), водомёт=bow_jet(), ветер=wind_force(),
                мелководье=shallow_table(), checks=checks())


if __name__ == "__main__":
    r = report()
    к, дж, в = r["колёса"], r["водомёт"], r["ветер"]
    print("Пара колёс: упор %.0f кН на плече %.1f м → %.0f кН·м" % (к["упор_колеса"], к["плечо"], к["момент"]))
    print("Водомёт %.0f кВт: %.0f кН на плече %.0f м → %.0f кН·м" % (дж["мощность"], дж["упор"], дж["плечо"], дж["момент"]))
    print("Ветер %.0f м/с: %.0f кН, момент %.0f кН·м" % (WIND_LOCK, в["сила"], в["момент"]))
    print("Мелководье (осадка %.2f):" % H.equilibrium().get("T", G.DRAFT))
    for row in r["мелководье"]:
        print("  h=%.1f м: по Fnh до %.1f км/ч; с просадкой идём %.1f км/ч, просадка %.2f, под килём %.2f"
              % (row["h"], row["v_fnh"], row["v"], row["squat"], row["запас"]))
    for c in r["checks"]:
        print("  %-44s %8s %-12s %s %s" % (c["name"], c["value"], c["unit"], "ок " if c["ok"] else "НЕТ", c["note"]))
