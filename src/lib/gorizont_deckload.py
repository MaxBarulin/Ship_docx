# -*- coding: utf-8 -*-
"""Солнечная палуба: размеры, что на ней стоит, и сколько на неё можно ставить.

Вопрос команды (22.09.2026): с мостом 13,8 м открытая палуба стала площадкой
под модульные номера — сколько килограммов туда можно и при каких условиях.
Ответ складывается из четырёх ограничений, каждое считается своей библиотекой:

1. **Осадка.** Каждая тонна на палубе — тонна водоизмещения: TPC из
   `gorizont_hydro.hydrostatics`. До расчётной осадки 1,30 м запас
   небольшой, а дальше падает скорость на мели 1,5 м (`gorizont_manoeuvre`).
2. **Остойчивость и парусность.** Груз стоит высоко (ЦТ модуля на 1,45 м
   над настилом) и парусит боковой стенкой; критерии РРР считаются
   `gorizont_hydro.rrr_checks` с дополнительной нагрузкой в `ДОПОЛНИТЕЛЬНО`.
3. **Дифферент.** Момент от груза относительно ЦВ ватерлинии, MCT оттуда же.
4. **Местная прочность настила.** Пластина 6 мм АМг5 при шпации 0,55 м;
   набор надстройки в библиотеке задан массой, а не профилями, поэтому
   распределённая нагрузка принимается по нормам, а точечные грузы идут
   только на фундаменты над рамными бимсами — это узел Глеба.

Всё, что здесь «принято», помечено и уточняется по КД фундамента.

    python -m lib.gorizont_deckload      # из src: размеры, бюджет массы, сценарии, проверки
"""
import math
from . import gorizont as G
from . import gorizont_ga as GA
from . import gorizont_super as SU
from . import gorizont_hydro as H
from . import gorizont_struct as S
from . import gorizont_wheel as W
from . import gorizont_manoeuvre as MN

ПАЛУБА = "солнечная"
Z_НАСТИЛ = G.DECKS[ПАЛУБА]
#: Расчётная распределённая нагрузка на открытую пассажирскую палубу — люди,
#: шезлонги, лёгкое оборудование. **Принято** по практике норм РРР для
#: открытых палуб; в проверке сравнивается с несущей способностью пластины.
НАГРУЗКА_НОРМА_КПА = 5.0
#: Допускаемое напряжение в пластине настила из АМг5 (сварное состояние):
#: 0,6 от предела текучести 125 МПа. **Принято**, уточнить по материалу Глеба.
СИГМА_ДОП_МПА = 0.6 * 125.0
#: Модульный номер: масса с отделкой, мебелью и двумя пассажирами — **принято**
#: по 20-футовому контейнеру high cube (тара 2,4 т) с лёгкой отделкой.
МОДУЛЬ_МАССА_Т = 4.3
МОДУЛЬ_ЦТ_НАД_НАСТИЛОМ = G.MODULES["фундамент"] + G.MODULES["высота"] / 2.0
#: Ограничения на посадку и дифферент, при которых судно остаётся «как спроектировано».
ДИФФЕРЕНТ_ДОП = 0.30       # м, сверх проектных 0,11 на корму по модулю
СКОРОСТЬ_НА_МЕЛИ_МИН = 5.0   # км/ч на глубине 1,5 м, ниже уже не ход
X_ТРУБА = W.X_AXIS + 17.0


# --- геометрия ---------------------------------------------------------------------
def ширина(x):
    """Ширина настила солнечной палубы на абсциссе x, м (по кромке яруса средней палубы)."""
    return 2.0 * max(SU.полуширота(x, "средняя", z=Z_НАСТИЛ - 0.05), 0.0)


def габариты():
    я = SU.ЯРУСЫ["средняя"]
    x0, x1 = я["x0"], я["x1"]
    станции = [(x, round(ширина(x), 2)) for x in range(int(math.ceil(x0)), int(x1) + 1, 5)]
    шир = [w for _, w in станции]
    return dict(x0=x0, x1=x1, длина=round(x1 - x0, 1), ширина_макс=round(max(шир), 2),
                ширина_мин=round(min(w for w in шир if w > 0), 2), станции=станции,
                высота_над_вл=round(Z_НАСТИЛ - H.equilibrium()["T"], 2),
                свободная_высота=G.module_clearance()["свободно"])


def сооружения():
    """Что стоит на палубе: прямоугольники (x0, x1, y0, y1) и высота, м."""
    X = W.X_AXIS
    р = SU.РУБКА
    out = [dict(имя="Рулевая рубка", x0=р["x0"], x1=р["x1"], y0=-р["полу"], y1=р["полу"], h=G.WHEELHOUSE_ROOF - Z_НАСТИЛ),
           dict(имя="Навес солнечных модулей %.0f кВт" % G.SOLAR_KW, x0=X - 8.0, x1=X + 8.0, y0=-5.5, y1=5.5, h=2.6),
           dict(имя="Световой фонарь атриума", x0=X + 1.0, x1=X + 7.0, y0=-3.4, y1=3.4, h=1.2),
           dict(имя="Дымовая труба", x0=X_ТРУБА - 1.4, x1=X_ТРУБА + 1.4, y0=-0.9, y1=0.9, h=2.5)]
    for имя in ("кормовой", "атриум"):
        a, b = GA.ТРАПЫ[имя]
        out.append(dict(имя="Выход трапа (%s)" % имя, x0=a + 0.2, x1=b - 0.2, y0=-1.55, y1=1.55, h=2.4))
    a, b, y0, y1 = GA.ЛИФТЫ["кормовой"]
    out.append(dict(имя="Шахта лифта", x0=a, x1=b, y0=y0, y1=y1, h=2.6))
    for s in out:
        s["площадь"] = round((s["x1"] - s["x0"]) * (s["y1"] - s["y0"]), 1)
    return out


def площадки_под_модули():
    """Открытые зоны, где модуль 3,2 м высотой встаёт: без навеса (2,6 м), без
    рубки, с отступом от трубы; ширина зоны — минимальная по её длине."""
    X = W.X_AXIS
    out = []
    for z in GA.зоны_с_площадями()[ПАЛУБА]:
        if z["тип"] != "open" or "модули" in z["имя"]:
            continue
        x0, x1 = z["x0"], z["x1"]
        ширины = [ширина(x) for x in [x0 + 0.5 + i for i in range(int(x1 - x0))]]
        w_min = min(ширины) if ширины else 0.0
        # труба режет прогулочную зону: модули не ближе 3 м к ней
        запреты = []
        if x0 <= X_ТРУБА <= x1:
            запреты.append((X_ТРУБА - 4.4, X_ТРУБА + 4.4))
        for имя in ("кормовой", "атриум"):
            a, b = GA.ТРАПЫ[имя]
            if a < x1 and b > x0:
                запреты.append((a, b))
        # рядов модулей поперёк: ширина минус проход 1,2 м по бортам и между рядами
        рядов = max(0, int((w_min - 1.2) // (G.MODULES["ширина"] + 1.2)))
        длина_чистая = (x1 - x0) - sum(max(0.0, min(b, x1) - max(a, x0)) for a, b in запреты)
        вдоль = int(длина_чистая // (G.MODULES["длина"] + 0.6))
        out.append(dict(зона=z["имя"], x0=x0, x1=x1, ширина_мин=round(w_min, 2), площадь=z["площадь"],
                        рядов=рядов, вдоль=вдоль, модулей=рядов * вдоль, запреты=запреты))
    return out


# --- нагрузки ----------------------------------------------------------------------
def настил():
    """Несущая способность пластины настила: длинная защемлённая пластина,
    σ = 0,5·p·(s/t)² → p_доп = 2·σ_доп·(t/s)²."""
    t = S.PLATES["настил солнечной палубы"] / 1000.0
    s = S.SPACING
    p = 2.0 * СИГМА_ДОП_МПА * (t / s) ** 2 * 1000.0   # кПа
    return dict(t_мм=t * 1000.0, шпация=s, p_пластины_кпа=round(p, 1), p_норма_кпа=НАГРУЗКА_НОРМА_КПА,
                кг_на_м2=round(НАГРУЗКА_НОРМА_КПА * 1000.0 / 9.81), рамная_шпация=S.FRAME_SPACING)


def бюджет_массы():
    e = H.equilibrium()
    h = e["hydro"]
    T, TPC, MCT = e["T"], h["TPC"], h["MCT"]
    до_расчётной = (G.DRAFT - T) * 100.0 * TPC
    # предел по мели: осадка, при которой на глубине 1,5 м ещё держится минимальная скорость
    T_lim, шаг = T, 0.01
    while T_lim < 2.0:
        v = MN.shallow_table((G.FAIRWAY_DEPTH,), T_lim + шаг)[0]["v"]
        if v < СКОРОСТЬ_НА_МЕЛИ_МИН:
            break
        T_lim += шаг
    до_мели = (T_lim - T) * 100.0 * TPC
    return dict(T=round(T, 3), TPC=round(TPC, 2), MCT=round(MCT, 1), xf=round(h["xf"], 2),
                до_расчётной_т=round(до_расчётной), T_расчётная=G.DRAFT,
                T_предел_мели=round(T_lim, 2), до_мели_т=round(до_мели),
                таблица_мели=[dict(T=round(t, 2), v=MN.shallow_table((G.FAIRWAY_DEPTH,), t)[0]["v"],
                                   под_килём=MN.shallow_table((G.FAIRWAY_DEPTH,), t)[0]["запас"])
                              for t in (T, 1.30, 1.35, 1.40, 1.45)])


def с_нагрузкой(масса_т, x, z=None, парусность_м2=0.0, высота_парус=0.0):
    """Посадка и остойчивость с грузом массы m на палубе в точке x."""
    z = Z_НАСТИЛ + МОДУЛЬ_ЦТ_НАД_НАСТИЛОМ if z is None else z
    H.ДОПОЛНИТЕЛЬНО[:] = [("Дополнительная нагрузка на солнечной палубе", масса_т, x, x, z,
                          парусность_м2, высота_парус, Z_НАСТИЛ + G.MODULES["фундамент"])]
    try:
        rows, s, w, e = H.rrr_checks()
        return dict(T=round(e["T"], 3), дифферент=round(e["trim"], 3), D=round(e["D"], 1), zg=round(e["zg"], 2),
                    h=round(s["h"], 2), K=round(w["K"], 2), крен_ветер=round(w["theta_stat"], 2),
                    парусность=round(w["A"], 0), ррр_не_прошло=[r["name"] for r in rows if not r["ok"]])
    finally:
        H.ДОПОЛНИТЕЛЬНО[:] = []


_СЦЕНАРИИ = None


def сценарии():
    """Модули на площадках: сколько штук, где, что с посадкой и остойчивостью.
    Каждый сценарий — полный расчёт остойчивости (пантокарены), поэтому
    результат кэшируется на время процесса."""
    global _СЦЕНАРИИ
    if _СЦЕНАРИИ is not None:
        return _СЦЕНАРИИ
    _СЦЕНАРИИ = _сценарии()
    return _СЦЕНАРИИ


def _сценарии():
    пл = площадки_под_модули()
    out = []
    for n in (0, 4, 8, 12, 16, 20):
        # раскладка: сначала прогулочная зона у миделя (меньше дифферент), потом солярий
        остаток, xs = n, []
        for z in sorted(пл, key=lambda z: abs(0.5 * (z["x0"] + z["x1"]) - H.equilibrium()["hydro"]["xf"])):
            k = min(остаток, z["модулей"])
            xs += [0.5 * (z["x0"] + z["x1"])] * k
            остаток -= k
        if остаток > 0:
            out.append(dict(модулей=n, размещено=n - остаток, помещается=False))
            continue
        m = n * МОДУЛЬ_МАССА_Т
        x = sum(xs) / len(xs) if xs else H.equilibrium()["hydro"]["xf"]
        парус = n * G.MODULES["длина"] * G.MODULES["высота"]
        r = с_нагрузкой(m, x, парусность_м2=парус, высота_парус=G.MODULES["высота"]) if n else с_нагрузкой(0.0, x)
        r.update(модулей=n, размещено=n, помещается=True, масса_т=round(m, 1), x=round(x, 1),
                 в_расчётной_осадке=r["T"] <= G.DRAFT + 1e-6)
        out.append(r)
    return out


def макс_модулей():
    """Сколько модулей встаёт без выхода за расчётную осадку и с нормами РРР."""
    best = 0
    for r in сценарии():
        if r.get("помещается") and r.get("в_расчётной_осадке") and not r.get("ррр_не_прошло"):
            best = r["модулей"]
    return best


def checks():
    out = []

    def c(name, value, allow, unit, ok, note):
        out.append(dict(name=name, value=value, allow=allow, unit=unit, ok=bool(ok), note=note))

    н = настил()
    c("Пластина настила держит норму", н["p_пластины_кпа"], НАГРУЗКА_НОРМА_КПА, "кПа", н["p_пластины_кпа"] >= НАГРУЗКА_НОРМА_КПА,
      "6 мм АМг5 при шпации %.2f м: %.1f кПа против %.1f" % (н["шпация"], н["p_пластины_кпа"], НАГРУЗКА_НОРМА_КПА))
    б = бюджет_массы()
    c("Запас массы до расчётной осадки", б["до_расчётной_т"], 40, "т", б["до_расчётной_т"] >= 40,
      "T %.3f → %.2f при TPC %.1f т/см" % (б["T"], G.DRAFT, б["TPC"]))
    сц = [r for r in сценарии() if r.get("помещается")]
    m = макс_модулей()
    c("Модулей в расчётной осадке по нормам РРР", m, 8, "шт", m >= 8,
      "по %.1f т, ЦТ на %.2f м над настилом, парусность стенок учтена" % (МОДУЛЬ_МАССА_Т, МОДУЛЬ_ЦТ_НАД_НАСТИЛОМ))
    худший = max((abs(r["дифферент"]) for r in сц), default=0.0)
    c("Дифферент с модулями", round(худший, 2), ДИФФЕРЕНТ_ДОП, "м", худший <= ДИФФЕРЕНТ_ДОП,
      "модули у миделя, ЦВ ватерлинии x = %.1f" % б["xf"])
    c("Свободная высота под мостом", G.module_clearance()["свободно"], round(G.MODULES["высота"] + G.MODULES["фундамент"], 2), "м",
      G.module_clearance()["запас"] >= 0, "мост %.1f, модуль с фундаментом %.2f" % (G.BRIDGE_MIN, G.MODULES["высота"] + G.MODULES["фундамент"]))
    return out


