def дорожная_карта():
    """Задачи редакции Лены с датами. Каждая — dict(id, ид_лены, группа, задача,
    начало, конец, кто, вид, ключ, веха, замечание, дней). Вехи — задачи с
    нулевой длительностью; договор дополнен вехой «Договор подписан»."""
    з = []
    for ид, группа, задача, начало, раб, кто, вид, ключ, замечание in ЛЕНА:
        конец = _раб(начало, раб) if раб else начало
        з.append(dict(id=len(з) + 1, ид_лены=ид, группа=группа, задача=задача, начало=начало, конец=конец,
                      кто=кто, вид=вид, ключ=ключ, веха=(раб == 0), замечание=замечание, изменено=замечание,
                      раб_дней=раб, дней=(конец - начало).days + 1))
        if ключ == "договор":
            з.append(dict(id=len(з) + 1, ид_лены=ид, группа=группа, задача="Договор подписан", начало=конец, конец=конец,
                          кто="ГД", вид=None, ключ="договор_веха", веха=True, замечание="", изменено="", раб_дней=0, дней=1))
    return з


def задача(ключ):
    return next(t for t in дорожная_карта() if t["ключ"] == ключ)


