def _раб(d0, n):
    """Конец задачи из n рабочих дней (пн-пт, без праздников - календарь MS Project в исходной карте)."""
    if n <= 0:
        return d0
    d, k = d0, 0
    while True:
        if d.weekday() < 5:
            k += 1
            if k == n:
                return d
        d += _dt.timedelta(days=1)


