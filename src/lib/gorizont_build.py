def _fmt(x, nd=0):
    s = ("%%.%df" % nd) % x
    if nd:
        a, b = s.split(".")
        return "%s,%s" % ("{:,}".format(int(a)).replace(",", " "), b)
    return "{:,}".format(int(round(float(s)))).replace(",", " ")


