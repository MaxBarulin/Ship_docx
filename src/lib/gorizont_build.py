# --- численность --------------------------------------------------------------
def _месяцев(a, b):
    return max((b - a).days + 1, 1) / 30.4375


def численность(D=None):
    """Численность по видам работ из трудоёмкости и длительности этапов карты.

    N = T / (месяцев × фонд × k_вн) - формула Мацкевича, как в примере коллег.
    Виды работ, разнесённые по нескольким задачам (трубомонтаж на стапеле и
    на достройке), считаются по сумме их длительностей.
    """
    тр = трудоёмкость(D)
    карта = дорожная_карта()
    T_по_виду = {в["вид"]: (в["T"], в["профессия"]) for в in тр["виды"]}
    T_по_виду["Электромонтаж"] = (тр["T_эмр"], "электромонтажники")
    for с in тр["стадии"]:
        T_по_виду[с["стадия"]] = (с["T"], "ИТР проектирования")
    этапы = []
    for вид, (T, проф) in T_по_виду.items():
        задачи = [t for t in карта if вид in _виды(t)]
        мес = sum(_месяцев(t["начало"], t["конец"]) for t in задачи)
        N = int(math.ceil(T / (мес * ФОНД_МЕС * K_ВН))) if мес else 0
        этапы.append(dict(вид=вид, профессия=проф, T=T, месяцев=мес, N=N,
                          начало=min(t["начало"] for t in задачи) if задачи else None,
                          конец=max(t["конец"] for t in задачи) if задачи else None,
                          задачи=[t["id"] for t in задачи]))
    # профиль по месяцам: сколько людей занято в каждом месяце
    m0 = Д(ТЗ.year, ТЗ.month, 1)
    m1 = сдача()["конец"]
    профиль = []
    m = m0
    while m <= m1:
        m_end = (Д(m.year + (m.month // 12), m.month % 12 + 1, 1) - _dt.timedelta(days=1))
        по_проф = {}
        for э in этапы:
            for tid in э["задачи"]:
                t = карта[tid - 1]
                if t["начало"] <= m_end and t["конец"] >= m:
                    по_проф[э["профессия"]] = по_проф.get(э["профессия"], 0) + э["N"]
                    break
        профиль.append(dict(месяц=m, по_профессиям=по_проф, всего=sum(по_проф.values())))
        m = Д(m.year + (m.month // 12), m.month % 12 + 1, 1)
    пик = max(профиль, key=lambda p: p["всего"])
    производство = [p for p in профиль if p["месяц"] >= Д(ДОГОВОР.year, ДОГОВОР.month, 1)]
    ср = sum(p["всего"] for p in производство) / len(производство)
    по_проф = {}
    for э in этапы:
        по_проф[э["профессия"]] = по_проф.get(э["профессия"], 0) + э["N"]
    опр = sum(v for k, v in по_проф.items() if k != "ИТР проектирования")
    пик_опр = max(sum(v for k, v in p["по_профессиям"].items() if k != "ИТР проектирования")
                  for p in профиль)
    return dict(этапы=этапы, профиль=профиль, пик=пик["всего"], пик_месяц=пик["месяц"],
                пик_опр=пик_опр, средняя=ср, по_профессиям=по_проф, ОПР_сумма=опр,
                вспомогательные=int(math.ceil(пик_опр * K_ВСПОМ)),
                ИТР_производства=int(math.ceil(пик_опр * K_ИТР)),
                всего_пик=пик["всего"] + int(math.ceil(пик_опр * K_ВСПОМ)) + int(math.ceil(пик_опр * K_ИТР)),
                чел_мес=sum(p["всего"] for p in профиль))


def затраты_на_персонал(ставки=None, D=None):
    """Затраты на персонал, руб. - сумма по профессиям T × ставка чел·ч.

    Ставок в проекте нет - их даёт Лена (нормо-час ОПР по НПА верфи, ИТР по
    рынку). Пока их нет, функция возвращает None, а не выдуманное число.
    """
    if not ставки:
        return None
    тр = трудоёмкость(D)
    T = {}
    for в in тр["виды"]:
        T[в["профессия"]] = T.get(в["профессия"], 0.0) + в["T"]
    T["электромонтажники"] = тр["T_эмр"]
    T["ИТР проектирования"] = тр["T_проект"]
    строки = [(п, t, ставки.get(п, 0.0), t * K_ВН * ставки.get(п, 0.0)) for п, t in T.items()]
    return dict(строки=строки, итого=sum(s[3] for s in строки))


