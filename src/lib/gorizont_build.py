def _доли():
    s = sum(д for _, д, _ in ВИДЫ_РАБОТ)
    добавка = (100.0 - s) / len(ВИДЫ_РАБОТ)
    return [д + добавка for _, д, _ in ВИДЫ_РАБОТ]


def трудоёмкость(D=None, k_усл=K_УСЛ, k_сер=K_СЕР):
    """Трудоёмкость постройки и проектирования, чел·ч."""
    D = водоизмещение_порожнем() if D is None else float(D)
    t = НОРМАТИВ_A - НОРМАТИВ_B * math.log(D)
    T_сер = t * D * k_усл
    T_гол = T_сер * k_сер
    T_эмр = T_гол * ДОЛЯ_ЭМР
    T_пр = T_сер * ДОЛЯ_ПРОЕКТ
    виды = [dict(вид=в, доля=д, профессия=п, T=T_гол * д / 100.0)
            for (в, _, п), д in zip(ВИДЫ_РАБОТ, _доли())]
    стадии = [dict(стадия=с, доля=д, T=T_пр * д / 100.0) for с, д in СТАДИИ_ПРОЕКТА]
    return dict(D=D, t_уд=t, k_усл=k_усл, k_сер=k_сер, T_сер=T_сер, T_гол=T_гол,
                T_эмр=T_эмр, T_проект=T_пр, T_всего=T_гол + T_эмр + T_пр,
                виды=виды, стадии=стадии)


