def awts_consumers():
    out = []
    for code, name, n, box, mirror, power, mass, note in M.EQUIPMENT:
        if code in AWTS_CODES and power:
            out.append((code, name, float(n * power), dict(AWTS_MODES)))
    return out


def thruster_consumers():
    """Подруливающие - работают только на манёврах и не одновременно на полную."""
    total = sum(t.get("power", t.get("kw", 0)) for t in G.THRUSTERS.values())
    return [("ПУ", "Носовой водомёт", float(total),
             {"манёвры": (1.0, 0.55)})]


def all_consumers():
    return CONSUMERS + awts_consumers() + thruster_consumers()


# --- Мощность на движителях -------------------------------------------------

def shaft_power(mode):
    """Мощность на фланцах гребных валов в режиме, кВт."""
    for key, _name, v, depth in MODES:
        if key != mode:
            continue
        if v is None:
            if mode == "манёвры":
                return MANOEUVRE_SHAFT_FRACTION * H.PROP_POWER
            return 0.0
        return H.power(v, depth=depth)["Pb"]
    return 0.0


def propulsion_load(mode):
    """Мощность, которую ГЭД берут с шин ГРЩ, кВт."""
    return shaft_power(mode) / ETA_DRIVE


# --- Баланс -----------------------------------------------------------------

def balance(mode):
    """Строки баланса и итог по режиму."""
    rows = []
    for code, name, p_inst, modes in all_consumers():
        ko, kz = modes.get(mode, (0.0, 0.0))
        p = p_inst * ko * kz
        rows.append(dict(code=code, name=name, installed=p_inst,
                         ko=ko, kz=kz, power=round(p, 1)))
    hotel = sum(r["power"] for r in rows)
    prop = propulsion_load(mode)
    return dict(mode=mode, rows=rows,
                installed=round(sum(r["installed"] for r in rows), 1),
                hotel=round(hotel, 1),
                shaft=round(shaft_power(mode), 1),
                propulsion=round(prop, 1),
                total=round(hotel + prop, 1))


def generators(total, unit=None, count=None):
    """Сколько ГДГ надо держать под нагрузкой и какова их загрузка.

    Дизель-генератор не любит долгой работы ниже половины номинала - растёт
    удельный расход, закоксовываются форсунки и турбина. Поэтому машин
    включают столько, чтобы каждая села в 60…90 % - и ни одной лишней.
    """
    unit = unit or G.DG_POWER
    count = count or G.DG_COUNT
    for n in range(1, count + 1):
        if total <= 0.9 * n * unit:
            return dict(n=n, load=round(100.0 * total / (n * unit), 1),
                        spare=round(n * unit - total, 1), ok=True)
    return dict(n=count, load=round(100.0 * total / (count * unit), 1),
                spare=round(count * unit - total, 1), ok=False)


def table():
    """Итоговая таблица баланса по всем режимам."""
    out = []
    for key, name, _v, _d in MODES:
        b = balance(key)
        if key == "аварийный":
            g = dict(n=1, load=round(100.0 * b["total"] / G.EMERGENCY_DG, 1),
                     spare=round(G.EMERGENCY_DG - b["total"], 1),
                     ok=b["total"] <= G.EMERGENCY_DG)
        else:
            g = generators(b["total"])
        out.append(dict(key=key, name=name, hotel=b["hotel"],
                        shaft=b["shaft"], propulsion=b["propulsion"],
                        total=b["total"], dg=g["n"], load=g["load"],
                        spare=g["spare"], ok=g["ok"]))
    return out


def redundancy(mode="ход", unit=None, count=None):
    """Что остаётся, если один ГДГ выведен из строя (режим n-1).

    Проверка не формальная - судно с 212 пассажирами не должно терять ход
    из-за одной машины - оно идёт по фарватеру с течением, шлюзами и
    встречным движением, и «дрейфовать до буксира» здесь негде.
    """
    unit = unit or G.DG_POWER
    count = (count or G.DG_COUNT) - 1
    b = balance(mode)
    depth = next((d for k, _n, _v, d in MODES if k == mode), None)
    available = 0.9 * count * unit - b["hotel"]
    shaft = max(available, 0.0) * ETA_DRIVE
    # Скорость считается НА ТОЙ ЖЕ ВОДЕ, что и режим: на мелководье
    # сопротивление в полтора раза больше, и оценка по глубокой воде
    # завысила бы результат проверки ровно там, где она важна.
    speed = H.max_speed(P_avail=min(shaft, H.PROP_POWER), depth=depth)
    return dict(mode=mode, dg=count, depth=depth,
                avail_bus=round(0.9 * count * unit, 1),
                hotel=b["hotel"], for_propulsion=round(available, 1),
                shaft=round(shaft, 1), speed=round(speed, 1),
                keeps_service=speed >= G.SPEED_KMH)


def battery_endurance(mode="стоянка"):
    """Сколько судно живёт на батарее без генераторов, часов."""
    b = balance(mode)
    return dict(mode=mode, load=b["total"],
                hours=round(G.BATTERY_KWH / max(b["total"], 1e-6), 2))


# --- Обоснование двух валов -------------------------------------------------

T_DEDUCTION = 0.18      # коэффициент засасывания
WAKE = 0.25             # коэффициент попутного потока
TIP_CLEARANCE = 0.15    # потребное заглубление верхней кромки, доли D


def max_propeller_diameter(T=None, axis=None):
    """Наибольший диаметр винта, который заглубляется при этой осадке.

    Верхняя кромка диска должна уйти под воду на 0.15·D, иначе винт
    захватывает воздух на волне и на циркуляции. Отсюда
    axis + D/2 <= T - 0.15·D, то есть D <= (T - axis) / 0.65.
    """
    T = T if T is not None else H.equilibrium()["T"]
    axis = axis if axis is not None else G.SHAFT_Z_PROP
    return (T - axis) / (0.5 + TIP_CLEARANCE)


def disc_loading(v_kmh, n_shafts, diameter, depth=None):
    """Нагрузка диска и идеальный пропульсивный КПД.

    Ct = T / (0.5·ρ·A·Va²), η_ид = 2 / (1 + √(1 + Ct)). Формула идеального
    движителя не даёт абсолютного КПД, но правильно сравнивает варианты:
    весь выигрыш двух валов перед одним сидит именно в площади диска.
    """
    r = H.power(v_kmh, depth=depth)
    thrust = r["R"] / (1.0 - T_DEDUCTION)              # кН, суммарный упор
    va = r["v"] * (1.0 - WAKE)
    area = n_shafts * math.pi / 4.0 * diameter ** 2
    ct = thrust * 1000.0 / (0.5 * 1000.0 * area * va ** 2)
    eta = 2.0 / (1.0 + math.sqrt(1.0 + ct))
    return dict(v=v_kmh, n=n_shafts, d=diameter, area=round(area, 2),
                thrust=round(thrust, 1), va=round(va, 2),
                ct=round(ct, 2), eta=round(eta, 3))


def single_shaft_comparison(v_kmh=22.0):
    """Сравнение двух валов с одним при той же осадке.

    Возвращает три варианта - принятый двухвальный, одновальный с тем же
    винтом и одновальный с винтом равной суммарной площади диска -
    последний и показывает, почему один вал здесь не проходит.
    """
    d = G.PROP_DIAMETER
    equal_area = d * math.sqrt(2.0)
    twin = disc_loading(v_kmh, 2, d)
    single_same = disc_loading(v_kmh, 1, d)
    single_equal = disc_loading(v_kmh, 1, equal_area)
    T = H.equilibrium()["T"]
    tip = G.SHAFT_Z_PROP + equal_area / 2.0
    return dict(
        twin=twin, single_same=single_same, single_equal=single_equal,
        equal_diameter=round(equal_area, 2),
        d_limit=round(max_propeller_diameter(), 3),
        tip_z=round(tip, 2), draft=round(T, 3),
        immersion=round(T - tip, 2),
        fits=tip <= T - TIP_CLEARANCE * equal_area,
        power_penalty=round(100.0 * (twin["eta"] / single_same["eta"] - 1.0), 1),
    )


def summary():
    return dict(area=round(AREA, 0), people=PEOPLE,
                modes=table(), n_minus_1=redundancy(),
                battery=battery_endurance(),
                shafts=single_shaft_comparison())
