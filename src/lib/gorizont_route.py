def _гаверсин(a, b):
    R = 6371.0088
    la1, lo1, la2, lo2 = map(math.radians, (a[1], a[0], b[1], b[0]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))


def путь():
    """Координаты фарватера [(lon, lat), ...] из маршрут.geojson; None, если не построен."""
    if not os.path.exists(ФАЙЛ_ПУТИ):
        return None
    g = json.load(open(ФАЙЛ_ПУТИ, encoding="utf-8"))
    for f in g["features"]:
        if f["geometry"]["type"] == "LineString" and f["properties"].get("тип") == "маршрут":
            return [tuple(p) for p in f["geometry"]["coordinates"]]
    return None


def плечи():
    """Длины участков между портами по фарватеру, км; по прямой, если пути нет."""
    п = путь()
    out = []
    if п is None:
        for a, b in zip(ПОРТЫ, ПОРТЫ[1:]):
            out.append(dict(от=a["порт"], до=b["порт"], км=round(_гаверсин((a["lon"], a["lat"]), (b["lon"], b["lat"])), 0), по="прямой"))
        return out
    g = json.load(open(ФАЙЛ_ПУТИ, encoding="utf-8"))
    for f in g["features"]:
        if f["properties"].get("тип") == "плечо":
            out.append(dict(от=f["properties"]["от"], до=f["properties"]["до"], км=f["properties"]["км"], по="фарватеру"))
    return out


def длина_км():
    return round(sum(p["км"] for p in плечи()))


