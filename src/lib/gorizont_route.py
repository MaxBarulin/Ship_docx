def _гаверсин(a, b):
    R = 6371.0088
    la1, lo1, la2, lo2 = map(math.radians, (a[1], a[0], b[1], b[0]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))


def путь():
    """Координаты фарватера [(lon, lat), ...] из маршрут.geojson; None, если не построен."""
    if not os.path.exists(ФАЙЛ_ПУТИ):
        return None
    g = json.load(open(ФАЙЛ_ПУТИ, encoding="utf-8"))
    for f in g["features"]:
        if f["geometry"]["type"] == "LineString" and f["properties"].get("тип") == "маршрут":
            return [tuple(p) for p in f["geometry"]["coordinates"]]
    return None


def плечи():
    """Длины участков между точками программы по фарватеру, км; по прямой, если пути нет."""
    п = путь()
    out = []
    if п is None:
        for a, b in zip(ПОРТЫ, ПОРТЫ[1:]):
            out.append(dict(от=a["порт"], до=b["порт"], км=round(_гаверсин((a["lon"], a["lat"]), (b["lon"], b["lat"])), 0), по="прямой"))
        return out
    g = json.load(open(ФАЙЛ_ПУТИ, encoding="utf-8"))
    for f in g["features"]:
        if f["properties"].get("тип") == "плечо":
            out.append(dict(от=f["properties"]["от"], до=f["properties"]["до"], км=f["properties"]["км"], по="фарватеру"))
    return out


def длина_км():
    return round(sum(p["км"] for p in плечи()))


#: Скорость течения, км/ч: водохранилища Волги и Камы почти стоячие, Белая — свободная река. Принято.
ТЕЧЕНИЕ = {"Волга": 1.0, "Кама": 1.0, "Белая": 3.0}
СТОЯНКА_Ч = 6.0     # экскурсионная стоянка в порту с однодневной программой, ч


def переходы():
    """Переходы между портами (ходовые дни склеены): км, часов в распоряжении, часов хода.

    До Уфы судно идёт против течения, от Уфы — по течению; скорость относительно
    берега — `gorizont.SPEED_KMH` минус или плюс среднее течение рек перехода.
    Часов в распоряжении — сутки между концом стоянки и днём прихода минус
    экскурсионная стоянка `СТОЯНКА_Ч`."""
    from . import gorizont as G
    пл = плечи()
    порты = [p for p in ПОРТЫ]
    уфа = next(k for k, p in enumerate(порты) if p["порт"] == "Уфа")
    out = []
    i = 0
    while i < len(порты) - 1:
        a = порты[i]
        j = i + 1
        км, реки = 0.0, {a["река"]}
        while j < len(порты):
            км += next((p["км"] for p in пл if p["от"] == порты[j - 1]["порт"] and p["до"] == порты[j]["порт"]), 0.0)
            реки.add(порты[j]["река"])
            if not порты[j].get("ход"):
                break
            j += 1
        b = порты[j]
        течение = sum(ТЕЧЕНИЕ[r] for r in реки) / len(реки)
        v = G.SPEED_KMH + (течение if i >= уфа else -течение)
        часов = (b["день"] - (a["день"] + a.get("стоянка", 1) - 1)) * 24.0 - СТОЯНКА_Ч
        out.append(dict(от=a["порт"], до=b["порт"], км=round(км), часов=часов, v=round(v, 1), ход_ч=round(км / v, 1),
                        по_течению=i >= уфа, ок=км / v <= часов))
        i = j
    return out


