def checks():
    from . import gorizont as G
    out = []

    def c(name, value, allow, unit, ok, note):
        out.append(dict(name=name, value=value, allow=allow, unit=unit, ok=bool(ok), note=note))

    запас = МОСТ_МИН - G.AIR_DRAFT
    c("Запас под самым низким мостом", round(запас, 2), 0.5, "м", запас >= 0.5,
      "мост %.1f м (данные Ивана), габарит %.2f м со стационарной рубкой" % (МОСТ_МИН, G.AIR_DRAFT))
    дни = ПОРТЫ[-1]["день"]
    c("Программа укладывается в автономность", дни, G.AUTONOMY_DAYS, "сут", дни <= G.AUTONOMY_DAYS,
      "%d дней тура при автономности %d суток" % (дни, G.AUTONOMY_DAYS))
    L = длина_км()
    ход_ч = L / G.SPEED_KMH
    c("Ходовое время по маршруту", round(ход_ч / 24, 1), ДНЕЙ * 0.6, "сут", ход_ч / 24 <= ДНЕЙ * 0.6,
      "%d км при %.1f км/ч — %.0f ч хода на %d дней, остальное стоянки" % (L, G.SPEED_KMH, ход_ч, ДНЕЙ))
    c("Путь по фарватеру построен", 1 if путь() else 0, 1, "", путь() is not None,
      "docs/проект/маршрут.geojson из scripts/маршрут.py" if путь() else "пути нет — длины по прямой")
    return out


